export interface EmojiEntry {
  emoji: string;
  words: string;
}

export const EMOJIS: readonly EmojiEntry[] = RAW.map(([emoji, words]) => ({ emoji, words }));

/** The emoji whose words contain every word typed (case does not matter); an empty search keeps them all. */
export function searchEmoji(query: string): readonly EmojiEntry[] {
  const parts = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return EMOJIS;
  return EMOJIS.filter((e) => parts.every((p) => e.words.includes(p)));
}
