// Builds src/features/_registry/nav.generated.ts from every src/features/<domain>/nav.ts, and
// settings.generated.ts from every src/features/<domain>/settings.ts (the Settings area's tiles).
// The outputs are gitignored, so adding a domain never edits a shared file.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', 'src', 'features');
const features = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_'))
  .map((d) => d.name)
  .sort();

mkdirSync(join(root, '_registry'), { recursive: true });

/** One registry: every feature that has `<file>.ts` exporting `<exportName>` (an array) is merged into `<exportName in caps>`. */
function build({ file, exportName, typeName, constName, outFile, label }) {
  const domains = features.filter((d) => existsSync(join(root, d, `${file}.ts`)));
  const lines = [
    '// GENERATED by scripts/gen-registry.mjs. Do not edit; do not commit.',
    `import type { ${typeName} } from './${typeName === 'NavItem' ? 'types' : 'settings-types'}';`,
    ...domains.map((d, i) => `import { ${exportName} as r${i} } from '../${d}/${file}';`),
    `export const ${constName}: ${typeName}[] = [${domains.map((_, i) => `...r${i}`).join(', ')}];`,
    '',
  ];
  writeFileSync(join(root, '_registry', outFile), lines.join('\n'));
  console.log(`${label} registry: ${domains.length} domain(s)`);
}

build({
  file: 'nav',
  exportName: 'nav',
  typeName: 'NavItem',
  constName: 'NAV',
  outFile: 'nav.generated.ts',
  label: 'nav',
});
build({
  file: 'settings',
  exportName: 'settings',
  typeName: 'SettingsTile',
  constName: 'SETTINGS',
  outFile: 'settings.generated.ts',
  label: 'settings',
});
