// Builds src/features/_registry/nav.generated.ts from every src/features/<domain>/nav.ts, and
// settings.generated.ts from every src/features/<domain>/settings.ts (the Settings area's tiles), and
// home-cards.generated.ts from every src/features/<domain>/home-cards.ts (the Home dashboard's cards, for the persona module catalog),
// help.generated.ts from every src/features/<domain>/help/*.md (the Help center's documents).
// The outputs are gitignored, so adding a domain never edits a shared file.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { compileRegistry, renderGenerated } from './help-compile.mjs';

const root = join(import.meta.dirname, '..', 'src', 'features');
const features = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_'))
  .map((d) => d.name)
  .sort();

mkdirSync(join(root, '_registry'), { recursive: true });

/** One registry: every feature that has `<file>.ts` exporting `<exportName>` (an array) is merged into `<exportName in caps>`. */
function build({ file, exportName, typeName, typesFile, constName, outFile, label }) {
  const domains = features.filter((d) => existsSync(join(root, d, `${file}.ts`)));
  const lines = [
    '// GENERATED by scripts/gen-registry.mjs. Do not edit; do not commit.',
    `import type { ${typeName} } from './${typesFile}';`,
    ...domains.map((d, i) => `import { ${exportName} as r${i} } from '../${d}/${file}';`),
    `export const ${constName}: ${typeName}[] = [${domains.map((_, i) => `...r${i}`).join(', ')}];`,
    '',
  ];
  writeFileSync(join(root, '_registry', outFile), lines.join('\n'));
  console.log(`${label} registry: ${domains.length} domain(s)`);
}

build({
  file: 'nav',
  exportName: 'nav',
  typeName: 'NavItem',
  typesFile: 'types',
  constName: 'NAV',
  outFile: 'nav.generated.ts',
  label: 'nav',
});
build({
  file: 'settings',
  exportName: 'settings',
  typeName: 'SettingsTile',
  typesFile: 'settings-types',
  constName: 'SETTINGS',
  outFile: 'settings.generated.ts',
  label: 'settings',
});
build({
  file: 'home-cards',
  exportName: 'homeCards',
  typeName: 'HomeCard',
  typesFile: 'types',
  constName: 'HOME_CARDS',
  outFile: 'home-cards.generated.ts',
  label: 'home cards',
});

/**
 * The persona module catalog (docs/specs/persona-profiles.md): every id a persona may show or hide, composed from the registries above
 * plus the planned entries and the contact page's own lists. The ids are computed where the registries are loaded, never typed twice.
 */
writeFileSync(
  join(root, '_registry', 'module-catalog.generated.ts'),
  [
    '// GENERATED by scripts/gen-registry.mjs. Do not edit; do not commit.',
    "import { ADD_TARGETS, CORE_SECTIONS, RELATED_SECTIONS } from '../contacts-attributes-tags/lib/sections';",
    "import { HOME_CARDS } from './home-cards.generated';",
    "import { buildModuleCatalog } from './module-catalog';",
    "import { NAV } from './nav.generated';",
    "import { PLANNED_NAV } from './planned';",
    "import { SETTINGS } from './settings.generated';",
    "import { PLANNED_SETTINGS } from './settings-planned';",
    'export const MODULE_CATALOG = buildModuleCatalog({',
    '  nav: NAV,',
    '  plannedNav: PLANNED_NAV,',
    '  settings: SETTINGS,',
    '  plannedSettings: PLANNED_SETTINGS,',
    '  homeCards: HOME_CARDS,',
    '  contactSections: [...CORE_SECTIONS, ...RELATED_SECTIONS],',
    '  contactActions: ADD_TARGETS,',
    '});',
    '',
  ].join('\n'),
);
console.log('module catalog: generated');

/** The Help center: every `features/<domain>/help/*.md`, compiled (see help-compile.mjs). A bad file stops the build. */
const helpFiles = features.flatMap((domain) => {
  const dir = join(root, domain, 'help');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((file) => file.endsWith('.md'))
    .map((file) => ({ domain, file, source: readFileSync(join(dir, file), 'utf8') }));
});
try {
  const docs = compileRegistry(helpFiles);
  writeFileSync(join(root, '_registry', 'help.generated.ts'), renderGenerated(docs));
  console.log(`help registry: ${docs.length} doc(s)`);
} catch (error) {
  console.error(`help registry: ${error.message}`);
  process.exit(1);
}
