// Regenerates features/wadesk.feature from src/app/**/page.tsx. Run from apps/web: node qa-daily/gen-feature.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { discoverRoutes } from './routes.mjs';

const KIND_STEP = {
  public: 'I am a signed-out visitor',
  app: 'I am signed in as a workspace admin',
  admin: 'I am signed in as a platform operator',
};
const routes = discoverRoutes();
const byArea = new Map();
for (const r of routes) {
  const key = `${r.kind}|${r.area}`;
  if (!byArea.has(key)) byArea.set(key, []);
  byArea.get(key).push(r);
}

const CHECKS = [
  'the response is not a 5xx and the page is not blank',
  'there is no uncaught script error, console error or failed request',
  'no error screen ("Something went wrong", 404, application error) is shown',
  'there is no horizontal overflow on desktop (1280px) or mobile (390px)',
  'every visible image loads and the page has a title',
];

let out = `# GENERATED by qa-daily/gen-feature.mjs from src/app/**/page.tsx. Do not edit by hand.
# explore.spec.ts visits every non-dynamic URL below and files each failed check as a bug in the Google Sheet.
@exploration
Feature: Explore every Wadesk page
  Every page loads cleanly for the role that owns it.

`;
for (const [key, list] of [...byArea].sort()) {
  const [kind, area] = key.split('|');
  const pages = list.filter((r) => !r.dynamic);
  const dynamic = list.filter((r) => r.dynamic);
  if (pages.length) {
    out += `  @${kind}\n  Scenario Outline: ${area} (${kind}) pages load cleanly\n`;
    out += `    Given ${KIND_STEP[kind]}\n    When I open "<url>"\n`;
    out += CHECKS.map((c, i) => `    ${i ? 'And' : 'Then'} ${c}\n`).join('');
    out += `    Examples:\n      | url |\n${pages.map((r) => `      | ${r.url} |\n`).join('')}\n`;
  }
  if (dynamic.length) {
    out += `  # Needs seeded data, listed for coverage and not visited:\n`;
    out += dynamic.map((r) => `  #   ${r.url}\n`).join('') + '\n';
  }
}

mkdirSync('qa-daily/features', { recursive: true });
writeFileSync('qa-daily/features/wadesk.feature', out);
const n = routes.filter((r) => !r.dynamic).length;
console.log(`feature file: ${n} explorable pages, ${routes.length - n} dynamic listed`);
