export const RTL_LOCALES = new Set(['ar', 'he', 'ur']);

/** The best supported language for an `Accept-Language` header (or a bare code): `pt-BR` finds `pt`, `zh-TW` finds `zh-CN`; `en` when none. */
export function pickChatLocale(header: string | undefined, explicit?: string): string {
  const wanted = [explicit ?? '', ...(header ?? '').split(',').map((p) => p.split(';')[0]!.trim())]
    .map((c) => c.trim())
    .filter(Boolean);
  for (const code of wanted) {
    if (CHAT_TEXT[code]) return code;
    const base = code.toLowerCase().split('-')[0]!;
    if (base === 'zh') return 'zh-CN';
    if (CHAT_TEXT[base]) return base;
  }
  return 'en';
}
