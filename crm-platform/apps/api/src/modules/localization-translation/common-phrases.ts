const base = (code: string) => code.toLowerCase().split('-')[0] ?? code.toLowerCase();

/** The dictionary's own casing, or null on a miss. Language codes may be regional (`zh-CN`). */
export function lookupCommonPhrase(text: string, from: string, to: string): string | null {
  const phrase = text.trim().toLowerCase();
  if (!phrase) return null;
  const src = base(from);
  const dst = base(to);
  if (src === dst) return phrase;

  // English is the pivot, so its words are keys; every other language is matched against its own column.
  const concept =
    src === 'en'
      ? phrase in COMMON_PHRASES
        ? phrase
        : undefined
      : Object.keys(COMMON_PHRASES).find((k) => COMMON_PHRASES[k]![src]?.toLowerCase() === phrase);
  if (!concept) return null;
  return COMMON_PHRASES[concept]![dst] ?? null;
}
