import type { Link, ResolvedSubject } from '../registry/types';

/**
 * Conversations, messages and the media behind them. Wiring map keys: inbox.messages, inbox.media, channels (email, sms, social,
 * whatsapp).
 *
 * `messages` is the one store of every channel (WhatsApp, SMS, email, Telegram, Facebook, Instagram, widget chat) and has no foreign
 * key to the contact (migration 20261014100600): the link is `conversation_id`, and a conversation belongs to a person through
 * `contact_id` or through its peer key (the phone digits or the email address). The subject resolver collects those conversations
 * up front, so the rows are still found after the contact's link has been nulled.
 */
const CONVERSATION: Link = { by: 'conversation', column: 'conversation_id' };

/** The bell rows keyed by a conversation: `msg:<uuid>` collapse keys, `new_chat:<uuid>:...` dedupe keys. */
const bellOfConversations: Link = {
  by: 'custom',
  column: 'dedupe_key',
  predicate: (s: ResolvedSubject) =>
    s.conversationUuids.length
      ? sql`EXISTS (
          SELECT 1 FROM unnest(${`{${s.conversationUuids.join(',')}}`}::text[]) AS u(id)
           WHERE collapse_key = 'msg:' || u.id OR dedupe_key LIKE '%:' || u.id || '%')`
      : sql`FALSE`,
};

