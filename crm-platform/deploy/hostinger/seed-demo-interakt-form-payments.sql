-- forms: payment attempts of a form submission (docs/specs/forms-builder-app.md section 10; FORMS-BLK-002, phase 3).
-- Why this migration exists: a form that takes money must remember WHAT the server decided to charge, on WHICH gateway, under WHICH reference,
-- and whether the gateway's own verified notification has arrived. The submission's `status` (awaiting_payment, paid) is the visitor-facing
-- summary; this table is the ledger of attempts behind it. One submission can have several attempts (an expired link, a retry) and at most
-- ONE counted as the payment (a second paid notification is kept as a paid attempt and flagged `duplicate_payment` on the submission for a
-- manual refund: money that really arrived is recorded, never dropped); the settler locks the row, so a replayed notification changes nothing.
--
-- `reference` is OUR id for the attempt (`FRM-<uuid>`): the shared workspace gateway echoes it back, and its prefix routes the verified
-- notification to the form settler (GatewayPaymentRegistry). `amount_minor` is computed by the server from the frozen form version; a
-- number the browser sends is never read.

CREATE TABLE web_form_payments (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  submission_id bigint NOT NULL,
  reference text NOT NULL,
  -- The slug of the gateway the link was minted on ("razorpay", "stripe"): a notification of another gateway cannot settle this attempt.
  gateway_slug text NOT NULL,
  amount_minor bigint NOT NULL,
  currency text NOT NULL,
  -- pending -> paid | expired | failed. `manual` marks a staff "mark as paid" for money that arrived outside the gateway.
  status text NOT NULL DEFAULT 'pending',
  settled_via text,
  provider_ref text,
  link_url text,
  paid_at timestamptz,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, reference),
  CONSTRAINT chk_web_form_payments_status CHECK (status IN ('pending', 'paid', 'failed', 'expired')),
  CONSTRAINT chk_web_form_payments_via CHECK (settled_via IS NULL OR settled_via IN ('gateway', 'manual')),
  CONSTRAINT chk_web_form_payments_amount CHECK (amount_minor > 0),
  CONSTRAINT chk_web_form_payments_currency CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_web_form_payments_paid CHECK ((status = 'paid') = (paid_at IS NOT NULL)),
  CONSTRAINT fk_web_form_payments_submission FOREIGN KEY (org_id, submission_id)
    REFERENCES web_form_submissions (org_id, id) ON DELETE CASCADE
);

CREATE INDEX idx_web_form_payments_submission ON web_form_payments (org_id, submission_id, id DESC);
-- The expiry sweep walks pending attempts past their deadline.
CREATE INDEX idx_web_form_payments_pending ON web_form_payments (expires_at) WHERE status = 'pending';

