import { z } from 'zod';
import { phoneSchema } from '../common/ids';

/**
 * Sign-up OTP delivery (TW-AUTH-006 sender side, TW-AUTH-007).
 *
 * The channel domains (WABA, WADEV, Twilio) own real connections. Until they
 * land, the auth zone keeps a small registry of "OTP senders": just enough to
 * deliver the sign-up code. `registration.otp.sender` stores `<kind>:<id>` and
 * resolves against this registry; the channel domains can replace the registry
 * behind the same reference format later.
 *
 * Secrets (Meta access token, Twilio auth token, bridge token) are write-only:
 * a response carries `hasSecret`, never the value.
 */

export const OTP_SENDER_KINDS = ['waba', 'twilio', 'device', 'dev'] as const;
export const otpSenderKindSchema = z.enum(OTP_SENDER_KINDS);
export type OtpSenderKind = z.infer<typeof otpSenderKindSchema>;

export const DEFAULT_GRAPH_BASE_URL = 'https://graph.facebook.com/v21.0';
export const DEFAULT_TWILIO_API_BASE_URL = 'https://api.twilio.com';

/** Short, stable, URL-safe. Generated by the API; never reused for another sender. */
export const otpSenderIdSchema = z.string().regex(/^[a-z0-9]{1,24}$/);

/** `<kind>:<id>`, what `registration.otp.sender` stores. */
export const OTP_SENDER_REF_PATTERN = /^(waba|twilio|device|dev):[a-z0-9]{1,24}$/;
export const otpSenderRefSchema = z
  .string()
  .regex(OTP_SENDER_REF_PATTERN, 'Use a sender from the list: kind:id.');

export function otpSenderRef(kind: OtpSenderKind, id: string): string {
  return `${kind}:${id}`;
}

export function parseOtpSenderRef(ref: string | null | undefined): {
  kind: OtpSenderKind;
  id: string;
} | null {
  if (!ref || !OTP_SENDER_REF_PATTERN.test(ref)) return null;
  const [kind, id] = ref.split(':') as [OtpSenderKind, string];
  return { kind, id };
}

const isHttpUrl = (u: string) => /^https?:\/\//i.test(u);
const httpUrl = z.string().trim().url().max(512).refine(isHttpUrl, 'Use an http or https address.');

const label = z.string().trim().min(1).max(60);
const digitsId = z
  .string()
  .trim()
  .regex(/^\d{5,24}$/, 'Digits only.');
const secret = z.string().min(1).max(4096);
const phoneLike = z.string().trim().min(5).max(24);
const accountSid = z
  .string()
  .trim()
  .regex(/^AC[0-9a-zA-Z]{32}$/, 'An account SID starts with AC and has 34 characters.');

// --- what the API returns --------------------------------------------------------------------------

const viewBase = { id: otpSenderIdSchema, label: z.string(), hasSecret: z.boolean() };

export const otpSenderViewSchema = z.discriminatedUnion('kind', [
  z.object({
    ...viewBase,
    kind: z.literal('waba'),
    phoneNumberId: z.string(),
    wabaId: z.string(),
    graphBaseUrl: z.string(),
  }),
  z.object({
    ...viewBase,
    kind: z.literal('twilio'),
    accountSid: z.string(),
    fromNumber: z.string(),
    apiBaseUrl: z.string(),
  }),
  z.object({
    ...viewBase,
    kind: z.literal('device'),
    bridgeUrl: z.string(),
    senderNumber: z.string(),
  }),
  z.object({ ...viewBase, kind: z.literal('dev') }),
]);
export type OtpSenderView = z.infer<typeof otpSenderViewSchema>;

export const otpSendersResponseSchema = z.object({
  senders: z.array(otpSenderViewSchema),
  /** The `dev` sender (log the code) exists only outside production. */
  devAllowed: z.boolean(),
});
export type OtpSendersResponse = z.infer<typeof otpSendersResponseSchema>;

// --- what the operator sends ---------------------------------------------------------------------

export const otpSenderCreateSchema = z.discriminatedUnion('kind', [
  z.object({
    kind: z.literal('waba'),
    label,
    phoneNumberId: digitsId,
    wabaId: digitsId,
    /** Defaults to Meta's Graph API. */
    graphBaseUrl: httpUrl.optional(),
    /** Meta access token. */
    secret,
  }),
  z.object({
    kind: z.literal('twilio'),
    label,
    accountSid,
    fromNumber: phoneLike,
    /** Defaults to Twilio's API. */
    apiBaseUrl: httpUrl.optional(),
    /** Twilio auth token. */
    secret,
  }),
  z.object({
    kind: z.literal('device'),
    label,
    bridgeUrl: httpUrl,
    senderNumber: phoneLike,
    /** The bridge's shared token (`X-Node-Token`). */
    secret,
  }),
  z.object({ kind: z.literal('dev'), label }),
]);
export type OtpSenderCreate = z.infer<typeof otpSenderCreateSchema>;

/**
 * Partial update. The kind never changes. Only fields that belong to the
 * sender's kind are accepted (the API rejects the rest). A blank or omitted
 * `secret` keeps the stored one; `clearSecret` deletes it.
 */
export const otpSenderPatchSchema = z.object({
  label: label.optional(),
  phoneNumberId: digitsId.optional(),
  wabaId: digitsId.optional(),
  graphBaseUrl: httpUrl.optional(),
  accountSid: accountSid.optional(),
  fromNumber: phoneLike.optional(),
  apiBaseUrl: httpUrl.optional(),
  bridgeUrl: httpUrl.optional(),
  senderNumber: phoneLike.optional(),
  secret: z.string().max(4096).optional(),
  clearSecret: z.boolean().optional(),
});
export type OtpSenderPatch = z.infer<typeof otpSenderPatchSchema>;

export const otpSenderDeleteResponseSchema = z.object({
  ok: z.literal(true),
  /** The removed sender was the one registration used; the selection and its template state were cleared. */
  selectionCleared: z.boolean(),
});
export type OtpSenderDeleteResponse = z.infer<typeof otpSenderDeleteResponseSchema>;

// --- the OTP template -------------------------------------------------------------------------------

/**
 * `waba`: an authentication template submitted to Meta (pending until approved).
 * `local`: a message text kept here, usable at once (Twilio, bridge, dev).
 */
export const otpTemplateStateSchema = z.object({
  name: z.string().max(80),
  kind: z.enum(['waba', 'local']),
  /** The sender (`kind:id`) this template belongs to. */
  sender: z.string().max(80),
  language: z.string().max(16),
  /** Local templates only: the text, with {{1}} standing for the code. */
  body: z.string().max(1024).nullable().default(null),
  /** Meta's template id (waba only). */
  metaTemplateId: z.string().max(64).nullable().default(null),
  status: z.enum(['pending', 'approved', 'rejected', 'local']),
  /** The expiry baked into the template when it was created. */
  codeExpirationMinutes: z.number().int().min(1).max(90),
  submittedAt: z.string().datetime().nullable().default(null),
  /** Last time the status was read back from Meta. */
  checkedAt: z.string().datetime().nullable().default(null),
  rejectedReason: z.string().max(500).nullable().default(null),
});
export type OtpTemplateState = z.infer<typeof otpTemplateStateSchema>;

export const OTP_ACTIVATION_REASONS = [
  'active',
  'disabled',
  'no_sender',
  'sender_missing',
  'sender_incomplete',
  'dev_in_production',
  'template_missing',
  'template_pending',
  'template_rejected',
] as const;
export const otpActivationReasonSchema = z.enum(OTP_ACTIVATION_REASONS);
export type OtpActivationReason = z.infer<typeof otpActivationReasonSchema>;

export const otpStatusSchema = z.object({
  /** The real activation rule: when false, sign-up silently skips the code step. */
  active: z.boolean(),
  reason: otpActivationReasonSchema,
});
export type OtpStatus = z.infer<typeof otpStatusSchema>;

export const otpTemplateOutcomeSchema = z.enum([
  /** Submitted to Meta; waiting for review. */
  'submitted',
  /** Sent again to Meta (a rejected or out-of-date template). */
  'resubmitted',
  /** Local template saved; usable now. */
  'local_ready',
  'already_pending',
  'already_approved',
  /** Status re-read from Meta. */
  'refreshed',
]);
export type OtpTemplateOutcome = z.infer<typeof otpTemplateOutcomeSchema>;

