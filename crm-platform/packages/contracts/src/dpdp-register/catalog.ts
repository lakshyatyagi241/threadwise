/**
 * One obligation of section 3 of docs/privacy/dpdpa-gap-analysis-and-plan.md. `id` is `r` plus the row number and is never reused.
 * `baseline` is the declared status when no check decides it (the plan's Status column); an item with checks is decided by them.
 * The titles are message keys on the web side, so the catalog carries none. A unit test pins the ids, the baseline totals
 * (1 following, 26 partial, 20 not following) and that every plan item exists in the plan, so a silent change fails.
 */
export interface DpdpCatalogItem {
  id: string;
  group: DpdpGroup;
  /** The Act section or rule, as in the plan row. */
  citation: string;
  owner: DpdpOwner;
  penaltyTier: DpdpPenaltyTier;
  /** The `DP-nn` plan items that close the gap. */
  planItems: string[];
  baseline: Exclude<DpdpItemStatus, 'unverified'>;
  checks: DpdpCheckKey[];
  /** Row 44 (Significant Data Fiduciary): shown and counted, marked "only if notified". */
  conditional?: true;
}

