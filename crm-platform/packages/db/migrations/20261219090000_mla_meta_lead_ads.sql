-- mla: Meta lead ads as a door into the lead pipeline (docs/specs/email-channel-and-social-leads.md L-06, BL-011, BL-064).
--
-- What this adds, and why a table of its own for each:
--
--  1. meta_lead_pages   per connected Facebook Page: is lead sync on, did Meta accept the `leadgen` subscription, when did the last lead
--                       arrive, what was the last thing Meta refused. Kept apart from `facebook_pages` (another domain's table, the
--                       Messenger channel): turning lead sync on or off must never touch a Page's tokens or its inbox channel.
--                       `page_id` is Meta's id and joins `facebook_pages (org_id, page_id)`. There is deliberately NO foreign key: when
--                       a Page is disconnected a worker consumer first releases the lead sources of its forms (through the lead
--                       pipeline's directory port, which deletes their stored events) and only then removes these rows; a cascading
--                       foreign key would delete the list of forms before anything could release their sources.
--  2. meta_lead_forms   one row per lead form the workspace picked. The form's questions and consent checkboxes are cached here so the
--                       mapping screen and the consent proof need no call to Meta. Each form feeds ONE lead source (kind
--                       `meta_lead_ads`), so mapping, owner, deal and notification settings are the lead sources' own. Deleting the
--                       source (from the sources list) removes the form row (ON DELETE CASCADE): the pick follows the source.
--
-- No new permission keys: `leads.sources.read` / `leads.sources.manage` and the `lead_sources` plan feature govern this door.
-- The webhook needs no table: the lead is fetched from Meta and stored as a `lead_events` row, idempotent on
-- (source, leadgen id) by the pipeline's own unique key.

CREATE TABLE meta_lead_pages (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Meta's Page id: joins facebook_pages (org_id, page_id). See the note above on why there is no foreign key.
  page_id text NOT NULL,
  -- Lead sync switched on by an admin. The sweep and the webhook worker ignore a Page that is off.
  enabled boolean NOT NULL DEFAULT false,
  -- When Meta accepted the `leadgen` subscription, and when a read of the subscription last confirmed it.
  subscribed_at timestamptz,
  verified_at timestamptz,
  last_lead_at timestamptz,
  -- The reconciliation sweep read every connected form of this Page to the end at this time.
  last_sweep_at timestamptz,
  last_error text,
  -- token = the Page's token is no longer valid (reconnect); permission = Meta withheld a lead permission (re-consent); other.
  last_error_kind text,
  last_error_at timestamptz,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_meta_lead_pages_page UNIQUE (org_id, page_id),
  CONSTRAINT chk_meta_lead_pages_error_kind CHECK (last_error_kind IS NULL OR last_error_kind IN ('token', 'permission', 'other')),
  CONSTRAINT fk_meta_lead_pages_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_meta_lead_pages_created_by ON meta_lead_pages (org_id, created_by);
-- The sweep's cross-tenant scan: Pages with sync on.
CREATE INDEX idx_meta_lead_pages_enabled ON meta_lead_pages (org_id, id) WHERE enabled;

ALTER TABLE meta_lead_pages ENABLE ROW LEVEL SECURITY;
ALTER TABLE meta_lead_pages FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON meta_lead_pages FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_meta_lead_pages_touch BEFORE UPDATE ON meta_lead_pages
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE meta_lead_forms (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  page_id text NOT NULL,
  -- Meta's lead form id.
  form_id text NOT NULL,
  name text NOT NULL,
  -- Meta's status (ACTIVE, ARCHIVED, DELETED, DRAFT) as of the last read.
  status text,
  locale text,
  -- [{ key, label, type }] as of the last read of the form: the mapping screen offers these as the paths a lead carries.
  questions jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- [{ key, text, required }] from the form's custom disclaimer: the ONLY place a consent proof is read from (a ticked box plus the
  -- wording shown beside it). A lead whose form has none, or whose box is not ticked, grants nothing.
  consent_checkboxes jsonb NOT NULL DEFAULT '[]'::jsonb,
  privacy_policy_url text,
  -- The lead source this form feeds. Unique: one form, one source.
  source_id bigint NOT NULL,
  connected_by bigint,
  connected_at timestamptz NOT NULL DEFAULT now(),
  last_lead_at timestamptz,
  last_error text,
  last_error_at timestamptz,
  -- The sweep checkpoint: leads created after (this minus a safety overlap) are re-read. Starts at connected_at, so a form brings in
  -- the leads from the moment it is picked, never a surprise backlog.
  sweep_checkpoint_at timestamptz NOT NULL DEFAULT now(),
  last_sweep_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_meta_lead_forms_form UNIQUE (org_id, page_id, form_id),
  CONSTRAINT uq_meta_lead_forms_source UNIQUE (org_id, source_id),
  CONSTRAINT chk_meta_lead_forms_questions CHECK (jsonb_typeof(questions) = 'array'),
  CONSTRAINT chk_meta_lead_forms_consent CHECK (jsonb_typeof(consent_checkboxes) = 'array'),
  CONSTRAINT fk_meta_lead_forms_source FOREIGN KEY (org_id, source_id)
    REFERENCES lead_sources (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_meta_lead_forms_connected_by FOREIGN KEY (org_id, connected_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (connected_by)
);
CREATE INDEX idx_meta_lead_forms_page ON meta_lead_forms (org_id, page_id);
CREATE INDEX idx_meta_lead_forms_connected_by ON meta_lead_forms (org_id, connected_by);

ALTER TABLE meta_lead_forms ENABLE ROW LEVEL SECURITY;
ALTER TABLE meta_lead_forms FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON meta_lead_forms FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_meta_lead_forms_touch BEFORE UPDATE ON meta_lead_forms
  FOR EACH ROW EXECUTE FUNCTION touch_row();
