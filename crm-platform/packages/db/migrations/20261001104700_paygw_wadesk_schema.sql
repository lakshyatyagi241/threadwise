-- paygw: platform-payment-gateways data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's platform payment gateways features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: payments, payment_gateways, orders

-- WaDesk `payments` (tenant; 0 rows in the reference DB)
CREATE TABLE payments (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  invoice_id bigint,
  deal_id bigint,
  contact_id bigint,
  company_id bigint,
  wa_order_id bigint,
  amount_minor bigint NOT NULL,
  currency text NOT NULL DEFAULT 'USD',
  method text NOT NULL DEFAULT 'manual',
  source text NOT NULL DEFAULT 'manual',
  paid_at timestamptz,
  reference text,
  note text,
  gateway_payment_id text,
  recorded_by bigint,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_payments_source_gateway_payment_id UNIQUE (org_id, source, gateway_payment_id),
  CONSTRAINT fk_payments_invoice_id FOREIGN KEY (org_id, invoice_id) REFERENCES invoices (org_id, id) ON DELETE SET NULL (invoice_id),
  CONSTRAINT fk_payments_deal_id FOREIGN KEY (org_id, deal_id) REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id),
  CONSTRAINT fk_payments_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_payments_company_id FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_payments_recorded_by FOREIGN KEY (org_id, recorded_by) REFERENCES users (org_id, id) ON DELETE SET NULL (recorded_by)
);
CREATE INDEX idx_payments_company_id ON payments (org_id, company_id);
CREATE INDEX idx_payments_contact_id ON payments (org_id, contact_id);
CREATE INDEX idx_payments_deal_id ON payments (org_id, deal_id);
CREATE INDEX idx_payments_invoice_id ON payments (org_id, invoice_id);
CREATE INDEX idx_payments_paid_at ON payments (org_id, paid_at);
CREATE INDEX idx_payments_wa_order_id ON payments (org_id, wa_order_id);

ALTER TABLE payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON payments FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_payments_touch BEFORE UPDATE ON payments
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `payment_gateways` (platform_only; 32 rows in the reference DB)
CREATE TABLE payment_gateways (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  slug text NOT NULL,
  name text NOT NULL,
  description text,
  is_active boolean NOT NULL DEFAULT false,
  credentials text,  -- encrypted
  mode text NOT NULL DEFAULT 'sandbox',
  extra_config jsonb,
  supported_currencies jsonb,
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_payment_gateways_slug UNIQUE (slug)
);
CREATE INDEX idx_payment_gateways_is_active_sort_order ON payment_gateways (is_active, sort_order);

ALTER TABLE payment_gateways ENABLE ROW LEVEL SECURITY;
ALTER TABLE payment_gateways FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON payment_gateways FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_payment_gateways_touch BEFORE UPDATE ON payment_gateways
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `orders` (tenant; 0 rows in the reference DB)
CREATE TABLE orders (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  order_number text NOT NULL,
  user_id bigint,
  package_id bigint,
  billing_period text NOT NULL DEFAULT 'monthly',
  auto_renew boolean NOT NULL DEFAULT true,
  credit_package_id bigint,
  coupon_id bigint,
  coupon_code text,
  gateway_id bigint,
  gateway_slug text,
  currency text NOT NULL,
  amount numeric(12,2) NOT NULL,
  discount_amount numeric(12,4) NOT NULL DEFAULT 0.0000,
  tax_rate numeric(5,2) NOT NULL DEFAULT 0.00,
  tax_amount numeric(12,4) NOT NULL DEFAULT 0.0000,
  total_amount numeric(12,4) NOT NULL DEFAULT 0.0000,
  customer_name text,
  customer_email text,
  billing_company text,
  billing_address text,
  billing_city text,
  billing_postal text,
  billing_country text,
  billing_tax_id text,
  base_amount_usd numeric(12,2),
  exchange_rate numeric(16,6),
  status text NOT NULL DEFAULT 'pending',
  gateway_order_id text,
  gateway_payment_id text,
  gateway_payload jsonb,
  failure_reason text,
  payment_proof_path text,
  payment_reference text,
  proof_note text,
  proof_submitted_at timestamptz,
  reviewed_by bigint,
  reviewed_at timestamptz,
  review_note text,
  paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_orders_order_number UNIQUE (order_number),
  CONSTRAINT fk_orders_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_orders_package_id FOREIGN KEY (package_id) REFERENCES packages (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_credit_package_id FOREIGN KEY (credit_package_id) REFERENCES credit_packages (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_coupon_id FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_gateway_id FOREIGN KEY (gateway_id) REFERENCES payment_gateways (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_reviewed_by FOREIGN KEY (org_id, reviewed_by) REFERENCES users (org_id, id) ON DELETE SET NULL (reviewed_by)
);
CREATE INDEX idx_orders_coupon_id ON orders (org_id, coupon_id);
CREATE INDEX idx_orders_credit_package_id ON orders (org_id, credit_package_id);
CREATE INDEX idx_orders_gateway_order_id ON orders (org_id, gateway_order_id);
CREATE INDEX idx_orders_package_id ON orders (org_id, package_id);
CREATE INDEX idx_orders_status ON orders (org_id, status);

ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON orders FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_orders_touch BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION touch_row();

