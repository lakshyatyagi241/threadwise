-- crm: the revenue report (`/crm/revenue`, TW-PAY-017): the export key, the table of prepared exports and two indexes.
-- Why this migration exists: Reference's CSV and PDF were built inside the request (a 5,000 row cap, a PDF rendered while the browser
-- waited). Here a file is prepared by the worker (queue `revenue-report-export`), stored gzipped on a row for 7 days and the
-- requester is mailed a link, the same shape as `audit_log_exports` and `contact_consent_exports`.
--
-- Permission keys. Reading the report needs no new key: it rides on `record.payments.read`, whose record scope cuts every number.
--   record.payments.export  prepare the report as CSV or PDF (Owner, Admin and Manager by default; an Agent can read their own numbers but
--                           not take a file of them away)
-- Owner and Admin presets get every new key by the trigger on `permission_defs` (20261013100000); `workspace_preset_baseline` makes sure
-- the Manager preset and any workspace provisioned later hold it too.

INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('record.payments.export', 'Export the revenue report and the payment ledger (CSV, PDF)', 'crm', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label,
      category = EXCLUDED.category,
      supports_scope = EXCLUDED.supports_scope;

INSERT INTO workspace_preset_baseline (preset_key, permission_key)
SELECT p.preset, 'record.payments.export'
FROM (VALUES ('admin'), ('workspace_admin'), ('manager')) AS p(preset)
ON CONFLICT (preset_key, permission_key) DO NOTHING;

SELECT set_config('app.privileged', 'on', true);
SELECT apply_workspace_preset_baseline(id) FROM organizations;
UPDATE organizations SET roles_version = roles_version + 1;

-- One row per requested export. The row stays (status `expired`) after the file is deleted, so the page can still say it was made.
-- `scope` is the record scope the requester's `record.payments.read` grant had when they asked: the worker cuts the file to it, so a
-- file never holds more than the screen showed that person.
CREATE TABLE revenue_report_exports (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  requested_by  bigint NOT NULL,
  -- Where the "your export is ready" mail went; kept so the page can say it even after the user changes address.
  emailed_to    text,
  format        text NOT NULL,
  csv_kind      text,
  scope         record_scope NOT NULL,
  -- The window as dates in the requester's zone, the grouping and the filters; fixed when the export was asked for.
  filters       jsonb NOT NULL,
  status        text NOT NULL DEFAULT 'queued',
  row_count     integer,
  file_name     text,
  file_bytes    integer,
  -- gzip of the CSV or of the PDF; served through gunzip either way
  file_gz       bytea,
  error         text,
  requested_at  timestamptz NOT NULL DEFAULT now(),
  started_at    timestamptz,
  completed_at  timestamptz,
  expires_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, requested_by) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_revenue_report_exports_status CHECK (status IN ('queued', 'running', 'ready', 'failed', 'expired')),
  CONSTRAINT chk_revenue_report_exports_format CHECK (format IN ('csv', 'pdf')),
  CONSTRAINT chk_revenue_report_exports_kind CHECK (
    (format = 'csv' AND csv_kind IN ('payments', 'summary')) OR (format = 'pdf' AND csv_kind IS NULL)
  )
);
CREATE INDEX idx_revenue_report_exports_org ON revenue_report_exports (org_id, requested_by, requested_at DESC);
-- The daily sweep finds files past their time and exports whose worker died.
CREATE INDEX idx_revenue_report_exports_expiry ON revenue_report_exports (expires_at) WHERE status = 'ready';
CREATE INDEX idx_revenue_report_exports_running ON revenue_report_exports (started_at) WHERE status = 'running';

ALTER TABLE revenue_report_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE revenue_report_exports FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON revenue_report_exports FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_revenue_report_exports_touch BEFORE UPDATE ON revenue_report_exports
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- The report cuts invoices by the day they were issued and by the day they became fully paid. Neither had an index that leads with the
-- date; both are partial, so they only carry the rows the report reads.
CREATE INDEX idx_invoices_report_issued ON invoices (org_id, issue_date) WHERE status = 'issued';
CREATE INDEX idx_invoices_report_paid ON invoices (org_id, paid_at) WHERE status = 'issued' AND payment_status = 'paid';
