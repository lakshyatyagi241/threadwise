-- Append-only, like the consent ledger: an event is never edited or deleted. The cascade from the request (a workspace wipe) is the only
-- way out, and it runs at trigger depth 2.
CREATE FUNCTION privacy_request_events_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND (app_is_privileged() OR pg_trigger_depth() > 1) THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'privacy_request_events is append-only' USING ERRCODE = 'integrity_constraint_violation';
END $$;
CREATE TRIGGER trg_privacy_request_events_immutable BEFORE UPDATE OR DELETE ON privacy_request_events
  FOR EACH ROW EXECUTE FUNCTION privacy_request_events_immutable();

