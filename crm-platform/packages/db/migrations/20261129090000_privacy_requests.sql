-- privacy: the data-subject rights service (BL-143, docs/specs/privacy-and-data-governance.md section 4.5). A product extension, not a
-- reference feature.
--
--   privacy_requests          one row per request a person (or their representative) made about their data: access / export /
--                             portability, erasure, rectification, restriction, objection, withdrawal. Status machine, identity
--                             verification (a method and a reference id, never a document), SLA (`due_at`), legal hold, the counts per
--                             table of the last dry run and of the execution, and the proof of erasure (counts and hashes, no personal
--                             value).
--   privacy_request_events    append-only history of the request (who did what, when, to which status). No personal value in `detail`.
--   privacy_request_exports   the built export of one request: a ZIP kept on the row for 7 days, then the file is dropped (row stays).
--   privacy_erasure_files     object-storage keys an erasure found; the worker moves them to the platform purge queue (that queue is
--                             platform-owned and only writable with the privileged flag, which an HTTP request never has).
--   privacy_settings          one row per workspace: the SLA in days (default 30).
--
-- The subject of a request is a contact, a lead, or a free identifier (phone or email) for a person who is not in the contacts. The free
-- identifier is stored sealed (AES-GCM, `subject_identifier_cipher`) and removed when the request completes; `subject_label` is a masked
-- display text only. Erasing the contact sets `contact_id` to NULL, the request survives its subject.

CREATE TABLE privacy_requests (
  org_id                      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                        uuid NOT NULL DEFAULT gen_random_uuid(),
  request_type                text NOT NULL,
  status                      text NOT NULL DEFAULT 'received',
  subject_kind                text NOT NULL,
  contact_id                  bigint,
  lead_id                     bigint,
  subject_identifier_kind     text,
  subject_identifier_cipher   text,
  subject_label               text NOT NULL,
  requester_channel           text NOT NULL DEFAULT 'other',
  internal_note               text,
  received_at                 timestamptz NOT NULL DEFAULT now(),
  due_at                      timestamptz NOT NULL,
  verification_method         text,
  verification_evidence_ref   text,
  verified_at                 timestamptz,
  verified_by                 bigint,
  legal_hold                  boolean NOT NULL DEFAULT false,
  legal_hold_reason           text,
  legal_hold_set_by           bigint,
  legal_hold_set_at           timestamptz,
  history_mode                text NOT NULL DEFAULT 'delete',
  rejection_reason            text,
  dry_run_at                  timestamptz,
  dry_run_summary             jsonb,
  result_summary              jsonb NOT NULL DEFAULT '{}'::jsonb,
  proof                       jsonb,
  proof_sha256                text,
  completed_at                timestamptz,
  created_by                  bigint,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now(),
  row_version                 integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_privacy_requests_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_privacy_requests_lead FOREIGN KEY (org_id, lead_id) REFERENCES leads (org_id, id) ON DELETE SET NULL (lead_id),
  CONSTRAINT fk_privacy_requests_verified_by FOREIGN KEY (org_id, verified_by) REFERENCES users (org_id, id) ON DELETE SET NULL (verified_by),
  CONSTRAINT fk_privacy_requests_hold_by FOREIGN KEY (org_id, legal_hold_set_by) REFERENCES users (org_id, id) ON DELETE SET NULL (legal_hold_set_by),
  CONSTRAINT fk_privacy_requests_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT ck_privacy_requests_type CHECK (request_type IN
    ('access', 'export', 'erasure', 'rectification', 'restriction', 'objection', 'withdrawal', 'portability')),
  CONSTRAINT ck_privacy_requests_status CHECK (status IN
    ('received', 'verifying', 'in_progress', 'completed', 'rejected', 'expired')),
  CONSTRAINT ck_privacy_requests_subject_kind CHECK (subject_kind IN ('contact', 'lead', 'identifier')),
  CONSTRAINT ck_privacy_requests_identifier_kind CHECK (subject_identifier_kind IS NULL OR subject_identifier_kind IN ('phone', 'email')),
  CONSTRAINT ck_privacy_requests_identifier CHECK (
    (subject_kind = 'identifier') = (subject_identifier_kind IS NOT NULL)
    OR status IN ('completed', 'rejected', 'expired')),
  CONSTRAINT ck_privacy_requests_channel CHECK (requester_channel IN
    ('email', 'whatsapp', 'phone', 'in_person', 'portal', 'staff', 'other')),
  CONSTRAINT ck_privacy_requests_method CHECK (verification_method IS NULL OR verification_method IN
    ('channel_code', 'email_link', 'known_contact', 'existing_session', 'id_document_checked', 'other')),
  CONSTRAINT ck_privacy_requests_evidence CHECK (verification_evidence_ref IS NULL OR char_length(verification_evidence_ref) <= 120),
  CONSTRAINT ck_privacy_requests_history_mode CHECK (history_mode IN ('delete', 'anonymise')),
  CONSTRAINT ck_privacy_requests_label CHECK (char_length(subject_label) BETWEEN 1 AND 120),
  CONSTRAINT ck_privacy_requests_note CHECK (internal_note IS NULL OR char_length(internal_note) <= 1000),
  CONSTRAINT ck_privacy_requests_hold_reason CHECK (legal_hold_reason IS NULL OR char_length(legal_hold_reason) <= 500),
  CONSTRAINT ck_privacy_requests_hold CHECK (NOT legal_hold OR legal_hold_reason IS NOT NULL),
  CONSTRAINT ck_privacy_requests_reject CHECK (rejection_reason IS NULL OR char_length(rejection_reason) <= 500),
  CONSTRAINT ck_privacy_requests_summary CHECK (jsonb_typeof(result_summary) = 'object' AND pg_column_size(result_summary) <= 65536)
);
CREATE INDEX idx_privacy_requests_list ON privacy_requests (org_id, received_at DESC, id DESC);
-- The SLA view and the reminders look at what is still open, soonest due first.
CREATE INDEX idx_privacy_requests_open ON privacy_requests (org_id, due_at) WHERE status IN ('received', 'verifying', 'in_progress');
CREATE INDEX idx_privacy_requests_contact ON privacy_requests (org_id, contact_id) WHERE contact_id IS NOT NULL;

ALTER TABLE privacy_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE privacy_requests FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON privacy_requests FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_privacy_requests_touch BEFORE UPDATE ON privacy_requests
  FOR EACH ROW EXECUTE FUNCTION touch_row();

