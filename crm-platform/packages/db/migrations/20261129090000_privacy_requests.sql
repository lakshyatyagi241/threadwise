  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, request_id) REFERENCES privacy_requests (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_privacy_request_events_actor FOREIGN KEY (org_id, actor_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (actor_user_id),
  CONSTRAINT ck_privacy_request_events_type CHECK (event_type ~ '^[a-z][a-z0-9_]{1,40}$'),
  CONSTRAINT ck_privacy_request_events_detail CHECK (jsonb_typeof(detail) = 'object' AND pg_column_size(detail) <= 16384)
);
