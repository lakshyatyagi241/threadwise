-- DLQ: a durable record for background work that ran out of retries or failed for good (docs/quality/dlq-strategy.md).
--
-- Why. An inbound webhook (WhatsApp, a channel, a store, a telephony callback) is acknowledged to the provider before it is worked, so
-- the queue job is the only copy. When its retries run out the job used to wait in the Redis failed set, which keeps it 3 days or the
-- newest 2 000 and is lost with Redis. One row here per logical operation keeps its identity, a stable error code, a sanitized summary,
-- the attempt count and, where the job is the only copy, the payload sealed with the credentials key, until an operator redrives or
-- closes it. The events table is the append-only history of every capture, redrive decision and closure.
--
-- Platform table, not tenant data (same shape as waboo_migration_runs and org_lifecycle_log): org_id only points at the workspace the
-- operation belonged to, when it is known at capture time (a WhatsApp payload is routed by its phone number later, so it can be NULL).
-- Every policy is privileged-only: no workspace reads or replays these rows, and no tenant policy exists to leak one.

CREATE TABLE failed_operations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  org_id bigint,
  source_queue text NOT NULL,
  job_name text NOT NULL,
  original_job_id text NOT NULL,
  status text NOT NULL DEFAULT 'OPEN',
  failure_category text NOT NULL,
  error_code text NOT NULL,
  error_summary text,
  attempts_made integer NOT NULL DEFAULT 0,
  max_attempts integer NOT NULL DEFAULT 1,
  payload_hash text,
  payload_sealed text,
  payload_schema_version integer NOT NULL DEFAULT 1,
  correlation_id text,
  policy_version text NOT NULL,
  replay_count integer NOT NULL DEFAULT 0,
  last_replay_at timestamptz,
  claimed_at timestamptz,
  next_review_at timestamptz,
  resolved_at timestamptz,
  resolution_reason text,
  first_failed_at timestamptz NOT NULL DEFAULT now(),
  last_failed_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  -- The logical operation: one row per queue and original job id, however many times the failure is reported or the job is replayed.
  CONSTRAINT uq_failed_operations_job UNIQUE (source_queue, original_job_id),
  CONSTRAINT chk_failed_operations_status CHECK (status IN
    ('OPEN', 'BLOCKED', 'RECONCILIATION_REQUIRED', 'READY_FOR_REDRIVE', 'REDRIVING', 'RESOLVED', 'TERMINAL', 'ESCALATED')),
  CONSTRAINT chk_failed_operations_category CHECK (failure_category IN
    ('TRANSIENT', 'PERMANENT', 'RATE_LIMITED', 'AMBIGUOUS', 'INFRASTRUCTURE', 'VALIDATION', 'AUTHORIZATION', 'POISON_MESSAGE')),
  CONSTRAINT chk_failed_operations_closed CHECK ((status IN ('RESOLVED', 'TERMINAL')) = (resolved_at IS NOT NULL)),
  CONSTRAINT chk_failed_operations_counts CHECK (attempts_made >= 0 AND max_attempts >= 1 AND replay_count >= 0)
);

-- The operator list (open work first, by queue) and the oldest-unresolved gauge.
CREATE INDEX idx_failed_operations_open ON failed_operations (source_queue, last_failed_at)
  WHERE status NOT IN ('RESOLVED', 'TERMINAL');
CREATE INDEX idx_failed_operations_org ON failed_operations (org_id, created_at DESC) WHERE org_id IS NOT NULL;
-- Retention cleanup of closed rows.
CREATE INDEX idx_failed_operations_closed ON failed_operations (resolved_at) WHERE resolved_at IS NOT NULL;

ALTER TABLE failed_operations ENABLE ROW LEVEL SECURITY;
ALTER TABLE failed_operations FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_only ON failed_operations FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_failed_operations_touch BEFORE UPDATE ON failed_operations
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE failed_operation_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  failed_operation_id bigint NOT NULL REFERENCES failed_operations (id) ON DELETE CASCADE,
  event_type text NOT NULL,
  actor_type text NOT NULL DEFAULT 'system',
  actor_id bigint,
  -- Sanitized facts only: codes, counts, reasons. Never a payload, token or message text.
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_failed_operation_events_type CHECK (event_type IN
    ('CAPTURED', 'FAILED_AGAIN', 'REDRIVE_ENQUEUED', 'REDRIVE_REJECTED', 'REDRIVE_REVERTED', 'REDRIVE_STALE', 'RESOLVED', 'TERMINATED', 'ESCALATED')),
  CONSTRAINT chk_failed_operation_events_detail CHECK (jsonb_typeof(detail) = 'object')
);
CREATE INDEX idx_failed_operation_events_op ON failed_operation_events (failed_operation_id, id);

ALTER TABLE failed_operation_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE failed_operation_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_only ON failed_operation_events FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
