-- wallet: price a message as Meta's cost plus OUR margin, per country and message category, set by plan and overridable per workspace.
-- Why this migration exists: WaDesk priced every message with a fixed customer amount typed next to Meta's cost in one grid, so a Meta
-- price change left every customer price stale until someone re-typed it. Here the Meta cost stays in `message_rates.meta_cost_micros`
-- and the customer price is derived: cost x (1 + margin). The margin is a percentage (basis points: 2500 = 25%, negative allowed down to
-- -10000 = free) looked up, most specific first, in three layers:
--   workspace_message_margins  an override an operator sets for ONE workspace (needs a reason)
--   plan_message_margins       the margin that comes with the workspace's plan; plan_slug '' is the platform default for every plan
-- Within a layer the same four-level fallback as the rate card applies: country+category, country, category, default.
-- The old fixed prices (`message_rates.credits`) remain the fallback where no Meta cost is known, and the whole mode is a platform
-- switch (`wallet.pricing_mode`: fixed | margin) so an upgrade changes nothing until an operator turns margin pricing on.

CREATE TABLE plan_message_margins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  plan_slug text NOT NULL DEFAULT '',
  country_code text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  margin_bps integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_plan_message_margins_key UNIQUE (plan_slug, country_code, category),
  CONSTRAINT chk_plan_message_margins_country CHECK (country_code ~ '^([A-Z]{2})?$'),
  CONSTRAINT chk_plan_message_margins_category CHECK (category IN ('', 'marketing', 'utility', 'authentication', 'service')),
  CONSTRAINT chk_plan_message_margins_bps CHECK (margin_bps BETWEEN -10000 AND 100000)
);
ALTER TABLE plan_message_margins ENABLE ROW LEVEL SECURITY;
ALTER TABLE plan_message_margins FORCE  ROW LEVEL SECURITY;
CREATE POLICY read_all ON plan_message_margins FOR SELECT USING (true);
CREATE POLICY operator_write ON plan_message_margins FOR ALL USING (app_is_privileged()) WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_plan_message_margins_touch BEFORE UPDATE ON plan_message_margins
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE workspace_message_margins (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  country_code text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  margin_bps integer NOT NULL,
  note text NOT NULL,
  set_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_workspace_message_margins_key UNIQUE (org_id, country_code, category),
  CONSTRAINT chk_workspace_message_margins_country CHECK (country_code ~ '^([A-Z]{2})?$'),
  CONSTRAINT chk_workspace_message_margins_category CHECK (category IN ('', 'marketing', 'utility', 'authentication', 'service')),
  CONSTRAINT chk_workspace_message_margins_bps CHECK (margin_bps BETWEEN -10000 AND 100000),
  CONSTRAINT chk_workspace_message_margins_note CHECK (length(btrim(note)) >= 5)
);
ALTER TABLE workspace_message_margins ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_message_margins FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON workspace_message_margins FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_workspace_message_margins_touch BEFORE UPDATE ON workspace_message_margins
  FOR EACH ROW EXECUTE FUNCTION touch_row();

