-- sales: sales-docs-proposals data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's sales docs proposals features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: sales_docs

-- WaDesk `sales_docs` (tenant; 0 rows in the reference DB)
CREATE TABLE sales_docs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  doc_type text NOT NULL DEFAULT 'proposal',
  number text,
  seq bigint NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'draft',
  title text,
  contact_id bigint,
  company_id bigint,
  deal_id bigint,
  buyer_name text,
  buyer_email text,
  buyer_phone text,
  currency text NOT NULL DEFAULT 'USD',
  currency_exponent smallint NOT NULL DEFAULT 2,
  subtotal_minor bigint NOT NULL DEFAULT 0,
  discount_minor bigint NOT NULL DEFAULT 0,
  tax_minor bigint NOT NULL DEFAULT 0,
  total_minor bigint NOT NULL DEFAULT 0,
  tax_rate_bp integer NOT NULL DEFAULT 0,
  items_json jsonb,
  notes text,
  valid_until date,
  sent_at timestamptz,
  decided_at timestamptz,
  invoice_id bigint,
  public_token text,
  owner_id bigint,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_sales_docs_public_token UNIQUE (public_token),
  CONSTRAINT fk_sales_docs_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_sales_docs_company_id FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_sales_docs_deal_id FOREIGN KEY (org_id, deal_id) REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id),
  CONSTRAINT fk_sales_docs_owner_id FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_id),
  CONSTRAINT fk_sales_docs_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_sales_docs_company_id ON sales_docs (org_id, company_id);
CREATE INDEX idx_sales_docs_contact_id ON sales_docs (org_id, contact_id);
CREATE INDEX idx_sales_docs_deal_id ON sales_docs (org_id, deal_id);
CREATE INDEX idx_sales_docs_doc_type_status ON sales_docs (org_id, doc_type, status);

ALTER TABLE sales_docs ENABLE ROW LEVEL SECURITY;
ALTER TABLE sales_docs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON sales_docs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_sales_docs_touch BEFORE UPDATE ON sales_docs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
