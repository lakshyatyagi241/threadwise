-- ar: auto-reply-keywords data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's auto reply keywords features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: auto_reply_lookups, keyword_replies, keyword_reply_contents, keyword_reply_logs

-- WaDesk `auto_reply_lookups` (stream; 0 rows in the reference DB)
CREATE SEQUENCE auto_reply_lookups_id_seq;
CREATE TABLE auto_reply_lookups (
  id bigint NOT NULL DEFAULT nextval('auto_reply_lookups_id_seq'),
  org_id bigint NOT NULL,
  device_id bigint,
  matched_keyword_reply_id bigint,
  contact_phone text NOT NULL,
  query_text text NOT NULL,
  latency_ms integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_auto_reply_lookups_created_at ON auto_reply_lookups (org_id, created_at);
CREATE INDEX idx_auto_reply_lookups_device_id_created_at ON auto_reply_lookups (org_id, device_id, created_at);
CREATE INDEX idx_auto_reply_lookups_matched_keyword_reply_id_created_at ON auto_reply_lookups (org_id, matched_keyword_reply_id, created_at);

ALTER TABLE auto_reply_lookups ENABLE ROW LEVEL SECURITY;
ALTER TABLE auto_reply_lookups FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON auto_reply_lookups FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

