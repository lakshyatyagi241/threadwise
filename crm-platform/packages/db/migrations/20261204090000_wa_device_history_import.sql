-- wahist: opt-in import of the existing chats of a PERSONAL WhatsApp number (unofficial engine, channel kind whatsapp_qr).
-- Why this migration exists: WhatsApp sends a number's history only right after a link, and only if the companion asked for it while it was
-- being registered. So the person's choice (made before the QR is scanned) has to be on the device row where the socket factory reads it,
-- and the progress of what then arrives needs a row that survives a worker restart and shows on the device page.
--
-- devices.history_import_mode is the choice for the pairing attempt in progress. It is reset to 'none' when the run ends or is cancelled, so
-- a reconnect never asks WhatsApp for history again and a number that never opted in behaves exactly as before.
-- wa_device_history_imports: one row per run (a re-link the person opts into again is a new run). At most one active run per device.
-- Counters count only what THIS run stored (a redelivered batch hits the inbox ledger and adds nothing), so a retry never inflates them.
-- No message text and no phone number is kept here, only counts, a short error code and times.

ALTER TABLE devices
  ADD COLUMN history_import_mode text NOT NULL DEFAULT 'none',
  ADD CONSTRAINT ck_devices_history_import_mode CHECK (history_import_mode IN ('none', 'recent', 'full'));

CREATE TABLE wa_device_history_imports (
  org_id                bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                    bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                  uuid NOT NULL DEFAULT gen_random_uuid(),
  device_id             bigint NOT NULL,
  mode                  text NOT NULL,
  state                 text NOT NULL DEFAULT 'idle',
  requested_by_user_id  bigint,
  -- The caps in force when the run was requested (platform settings can change later without rewriting what a run was told).
  window_days           integer NOT NULL,
  max_messages          integer NOT NULL,
  max_messages_per_chat integer NOT NULL,
  max_chats             integer NOT NULL,
  chats_count           integer NOT NULL DEFAULT 0,
  contacts_count        integer NOT NULL DEFAULT 0,
  messages_count        integer NOT NULL DEFAULT 0,
  batches_count         integer NOT NULL DEFAULT 0,
  progress              smallint NOT NULL DEFAULT 0,
  error_code            text,
  started_at            timestamptz,
  last_batch_at         timestamptz,
  finished_at           timestamptz,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  row_version           integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_wa_device_history_imports_device FOREIGN KEY (org_id, device_id)
    REFERENCES devices (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_wa_device_history_imports_user FOREIGN KEY (org_id, requested_by_user_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (requested_by_user_id),
  CONSTRAINT ck_wa_device_history_imports_mode CHECK (mode IN ('recent', 'full')),
  CONSTRAINT ck_wa_device_history_imports_state CHECK (state IN ('idle', 'running', 'done', 'failed', 'cancelled', 'limit_reached')),
  CONSTRAINT ck_wa_device_history_imports_progress CHECK (progress BETWEEN 0 AND 100),
  CONSTRAINT ck_wa_device_history_imports_counts CHECK (chats_count >= 0 AND contacts_count >= 0 AND messages_count >= 0 AND batches_count >= 0)
);

-- One active run per device: a second request supersedes the first in the same transaction.
CREATE UNIQUE INDEX uq_wa_device_history_imports_active ON wa_device_history_imports (org_id, device_id)
  WHERE state IN ('idle', 'running');
CREATE INDEX idx_wa_device_history_imports_device ON wa_device_history_imports (org_id, device_id, id DESC);
-- The sweep that finishes idle runs and gives up on runs that never received anything.
CREATE INDEX idx_wa_device_history_imports_sweep ON wa_device_history_imports (state, last_batch_at) WHERE state IN ('idle', 'running');

ALTER TABLE wa_device_history_imports ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_device_history_imports FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_device_history_imports FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_device_history_imports_touch BEFORE UPDATE ON wa_device_history_imports
  FOR EACH ROW EXECUTE FUNCTION touch_row();
