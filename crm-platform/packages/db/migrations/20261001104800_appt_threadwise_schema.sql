-- appt: appointments-booking data model, ported from Reference
-- Why this migration exists: the tables Reference's appointments booking features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: booking_types, slot_reservations, appointments, booking_availability_overrides, booking_availability_rules, booking_financials, booking_integrations, booking_questions, booking_reminders, booking_templates

-- Reference `booking_types` (tenant; 0 rows in the reference DB)
CREATE TABLE booking_types (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  name text NOT NULL,
  slug text NOT NULL,
  description text,
  location_type text NOT NULL DEFAULT 'address',
  location_value text,
  color text,
  duration_minutes smallint NOT NULL DEFAULT 30,
  increment_minutes smallint NOT NULL DEFAULT 30,
  buffer_before_minutes smallint NOT NULL DEFAULT 0,
  buffer_after_minutes smallint NOT NULL DEFAULT 0,
  min_notice_minutes integer NOT NULL DEFAULT 240,
  max_advance_days smallint NOT NULL DEFAULT 30,
  max_per_day smallint,
  capacity smallint NOT NULL DEFAULT 1,
  timezone text,
  intro_message text,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  meta jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_booking_types_location_type CHECK (location_type IN ('address', 'virtual', 'phone')),
  CONSTRAINT uq_booking_types_slug UNIQUE (org_id, slug),
  CONSTRAINT fk_booking_types_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_booking_types_is_active ON booking_types (org_id, is_active);

ALTER TABLE booking_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking_types FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON booking_types FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_booking_types_touch BEFORE UPDATE ON booking_types
  FOR EACH ROW EXECUTE FUNCTION touch_row();

