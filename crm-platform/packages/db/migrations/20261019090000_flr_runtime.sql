-- flr: the persistent run store of the flow runtime engine (TW-FLR-011, 014, 015, 016, 051)
-- Why this migration exists: Reference kept every live run in the memory of one Node process (no checkpoint, no queue), so a restart
-- or the hour-long sweeper silently ended runs (TW-FLR-015, "all run state is in memory"). The port keeps a run as a row: where it
-- stands, its variables, what it waits for and when it wakes, so a restart loses nothing and a Delay can last days. The graph is
-- snapshotted on the row at start so editing a flow never changes a run in flight.
--
-- Tables: flow_runs, flow_run_steps. Also: flows.trigger_channel_id (replaces the polymorphic trigger_device_id, TW-FLR-001 port
-- notes), flow_subscribers.source and last_run_id (every launch path now writes a subscriber row, TW-FLR-010).

ALTER TABLE flows ADD COLUMN trigger_channel_id bigint;
ALTER TABLE flows ADD CONSTRAINT fk_flows_trigger_channel_id
  FOREIGN KEY (org_id, trigger_channel_id) REFERENCES channels (org_id, id) ON DELETE SET NULL (trigger_channel_id);
CREATE INDEX idx_flows_live_trigger ON flows (org_id, trigger_kind, trigger_value) WHERE is_published AND is_active;

ALTER TABLE flow_subscribers ADD COLUMN source text NOT NULL DEFAULT 'enroll';
-- last_run_id is a plain pointer, not a foreign key: flow_runs already references flow_subscribers, and a deleted run only makes it stale.
ALTER TABLE flow_subscribers ADD COLUMN last_run_id bigint;

CREATE TABLE flow_runs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_id bigint NOT NULL,
  subscriber_id bigint,
  contact_id bigint,
  channel_id bigint,
  -- The customer's key on the channel (digits for a phone channel): with channel_id it is the pair one run may hold at a time.
  peer_key text NOT NULL,
  conversation_id bigint,
  -- What started it: keyword, any_message, tag_added, group_join, contact_created, opt_in, order_placed, deal_stage_changed, away,
  -- out_of_hours, manual, api, routing, campaign, webhook_lead, handoff, retry.
  source text NOT NULL,
  trigger_ref text,
  -- The typed text that started a keyword run: typing it again restarts the run (TW-FLR-002 rule 1a).
  trigger_text text,
  -- running: a worker is walking it. waiting: parked on a customer reply. sleeping: a Delay is counting down (resume_at).
  -- halted: the channel was down or the daily cap was reached; it tries again at resume_at. The rest are final.
  status text NOT NULL DEFAULT 'running'
    CHECK (status IN ('running', 'waiting', 'sleeping', 'halted', 'completed', 'failed', 'cancelled', 'expired')),
  end_reason text,
  failure_code text,
  failure_reason text,
  -- The compiled runtime graph, frozen at start.
  graph jsonb NOT NULL,
  current_node_id text,
  -- Counts every step taken; a queued job carries the value it expects, so a stale or duplicate job does nothing.
  step_seq integer NOT NULL DEFAULT 0,
  vars jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Executions per node: the loop guard stops a node at 20 (TW-FLR-016 rule 7).
  visits jsonb NOT NULL DEFAULT '{}'::jsonb,
  wait jsonb,
  last_menu jsonb,
  last_out jsonb,
  -- The idle seconds a wait may last, and the pause after the run ends before another canned reply may go out.
  timeout_seconds integer NOT NULL DEFAULT 600,
  cooldown_seconds integer NOT NULL DEFAULT 0,
  variant text,
  campaign_id bigint,
  halt_reason text,
  started_at timestamptz NOT NULL DEFAULT now(),
  last_activity_at timestamptz NOT NULL DEFAULT now(),
  -- When an idle wait gives up; null while the run is not waiting.
  expires_at timestamptz,
  -- The absolute end of the run's life, whatever it is doing.
  max_expires_at timestamptz NOT NULL,
  resume_at timestamptz,
  ended_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_flow_runs_flow_id FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_flow_runs_subscriber_id FOREIGN KEY (org_id, subscriber_id) REFERENCES flow_subscribers (org_id, id) ON DELETE SET NULL (subscriber_id),
  CONSTRAINT fk_flow_runs_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_flow_runs_channel_id FOREIGN KEY (org_id, channel_id) REFERENCES channels (org_id, id) ON DELETE SET NULL (channel_id)
);
-- One live run per customer on a channel: a new start replaces the old one (TW-FLR-015 rule 1).
CREATE UNIQUE INDEX uq_flow_runs_live_peer ON flow_runs (org_id, channel_id, peer_key)
  WHERE status IN ('running', 'waiting', 'sleeping', 'halted') AND channel_id IS NOT NULL;
CREATE INDEX idx_flow_runs_flow_status ON flow_runs (org_id, flow_id, status);
CREATE INDEX idx_flow_runs_contact ON flow_runs (org_id, contact_id);
CREATE INDEX idx_flow_runs_subscriber ON flow_runs (org_id, subscriber_id);
CREATE INDEX idx_flow_runs_started ON flow_runs (org_id, started_at DESC);
-- The sweeper reads the runs that are due: a wait that gave up, a Delay or halt that should wake.
CREATE INDEX idx_flow_runs_due ON flow_runs (status, expires_at, resume_at) WHERE status IN ('waiting', 'sleeping', 'halted', 'running');

ALTER TABLE flow_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_runs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_runs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_flow_runs_touch BEFORE UPDATE ON flow_runs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- The execution history of a run: one row per step, what the node did and why a run ended (TW-FLR-054, 055). Written in the same
-- transaction as the step, so the log never disagrees with the run.
CREATE TABLE flow_run_steps (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  run_id bigint NOT NULL,
  seq integer NOT NULL,
  node_id text,
  node_type text,
  -- exec, reply, wait, sleep, advance, end, halt, error, restart.
  event text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  CONSTRAINT fk_flow_run_steps_run_id FOREIGN KEY (org_id, run_id) REFERENCES flow_runs (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_flow_run_steps_run ON flow_run_steps (org_id, run_id, seq, id);

ALTER TABLE flow_run_steps ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_run_steps FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_run_steps FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

