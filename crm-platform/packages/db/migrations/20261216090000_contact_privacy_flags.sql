-- contact privacy flags (BL-180, spec docs/specs/privacy-and-data-governance.md section 11.9): three facts about ONE contact that the
-- consent ledger cannot hold, because the ledger stores a grant or a withdrawal per (channel, purpose):
--
--   minor               the contact is under the age of consent. The ConsentGate holds marketing to a flagged minor when the
--                       workspace's children setting (compliance_settings.children_policy / parental_consent_required) asks for it.
--   guardian_consent    a parent or guardian agreed for the minor. EVIDENCE only: it never writes a marketing grant (the ledger stays
--                       the only place a grant lives); it lifts the hold where the workspace allows minors at all.
--   sale_share_opt_out  "Do Not Sell or Share" (CCPA / CPRA), set by staff, the API, or the Global Privacy Control signal.
--
-- Same pattern as the consent ledger, in two additive tables (no existing table or applied migration is touched):
--
--   contact_privacy_events  append-only history: who changed a flag, when, from which source, with which evidence (ids and references,
--                           never an IP or free text about the person). A trigger rejects UPDATE and DELETE.
--   contact_privacy_flags   the current value of each flag per contact, written in the same transaction as the event. One row, one
--                           primary-key lookup for the gate.
--
-- Nothing is backfilled: no contact is a minor or opted out until a person or the browser signal says so.

CREATE TABLE contact_privacy_events (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Erasing a contact anonymises its events (the link goes to NULL); the rows are never edited or deleted.
  contact_id      bigint,
  kind            text NOT NULL,
  -- true = the flag is on (is a minor / guardian agreed / opted out), false = cleared.
  value           boolean NOT NULL,
  source          text NOT NULL,
  evidence        jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id   bigint,
  note            text,
  occurred_at     timestamptz NOT NULL DEFAULT now(),
  recorded_at     timestamptz NOT NULL DEFAULT now(),
  -- One per source event ("gpc:form:<submission uuid>", "manual:<request key>"): a redelivery inserts nothing.
  idempotency_key text NOT NULL,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, idempotency_key),
  CONSTRAINT fk_privacy_events_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_privacy_events_actor FOREIGN KEY (org_id, actor_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (actor_user_id),
  CONSTRAINT ck_privacy_events_kind CHECK (kind IN ('minor', 'guardian_consent', 'sale_share_opt_out')),
  CONSTRAINT ck_privacy_events_source CHECK (source IN ('manual', 'api', 'contact_request', 'gpc')),
  CONSTRAINT ck_privacy_events_evidence CHECK (jsonb_typeof(evidence) = 'object' AND pg_column_size(evidence) <= 4096),
  CONSTRAINT ck_privacy_events_note CHECK (note IS NULL OR char_length(note) <= 500),
  CONSTRAINT ck_privacy_events_key CHECK (char_length(idempotency_key) BETWEEN 1 AND 200)
);
CREATE INDEX idx_privacy_events_contact ON contact_privacy_events (org_id, contact_id, occurred_at DESC, id DESC) WHERE contact_id IS NOT NULL;

ALTER TABLE contact_privacy_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_privacy_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_privacy_events FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- History is never edited. The only change the database itself may make is a reference going to NULL (ON DELETE SET NULL of the
-- contact or the user: erasure). DELETE is for a privileged session and for the workspace cascade. Same rule as the consent ledger.
CREATE FUNCTION contact_privacy_events_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF app_is_privileged() OR pg_trigger_depth() > 1 THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'contact_privacy_events is append-only: an event cannot be deleted' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (to_jsonb(NEW) - 'contact_id' - 'actor_user_id') IS NOT DISTINCT FROM (to_jsonb(OLD) - 'contact_id' - 'actor_user_id')
     AND (NEW.contact_id IS NULL OR NEW.contact_id IS NOT DISTINCT FROM OLD.contact_id)
     AND (NEW.actor_user_id IS NULL OR NEW.actor_user_id IS NOT DISTINCT FROM OLD.actor_user_id) THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'contact_privacy_events is append-only: an event cannot be changed' USING ERRCODE = 'integrity_constraint_violation';
END $$;

CREATE TRIGGER trg_privacy_events_immutable BEFORE UPDATE OR DELETE ON contact_privacy_events
  FOR EACH ROW EXECUTE FUNCTION contact_privacy_events_immutable();

-- ---------------------------------------------------------------------------------------------------------------------------
-- the current value of each flag
-- ---------------------------------------------------------------------------------------------------------------------------

CREATE TABLE contact_privacy_flags (
  org_id              bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  contact_id          bigint NOT NULL,
  is_minor            boolean NOT NULL DEFAULT false,
  minor_since         timestamptz,
  minor_source        text,
  guardian_consent    boolean NOT NULL DEFAULT false,
  guardian_since      timestamptz,
  do_not_sell_share   boolean NOT NULL DEFAULT false,
  dns_since           timestamptz,
  dns_source          text,
  updated_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, contact_id),
  CONSTRAINT fk_privacy_flags_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  -- A guardian agrees FOR a minor: clearing the minor flag clears the guardian flag in the same transaction.
  CONSTRAINT ck_privacy_flags_guardian CHECK (NOT guardian_consent OR is_minor),
  CONSTRAINT ck_privacy_flags_sources CHECK (
    (minor_source IS NULL OR minor_source IN ('manual', 'api', 'contact_request', 'gpc'))
    AND (dns_source IS NULL OR dns_source IN ('manual', 'api', 'contact_request', 'gpc'))
  )
);
-- "Which contacts are minors / opted out": the Compliance center counts and the audience screens read these.
CREATE INDEX idx_privacy_flags_minor ON contact_privacy_flags (org_id, contact_id) WHERE is_minor;
CREATE INDEX idx_privacy_flags_dns ON contact_privacy_flags (org_id, contact_id) WHERE do_not_sell_share;

ALTER TABLE contact_privacy_flags ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_privacy_flags FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_privacy_flags FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
