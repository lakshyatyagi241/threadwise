-- add: addons-extension-registry data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's addons extension registry features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: extensions, extension_api_tokens

-- WaDesk `extensions` (platform_only; 0 rows in the reference DB)
CREATE TABLE extensions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  slug text NOT NULL,
  name text NOT NULL,
  version text NOT NULL DEFAULT '1.0.0',
  purchase_code text,
  status text NOT NULL DEFAULT 'active',
  files jsonb,
  manifest jsonb,
  installed_at timestamptz,
  installed_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_extensions_slug UNIQUE (slug)
);
CREATE INDEX idx_extensions_installed_by ON extensions (installed_by);
CREATE INDEX idx_extensions_slug_status ON extensions (slug, status);

ALTER TABLE extensions ENABLE ROW LEVEL SECURITY;
ALTER TABLE extensions FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON extensions FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_extensions_touch BEFORE UPDATE ON extensions
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `extension_api_tokens` (child; 0 rows in the reference DB)
CREATE TABLE extension_api_tokens (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  token_hash text NOT NULL,
  label text,
  last_used_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_extension_api_tokens_token_hash UNIQUE (org_id, token_hash),
  CONSTRAINT fk_extension_api_tokens_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_extension_api_tokens_user_id ON extension_api_tokens (org_id, user_id);

ALTER TABLE extension_api_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE extension_api_tokens FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON extension_api_tokens FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_extension_api_tokens_touch BEFORE UPDATE ON extension_api_tokens
  FOR EACH ROW EXECUTE FUNCTION touch_row();
