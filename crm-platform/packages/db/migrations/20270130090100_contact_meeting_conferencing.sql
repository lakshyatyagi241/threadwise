-- contact_meeting_conferencing: the video link and calendar entry asked for on a typed-in meeting (BL-361, BL-362).
-- Why this migration exists: the Add meeting form can ask for a Zoom, Teams or Google Meet link and for the meeting to be put on the
-- workspace's calendar. The request is saved WITH the meeting (so a provider that is down never loses a meeting), and what the provider
-- answered is kept beside it: which provider holds the room, the provider's ids (needed to move or delete it later), and a short problem code
-- when it did not work (shown on the meeting with a Retry). It is a table of its own, one row per meeting, so `contact_meetings` keeps its
-- shape; the join address itself goes to the existing `contact_meetings.join_url`, which a booking's Meet or Teams link already uses.
--
--   video_provider     'zoom' | 'teams' | 'meet', null when no link was asked for.
--   video_meeting_id   the provider's id of the room (Zoom meeting id, Graph online meeting id); null for 'meet' (the room is part of the
--                      calendar event) and until the provider answers.
--   video_status       'pending' (asked, not answered), 'ready', 'failed' (see video_error).
--   host_user_id       whose connected account made the room: the person who scheduled the meeting. A change of provider or a delete is
--                      done in THEIR account, even when someone else edits the meeting.
--   add_to_calendar    put the meeting on the workspace's connected calendar. `send_invitation`: the calendar also invites the contact by email.
--   calendar_*         where the event is (provider, calendar id, event id) and whether the last write worked.
--
-- Nothing here is read by the booking mirror: a row mirroring an appointment has none (it is changed on the appointment).

CREATE TABLE contact_meeting_conferencing (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  meeting_id bigint NOT NULL,
  host_user_id bigint,
  video_provider text,
  video_meeting_id text,
  video_status text,
  video_error text,
  add_to_calendar boolean NOT NULL DEFAULT false,
  send_invitation boolean NOT NULL DEFAULT false,
  calendar_provider text,
  calendar_id text,
  calendar_event_id text,
  calendar_status text,
  calendar_error text,
  synced_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_contact_meeting_conferencing_meeting UNIQUE (org_id, meeting_id),
  CONSTRAINT chk_contact_meeting_conferencing_video_provider CHECK (video_provider IS NULL OR video_provider IN ('zoom', 'teams', 'meet')),
  CONSTRAINT chk_contact_meeting_conferencing_video_status CHECK (video_status IS NULL OR video_status IN ('pending', 'ready', 'failed')),
  CONSTRAINT chk_contact_meeting_conferencing_calendar_provider CHECK (calendar_provider IS NULL OR calendar_provider IN ('google', 'microsoft')),
  CONSTRAINT chk_contact_meeting_conferencing_calendar_status CHECK (calendar_status IS NULL OR calendar_status IN ('synced', 'failed')),
  CONSTRAINT chk_contact_meeting_conferencing_status_has_provider CHECK ((video_status IS NULL) = (video_provider IS NULL)),
  -- The meeting is the parent: deleting it removes this row (the provider-side room and event are removed by the application, from the
  -- ids captured in the delete's outbox event).
  CONSTRAINT fk_contact_meeting_conferencing_meeting FOREIGN KEY (org_id, meeting_id)
    REFERENCES contact_meetings (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_contact_meeting_conferencing_host FOREIGN KEY (org_id, host_user_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (host_user_id)
);
CREATE INDEX idx_contact_meeting_conferencing_host ON contact_meeting_conferencing (org_id, host_user_id);

ALTER TABLE contact_meeting_conferencing ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_meeting_conferencing FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_meeting_conferencing FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

