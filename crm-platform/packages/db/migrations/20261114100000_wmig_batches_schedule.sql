-- wmig: bulk batches, scheduling and the verdict. Additive to 20261113100000_wmig_waboo_migration_runs.sql (never edit an applied migration).
-- Platform (operator) tables: no tenant column. No credential is ever stored here.

CREATE TABLE waboo_migration_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  status text NOT NULL DEFAULT 'queued',
  mode text NOT NULL DEFAULT 'dry',
  -- null = start now; otherwise a BullMQ delayed job fires at this time (max 90 days ahead, checked by the API)
  run_at timestamptz,
  -- the staging server cannot run two migrations at once: children run one after another
  concurrency smallint NOT NULL DEFAULT 1,
  stop_on_failure boolean NOT NULL DEFAULT false,
  total_count integer NOT NULL,
  -- snapshot written when the batch ends: {completed,failed,blocked,cancelled}
  counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by bigint,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_wmigb_status CHECK (status IN ('queued', 'running', 'completed', 'failed', 'cancelled')),
  CONSTRAINT chk_wmigb_mode CHECK (mode IN ('dry', 'load')),
  CONSTRAINT chk_wmigb_concurrency CHECK (concurrency = 1),
  CONSTRAINT chk_wmigb_total CHECK (total_count BETWEEN 1 AND 50)
);
CREATE INDEX idx_wmigb_status ON waboo_migration_batches (status);
CREATE INDEX idx_wmigb_created ON waboo_migration_batches (created_at DESC);

ALTER TABLE waboo_migration_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE waboo_migration_batches FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON waboo_migration_batches FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_waboo_migration_batches_touch BEFORE UPDATE ON waboo_migration_batches
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE waboo_migration_runs
  ADD COLUMN batch_id bigint REFERENCES waboo_migration_batches (id) ON DELETE CASCADE,
  ADD COLUMN position integer,
  ADD COLUMN run_at timestamptz;

ALTER TABLE waboo_migration_runs DROP CONSTRAINT chk_wmig_status;
ALTER TABLE waboo_migration_runs ADD CONSTRAINT chk_wmig_status
  CHECK (status IN ('queued', 'running', 'completed', 'failed', 'cancelled', 'blocked'));

CREATE INDEX idx_wmig_batch ON waboo_migration_runs (batch_id, position) WHERE batch_id IS NOT NULL;

-- Whatever the number of workers or batches, at most ONE run executes at a time in this environment.
-- A constant-expression unique index: the database, not app code, refuses a second concurrent run.
CREATE UNIQUE INDEX uq_wmig_one_running ON waboo_migration_runs ((1)) WHERE status = 'running';
