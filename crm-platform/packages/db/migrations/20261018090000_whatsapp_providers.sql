-- whatsapp-providers: the platform operator's registry of WhatsApp providers (BSPs) and the per-workspace override.
-- Why this migration exists: the WABA module reaches a number through one of two hard-coded routes ('meta' | 'interakt'), picked
-- platform-wide by WABA_DEFAULT_PROVIDER. The owner wants the platform operator to switch BSPs from the admin panel, so the route
-- becomes data: a provider is a row (address, version, auth scheme, header templates, credential mode, webhook signature scheme),
-- a workspace may be assigned one, and each connected number records the provider it is on (`wa_provider_configs.meta_json.provider_key`,
-- no column: the row already carries the other connection facts in meta_json and nothing queries by it except the operator's switch).
--
--  1. whatsapp_providers: platform-owned, NOT tenant data (no org_id). Protected like platform_settings: forced RLS, one
--     privileged-only policy, reached only through PlatformStore. Credentials (provider token, app secret, webhook secret, verify
--     token) are one sealed CryptoService envelope; only the last four characters of each are kept in the clear (`credential_hints`) so the
--     console can say "set" without decrypting.
--  2. Two built-in rows mirror the WABA module's own routes ('meta', 'interakt'). They are never read for routing: their address,
--     version and secrets stay the console WhatsApp settings page's (WABA_ENV), so nothing changes while the registry holds only them.
--  3. At most one default (partial unique index). No default row = the platform setting (WABA_DEFAULT_PROVIDER) decides, as today.
--  4. org_whatsapp_provider_assignment: a workspace's override for NEW numbers. A tenant may read its own row; only the privileged path
--     (the operator API) writes. The provider parent has no org_id, so the foreign key is a plain one (the composite-key rule is for
--     references between tenant tables); RESTRICT keeps a provider that a workspace still points at from being deleted.
--  5. Three platform permission keys, granted to Super Admin and Admin (WD-RBAC: new platform keys arrive by migration).

CREATE TABLE whatsapp_providers (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                   uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  key                    text NOT NULL UNIQUE,
  label                  text NOT NULL,
  -- 'meta' | 'interakt' for the two rows that mirror the WABA module's routes; null for a provider added through the operator API.
  builtin                text,
  adapter_kind           text NOT NULL DEFAULT 'meta_graph',
  base_url               text NOT NULL,
  api_version            text NOT NULL,
  auth_scheme            text NOT NULL,
  header_templates       jsonb NOT NULL DEFAULT '{}'::jsonb,
  credential_mode        text NOT NULL,
  -- CryptoService envelope of {"providerToken","appSecret","webhookSecret","verifyToken"} (only the keys that are set).
  credentials_enc        text,
  -- {"providerToken":"1234",...}: last four characters of each stored secret.
  credential_hints       jsonb NOT NULL DEFAULT '{}'::jsonb,
  webhook_mode           text NOT NULL DEFAULT 'number_level_override',
  signature_scheme       text NOT NULL DEFAULT 'meta_app_secret_sha256',
  signature_header_name  text,
  billing_mode           text NOT NULL DEFAULT 'provider_credit_line',
  capabilities           jsonb NOT NULL DEFAULT '{"mediaUpload": true}'::jsonb,
  onboarding             text NOT NULL DEFAULT 'manual',
  onboarding_app_id      text,
  onboarding_config_id   text,
  status                 text NOT NULL DEFAULT 'disabled',
  is_default             boolean NOT NULL DEFAULT false,
  notes                  text,
  last_test              jsonb,
  last_tested_at         timestamptz,
  created_by_operator_id bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  row_version            integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_whatsapp_providers_key CHECK (key ~ '^[a-z][a-z0-9_-]{1,39}$'),
  CONSTRAINT chk_whatsapp_providers_builtin CHECK (builtin IS NULL OR builtin IN ('meta', 'interakt')),
  CONSTRAINT chk_whatsapp_providers_adapter CHECK (adapter_kind IN ('meta_graph')),
  CONSTRAINT chk_whatsapp_providers_auth CHECK (auth_scheme IN ('bearer', 'custom_headers')),
  CONSTRAINT chk_whatsapp_providers_credential_mode CHECK (credential_mode IN ('platform_token', 'channel_token')),
  CONSTRAINT chk_whatsapp_providers_webhook_mode CHECK (webhook_mode IN ('meta_app_level', 'number_level_override')),
  CONSTRAINT chk_whatsapp_providers_signature CHECK (signature_scheme IN ('meta_app_secret_sha256', 'shared_secret_header', 'none')),
  CONSTRAINT chk_whatsapp_providers_signature_header CHECK (signature_scheme <> 'shared_secret_header' OR signature_header_name IS NOT NULL),
  CONSTRAINT chk_whatsapp_providers_billing CHECK (billing_mode IN ('provider_credit_line', 'customer_direct', 'meta_reseller')),
  CONSTRAINT chk_whatsapp_providers_onboarding CHECK (onboarding IN ('manual', 'embedded_signup')),
  CONSTRAINT chk_whatsapp_providers_status CHECK (status IN ('active', 'disabled', 'archived')),
  -- A default is something a number can be connected through: it must be active.
  CONSTRAINT chk_whatsapp_providers_default_active CHECK (NOT is_default OR status = 'active'),
  CONSTRAINT chk_whatsapp_providers_base_url CHECK (base_url ~ '^https?://' AND length(base_url) <= 200)
);

-- At most one default provider.
CREATE UNIQUE INDEX uq_whatsapp_providers_default ON whatsapp_providers (is_default) WHERE is_default;

CREATE TRIGGER trg_whatsapp_providers_touch BEFORE UPDATE ON whatsapp_providers
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE whatsapp_providers ENABLE ROW LEVEL SECURITY;
ALTER TABLE whatsapp_providers FORCE  ROW LEVEL SECURITY;
CREATE POLICY privileged_only ON whatsapp_providers FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
GRANT SELECT, INSERT, UPDATE, DELETE ON whatsapp_providers TO crm_app, crm_worker;

CREATE TABLE org_whatsapp_provider_assignment (
  org_id                     bigint PRIMARY KEY REFERENCES organizations (id) ON DELETE CASCADE,
  provider_id                bigint NOT NULL REFERENCES whatsapp_providers (id) ON DELETE RESTRICT,
  note                       text,
  assigned_by_operator_id    bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  created_at                 timestamptz NOT NULL DEFAULT now(),
  updated_at                 timestamptz NOT NULL DEFAULT now(),
  row_version                integer NOT NULL DEFAULT 1
);
CREATE INDEX idx_org_whatsapp_provider_assignment_provider ON org_whatsapp_provider_assignment (provider_id);

CREATE TRIGGER trg_org_whatsapp_provider_assignment_touch BEFORE UPDATE ON org_whatsapp_provider_assignment
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE org_whatsapp_provider_assignment ENABLE ROW LEVEL SECURITY;
ALTER TABLE org_whatsapp_provider_assignment FORCE  ROW LEVEL SECURITY;
-- The standard tenant policy lets a workspace see its own override; the three RESTRICTIVE policies are ANDed on top of it, so nobody but
-- the privileged path (the operator API) can insert, change or delete one. A workspace must not pick its own BSP.
CREATE POLICY tenant_isolation ON org_whatsapp_provider_assignment FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE POLICY privileged_insert_only ON org_whatsapp_provider_assignment AS RESTRICTIVE FOR INSERT
  WITH CHECK (app_is_privileged());
CREATE POLICY privileged_update_only ON org_whatsapp_provider_assignment AS RESTRICTIVE FOR UPDATE
  USING (app_is_privileged());
CREATE POLICY privileged_delete_only ON org_whatsapp_provider_assignment AS RESTRICTIVE FOR DELETE
  USING (app_is_privileged());
GRANT SELECT, INSERT, UPDATE, DELETE ON org_whatsapp_provider_assignment TO crm_app, crm_worker;

