-- wsp: workspaces-teams-tenancy data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's workspaces teams tenancy features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: impersonation_sessions, user_device_tokens, workspace_addons, workspace_email_accounts, workspace_flags, workspace_ig_accounts, workspace_payment_configs, workspace_settings

-- --- additions to tables this repo already has ----------------------------------------
-- users: the membership timestamps WaDesk keeps on workspace_user. WaDesk lets one account join several workspaces; here
-- a user row already belongs to exactly one org, so these two columns live on the row itself.
ALTER TABLE users
  ADD COLUMN invited_at timestamptz,
  ADD COLUMN joined_at  timestamptz;

-- teams: WaDesk's team settings (routing strategy, hours, devices). The slug is unique per org but nullable so the teams
-- that already exist keep working until someone names them.
ALTER TABLE teams
  ADD COLUMN slug                text,
  ADD COLUMN color               text NOT NULL DEFAULT '#075E54',
  ADD COLUMN description         text,
  ADD COLUMN default_assignee_id bigint,
  ADD COLUMN assignment_strategy text NOT NULL DEFAULT 'manual',
  ADD COLUMN business_hours      jsonb,
  ADD COLUMN timezone            text,
  ADD COLUMN device_ids          jsonb,
  ADD COLUMN is_default          boolean NOT NULL DEFAULT false,
  ADD COLUMN sort                integer NOT NULL DEFAULT 0,
  ADD CONSTRAINT uq_teams_org_slug UNIQUE (org_id, slug),
  ADD CONSTRAINT fk_teams_default_assignee_id FOREIGN KEY (org_id, default_assignee_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (default_assignee_id);
CREATE INDEX idx_teams_org_default ON teams (org_id, is_default);

-- team_members: WaDesk team_user carries lead flag and a concurrent-conversation capacity per member.
ALTER TABLE team_members
  ADD COLUMN is_lead  boolean NOT NULL DEFAULT false,
  ADD COLUMN capacity integer NOT NULL DEFAULT 20;

-- WaDesk `impersonation_sessions` (platform_only; 0 rows in the reference DB)
CREATE TABLE impersonation_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  admin_user_id bigint NOT NULL,
  target_workspace_id bigint NOT NULL,
  original_workspace_id bigint,
  reason text NOT NULL,
  ip text,
  user_agent text,
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT fk_impersonation_sessions_target_workspace_id FOREIGN KEY (target_workspace_id) REFERENCES organizations (id) ON DELETE CASCADE,
  CONSTRAINT fk_impersonation_sessions_original_workspace_id FOREIGN KEY (original_workspace_id) REFERENCES organizations (id) ON DELETE SET NULL
);
CREATE INDEX idx_impersonation_sessions_admin_user_id_ended_at ON impersonation_sessions (admin_user_id, ended_at);
CREATE INDEX idx_impersonation_sessions_target_workspace_id ON impersonation_sessions (target_workspace_id);

ALTER TABLE impersonation_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE impersonation_sessions FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON impersonation_sessions FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_impersonation_sessions_touch BEFORE UPDATE ON impersonation_sessions
  FOR EACH ROW EXECUTE FUNCTION touch_row();

