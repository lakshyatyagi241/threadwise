-- seg: a third visibility, 'specific': a segment only the people (or teams) the owner picks can see, plus the owner and
-- everyone who can edit every segment. Intended change beyond Reference, by request (Reference has no segments at all).
-- Why a table and not a uuid[] on segments: the picks must be foreign keys, so a removed user or team drops out of the list by
-- itself (ON DELETE CASCADE) and a pick can never point into another workspace (composite FKs on org_id).
-- Why shares_rev: a change of the people list alone touches no column of segments, so the touch trigger would not bump
-- row_version and two editors could overwrite each other's list without a 409. The service bumps this counter with every
-- change of the list, which is a real column change and so moves row_version.

ALTER TABLE segments ADD COLUMN shares_rev integer NOT NULL DEFAULT 0;

-- Existing rows are 'private' or 'shared' and are not rewritten.
ALTER TABLE segments DROP CONSTRAINT chk_segments_visibility;
ALTER TABLE segments ADD CONSTRAINT chk_segments_visibility CHECK (visibility IN ('private', 'shared', 'specific'));

CREATE TABLE segment_shares (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid       uuid NOT NULL DEFAULT gen_random_uuid(),
  segment_id bigint NOT NULL,
  -- Exactly one of user_id / team_id: a person, or every member of a team (read at the time of the question).
  user_id    bigint,
  team_id    bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, segment_id) REFERENCES segments (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, team_id) REFERENCES teams (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_segment_shares_target CHECK ((user_id IS NULL) <> (team_id IS NULL))
);

CREATE UNIQUE INDEX uq_segment_shares_user ON segment_shares (org_id, segment_id, user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uq_segment_shares_team ON segment_shares (org_id, segment_id, team_id) WHERE team_id IS NOT NULL;
-- "Which segments can this person see": the list and the pickers.
CREATE INDEX idx_segment_shares_user ON segment_shares (org_id, user_id) WHERE user_id IS NOT NULL;
CREATE INDEX idx_segment_shares_team ON segment_shares (org_id, team_id) WHERE team_id IS NOT NULL;

ALTER TABLE segment_shares ENABLE ROW LEVEL SECURITY;
ALTER TABLE segment_shares FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON segment_shares FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
