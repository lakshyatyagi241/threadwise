-- notif: notifications-activity-audit data model, ported from Reference
-- Why this migration exists: the tables Reference's notifications activity audit features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: inbox_notifications, notifications, push_subscriptions

-- Reference `inbox_notifications` (tenant; 0 rows in the reference DB)
CREATE TABLE inbox_notifications (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  type text NOT NULL,
  title text NOT NULL,
  body text,
  data jsonb,
  link text,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_inbox_notifications_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_inbox_notifications_read_at ON inbox_notifications (org_id, read_at);
CREATE INDEX idx_inbox_notifications_type ON inbox_notifications (org_id, type);
CREATE INDEX idx_inbox_notifications_user_id_read_at ON inbox_notifications (org_id, user_id, read_at);

ALTER TABLE inbox_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE inbox_notifications FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON inbox_notifications FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_inbox_notifications_touch BEFORE UPDATE ON inbox_notifications
  FOR EACH ROW EXECUTE FUNCTION touch_row();

