-- wallet_holds: one row per send that has been allowed against a wallet balance but has not been charged yet.
-- Why this migration exists: a bulk send passed the wallet check on a cached "ok" for 3 seconds, so concurrent sends could all pass the
-- same balance (#1066). A hold takes the send's price out of the available balance (balance - reserved) when the send is allowed. The
-- hold is settled when the provider reports the delivery (its charge is posted and the hold is consumed) and expires on its own if the
-- delivery never comes, so a message that is accepted and then lost cannot lock the balance for ever.

CREATE TABLE wallet_holds (
  org_id       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  unit         text NOT NULL,
  amount       numeric(20,4) NOT NULL,
  status       text NOT NULL DEFAULT 'held',
  expires_at   timestamptz NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  settled_at   timestamptz,
  PRIMARY KEY (org_id, id),
  FOREIGN KEY (org_id, unit) REFERENCES wallets (org_id, unit) ON DELETE CASCADE,
  CONSTRAINT chk_wallet_holds_amount CHECK (amount > 0),
  CONSTRAINT chk_wallet_holds_status CHECK (status IN ('held', 'consumed', 'expired'))
);

-- The sweep and the settlement both look for the held rows of one wallet, oldest first.
CREATE INDEX idx_wallet_holds_held ON wallet_holds (org_id, unit, created_at) WHERE status = 'held';

ALTER TABLE wallet_holds ENABLE ROW LEVEL SECURITY;
ALTER TABLE wallet_holds FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wallet_holds FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
