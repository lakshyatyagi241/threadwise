-- camp: campaigns data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's campaigns features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: wpcampaigns, wp_campaign_contacts

-- WaDesk `wpcampaigns` (tenant; 3 rows in the reference DB)
CREATE TABLE wpcampaigns (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  scheduled_message_id bigint,
  campaign_name text NOT NULL,
  device_id bigint,
  campaign_type text NOT NULL DEFAULT 'text',
  status text NOT NULL DEFAULT 'draft',
  ab_testing boolean NOT NULL DEFAULT false,
  ab_split smallint NOT NULL DEFAULT 50,
  custom_message text,
  custom_message_b text,
  custom_header text,
  custom_footer text,
  custom_buttons jsonb,
  custom_quick_replies jsonb,
  custom_variable_map jsonb,
  custom_image text,
  custom_video text,
  custom_document text,
  template_id bigint,
  template_id_a bigint,
  template_id_b bigint,
  template_overrides jsonb,
  template_overrides_b jsonb,
  flow_id bigint,
  flow_id_b bigint,
  use_attributes boolean NOT NULL DEFAULT false,
  tracking_enabled boolean NOT NULL DEFAULT true,
  schedule_type text NOT NULL DEFAULT 'now',
  send_date date,
  send_time time,
  timezone text,
  repeat_interval text,
  repeat_until date,
  throttle_min_sec smallint,
  throttle_max_sec smallint,
  batch_size smallint,
  batch_pause_min smallint,
  daily_limit integer,
  window_start text,
  window_end text,
  last_run_at timestamptz,
  node_schedule_id text,
  total_recipients integer NOT NULL DEFAULT 0,
  sent_count integer NOT NULL DEFAULT 0,
  failed_count integer NOT NULL DEFAULT 0,
  delivered_count integer NOT NULL DEFAULT 0,
  read_count integer NOT NULL DEFAULT 0,
  responded_count integer NOT NULL DEFAULT 0,
  clicked_count integer NOT NULL DEFAULT 0,
  meta_clicked_count integer NOT NULL DEFAULT 0,
  meta_analytics_synced_at timestamptz,
  completed_at timestamptz,
  created_by bigint,
  provider text NOT NULL DEFAULT 'baileys',
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_wpcampaigns_template_id FOREIGN KEY (org_id, template_id) REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (template_id),
  CONSTRAINT fk_wpcampaigns_template_id_a FOREIGN KEY (org_id, template_id_a) REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (template_id_a),
  CONSTRAINT fk_wpcampaigns_template_id_b FOREIGN KEY (org_id, template_id_b) REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (template_id_b),
  CONSTRAINT fk_wpcampaigns_flow_id FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE SET NULL (flow_id),
  CONSTRAINT fk_wpcampaigns_flow_id_b FOREIGN KEY (org_id, flow_id_b) REFERENCES flows (org_id, id) ON DELETE SET NULL (flow_id_b),
  CONSTRAINT fk_wpcampaigns_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_wpcampaigns_created_by ON wpcampaigns (org_id, created_by);
CREATE INDEX idx_wpcampaigns_scheduled_message_id ON wpcampaigns (org_id, scheduled_message_id);
CREATE INDEX idx_wpcampaigns_provider ON wpcampaigns (org_id, provider);

ALTER TABLE wpcampaigns ENABLE ROW LEVEL SECURITY;
ALTER TABLE wpcampaigns FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wpcampaigns FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wpcampaigns_touch BEFORE UPDATE ON wpcampaigns
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `wp_campaign_contacts` (child; 0 rows in the reference DB)
CREATE TABLE wp_campaign_contacts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  campaign_id bigint NOT NULL,
  contact_id bigint,
  variant text,
  status text NOT NULL DEFAULT 'queued',
  send_attempts smallint NOT NULL DEFAULT 0,
  next_attempt_at timestamptz,
  phone_number text,
  recipient_name text,
  whatsapp_message_id text,
  tracking_id text,
  sent_at timestamptz,
  delivered_at timestamptz,
  read_at timestamptz,
  response text,
  responded_at timestamptz,
  clicked boolean NOT NULL DEFAULT false,
  clicked_at timestamptz,
  click_count integer NOT NULL DEFAULT 0,
  unsubscribed boolean NOT NULL DEFAULT false,
  is_unsubscribed boolean NOT NULL DEFAULT false,
  unsubscribed_at timestamptz,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_wp_campaign_contacts_campaign_id FOREIGN KEY (org_id, campaign_id) REFERENCES wpcampaigns (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_wp_campaign_contacts_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id)
);
CREATE INDEX idx_wp_campaign_contacts_campaign_id_status_send_attempts ON wp_campaign_contacts (org_id, campaign_id, status, send_attempts);
CREATE INDEX idx_wp_campaign_contacts_contact_id ON wp_campaign_contacts (org_id, contact_id);
CREATE INDEX idx_wp_campaign_contacts_next_attempt_at ON wp_campaign_contacts (org_id, next_attempt_at);
CREATE INDEX idx_wp_campaign_contacts_tracking_id ON wp_campaign_contacts (org_id, tracking_id);

ALTER TABLE wp_campaign_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE wp_campaign_contacts FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wp_campaign_contacts FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wp_campaign_contacts_touch BEFORE UPDATE ON wp_campaign_contacts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- foreign key from broadcasts (bcast), whose migration runs earlier than this table exists
ALTER TABLE wa_link_clicks ADD CONSTRAINT fk_wa_link_clicks_campaign_id FOREIGN KEY (org_id, campaign_id) REFERENCES wpcampaigns (org_id, id) ON DELETE SET NULL (campaign_id);
