-- wallet: wallet-message-billing data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's wallet message billing features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: message_rates, wallet_transactions, usage_charges, wallets

-- WaDesk `message_rates` (global_read; 16 rows in the reference DB)
CREATE TABLE message_rates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  country_code text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT '',
  credits integer NOT NULL DEFAULT 1,
  meta_cost_minor bigint,
  currency text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_message_rates_country_code_category UNIQUE (country_code, category)
);

ALTER TABLE message_rates ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_rates FORCE  ROW LEVEL SECURITY;
CREATE POLICY read_all ON message_rates FOR SELECT USING (true);
CREATE POLICY operator_write ON message_rates FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_message_rates_touch BEFORE UPDATE ON message_rates
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `wallet_transactions` (child; 0 rows in the reference DB)
CREATE TABLE wallet_transactions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  kind text NOT NULL,
  type text NOT NULL,
  amount numeric(20,4) NOT NULL,
  balance_after numeric(20,4) NOT NULL,
  source text,
  subject_type text,
  subject_id bigint,
  description text,
  meta jsonb,
  idempotency_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wallet_transactions_idempotency_key UNIQUE (org_id, idempotency_key),
  CONSTRAINT fk_wallet_transactions_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_wallet_transactions_kind_source ON wallet_transactions (org_id, kind, source);
CREATE INDEX idx_wallet_transactions_subject_type_subject_id ON wallet_transactions (org_id, subject_type, subject_id);
CREATE INDEX idx_wallet_transactions_user_id_created_at ON wallet_transactions (org_id, user_id, created_at);

ALTER TABLE wallet_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE wallet_transactions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wallet_transactions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wallet_transactions_touch BEFORE UPDATE ON wallet_transactions
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `usage_charges` (stream; 0 rows in the reference DB)
CREATE SEQUENCE usage_charges_id_seq;
CREATE TABLE usage_charges (
  id bigint NOT NULL DEFAULT nextval('usage_charges_id_seq'),
  org_id bigint NOT NULL,
  user_id bigint,
  provider text,
  wamid text NOT NULL,
  to_country text,
  category text,
  source text,
  credits integer NOT NULL DEFAULT 0,
  revenue_minor bigint NOT NULL DEFAULT 0,
  cost_minor bigint,
  status text NOT NULL DEFAULT 'charged',
  wallet_tx_id bigint,
  meta text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at),
  CONSTRAINT chk_usage_charges_status CHECK (status IN ('free', 'charged', 'refunded'))
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_usage_charges_status ON usage_charges (org_id, status);
CREATE INDEX idx_usage_charges_user_id ON usage_charges (org_id, user_id);
CREATE INDEX idx_usage_charges_created_at ON usage_charges (org_id, created_at);

ALTER TABLE usage_charges ENABLE ROW LEVEL SECURITY;
ALTER TABLE usage_charges FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON usage_charges FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- WaDesk `wallets` (tenant; 0 rows in the reference DB)
CREATE TABLE wallets (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  unit text NOT NULL,
  balance numeric(20,4) NOT NULL DEFAULT 0,
  reserved numeric(20,4) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_wallet_invariant CHECK (balance >= 0 AND reserved >= 0 AND reserved <= balance),
  CONSTRAINT uq_wallets_unit UNIQUE (org_id, unit)
);

ALTER TABLE wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE wallets FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wallets FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wallets_touch BEFORE UPDATE ON wallets
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Bootstrap partitions (previous month, current, next two) and a catch-all so a gap in partition
-- maintenance degrades into rows landing in _default instead of failed writes. Add each parent to
-- PARTITIONED_TABLES in apps/api/src/workers/partition-maintenance.service.ts.
DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('usage_charges', m);
  END LOOP;
END $$;
CREATE TABLE usage_charges_default PARTITION OF usage_charges DEFAULT;
