-- 0017_add_contact_detail_tables
-- Contact detail page tabs: Notes, Files, Activity Timeline, Meetings.
-- docs/global-schema-design.dbml lines 527-583, minus contact_tasks
-- (stays stubbed — Phase 14's Tasks module owns this, see phase-plan.md's
-- circular-dependency note) and contact_field_history (redundant with
-- audit_log, which already captures a delta per field on every write).

CREATE TABLE contact_notes (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id  bigint NOT NULL,
  body        text NOT NULL,
  created_by  bigint,
  updated_by  bigint,
  row_version integer NOT NULL DEFAULT 1,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, created_by) REFERENCES users    (org_id, id) ON DELETE SET NULL,
  FOREIGN KEY (org_id, updated_by) REFERENCES users    (org_id, id) ON DELETE SET NULL
);
CREATE INDEX idx_contact_notes_contact ON contact_notes (org_id, contact_id, created_at DESC);

-- Metadata only — actual byte storage is Phase 9 (File Manager)'s job.
-- storage_key is caller-supplied (wherever the bytes actually ended up);
-- immutable once created, so no row_version.
CREATE TABLE contact_files (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id      bigint NOT NULL,
  file_name       text NOT NULL,
  file_size_bytes bigint,
  storage_key     text NOT NULL,
  mime_type       text,
  uploaded_by     bigint,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id)  REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, uploaded_by) REFERENCES users    (org_id, id) ON DELETE SET NULL
);
CREATE INDEX idx_contact_files_contact ON contact_files (org_id, contact_id, created_at DESC);

-- Append-only timeline. 'source' distinguishes a manual note-to-self from a
-- system/bot-generated entry (stage change, form submission, ...) — no
-- automated writer exists yet, this just leaves room for one. Never edited,
-- so no row_version.
CREATE TABLE contact_activities (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id    bigint NOT NULL,
  activity_type text NOT NULL,
  title         text NOT NULL,
  body          text,
  source        text NOT NULL DEFAULT 'user',
  actor_id      bigint,
  occurred_at   timestamptz NOT NULL DEFAULT now(),
  created_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, actor_id)   REFERENCES users    (org_id, id) ON DELETE SET NULL,
  CONSTRAINT chk_contact_activities_source CHECK (source IN ('system', 'user', 'bot'))
);
CREATE INDEX idx_contact_activities_contact ON contact_activities (org_id, contact_id, occurred_at DESC);

CREATE TABLE contact_meetings (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id  bigint NOT NULL,
  title       text NOT NULL,
  starts_at   timestamptz,
  ends_at     timestamptz,
  location    text,
  created_by  bigint,
  row_version integer NOT NULL DEFAULT 1,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, created_by) REFERENCES users    (org_id, id) ON DELETE SET NULL
);
CREATE INDEX idx_contact_meetings_contact ON contact_meetings (org_id, contact_id, starts_at DESC);

DO $$
DECLARE
  t text;
  new_tables text[] := ARRAY['contact_notes', 'contact_files', 'contact_activities', 'contact_meetings'];
BEGIN
  FOREACH t IN ARRAY new_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
        FOR ALL
        USING      (org_id = current_org_id() OR app_is_privileged())
        WITH CHECK (org_id = current_org_id() OR app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
  END LOOP;
END $$;

