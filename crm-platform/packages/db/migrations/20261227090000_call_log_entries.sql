CREATE TABLE call_logging_settings (
  org_id                                bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  -- A number nobody knows becomes a contact when a call from it is reported (off: the call is not stored, so a personal call on a
  -- salesperson's phone never creates a record about a stranger).
  create_contacts_from_unknown_callers  boolean NOT NULL DEFAULT false,
  -- How long the person who logged a call may still edit or delete it.
  edit_window_hours                     integer NOT NULL DEFAULT 24,
  updated_by                            bigint,
  created_at                            timestamptz NOT NULL DEFAULT now(),
  updated_at                            timestamptz NOT NULL DEFAULT now(),
  row_version                           integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT fk_call_logging_settings_updated_by FOREIGN KEY (org_id, updated_by) REFERENCES users (org_id, id) ON DELETE SET NULL (updated_by),
  CONSTRAINT ck_call_logging_settings_window CHECK (edit_window_hours BETWEEN 1 AND 720)
);
