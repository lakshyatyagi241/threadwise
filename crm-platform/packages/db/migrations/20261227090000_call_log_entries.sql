-- call-logging: one record of every call that is NOT a WhatsApp call (the unified Call logs framework).
-- Why this migration exists. Until now only WhatsApp business calls (`wa_calls`, Meta's direction vocabulary) were logged. A call a person
-- makes or takes by any other means left no trace: nobody could log a call they just had, a telephony/IVR provider's calls were lost, a call
-- placed from the phone's own dialer by tapping a number in the mobile app was lost, and a click-to-call from the web was lost. The CRM's
-- timeline and the Call logs screen therefore showed only the WhatsApp half of a customer's phone history.
--
--   call_log_entries        one row per such call. `source` says how it got here (manual | telephony | mobile_app | web_click_to_call), `outcome`
--                           what came of it. (org, source, external_id) is unique: the provider's call id, or the device id plus the
--                           device's call id, so a redelivered webhook or a re-sent mobile batch lands once.
--   call_logging_settings   one row per workspace: whether an unknown caller becomes a contact (off by default), and how long the person
--                           who logged a call may still edit or delete it.
--   telephony_connections   a workspace's link to a telephony provider: its provider key, a label, the numbers it serves and the secret that
--                           signs the provider's status callbacks (kept encrypted by the application; shown once). No provider
--                           credentials are stored: calls are only ever REPORTED to us, or bridged through an adapter that holds its own.
--   telephony_click_calls   a click-to-call we asked a provider to bridge: who clicked, which contact, which number. The provider's completion
--                           callback names only its call id, so this is how the finished call gets its handler and contact back.
--
-- Recording. `recording_ref` is a REFERENCE on the provider's side, never audio, and it is stored only after the ConsentGate allowed it
-- (call_recording purpose: the workspace switch on, a delivered notice, the person's agreement). The retention sweep clears it after the
-- workspace's window like it clears a WhatsApp recording. Nothing here stores or plays a file.
--
-- Additive: nothing is backfilled and no existing statement is touched.

CREATE TABLE telephony_connections (
  org_id                 bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                     bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                   uuid NOT NULL DEFAULT gen_random_uuid(),
  provider               text NOT NULL,
  label                  text NOT NULL,
  -- The workspace's own numbers this provider serves, E.164 with the plus: an inbound call to one of them is ours, and the label on the log.
  numbers                text[] NOT NULL DEFAULT '{}',
  -- The key that signs the provider's callbacks, encrypted with the application key. The hint is its last four characters, for the screen.
  webhook_secret_cipher  text NOT NULL,
  secret_hint            text NOT NULL,
  -- The workspace attests that its IVR or dialer plays the recording notice before it records (the "announcement" consent mode).
  plays_recording_notice boolean NOT NULL DEFAULT false,
  status                 text NOT NULL DEFAULT 'active',
  last_event_at          timestamptz,
  created_by             bigint,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  row_version            integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_telephony_connections_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT ck_telephony_connections_provider CHECK (provider ~ '^[a-z][a-z0-9_]{1,31}$'),
  CONSTRAINT ck_telephony_connections_label CHECK (char_length(btrim(label)) BETWEEN 1 AND 80),
  CONSTRAINT ck_telephony_connections_status CHECK (status IN ('active', 'disabled')),
  CONSTRAINT ck_telephony_connections_numbers CHECK (cardinality(numbers) <= 20)
);
CREATE INDEX idx_telephony_connections_org ON telephony_connections (org_id, created_at DESC);

ALTER TABLE telephony_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE telephony_connections FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON telephony_connections FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_telephony_connections_touch BEFORE UPDATE ON telephony_connections
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A provider's callback names the connection in its address and nothing about the workspace, and there is no session: this finds the
-- connection (and so the workspace and the secret to check the signature with) the way `sms_sender_by_dlr_secret` does for SMS.
CREATE OR REPLACE FUNCTION telephony_connection_for_webhook(p_uuid uuid)
RETURNS TABLE (conn_org_id bigint, conn_id bigint, conn_provider text, conn_secret_cipher text, conn_status text, conn_plays_notice boolean)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT c.org_id, c.id, c.provider, c.webhook_secret_cipher, c.status, c.plays_recording_notice
    FROM telephony_connections c
    WHERE c.uuid = p_uuid
    LIMIT 1;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION telephony_connection_for_webhook(uuid) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION telephony_connection_for_webhook(uuid) TO crm_app_user;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_worker_user') THEN
    GRANT EXECUTE ON FUNCTION telephony_connection_for_webhook(uuid) TO crm_worker_user;
  END IF;
END
$$;

CREATE TABLE call_log_entries (
  org_id                    bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                        bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                      uuid NOT NULL DEFAULT gen_random_uuid(),
  source                    text NOT NULL,
  -- inbound: the customer called us. outbound: we called the customer.
  direction                 text NOT NULL,
  outcome                   text NOT NULL,
  started_at                timestamptz NOT NULL,
  duration_sec              integer NOT NULL DEFAULT 0,
  contact_id                bigint,
  -- The customer's number as E.164 with the plus; null for a caller who withheld it (a provider can report one).
  customer_phone            text,
  -- The workspace's own number and the label it carries on the log ("Sales line").
  our_phone                 text,
  number_label              text,
  -- The teammate who took or made the call.
  handler_user_id           bigint,
  notes                     text,
  external_id               text,
  telephony_connection_id   bigint,
  recording_ref             text,
  recording_stored_at       timestamptz,
  recording_consent_status  text,
  recording_consent_method  text,
  recording_notice_version  integer,
  recording_deleted_at      timestamptz,
  follow_up_task_id         bigint,
  -- The line this call wrote on the contact's Activity Timeline (kept in step when the entry is edited, removed when it is deleted).
  activity_id               bigint,
  created_by                bigint,
  created_at                timestamptz NOT NULL DEFAULT now(),
  updated_at                timestamptz NOT NULL DEFAULT now(),
  row_version               integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- One row per call as the source names it. NULLs are distinct, so entries typed by hand (no external id) never collide.
  CONSTRAINT uq_call_log_entries_external UNIQUE (org_id, source, external_id),
  CONSTRAINT fk_call_log_entries_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_call_log_entries_handler FOREIGN KEY (org_id, handler_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (handler_user_id),
  CONSTRAINT fk_call_log_entries_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT fk_call_log_entries_task FOREIGN KEY (org_id, follow_up_task_id) REFERENCES tasks (org_id, id) ON DELETE SET NULL (follow_up_task_id),
  CONSTRAINT fk_call_log_entries_activity FOREIGN KEY (org_id, activity_id) REFERENCES contact_activities (org_id, id) ON DELETE SET NULL (activity_id),
  CONSTRAINT fk_call_log_entries_connection FOREIGN KEY (org_id, telephony_connection_id) REFERENCES telephony_connections (org_id, id) ON DELETE SET NULL (telephony_connection_id),
  CONSTRAINT ck_call_log_entries_source CHECK (source IN ('manual', 'telephony', 'mobile_app', 'web_click_to_call')),
  CONSTRAINT ck_call_log_entries_direction CHECK (direction IN ('inbound', 'outbound')),
  CONSTRAINT ck_call_log_entries_outcome CHECK (outcome IN ('connected', 'no_answer', 'busy', 'left_voicemail', 'wrong_number', 'declined', 'failed')),
  CONSTRAINT ck_call_log_entries_duration CHECK (duration_sec BETWEEN 0 AND 86400),
  CONSTRAINT ck_call_log_entries_phone CHECK (customer_phone IS NULL OR customer_phone ~ '^\+[1-9][0-9]{6,14}$'),
  CONSTRAINT ck_call_log_entries_notes CHECK (notes IS NULL OR char_length(notes) <= 2000),
  CONSTRAINT ck_call_log_entries_external CHECK (external_id IS NULL OR char_length(external_id) BETWEEN 1 AND 200),
  CONSTRAINT ck_call_log_entries_label CHECK (number_label IS NULL OR char_length(number_label) <= 80),
  CONSTRAINT ck_call_log_entries_recording_consent CHECK (recording_consent_status IS NULL OR recording_consent_status IN ('granted', 'declined')),
  -- A reference to a recording is never kept without the consent evidence that allowed it. (A CHECK passes on NULL, so each part says
  -- IS NOT NULL out loud: a missing status must fail, not pass.)
  CONSTRAINT ck_call_log_entries_recording_needs_consent CHECK (
    recording_ref IS NULL OR (recording_consent_status IS NOT NULL AND recording_consent_status = 'granted' AND recording_notice_version IS NOT NULL))
);
-- The log: newest first inside a window of days, and the by-teammate analytics.
CREATE INDEX idx_call_log_entries_started ON call_log_entries (org_id, started_at DESC, id DESC);
CREATE INDEX idx_call_log_entries_contact ON call_log_entries (org_id, contact_id, started_at DESC) WHERE contact_id IS NOT NULL;
CREATE INDEX idx_call_log_entries_handler ON call_log_entries (org_id, handler_user_id, started_at DESC) WHERE handler_user_id IS NOT NULL;
-- The retention sweep.
CREATE INDEX idx_call_log_entries_recording ON call_log_entries (recording_stored_at) WHERE recording_ref IS NOT NULL;
-- Cleanup of a task or an activity that points back here.
CREATE INDEX idx_call_log_entries_task ON call_log_entries (org_id, follow_up_task_id) WHERE follow_up_task_id IS NOT NULL;
CREATE INDEX idx_call_log_entries_activity ON call_log_entries (org_id, activity_id) WHERE activity_id IS NOT NULL;

