-- wfl: forms-links-groups data model, ported from Reference
-- Why this migration exists: the tables Reference's forms links groups features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: wa_chat_links, wa_forms, wa_form_submissions, wa_groups, wa_group_members

-- Reference `wa_chat_links` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_chat_links (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  name text NOT NULL,
  slug text NOT NULL,
  country_code text NOT NULL,
  phone_number text NOT NULL,
  welcome_message text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  click_count bigint NOT NULL DEFAULT 0,
  last_clicked_at timestamptz,
  expires_at timestamptz,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_chat_links_slug UNIQUE (slug),
  CONSTRAINT fk_wa_chat_links_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_wa_chat_links_user_id ON wa_chat_links (org_id, user_id);
CREATE INDEX idx_wa_chat_links_status ON wa_chat_links (org_id, status);

ALTER TABLE wa_chat_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_chat_links FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_chat_links FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_chat_links_touch BEFORE UPDATE ON wa_chat_links
  FOR EACH ROW EXECUTE FUNCTION touch_row();

