-- consent: asynchronous export of the consent proof. The synchronous CSV stops at 50,000 rows; a larger ledger is built by the worker
-- (queue `consent-export`), stored gzipped on this row for 7 days, and the requester is mailed a link to the page that offers it.
-- Not a Reference feature (see docs/specs/contact-consent-ledger.md). Same shape as `message_log_exports`.
--
-- One row per requested export; the row stays (status `expired`) after the file is deleted, so the page can still say it was made.

CREATE TABLE contact_consent_exports (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  requested_by  bigint NOT NULL,
  -- Where the "your export is ready" mail went; kept so the page can say it even after the user changes address.
  emailed_to    text,
  status        text NOT NULL DEFAULT 'queued',
  row_count     integer,
  file_name     text,
  file_bytes    integer,
  file_gz       bytea,
  error         text,
  requested_at  timestamptz NOT NULL DEFAULT now(),
  started_at    timestamptz,
  completed_at  timestamptz,
  expires_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, requested_by) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_contact_consent_exports_status CHECK (status IN ('queued', 'running', 'ready', 'failed', 'expired'))
);
CREATE INDEX idx_contact_consent_exports_org ON contact_consent_exports (org_id, requested_at DESC);
-- The daily sweep finds files past their time and exports whose worker died.
CREATE INDEX idx_contact_consent_exports_expiry ON contact_consent_exports (expires_at) WHERE status = 'ready';
CREATE INDEX idx_contact_consent_exports_running ON contact_consent_exports (started_at) WHERE status = 'running';

ALTER TABLE contact_consent_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_consent_exports FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_consent_exports FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_contact_consent_exports_touch BEFORE UPDATE ON contact_consent_exports
  FOR EACH ROW EXECUTE FUNCTION touch_row();
