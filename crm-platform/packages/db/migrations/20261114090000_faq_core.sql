-- faq: the FAQ knowledge base with semantic matching (ADR-0021). Not a Reference table set: Reference has no FAQ feature.
--
-- Tables: faq_settings (one row per workspace), faqs, faq_variations (the text and its pgvector embedding), faq_match_logs.
--
-- Why a vector column on the variation row and no ANN index: see ADR-0021. A workspace holds hundreds to a few thousand
-- variations, so the matcher scans `(org_id)` exactly; an HNSW index is added only past ~50k rows in one workspace.
-- Why halfvec(3072): the two best embedding models measured (openai/text-embedding-3-large, google/gemini-embedding-2)
-- answer in 3072 dimensions, halfvec halves the storage and the loss is far below the gap between matches and non-matches.

-- The extension is created (guarded) by 0001_extensions; this migration needs it, so fail loudly if it is missing.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector') THEN
    CREATE EXTENSION vector;
  END IF;
END $$;

-- ---------------------------------------------------------------------------------------------------------------------
-- faq_settings: the workspace's switch and matching knobs. No row means "not enabled, defaults".
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE faq_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  enabled boolean NOT NULL DEFAULT false,
  -- Cosine similarity the best variation must reach. Default for the platform's default embedding model.
  threshold numeric(4,3) NOT NULL DEFAULT 0.450,
  -- How far the best FAQ must lead the runner-up FAQ; 0 switches the check off.
  min_margin numeric(4,3) NOT NULL DEFAULT 0.000,
  -- Keep the customer's text in faq_match_logs. Off: only scores and outcomes are kept.
  log_queries boolean NOT NULL DEFAULT true,
  -- The embedding model in force when the workspace last saved. Similarity scores are not comparable between models (the same
  -- 0.45 is 97% precise on one and 71% on another), so the screens warn when the platform has changed the model since.
  tuned_model text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT ck_faq_settings_threshold CHECK (threshold BETWEEN 0.050 AND 0.990),
  CONSTRAINT ck_faq_settings_margin CHECK (min_margin BETWEEN 0.000 AND 0.500)
);

ALTER TABLE faq_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE faq_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON faq_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_faq_settings_touch BEFORE UPDATE ON faq_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- faqs: a question and what answers it (a text, or a flow that starts).
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE faqs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  question text NOT NULL,
  answer_type text NOT NULL DEFAULT 'text',
  answer_text text,
  flow_id bigint,
  category text,
  status text NOT NULL DEFAULT 'active',
  -- Overrides the workspace threshold for this FAQ only (a sensitive one can demand more); null = use the workspace's.
  -- There is no hit counter here on purpose: a counter UPDATE would fire touch_row and bump row_version on every customer match,
  -- so an editor would get a 409 for a change nobody made. Hits are counted from faq_match_logs (idx_faq_match_logs_faq).
  threshold_override numeric(4,3),
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT ck_faqs_answer_type CHECK (answer_type IN ('text', 'flow')),
  CONSTRAINT ck_faqs_status CHECK (status IN ('active', 'paused')),
  CONSTRAINT ck_faqs_answer_shape CHECK (
    (answer_type = 'text' AND answer_text IS NOT NULL AND btrim(answer_text) <> '')
    OR (answer_type = 'flow')
  ),
  CONSTRAINT ck_faqs_threshold_override CHECK (threshold_override IS NULL OR threshold_override BETWEEN 0.050 AND 0.990),
  CONSTRAINT fk_faqs_flow FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE SET NULL (flow_id),
  CONSTRAINT fk_faqs_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_faqs_status ON faqs (org_id, status);
CREATE INDEX idx_faqs_flow ON faqs (org_id, flow_id) WHERE flow_id IS NOT NULL;
CREATE INDEX idx_faqs_category ON faqs (org_id, category) WHERE category IS NOT NULL;
CREATE UNIQUE INDEX uq_faqs_question ON faqs (org_id, lower(btrim(question)));

ALTER TABLE faqs ENABLE ROW LEVEL SECURITY;
ALTER TABLE faqs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON faqs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_faqs_touch BEFORE UPDATE ON faqs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- faq_variations: every phrasing of a question that should reach the FAQ, with its embedding.
-- The question itself is stored as a variation with source 'question' (kept in step by the service), so a match needs one table.
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE faq_variations (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  faq_id bigint NOT NULL,
  text text NOT NULL,
  source text NOT NULL DEFAULT 'manual',
  -- pending: needs (re-)embedding; ready: embedding belongs to embedding_model; failed: gave up after embed_attempts.
  embed_state text NOT NULL DEFAULT 'pending',
  embedding halfvec(3072),
  embedding_model text,
  embedded_at timestamptz,
  embed_attempts smallint NOT NULL DEFAULT 0,
  embed_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT ck_faq_variations_source CHECK (source IN ('question', 'manual', 'ai', 'import', 'learned')),
  CONSTRAINT ck_faq_variations_state CHECK (embed_state IN ('pending', 'ready', 'failed')),
  CONSTRAINT ck_faq_variations_ready CHECK (embed_state <> 'ready' OR (embedding IS NOT NULL AND embedding_model IS NOT NULL)),
  CONSTRAINT fk_faq_variations_faq FOREIGN KEY (org_id, faq_id) REFERENCES faqs (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_faq_variations_faq ON faq_variations (org_id, faq_id);
-- The embed worker's queue: only the rows that still need work.
CREATE INDEX idx_faq_variations_pending ON faq_variations (org_id, id) WHERE embed_state = 'pending';
CREATE UNIQUE INDEX uq_faq_variations_text ON faq_variations (org_id, faq_id, lower(btrim(text)));

ALTER TABLE faq_variations ENABLE ROW LEVEL SECURITY;
ALTER TABLE faq_variations FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON faq_variations FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_faq_variations_touch BEFORE UPDATE ON faq_variations
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- faq_match_logs: one row per match decision, for the "why" view, the unanswered list and threshold tuning.
-- Append-only, swept after 90 days by FaqRetentionService. Not partitioned: the sweep is a bounded delete, and the table stays
-- small because only customer-typed text messages of enabled workspaces write to it.
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE faq_match_logs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- inbound: a customer's message; test: the playground (never answers anybody).
  origin text NOT NULL DEFAULT 'inbound',
  conversation_id bigint,
  channel_id bigint,
  -- Null when the workspace switched query logging off.
  query text,
  query_length integer NOT NULL DEFAULT 0,
  -- answered: a text was sent; flow_started; below_threshold; low_margin; no_faqs; provider_error (fell back to trigram);
  -- not_sent: matched but the reply could not be queued (window closed, channel down).
  outcome text NOT NULL,
  -- exact, semantic or trigram: which tier decided.
  tier text,
  matched_faq_id bigint,
  score numeric(5,4),
  second_score numeric(5,4),
  matched_text text,
  -- The top candidates [{faqUuid, question, score, text}], so the screen can show the near misses.
  candidates jsonb NOT NULL DEFAULT '[]',
  embedding_model text,
  latency_ms integer,
  error text,
  -- Set once a person turned this unanswered query into a variation or a new FAQ.
  resolved_at timestamptz,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT ck_faq_match_logs_origin CHECK (origin IN ('inbound', 'test')),
  CONSTRAINT ck_faq_match_logs_outcome CHECK (
    outcome IN ('answered', 'flow_started', 'below_threshold', 'low_margin', 'no_faqs', 'provider_error', 'not_sent')
  ),
  CONSTRAINT fk_faq_match_logs_faq FOREIGN KEY (org_id, matched_faq_id) REFERENCES faqs (org_id, id) ON DELETE SET NULL (matched_faq_id)
);
CREATE INDEX idx_faq_match_logs_created ON faq_match_logs (org_id, created_at DESC);
CREATE INDEX idx_faq_match_logs_faq ON faq_match_logs (org_id, matched_faq_id, created_at DESC) WHERE matched_faq_id IS NOT NULL;
-- The "unanswered" list: inbound queries nothing answered and nobody handled yet.
CREATE INDEX idx_faq_match_logs_unanswered ON faq_match_logs (org_id, created_at DESC)
  WHERE origin = 'inbound' AND outcome IN ('below_threshold', 'low_margin', 'no_faqs') AND resolved_at IS NULL;

ALTER TABLE faq_match_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE faq_match_logs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON faq_match_logs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
