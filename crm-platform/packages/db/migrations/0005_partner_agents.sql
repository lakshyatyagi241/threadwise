-- 0005_partner_agents
-- Sub-agents / channel partners, and the API-key surface they (and any other
-- external system) authenticate with.
--
-- Why a separate identity pool instead of a role on `users` (ADR-0014):
-- sub-agents are external parties. Putting them in the staff table means one
-- forgotten filter away from an external agent appearing in an assignment
-- dropdown, an SLA report, or a team inbox. A separate table makes that class
-- of bug impossible rather than merely unlikely.

CREATE TABLE partner_agents (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Shown on the lead as "Submitted by", e.g. AG-SHUBHAM
  code          text NOT NULL,
  name          text NOT NULL,
  email         citext NOT NULL,
  phone         text,
  password_hash text,
  status        partner_agent_status NOT NULL DEFAULT 'active',
  -- Commission %, region, allowed colleges — partner terms, not platform config.
  settings      jsonb NOT NULL DEFAULT '{}',
  last_login_at timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, email),
  UNIQUE (org_id, code)
);

-- The id mapping agreed in the requirements call: the partner portal stores
-- ONLY this row. Name, stage and everything else are read live from the CRM on
-- open, so there is exactly one source of truth for a lead's stage and no
-- two-way sync to keep honest.
CREATE TABLE partner_agent_leads (
  org_id       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  agent_id     bigint NOT NULL,
  contact_id   bigint NOT NULL,
  -- Snapshot of what the agent typed, kept verbatim. If staff later correct
  -- the contact, this still shows what was originally submitted — which is
  -- what a commission dispute actually turns on.
  submitted_payload jsonb NOT NULL DEFAULT '{}',
  college_tag  text,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  -- One agent cannot claim the same contact twice; two different agents
  -- submitting the same person is allowed and is exactly the duplicate case
  -- the review queue exists for.
  UNIQUE (org_id, agent_id, contact_id),
  FOREIGN KEY (org_id, agent_id)   REFERENCES partner_agents (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts       (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_partner_leads_agent   ON partner_agent_leads (org_id, agent_id, submitted_at DESC, id DESC);
CREATE INDEX idx_partner_leads_contact ON partner_agent_leads (org_id, contact_id);

-- Denormalised pointer so staff-side list views can show "Submitted by" without
-- a join, and so lead attribution survives even if the mapping row is purged.
ALTER TABLE contacts ADD COLUMN submitted_by_agent_id bigint;
ALTER TABLE contacts ADD CONSTRAINT fk_contacts_submitted_by_agent
  FOREIGN KEY (org_id, submitted_by_agent_id) REFERENCES partner_agents (org_id, id) ON DELETE SET NULL;
CREATE INDEX idx_contacts_submitted_by ON contacts (org_id, submitted_by_agent_id)
  WHERE submitted_by_agent_id IS NOT NULL;

-- --- API keys --------------------------------------------------------------
-- Not in the original diagram; required the moment anything outside the
-- platform calls in (partner portal backend, the legacy Geta bridge, a
-- college's own system).
CREATE TABLE api_keys (
  org_id       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid         uuid NOT NULL DEFAULT gen_random_uuid(),
  name         text NOT NULL,
  -- Public, non-secret lookup prefix (e.g. "pk_live_7f3a"). Indexed, sent in
  -- the clear, used to find the row before verifying the secret.
  key_prefix   text NOT NULL,
  -- Argon2 hash of the secret half. The plaintext is shown exactly once, at
  -- creation, and is never recoverable afterwards.
  key_hash     text NOT NULL,
  -- HMAC signing secret for request signatures, encrypted at the application
  -- layer before it is written here.
  signing_secret_enc text NOT NULL,
  scopes       text[] NOT NULL DEFAULT '{}',
  status       api_key_status NOT NULL DEFAULT 'active',
  rate_limit_per_minute integer NOT NULL DEFAULT 120,
  last_used_at timestamptz,
  expires_at   timestamptz,
  created_by   bigint,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  row_version  integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid)
);
-- Global unique: a prefix must resolve to one org without knowing the org yet.
CREATE UNIQUE INDEX uq_api_keys_prefix ON api_keys (key_prefix);
CREATE INDEX idx_api_keys_org_status ON api_keys (org_id, status);

CREATE TRIGGER trg_partner_agents_touch BEFORE UPDATE ON partner_agents FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_api_keys_touch       BEFORE UPDATE ON api_keys       FOR EACH ROW EXECUTE FUNCTION touch_row();
