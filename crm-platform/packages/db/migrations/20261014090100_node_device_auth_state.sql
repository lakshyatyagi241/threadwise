-- node: the saved WhatsApp session of a device (WD-NODE-011, 007)
-- Why this migration exists: WaDesk's bridge kept each paired number's session as files in `baileys_auth/session_<phone>/` on
-- one server's disk, so a second server, a redeploy or a lost disk meant every customer scanning a QR again. A session is the
-- device's credentials plus its signal keys; here each one is a row, encrypted by the application, so any worker can adopt a
-- device (the Redis lease decides which). Hard delete: forgetting a session is the point of a logout.

CREATE TABLE device_auth_state (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  device_id bigint NOT NULL,
  -- `creds`, or `<type>-<id>` for a signal key (the names Baileys' multi-file store uses)
  name text NOT NULL,
  -- encrypted JSON
  value text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_device_auth_state_device_name UNIQUE (org_id, device_id, name),
  FOREIGN KEY (org_id, device_id) REFERENCES devices (org_id, id) ON DELETE CASCADE
);

ALTER TABLE device_auth_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE device_auth_state FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON device_auth_state FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_device_auth_state_touch BEFORE UPDATE ON device_auth_state
  FOR EACH ROW EXECUTE FUNCTION touch_row();
