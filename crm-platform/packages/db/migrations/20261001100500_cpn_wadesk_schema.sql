-- cpn: coupons-credits-referral-currency data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's coupons credits referral currency features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: coupons, credit_packages, currencies, referrals, referral_codes

-- WaDesk `coupons` (platform_only; 2 rows in the reference DB)
CREATE TABLE coupons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  code text NOT NULL,
  description text,
  admin_note text,
  type text NOT NULL DEFAULT 'percent',
  amount numeric(12,4) NOT NULL DEFAULT 0.0000,
  currency_code text,
  max_discount_amount numeric(14,4),
  min_order_amount numeric(12,4),
  max_uses integer,
  per_user_limit integer,
  uses_count integer NOT NULL DEFAULT 0,
  applicable_package_ids jsonb,
  starts_at timestamptz,
  expires_at timestamptz,
  is_active boolean NOT NULL DEFAULT true,
  first_purchase_only boolean NOT NULL DEFAULT false,
  stackable_with_other boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_coupons_code UNIQUE (code)
);
CREATE INDEX idx_coupons_is_active_expires_at ON coupons (is_active, expires_at);

ALTER TABLE coupons ENABLE ROW LEVEL SECURITY;
ALTER TABLE coupons FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON coupons FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_coupons_touch BEFORE UPDATE ON coupons
  FOR EACH ROW EXECUTE FUNCTION touch_row();

