-- fb: channel-facebook data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's channel facebook features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: facebook_pages, facebook_posts, facebook_broadcasts, facebook_broadcast_recipients

-- WaDesk `facebook_pages` (tenant; 0 rows in the reference DB)
CREATE TABLE facebook_pages (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  page_id text NOT NULL,
  name text,
  category text,
  username text,
  picture_url text,
  access_token text,  -- encrypted
  token_expires_at timestamptz,
  data_access_expires_at timestamptz,
  scopes jsonb,
  tasks jsonb,
  status text NOT NULL DEFAULT 'connected',
  connect_method text NOT NULL DEFAULT 'oauth',
  fan_count bigint,
  last_error text,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_facebook_pages_page_id UNIQUE (org_id, page_id),
  CONSTRAINT fk_facebook_pages_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);

ALTER TABLE facebook_pages ENABLE ROW LEVEL SECURITY;
ALTER TABLE facebook_pages FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON facebook_pages FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_facebook_pages_touch BEFORE UPDATE ON facebook_pages
  FOR EACH ROW EXECUTE FUNCTION touch_row();

