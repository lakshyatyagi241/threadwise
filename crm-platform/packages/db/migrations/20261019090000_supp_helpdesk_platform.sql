-- supp: the platform-owned half of the helpdesk (agents, playbooks, SLA) and the operator columns of the platform inbox.
-- Why this migration exists: Reference keeps `support_agents`, `playbooks` and the helpdesk's SLA policies as tenant-style rows (a
-- nullable workspace_id that is always NULL, `sla_policies` shared with the workspace SLA of TIB2), and its inbox actions write a
-- tenant `users` id. Here the helpdesk's staff are platform operators (separate identity pool), so:
--   * support_agent_roster, support_playbooks and support_sla_policies are platform-layer tables (privileged only, no org_id).
--     The helpdesk's SLA policies get their own table so that setting a default can never clear a workspace's policy (Reference's
--     "default-policy clobber", inventory open question 4) and a deleted policy can never delete a workspace's.
--   * support_sla_breaches is the breach ledger of tickets. It is unique per (ticket, breach type), so the scanner is idempotent
--     in the database instead of by a racing exists() check.
--   * platform_notes and workspace_flags record WHICH OPERATOR acted (their *_user_id columns reference tenant users).

-- --- the agent roster -------------------------------------------------------------------------------------------------------------

CREATE TABLE support_agent_roster (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid         uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  operator_id  bigint NOT NULL UNIQUE REFERENCES platform_operators (id) ON DELETE CASCADE,
  is_active    boolean NOT NULL DEFAULT true,
  specialty    text,
  -- Kept for parity with Reference's column; nothing maintains it (TW-SUPP-019 is docs-only there and here).
  current_load integer NOT NULL DEFAULT 0,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  row_version  integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_support_agent_roster_specialty CHECK (specialty IS NULL OR length(specialty) <= 60),
  CONSTRAINT chk_support_agent_roster_load CHECK (current_load >= 0)
);

-- --- playbooks --------------------------------------------------------------------------------------------------------------------

CREATE TABLE support_playbooks (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  name          text NOT NULL,
  slug          text NOT NULL UNIQUE,
  trigger_type  text NOT NULL DEFAULT 'manual',
  trigger_value text,
  steps         jsonb NOT NULL DEFAULT '[]'::jsonb,
  is_active     boolean NOT NULL DEFAULT true,
  use_count     integer NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_support_playbooks_name CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT chk_support_playbooks_trigger_type CHECK (trigger_type IN ('manual', 'status_change', 'tag_added')),
  CONSTRAINT chk_support_playbooks_trigger_value CHECK (trigger_value IS NULL OR length(trigger_value) <= 120),
  CONSTRAINT chk_support_playbooks_steps CHECK (jsonb_typeof(steps) = 'array'),
  CONSTRAINT chk_support_playbooks_use_count CHECK (use_count >= 0)
);

-- --- SLA policies -----------------------------------------------------------------------------------------------------------------

CREATE TABLE support_sla_policies (
  id                             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                           uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  name                           text NOT NULL,
  first_response_minutes         integer NOT NULL,
  resolution_minutes             integer NOT NULL,
  pause_when_waiting_on_customer boolean NOT NULL DEFAULT false,
  respect_business_hours         boolean NOT NULL DEFAULT true,
  is_default                     boolean NOT NULL DEFAULT false,
  created_at                     timestamptz NOT NULL DEFAULT now(),
  updated_at                     timestamptz NOT NULL DEFAULT now(),
  row_version                    integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_support_sla_policies_name CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT chk_support_sla_policies_first CHECK (first_response_minutes BETWEEN 1 AND 10080),
  CONSTRAINT chk_support_sla_policies_resolution CHECK (resolution_minutes BETWEEN 1 AND 43200)
);
-- At most one default, enforced by the database (Reference cleared the flag in application code, racing itself).
CREATE UNIQUE INDEX uq_support_sla_policies_default ON support_sla_policies (is_default) WHERE is_default;

DO $$
DECLARE
  t text;
  platform_tables text[] := ARRAY['support_agent_roster', 'support_playbooks', 'support_sla_policies'];
BEGIN
  FOREACH t IN ARRAY platform_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY privileged_only ON %I FOR ALL
        USING      (app_is_privileged())
        WITH CHECK (app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
    EXECUTE format('CREATE TRIGGER trg_%s_touch BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_row()', t, t);
  END LOOP;
END $$;

-- --- the breach ledger ------------------------------------------------------------------------------------------------------------

CREATE TABLE support_sla_breaches (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  ticket_id       bigint NOT NULL,
  policy_id       bigint REFERENCES support_sla_policies (id) ON DELETE SET NULL,
  breach_type     text NOT NULL,
  breached_at     timestamptz NOT NULL DEFAULT now(),
  severity        text NOT NULL DEFAULT 'breach',
  over_by_minutes integer NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_support_sla_breaches_ticket_type UNIQUE (org_id, ticket_id, breach_type),
  CONSTRAINT fk_support_sla_breaches_ticket FOREIGN KEY (org_id, ticket_id)
    REFERENCES support_tickets (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_support_sla_breaches_type CHECK (breach_type IN ('first_response', 'resolution')),
  CONSTRAINT chk_support_sla_breaches_severity CHECK (severity IN ('warn', 'breach', 'hard_breach')),
  CONSTRAINT chk_support_sla_breaches_over CHECK (over_by_minutes >= 0)
);
CREATE INDEX idx_support_sla_breaches_breached_at ON support_sla_breaches (breached_at DESC);
CREATE INDEX idx_support_sla_breaches_policy ON support_sla_breaches (policy_id);

ALTER TABLE support_sla_breaches ENABLE ROW LEVEL SECURITY;
ALTER TABLE support_sla_breaches FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON support_sla_breaches FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_support_sla_breaches_touch BEFORE UPDATE ON support_sla_breaches
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- platform inbox: which operator wrote a note or a flag --------------------------------------------------------------------------

ALTER TABLE platform_notes
  ADD COLUMN admin_operator_id bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  ADD CONSTRAINT fk_platform_notes_conversation FOREIGN KEY (org_id, conversation_id)
    REFERENCES conversations (org_id, id) ON DELETE CASCADE,
  ADD CONSTRAINT chk_platform_notes_severity CHECK (severity IN ('info', 'warn', 'critical')),
  ADD CONSTRAINT chk_platform_notes_body CHECK (length(body) BETWEEN 1 AND 8000);
CREATE INDEX idx_platform_notes_created_at ON platform_notes (org_id, created_at DESC);

ALTER TABLE workspace_flags
  ADD COLUMN flagged_by_operator_id bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  ADD COLUMN cleared_by_operator_id bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  ADD CONSTRAINT chk_workspace_flags_flag
    CHECK (flag IN ('spam', 'abuse', 'fraud', 'billing_overdue', 'tos_violation', 'frozen')),
  ADD CONSTRAINT chk_workspace_flags_reason CHECK (reason IS NULL OR length(reason) <= 500);
-- One ACTIVE flag of a type per workspace (Reference stacked duplicates, so a single clear never lifted the block).
CREATE UNIQUE INDEX uq_workspace_flags_active ON workspace_flags (org_id, flag) WHERE cleared_at IS NULL;
