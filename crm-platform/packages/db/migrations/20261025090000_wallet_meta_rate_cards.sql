-- wallet: Meta's published rate cards, one per billing currency
-- Why this migration exists: Meta publishes a separate price list for each currency (USD, INR, ...), and a workspace billed in
-- INR must see and be charged against Meta's INR card, not the USD figure run through an exchange rate. `message_rates` holds
-- ONE cost per country in the platform currency; this table holds Meta's own list per (currency, market, category), imported
-- from the files Meta publishes each quarter (1 Jan, Apr, Jul, Oct). A market is Meta's unit, not a country: a few dozen
-- countries stand alone, the rest are grouped ("Rest of Asia Pacific", "North America", "Other"). The country-to-market map
-- lives in code (meta-markets.ts) because Meta changes it rarely and it is documentation, not operator data.
--
-- Global table (no org_id): readable by everyone, writable only by the privileged operator path, like message_rates.

CREATE TABLE meta_rate_cards (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  currency text NOT NULL,
  market text NOT NULL,
  category text NOT NULL,
  -- millionths of the currency unit, the same scale as message_rates.meta_cost_micros
  cost_micros bigint NOT NULL,
  -- the date Meta says this card takes effect, read from the file
  effective_on date NOT NULL,
  source_label text NOT NULL,
  imported_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_meta_rate_cards_key UNIQUE (currency, market, category),
  CONSTRAINT chk_meta_rate_cards_currency CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_meta_rate_cards_category CHECK (
    category IN ('marketing', 'utility', 'authentication', 'authentication_international', 'service')
  ),
  CONSTRAINT chk_meta_rate_cards_cost CHECK (cost_micros >= 0)
);

ALTER TABLE meta_rate_cards ENABLE ROW LEVEL SECURITY;
ALTER TABLE meta_rate_cards FORCE  ROW LEVEL SECURITY;
CREATE POLICY read_all ON meta_rate_cards FOR SELECT USING (true);
CREATE POLICY operator_write ON meta_rate_cards FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
