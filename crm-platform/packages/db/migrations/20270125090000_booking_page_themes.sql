-- Booking page appearance (BL-355..BL-358).
--
-- Why: the public booking page (/book/<workspace>/<service>) looked the same for every business: a letter tile, the product's
-- purple and the product's name in the footer. A workspace now sets how its own page looks (logo, colours, background, fonts, wording),
-- and a single service may override part of it. Nothing changes for a workspace that never saves a theme: no row means the page is
-- drawn from the workspace brand kit (Settings > Branding: colours and logo) and then from the product defaults.
--
-- One row per scope: booking_type_id NULL is the workspace default, a value is that service's override. Every appearance column is
-- nullable and NULL means "inherit from the next level up" (service -> workspace default -> brand kit -> product default), so an
-- override row only stores what differs. Colours are #RRGGBB only (they end up in a style attribute), fonts and corners are fixed
-- lists (no arbitrary CSS), the logo and the cover are uploaded files served by the API (never a typed URL).

CREATE TABLE booking_page_themes (
  org_id                bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                    bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                  uuid NOT NULL DEFAULT gen_random_uuid(),
  -- NULL: the workspace default. A value: the override of that service.
  booking_type_id       bigint,
  primary_color         text,
  -- The button / call to action colour. NULL falls back to the primary colour.
  accent_color          text,
  background_color      text,
  -- solid: background_color (or the page default); tint: a soft wash of the primary colour; image: the uploaded cover as a banner.
  background_style      text,
  page_title            text,
  welcome_text          text,
  button_label          text,
  font                  text,
  corner_style          text,
  color_mode            text,
  show_powered_by       boolean,
  show_language_switch  boolean,
  -- Workspace row only: when true (default) a colour or a logo that is not set here is taken from Settings > Branding.
  use_workspace_brand   boolean NOT NULL DEFAULT true,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  row_version           integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_booking_page_themes_booking_type_id FOREIGN KEY (org_id, booking_type_id)
    REFERENCES booking_types (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_booking_page_themes_primary CHECK (primary_color IS NULL OR primary_color ~ '^#[0-9a-f]{6}$'),
  CONSTRAINT chk_booking_page_themes_accent CHECK (accent_color IS NULL OR accent_color ~ '^#[0-9a-f]{6}$'),
  CONSTRAINT chk_booking_page_themes_background CHECK (background_color IS NULL OR background_color ~ '^#[0-9a-f]{6}$'),
  CONSTRAINT chk_booking_page_themes_background_style CHECK (
    background_style IS NULL OR background_style IN ('solid', 'tint', 'image')),
  CONSTRAINT chk_booking_page_themes_font CHECK (
    font IS NULL OR font IN ('default', 'system', 'serif', 'rounded', 'humanist')),
  CONSTRAINT chk_booking_page_themes_corner CHECK (
    corner_style IS NULL OR corner_style IN ('square', 'rounded', 'pill')),
  CONSTRAINT chk_booking_page_themes_mode CHECK (
    color_mode IS NULL OR color_mode IN ('light', 'dark', 'auto')),
  CONSTRAINT chk_booking_page_themes_text CHECK (
    (page_title IS NULL OR char_length(page_title) <= 120)
    AND (welcome_text IS NULL OR char_length(welcome_text) <= 600)
    AND (button_label IS NULL OR char_length(button_label) <= 40))
);

-- NULL is distinct in a unique key, so the workspace row and the per-service rows each get their own index.
CREATE UNIQUE INDEX uq_booking_page_themes_workspace ON booking_page_themes (org_id) WHERE booking_type_id IS NULL;
CREATE UNIQUE INDEX uq_booking_page_themes_type ON booking_page_themes (org_id, booking_type_id) WHERE booking_type_id IS NOT NULL;

ALTER TABLE booking_page_themes ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking_page_themes FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON booking_page_themes FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_booking_page_themes_touch BEFORE UPDATE ON booking_page_themes
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- The uploaded logo and cover of a theme. Bytes live here for the same reason as workspace_brand_assets (reading a theme never drags a
-- blob through the buffer cache, and one row per slot means a replaced file overwrites instead of leaving the old one behind).
-- The API serves them to anyone who holds the page address, so only an image the workspace chose for its public page belongs here.
CREATE TABLE booking_page_assets (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  theme_id    bigint NOT NULL,
  slot        text NOT NULL,
  mime        text NOT NULL,
  bytes       bytea NOT NULL,
  etag        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_booking_page_assets_theme_slot UNIQUE (org_id, theme_id, slot),
  CONSTRAINT fk_booking_page_assets_theme_id FOREIGN KEY (org_id, theme_id)
    REFERENCES booking_page_themes (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_booking_page_assets_slot CHECK (slot IN ('logo', 'cover')),
  CONSTRAINT chk_booking_page_assets_mime CHECK (mime IN ('image/png', 'image/jpeg', 'image/webp', 'image/gif')),
  CONSTRAINT chk_booking_page_assets_size CHECK (octet_length(bytes) <= 3145728)
);

ALTER TABLE booking_page_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE booking_page_assets FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON booking_page_assets FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_booking_page_assets_touch BEFORE UPDATE ON booking_page_assets
  FOR EACH ROW EXECUTE FUNCTION touch_row();
