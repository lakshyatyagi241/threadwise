-- cat: catalog-products data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's catalog products features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: wa_catalogs, wa_products, wa_product_reviews, wa_product_sets, wa_stock_reservations

-- WaDesk `wa_catalogs` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_catalogs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider text NOT NULL,
  catalog_id text NOT NULL,
  catalog_name text,
  waba_id text,
  phone_number_id text,
  access_token_enc text,  -- encrypted
  is_cart_enabled boolean NOT NULL DEFAULT true,
  is_catalog_visible boolean NOT NULL DEFAULT true,
  last_synced_at timestamptz,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_catalogs_provider UNIQUE (org_id, provider)
);
CREATE INDEX idx_wa_catalogs_catalog_id ON wa_catalogs (org_id, catalog_id);

ALTER TABLE wa_catalogs ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_catalogs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_catalogs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_catalogs_touch BEFORE UPDATE ON wa_catalogs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `wa_products` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_products (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  storefront_id bigint,
  shopify_product_id text,
  woo_product_id text,
  user_id bigint,
  sku text,
  name text NOT NULL,
  slug text NOT NULL,
  description text,
  body_html text,
  price_minor bigint NOT NULL DEFAULT 0,
  compare_price_minor bigint,
  weight_grams integer,
  category text,
  tags_json jsonb,
  aliases_json jsonb,
  status text NOT NULL DEFAULT 'active',
  availability text NOT NULL DEFAULT 'in stock',
  condition text NOT NULL DEFAULT 'new',
  brand text,
  product_url text,
  google_product_category text,
  currency_code text NOT NULL DEFAULT 'INR',
  image_url text,
  gallery_json jsonb,
  in_stock boolean NOT NULL DEFAULT true,
  stock_qty integer,
  reserved_qty integer NOT NULL DEFAULT 0,
  sort_order integer NOT NULL DEFAULT 0,
  meta_retailer_id text,
  meta_sync_status text,
  meta_synced_at timestamptz,
  meta_batch_handle text,
  meta_last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_wa_products_availability CHECK (availability IN ('in stock', 'out of stock', 'available for order', 'discontinued')),
  CONSTRAINT chk_wa_products_condition CHECK (condition IN ('new', 'refurbished', 'used')),
  CONSTRAINT uq_wa_products_slug UNIQUE (org_id, slug),
  CONSTRAINT fk_wa_products_storefront_id FOREIGN KEY (org_id, storefront_id) REFERENCES wa_storefronts (org_id, id) ON DELETE SET NULL (storefront_id),
  CONSTRAINT fk_wa_products_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_wa_products_shopify_product_id ON wa_products (org_id, shopify_product_id);
CREATE INDEX idx_wa_products_storefront_id ON wa_products (org_id, storefront_id);
CREATE INDEX idx_wa_products_user_id ON wa_products (org_id, user_id);
CREATE INDEX idx_wa_products_woo_product_id ON wa_products (org_id, woo_product_id);
CREATE INDEX idx_wa_products_category ON wa_products (org_id, category);
CREATE INDEX idx_wa_products_in_stock_sort_order ON wa_products (org_id, in_stock, sort_order);
CREATE INDEX idx_wa_products_status ON wa_products (org_id, status);
CREATE INDEX idx_wa_products_meta_sync_status ON wa_products (org_id, meta_sync_status);

ALTER TABLE wa_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_products FORCE  ROW LEVEL SECURITY;
