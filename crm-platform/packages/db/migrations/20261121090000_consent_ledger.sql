SELECT set_config('app.privileged', 'on', true);

INSERT INTO contact_consent_events (org_id, contact_id, channel, purpose, action, source, evidence, note, occurred_at, idempotency_key)
SELECT c.org_id, c.id, 'whatsapp', 'marketing', 'withdrawn', 'legacy', '{}'::jsonb,
       'Opted out before the consent ledger existed', coalesce(c.unsubscribed_at, c.created_at, now()), 'legacy:' || c.id
FROM contacts c
WHERE c.is_unsubscribed
ON CONFLICT (org_id, idempotency_key) DO NOTHING;

INSERT INTO contact_consent_state (org_id, contact_id, channel, purpose, state, last_event_id, last_occurred_at)
SELECT e.org_id, e.contact_id, e.channel, e.purpose, 'withdrawn', e.id, e.occurred_at
FROM contact_consent_events e
WHERE e.source = 'legacy' AND e.contact_id IS NOT NULL
ON CONFLICT DO NOTHING;
