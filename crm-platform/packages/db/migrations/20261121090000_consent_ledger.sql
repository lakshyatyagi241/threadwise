-- consent: the contact consent ledger (docs/specs/contact-consent-ledger.md). A product extension; the reference has only the
-- contacts.is_unsubscribed flag, which stays the roll-up every existing send path and filter reads.
--
--   contact_consent_events    append-only history: who granted / withdrew consent, when, on which channel, from which source,
--                             with which evidence (ids and hashes, never an IP or free personal text)
--   contact_consent_state     the current state per (contact, channel, purpose), written in the same transaction as the event
--   contact_consent_settings  one row per workspace: STOP / START keywords, auto replies, the opt-out line, the policy switch
--
-- Backfill: a contact that is already is_unsubscribed gets one `withdrawn` event with source `legacy`. A contact that is not gets
-- NOTHING: its state is `unknown` ("No consent recorded"); we never invent consent.

CREATE TABLE contact_consent_events (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Erasing a contact anonymises its events (the link goes to NULL); the rows are never edited or deleted.
  contact_id bigint,
  channel text NOT NULL,
  purpose text NOT NULL DEFAULT 'marketing',
  action text NOT NULL,
  source text NOT NULL,
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id bigint,
  note text,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  recorded_at timestamptz NOT NULL DEFAULT now(),
  -- One per source event ("keyword:<message uuid>", "form:<submission uuid>", ...): a redelivery inserts nothing.
  idempotency_key text NOT NULL,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, idempotency_key),
  CONSTRAINT fk_consent_events_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_consent_events_actor FOREIGN KEY (org_id, actor_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (actor_user_id),
  CONSTRAINT ck_consent_events_channel CHECK (channel ~ '^[a-z][a-z0-9_]{1,30}$'),
  CONSTRAINT ck_consent_events_purpose CHECK (purpose IN ('marketing', 'utility')),
  CONSTRAINT ck_consent_events_action CHECK (action IN ('granted', 'withdrawn')),
  CONSTRAINT ck_consent_events_source CHECK (source IN ('form', 'keyword', 'manual', 'import', 'api', 'flow', 'inbound_message', 'contact_request', 'legacy')),
  CONSTRAINT ck_consent_events_evidence CHECK (jsonb_typeof(evidence) = 'object' AND pg_column_size(evidence) <= 4096),
  CONSTRAINT ck_consent_events_note CHECK (note IS NULL OR char_length(note) <= 500),
  CONSTRAINT ck_consent_events_key CHECK (char_length(idempotency_key) BETWEEN 1 AND 200)
);
CREATE INDEX idx_consent_events_contact ON contact_consent_events (org_id, contact_id, occurred_at DESC, id DESC) WHERE contact_id IS NOT NULL;
CREATE INDEX idx_consent_events_recorded ON contact_consent_events (org_id, recorded_at DESC, id DESC);

ALTER TABLE contact_consent_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_consent_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_consent_events FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- History is never edited. The only change the database itself may make is a reference going to NULL (ON DELETE SET NULL of the
-- contact or the user: erasure). DELETE is for a privileged session and for the workspace cascade.
CREATE FUNCTION contact_consent_events_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF app_is_privileged() OR pg_trigger_depth() > 1 THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'contact_consent_events is append-only: an event cannot be deleted' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (to_jsonb(NEW) - 'contact_id' - 'actor_user_id') IS NOT DISTINCT FROM (to_jsonb(OLD) - 'contact_id' - 'actor_user_id')
     AND (NEW.contact_id IS NULL OR NEW.contact_id IS NOT DISTINCT FROM OLD.contact_id)
     AND (NEW.actor_user_id IS NULL OR NEW.actor_user_id IS NOT DISTINCT FROM OLD.actor_user_id) THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'contact_consent_events is append-only: an event cannot be changed' USING ERRCODE = 'integrity_constraint_violation';
END $$;

CREATE TRIGGER trg_consent_events_immutable BEFORE UPDATE OR DELETE ON contact_consent_events
  FOR EACH ROW EXECUTE FUNCTION contact_consent_events_immutable();

-- ---------------------------------------------------------------------------------------------------------------------------
-- the current state
-- ---------------------------------------------------------------------------------------------------------------------------

CREATE TABLE contact_consent_state (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  contact_id bigint NOT NULL,
  channel text NOT NULL,
  purpose text NOT NULL,
  state text NOT NULL,
  last_event_id bigint NOT NULL,
  last_occurred_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, contact_id, channel, purpose),
  CONSTRAINT fk_consent_state_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_consent_state_event FOREIGN KEY (org_id, last_event_id) REFERENCES contact_consent_events (org_id, id),
  CONSTRAINT ck_consent_state_state CHECK (state IN ('granted', 'withdrawn')),
  CONSTRAINT ck_consent_state_purpose CHECK (purpose IN ('marketing', 'utility'))
);
-- The send paths ask "which contacts are granted" (policy switch on): partial index per state.
CREATE INDEX idx_consent_state_granted ON contact_consent_state (org_id, contact_id) WHERE purpose = 'marketing' AND state = 'granted';

ALTER TABLE contact_consent_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_consent_state FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_consent_state FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- ---------------------------------------------------------------------------------------------------------------------------
-- settings
-- ---------------------------------------------------------------------------------------------------------------------------

CREATE TABLE contact_consent_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  detection_enabled boolean NOT NULL DEFAULT true,
  require_consent_for_marketing boolean NOT NULL DEFAULT false,
  auto_reply_enabled boolean NOT NULL DEFAULT true,
  footer_default_on boolean NOT NULL DEFAULT true,
  -- {optOutKeywords, optInKeywords, optOutReply, optInReply, footerText}: per language maps, validated by the contract.
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT ck_consent_settings_config CHECK (jsonb_typeof(config) = 'object' AND pg_column_size(config) <= 65536)
);
ALTER TABLE contact_consent_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_consent_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_consent_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_consent_settings_touch BEFORE UPDATE ON contact_consent_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------------
-- backfill: already-unsubscribed contacts only
