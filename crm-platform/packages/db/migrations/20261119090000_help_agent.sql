-- help agent: the in-app assistant that guides or does a task on the person's own session (docs/specs/help-agent-assistant.md).
-- Not a Reference feature (product extension): Reference has no assistant.
--
-- What this migration adds:
--  1. Two capability keys. `help.agent.use` lets a person open the assistant; `help.agent.manage` switches it on for the workspace.
--     Kept apart so handing out "use" never hands out "turn on and share page text with the AI provider".
--  2. The plan feature `help_agent`. It spends AI tokens, so the owner decided it is not in every plan: every plan row says false
--     explicitly except the three demo plans `seed:auth` creates (starter, growth, scale), so local testing works.
--  3. `help_agent_settings`: the workspace switch, default OFF. No row means off. Own table (as faq_settings) rather than a column of
--     workspace_settings, which belongs to the workspaces domain.
--  4. `help_agent_tasks`: one row per task the assistant ran. It is what the server counts to enforce the step budget and the daily
--     caps (the browser cannot be trusted with them), and what the single audit event per task is built from. It holds counts and an
--     outcome code only: never the task sentence, never page text, never a model answer.

INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('help.agent.use',    'Use the Help assistant (it can click and type for you on your own session)', 'help', false),
  ('help.agent.manage', 'Switch the Help assistant on or off for the workspace',                       'help', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label, category = EXCLUDED.category, supports_scope = EXCLUDED.supports_scope;

-- Owner and Admin hold both (the Owner and Admin presets get every new key from the trigger on permission_defs; the baseline is what a
-- workspace provisioned later starts with). Manager, Agent and Viewer hold neither; any role can be given `help.agent.use`.
INSERT INTO workspace_preset_baseline (preset_key, permission_key)
SELECT p.preset, k.key
FROM (VALUES ('admin'), ('workspace_admin')) AS p(preset)
CROSS JOIN (VALUES ('help.agent.use'), ('help.agent.manage')) AS k(key)
ON CONFLICT (preset_key, permission_key) DO NOTHING;

SELECT set_config('app.privileged', 'on', true);
SELECT apply_workspace_preset_baseline(id) FROM organizations;
UPDATE organizations SET roles_version = roles_version + 1;

UPDATE plans SET features = features || '{"help_agent": false}'::jsonb
 WHERE kind = 'plan' AND NOT (features ? 'help_agent');
UPDATE plans SET features = features || '{"help_agent": true}'::jsonb
 WHERE kind = 'plan' AND slug IN ('starter', 'growth', 'scale');

-- ---------------------------------------------------------------------------------------------------------------------
-- help_agent_settings: the workspace switch. No row means off.
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE help_agent_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  enabled boolean NOT NULL DEFAULT false,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT fk_help_agent_settings_updated_by FOREIGN KEY (org_id, updated_by) REFERENCES users (org_id, id) ON DELETE SET NULL (updated_by)
);

ALTER TABLE help_agent_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE help_agent_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON help_agent_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_help_agent_settings_touch BEFORE UPDATE ON help_agent_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- help_agent_tasks: one row per task. `steps` counts the model calls the server answered (the step budget is enforced here).
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE help_agent_tasks (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  status text NOT NULL DEFAULT 'running',
  locale text NOT NULL,
  -- Only the LENGTH of the sentence the person typed. The sentence is never stored (it routinely carries names and numbers).
  task_length integer NOT NULL,
  -- The page path the task started on: no query, no hash.
  route text NOT NULL,
  steps integer NOT NULL DEFAULT 0,
  confirmed_actions integer NOT NULL DEFAULT 0,
  denied_actions integer NOT NULL DEFAULT 0,
  prompt_tokens bigint NOT NULL DEFAULT 0,
  completion_tokens bigint NOT NULL DEFAULT 0,
  started_at timestamptz NOT NULL DEFAULT now(),
  last_step_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_help_agent_tasks_user FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT ck_help_agent_tasks_status CHECK (status IN ('running', 'completed', 'failed', 'stopped', 'error', 'abandoned')),
  CONSTRAINT ck_help_agent_tasks_counts CHECK (steps >= 0 AND confirmed_actions >= 0 AND denied_actions >= 0
    AND prompt_tokens >= 0 AND completion_tokens >= 0 AND task_length > 0)
);

-- The daily caps count a person's and a workspace's task starts; the running-task lookup is the same shape.
CREATE INDEX idx_help_agent_tasks_user_started ON help_agent_tasks (org_id, user_id, started_at DESC);
CREATE INDEX idx_help_agent_tasks_org_started ON help_agent_tasks (org_id, started_at DESC);

