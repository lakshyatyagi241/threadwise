-- wfwd: fan out the one Meta webhook to many platform-configured targets.
-- Why this migration exists: Meta allows a single callback URL per app, but several of our products (WaDesk, Geta, Wabo)
-- need the same Meta events. The receiver verifies the signature, then forwards the raw body to every active target
-- unchanged (including the original X-Hub-Signature-256) so each product can still verify it with the app secret.
-- Both tables are platform (operator) tables: no org_id, writes only under the privileged flag, like admin_ai_keys.
-- The failures table keeps the raw bytes of a delivery that exhausted its retries so an operator can replay it;
-- successes are only counted on the target, so the log cannot grow with webhook volume.

CREATE TABLE webhook_forward_targets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  name text NOT NULL,
  url text NOT NULL,
  -- Optional extra header the target wants (e.g. a shared secret). Value is encrypted, never returned.
  auth_header_name text,
  auth_header_value text,
  auth_header_last4 text,
  is_active boolean NOT NULL DEFAULT true,
  -- NULL = every field. Otherwise forward only payloads that carry at least one of these Meta change fields.
  field_filter text[],
  timeout_ms integer NOT NULL DEFAULT 10000,
  max_attempts integer NOT NULL DEFAULT 5,
  success_count bigint NOT NULL DEFAULT 0,
  failure_count bigint NOT NULL DEFAULT 0,
  last_status integer,
  last_error text,
  last_success_at timestamptz,
  last_failure_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_webhook_forward_targets_name UNIQUE (name),
  CONSTRAINT chk_wfwd_url_https CHECK (url ~* '^https://'),
  CONSTRAINT chk_wfwd_timeout CHECK (timeout_ms BETWEEN 1000 AND 30000),
  CONSTRAINT chk_wfwd_attempts CHECK (max_attempts BETWEEN 1 AND 10),
  CONSTRAINT chk_wfwd_header_pair CHECK ((auth_header_name IS NULL) = (auth_header_value IS NULL))
);

ALTER TABLE webhook_forward_targets ENABLE ROW LEVEL SECURITY;
ALTER TABLE webhook_forward_targets FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON webhook_forward_targets FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_webhook_forward_targets_touch BEFORE UPDATE ON webhook_forward_targets
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE webhook_forward_failures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  target_id bigint NOT NULL REFERENCES webhook_forward_targets (id) ON DELETE CASCADE,
  body bytea NOT NULL,
  signature_header text,
  content_type text,
  attempts integer NOT NULL,
  status_code integer,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  replayed_at timestamptz
);
CREATE INDEX idx_wfwd_failures_target ON webhook_forward_failures (target_id, created_at DESC);
CREATE INDEX idx_wfwd_failures_created ON webhook_forward_failures (created_at);

ALTER TABLE webhook_forward_failures ENABLE ROW LEVEL SECURITY;
ALTER TABLE webhook_forward_failures FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON webhook_forward_failures FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
