-- supp: platform-support-desk data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's platform support desk features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: platform_notes, playbooks, support_agents, support_tickets, support_assignments, support_messages

-- WaDesk `platform_notes` (tenant; 0 rows in the reference DB)
CREATE TABLE platform_notes (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  conversation_id bigint,
  admin_user_id bigint,
  body text NOT NULL,
  severity text NOT NULL DEFAULT 'info',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_platform_notes_admin_user_id FOREIGN KEY (org_id, admin_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (admin_user_id)
);
CREATE INDEX idx_platform_notes_conversation_id ON platform_notes (org_id, conversation_id);

ALTER TABLE platform_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform_notes FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON platform_notes FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_platform_notes_touch BEFORE UPDATE ON platform_notes
  FOR EACH ROW EXECUTE FUNCTION touch_row();

