-- --- the public link lookup (the one cross-tenant read an unauthenticated request needs) -----------------------------------

-- A buyer arrives with a token and no tenant. The lookup has to find the org before a tenant context can exist, which would
-- otherwise need privileged() on an HTTP path (forbidden by CONTRIBUTING rule 1). This function does only that: it takes the
-- SHA-256 of the token and returns the two ids, nothing else. `SET app.privileged` is scoped to the call (a function-level SET is
-- restored when the function returns), so the caller's transaction is not left privileged.
CREATE FUNCTION invoice_by_public_token(p_hash text) RETURNS TABLE (org_id bigint, invoice_id bigint)
  LANGUAGE sql STABLE SECURITY DEFINER
  SET search_path = public, pg_temp
  SET app.privileged = 'on'
AS $$
  SELECT i.org_id, i.id FROM invoices i WHERE i.public_token_hash = p_hash AND i.status <> 'draft' LIMIT 1
$$;
REVOKE ALL ON FUNCTION invoice_by_public_token(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION invoice_by_public_token(text) TO crm_app, crm_worker;
COMMENT ON FUNCTION invoice_by_public_token(text) IS
  'Resolves a public invoice link (SHA-256 of the token) to its org and invoice id. SECURITY DEFINER because the buyer has no tenant context; returns ids only.';
