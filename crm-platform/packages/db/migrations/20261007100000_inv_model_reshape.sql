-- inv: reshape the drafted Reference invoicing tables into a sales invoicing product (TW-INV / TW-PAY, "Port decisions").
-- Why this migration exists: 20261001104600_inv_threadwise_schema.sql is a literal copy of Reference's auto-issued store receipts
-- (statuses issued/paid, a plaintext bearer token, a 6-digit number allocated before the row existed, CRM links hidden in a
-- JSON blob, tax as one free-form percent per line). The decisions this migration settles:
--   D-01  stored status is draft / issued / void; payment status (unpaid / partially_paid / paid) is a cache the payment ledger
--         maintains (trigger in 20261007100100); "overdue" is derived from due_date, never stored as a status;
--   D-02  due_date and issue_date are real dates in the workspace calendar; overdue_at is the sweep's one-shot stamp;
--   D-04  every amount is an integer in minor units of the document's currency, the exponent is per currency, and a CHECK makes
--         the database refuse a row whose totals do not add up (D-06);
--   D-08  numbers come from a locked per-org per-series counter, allocated when the invoice is ISSUED in the same transaction
--         (a draft has no number), unique and never reused; receipts and proformas have their own series;
--   D-15  the public link is a SHA-256 lookup hash plus an encrypted copy (so staff can copy the link again), it can expire
--         and be revoked, and viewing it is counted;
--   D-25  contact / company / deal / quote are real columns with composite tenant foreign keys;
--   tax   a tax_rates table (inclusive or exclusive, one default); lines SNAPSHOT name and rate so editing a rate never
--         changes an issued invoice.
-- The tables have never been written by any code (0 rows), so dropped columns are not migrated.

-- --- tax rates --------------------------------------------------------------------------------------------------------------

CREATE TABLE tax_rates (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  name        text NOT NULL,
  -- basis points: 18% = 1800, 7.25% = 725
  rate_bp     integer NOT NULL,
  -- an inclusive rate is already inside the entered price (VAT-style); an exclusive one is added on top
  inclusive   boolean NOT NULL DEFAULT false,
  is_default  boolean NOT NULL DEFAULT false,
  is_active   boolean NOT NULL DEFAULT true,
  description text,
  created_by  bigint,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_tax_rates_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_tax_rates_name CHECK (length(btrim(name)) BETWEEN 1 AND 60),
  CONSTRAINT chk_tax_rates_rate CHECK (rate_bp BETWEEN 0 AND 10000),
  -- a default that is switched off would silently tax nothing
  CONSTRAINT chk_tax_rates_default_active CHECK (NOT is_default OR is_active)
);
CREATE UNIQUE INDEX uq_tax_rates_name ON tax_rates (org_id, lower(name));
-- at most one default per organization
CREATE UNIQUE INDEX uq_tax_rates_default ON tax_rates (org_id) WHERE is_default;

