-- The allocator. One row per org and series; the row lock taken by the upsert serialises concurrent issuers until the issuing
-- transaction ends, so two invoices can never share a number, and a rolled-back issue gives its number back (a gap is only
-- ever left by a VOID, which keeps its number on purpose). The counter is also floored by what already exists in the series,
-- so a counter row that was lost or restored from an old backup resumes after the highest number, never inside it.
CREATE FUNCTION allocate_series_seq(p_org bigint, p_series text) RETURNS integer
  LANGUAGE plpgsql
AS $$
DECLARE
  floor_seq integer;
  got integer;
BEGIN
  IF p_org IS DISTINCT FROM current_org_id() AND NOT app_is_privileged() THEN
    RAISE EXCEPTION 'allocate_series_seq: org % is not the current tenant', p_org USING ERRCODE = '42501';
  END IF;
  SELECT coalesce(max(seq), 0) + 1 INTO floor_seq FROM invoices WHERE org_id = p_org AND series = p_series;
  INSERT INTO invoice_number_sequences (org_id, series, next_seq)
    VALUES (p_org, p_series, greatest(floor_seq, 1) + 1)
  ON CONFLICT (org_id, series) DO UPDATE
    SET next_seq = greatest(invoice_number_sequences.next_seq, floor_seq) + 1
  RETURNING next_seq - 1 INTO got;
  RETURN got;
END $$;

