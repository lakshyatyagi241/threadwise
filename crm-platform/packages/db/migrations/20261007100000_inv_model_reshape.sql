-- --- immutability of an issued invoice --------------------------------------------------------------------------------------

-- What a buyer was told never changes: once an invoice leaves draft, its money, currency, lines and numbering are frozen.
-- Allowed on an issued invoice: the ledger cache (paid_minor, payment_status, paid_at, refunded_minor), status moves
-- (issued -> void), delivery and view tracking, the public link, due date, notes, terms, owner, CRM links, and the sweep stamp.
CREATE FUNCTION invoices_freeze() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'draft' THEN
    RETURN NEW;
  END IF;
  IF OLD.status = 'void' AND NEW.status <> 'void' THEN
    RAISE EXCEPTION 'a void invoice cannot be reopened' USING ERRCODE = '55000';
  END IF;
  IF NEW.status = 'draft' THEN
    RAISE EXCEPTION 'an issued invoice cannot go back to draft' USING ERRCODE = '55000';
  END IF;
  IF (NEW.invoice_number, NEW.series, NEW.seq, NEW.doc_type, NEW.currency, NEW.currency_exponent,
      NEW.subtotal_minor, NEW.discount_minor, NEW.doc_discount_minor, NEW.shipping_minor, NEW.tax_minor, NEW.tax_added_minor,
      NEW.total_minor, NEW.discount_kind, NEW.discount_value, NEW.tax_inclusive, NEW.buyer_name, NEW.issued_at, NEW.issue_date)
     IS DISTINCT FROM
     (OLD.invoice_number, OLD.series, OLD.seq, OLD.doc_type, OLD.currency, OLD.currency_exponent,
      OLD.subtotal_minor, OLD.discount_minor, OLD.doc_discount_minor, OLD.shipping_minor, OLD.tax_minor, OLD.tax_added_minor,
      OLD.total_minor, OLD.discount_kind, OLD.discount_value, OLD.tax_inclusive, OLD.buyer_name, OLD.issued_at, OLD.issue_date)
  THEN
    RAISE EXCEPTION 'an issued invoice is frozen: its number, buyer, currency and amounts cannot change' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_invoices_freeze BEFORE UPDATE ON invoices
  FOR EACH ROW EXECUTE FUNCTION invoices_freeze();

-- Lines belong to a draft: inserting, changing or deleting a line of an issued invoice is refused. A cascade from the invoice
-- (or the organization) removes lines after the parent row is gone, so the parent lookup finds nothing and the delete passes.
CREATE FUNCTION invoice_items_freeze() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  parent_status text;
  parent_id bigint := CASE WHEN TG_OP = 'DELETE' THEN OLD.invoice_id ELSE NEW.invoice_id END;
  parent_org bigint := CASE WHEN TG_OP = 'DELETE' THEN OLD.org_id ELSE NEW.org_id END;
BEGIN
  SELECT status INTO parent_status FROM invoices WHERE org_id = parent_org AND id = parent_id;
  IF parent_status IS NOT NULL AND parent_status <> 'draft' THEN
    RAISE EXCEPTION 'the lines of an issued invoice are frozen' USING ERRCODE = '55000';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER trg_invoice_items_freeze BEFORE INSERT OR UPDATE OR DELETE ON invoice_items
  FOR EACH ROW EXECUTE FUNCTION invoice_items_freeze();
CREATE TRIGGER trg_invoice_tax_summary_freeze BEFORE INSERT OR UPDATE OR DELETE ON invoice_tax_summary
  FOR EACH ROW EXECUTE FUNCTION invoice_items_freeze();

