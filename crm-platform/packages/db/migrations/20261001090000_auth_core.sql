-- 20261001090000_auth_core
-- Why this migration exists (ADR-0019): the auth domain needs server-side
-- sessions (revocation, device list, idle timeout, session cap), one-time
-- tokens (verify email, reset password), per-user credentials/MFA/profile data
-- that does not belong on the shared `users` row, social identity links, and a
-- platform-staff layer (operators, platform settings, a security event stream).
--
-- File name is a timestamp, not the next 00NN: three developers adding
-- numbered migrations on parallel branches collide on the number.
--
-- Tenant tables follow the usual shape (org_id first, composite FKs, forced
-- RLS). The four platform tables have no org_id: their RLS policies are
-- satisfied only by app_is_privileged(), so a tenant transaction can never
-- read them, even through a bug. security_events is the one exception — any
-- transaction may INSERT (so a failed login is recorded in the same
-- transaction as whatever else it did), only privileged ones may SELECT.

-- --- per-user data (one row per user, created on demand) -------------------

CREATE TABLE user_security (
  org_id                bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  user_id               bigint NOT NULL,
  email_verified_at     timestamptz,
  password_changed_at   timestamptz,
  force_password_change boolean NOT NULL DEFAULT false,
  last_login_at         timestamptz,
  mfa_enabled           boolean NOT NULL DEFAULT false,
  -- AES-256-GCM envelope from CryptoService, never the raw base32 secret.
  mfa_secret_enc        text,
  mfa_confirmed_at      timestamptz,
  -- Highest TOTP time-step already accepted: a code can be used once.
  mfa_last_step         bigint,
  -- argon2 hashes of the single-use recovery codes.
  mfa_recovery_hashes   jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  row_version           integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, user_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);

CREATE TABLE user_profiles (
  org_id       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  user_id      bigint NOT NULL,
  display_name text,
  -- E.164 (+<digits>); the country is derived at the edge, not stored twice.
  phone_e164   text,
  phone_verified_at timestamptz,
  locale       text,
  theme        text NOT NULL DEFAULT 'paper',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  row_version  integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, user_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_user_profiles_theme CHECK (theme IN ('paper', 'bright', 'dark'))
);

-- Avatar bytes live in their own table so reading a profile never drags a
-- blob through the buffer cache. Interim storage: moves to object storage
-- (presigned upload) when the storage adapter lands.
CREATE TABLE user_avatars (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  user_id    bigint NOT NULL,
  mime       text NOT NULL,
  bytes      bytea NOT NULL,
  etag       text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, user_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_user_avatars_size CHECK (octet_length(bytes) <= 1048576)
);

-- --- sessions ---------------------------------------------------------------

CREATE TABLE auth_sessions (
  org_id            bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  -- The `sid` claim. The only session identifier that leaves the system.
  uuid              uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id           bigint NOT NULL,
  -- Refresh tokens are signed JWTs carrying this counter (`rv`). A refresh
  -- bumps it. Presenting rv = current - 1 within a few seconds of rotated_at is
  -- two tabs racing and is answered with the current token; anything older is
  -- a replayed token and revokes the whole session. No token material is stored.
  refresh_version   integer NOT NULL DEFAULT 1,
  rotated_at        timestamptz NOT NULL DEFAULT now(),
  remember          boolean NOT NULL DEFAULT false,
  mfa_verified      boolean NOT NULL DEFAULT false,
  ip                inet,
  user_agent        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  last_used_at      timestamptz NOT NULL DEFAULT now(),
  expires_at        timestamptz NOT NULL,
  revoked_at        timestamptz,
  revoked_reason    text,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_auth_sessions_user ON auth_sessions (org_id, user_id, created_at DESC);
CREATE INDEX idx_auth_sessions_live ON auth_sessions (org_id, user_id, last_used_at DESC)
  WHERE revoked_at IS NULL;

-- --- one-time tokens ----------------------------------------------------------

CREATE TABLE user_tokens (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id     bigint NOT NULL,
  kind        text NOT NULL,
  -- sha256 of the random token. The token only ever exists in the mail.
  token_hash  text NOT NULL,
  -- e.g. the new address for an email change.
  payload     jsonb NOT NULL DEFAULT '{}'::jsonb,
  expires_at  timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, kind, token_hash),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_user_tokens_kind CHECK (kind IN ('email_verify', 'password_reset', 'email_change'))
);
CREATE INDEX idx_user_tokens_user ON user_tokens (org_id, user_id, kind, created_at DESC);

-- --- social sign-in links --------------------------------------------------------

CREATE TABLE social_identities (
  org_id           bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id          bigint NOT NULL,
  provider         text NOT NULL,
  provider_subject text NOT NULL,
  email            text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  -- Reference indexes (provider, id) without UNIQUE; two accounts could end up
  -- bound to one Google identity. Here a subject maps to exactly one user.
  UNIQUE (org_id, provider, provider_subject),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_social_provider CHECK (provider IN ('google', 'facebook'))
);
CREATE INDEX idx_social_identities_user ON social_identities (org_id, user_id);

-- Identity-directory lookups ("which organizations have a verified user with
-- this email") start from the email; (org_id, email) cannot serve them.
CREATE INDEX idx_users_email ON users (email);

DO $$
DECLARE
  t text;
  tenant_tables text[] := ARRAY[
    'user_security', 'user_profiles', 'user_avatars', 'auth_sessions', 'user_tokens',
    'social_identities'
  ];
BEGIN
  FOREACH t IN ARRAY tenant_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I FOR ALL
        USING      (org_id = current_org_id() OR app_is_privileged())
        WITH CHECK (org_id = current_org_id() OR app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
  END LOOP;
END $$;

CREATE TRIGGER trg_user_security_touch BEFORE UPDATE ON user_security
  FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_user_profiles_touch BEFORE UPDATE ON user_profiles
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- platform layer (no org_id) --------------------------------------------------

CREATE TABLE platform_settings (
  key         text PRIMARY KEY,
  value       jsonb NOT NULL,
  -- true: value is a CryptoService envelope and is never returned by the API.
  is_secret   boolean NOT NULL DEFAULT false,
  updated_by  bigint,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE platform_operators (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                  uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  email                 citext NOT NULL UNIQUE,
  full_name             text NOT NULL,
  password_hash         text NOT NULL,
  role                  text NOT NULL DEFAULT 'support',
  status                text NOT NULL DEFAULT 'active',
  force_password_change boolean NOT NULL DEFAULT false,
  password_changed_at   timestamptz,
  last_login_at         timestamptz,
  mfa_enabled           boolean NOT NULL DEFAULT false,
  mfa_secret_enc        text,
  mfa_confirmed_at      timestamptz,
  mfa_last_step         bigint,
  mfa_recovery_hashes   jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  row_version           integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_operator_role CHECK (role IN ('super_admin', 'support', 'auditor')),
  CONSTRAINT chk_operator_status CHECK (status IN ('active', 'suspended'))
);

CREATE TABLE platform_sessions (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid              uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  operator_id       bigint NOT NULL REFERENCES platform_operators (id) ON DELETE CASCADE,
  refresh_version   integer NOT NULL DEFAULT 1,
  rotated_at        timestamptz NOT NULL DEFAULT now(),
  mfa_verified      boolean NOT NULL DEFAULT false,
  ip                inet,
  user_agent        text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  last_used_at      timestamptz NOT NULL DEFAULT now(),
  expires_at        timestamptz NOT NULL,
  revoked_at        timestamptz,
  revoked_reason    text
);
CREATE INDEX idx_platform_sessions_operator ON platform_sessions (operator_id, created_at DESC);

-- Append-only stream of security-relevant events across every tenant and the
-- platform. Not partitioned yet: it is pruned by audit_log_retention_days and
-- the KPI queries are all "last 24h / 7d", served by the indexes below.
CREATE TABLE security_events (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  at          timestamptz NOT NULL DEFAULT now(),
  -- No FK: an event must outlive the organization it describes.
  org_id      bigint,
  actor_type  text NOT NULL,
  actor_id    bigint,
  event       text NOT NULL,
  status      text NOT NULL,
  ip          inet,
  user_agent  text,
  request_id  text,
  payload     jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT chk_security_events_status CHECK (status IN ('success', 'failure', 'warning', 'info'))
);
CREATE INDEX idx_security_events_at ON security_events (at DESC);
CREATE INDEX idx_security_events_event ON security_events (event, at DESC);
CREATE INDEX idx_security_events_attention ON security_events (at DESC)
  WHERE status IN ('failure', 'warning');

DO $$
DECLARE
  t text;
  platform_tables text[] := ARRAY['platform_settings', 'platform_operators', 'platform_sessions'];
BEGIN
  FOREACH t IN ARRAY platform_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY privileged_only ON %I FOR ALL
        USING      (app_is_privileged())
        WITH CHECK (app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
  END LOOP;
END $$;

CREATE TRIGGER trg_platform_operators_touch BEFORE UPDATE ON platform_operators
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE security_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE security_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY append_any ON security_events FOR INSERT WITH CHECK (true);
CREATE POLICY read_privileged ON security_events FOR SELECT USING (app_is_privileged());
CREATE POLICY prune_privileged ON security_events FOR DELETE USING (app_is_privileged());
GRANT SELECT, INSERT, DELETE ON security_events TO crm_app, crm_worker;

