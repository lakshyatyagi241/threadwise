-- wgt: chatbot-widget data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's chatbot widget features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: chatbot_widgets, chatbot_widget_visitors

-- WaDesk `chatbot_widgets` (tenant; 0 rows in the reference DB)
CREATE TABLE chatbot_widgets (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  assistant_id bigint,
  name text NOT NULL,
  slug text NOT NULL,
  embed_token text NOT NULL,
  mode text NOT NULL DEFAULT 'ai',
  target_whatsapp_cc text,
  target_whatsapp_number text,
  prefilled_message text,
  position text NOT NULL DEFAULT 'bottom_right',
  button_color text NOT NULL DEFAULT '#075E54',
  button_image_url text,
  header_title text NOT NULL DEFAULT 'Chat with us',
  header_bg text NOT NULL DEFAULT '#075E54',
  header_text_color text NOT NULL DEFAULT '#FFFFFF',
  welcome_message text,
  message_bubble_color text NOT NULL DEFAULT '#FFFFFF',
  message_text_color text NOT NULL DEFAULT '#222222',
  body_bg_kind text NOT NULL DEFAULT 'color',
  body_bg_color text NOT NULL DEFAULT '#ECE5DD',
  body_bg_image_url text,
  auto_open boolean NOT NULL DEFAULT false,
  button_label text NOT NULL DEFAULT 'Start chat',
  action_button_bg text NOT NULL DEFAULT '#075E54',
  action_button_text_color text NOT NULL DEFAULT '#FFFFFF',
  collect_name boolean NOT NULL DEFAULT true,
  collect_email boolean NOT NULL DEFAULT false,
  collect_phone boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'active',
  allowed_domains jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_chatbot_widgets_embed_token UNIQUE (embed_token),
  CONSTRAINT uq_chatbot_widgets_slug UNIQUE (org_id, slug),
  CONSTRAINT fk_chatbot_widgets_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_chatbot_widgets_assistant_id FOREIGN KEY (org_id, assistant_id) REFERENCES ai_chat_assistants (org_id, id) ON DELETE SET NULL (assistant_id)
);
CREATE INDEX idx_chatbot_widgets_assistant_id ON chatbot_widgets (org_id, assistant_id);
CREATE INDEX idx_chatbot_widgets_user_id ON chatbot_widgets (org_id, user_id);
CREATE INDEX idx_chatbot_widgets_status ON chatbot_widgets (org_id, status);

ALTER TABLE chatbot_widgets ENABLE ROW LEVEL SECURITY;
ALTER TABLE chatbot_widgets FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON chatbot_widgets FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_chatbot_widgets_touch BEFORE UPDATE ON chatbot_widgets
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `chatbot_widget_visitors` (tenant; 0 rows in the reference DB)
CREATE TABLE chatbot_widget_visitors (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  widget_id bigint NOT NULL,
  conversation_id bigint,
  visitor_uuid text NOT NULL,
  name text,
  email text,
  phone text,
  referrer_url text,
  user_agent text,
  ip text,
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_chatbot_widget_visitors_visitor_uuid UNIQUE (visitor_uuid),
  CONSTRAINT fk_chatbot_widget_visitors_widget_id FOREIGN KEY (org_id, widget_id) REFERENCES chatbot_widgets (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_chatbot_widget_visitors_conversation_id ON chatbot_widget_visitors (org_id, conversation_id);
CREATE INDEX idx_chatbot_widget_visitors_widget_id ON chatbot_widget_visitors (org_id, widget_id);

ALTER TABLE chatbot_widget_visitors ENABLE ROW LEVEL SECURITY;
ALTER TABLE chatbot_widget_visitors FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON chatbot_widget_visitors FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_chatbot_widget_visitors_touch BEFORE UPDATE ON chatbot_widget_visitors
  FOR EACH ROW EXECUTE FUNCTION touch_row();
