-- workspace inactivity lifecycle: remind, archive, erase (ADR-0028).
-- Why this migration exists: a workspace nobody uses keeps its contacts, messages and files forever. The owner wants an idle workspace
-- archived after 90 days and erased after 180, three reminders before each step, and an operator override per workspace (change the
-- timings, mark it "never delete"). DPDP and GDPR ask for storage limitation and a documented notice before an irreversible erase.
--
--  1. organizations gets the inactivity clock (`last_activity_at`), the archive stamp and the operator's controls: per-workspace
--     timings, the never-delete exemption (a reason is mandatory; it may carry an expiry so it is re-reviewed) and the legal hold.
--     The migration starts every clock at now(): nothing is archived or erased because of history it could not see.
--     `status` gains the value 'archived' (it already holds 'active', 'suspended' and 'deleted'); every sign-in, refresh and public link
--     already requires 'active', so an archived workspace is shut out without a new gate. No CHECK on `status`: other domains own its values.
--  2. org_lifecycle_log: the append-only record of every decision (reminder, archive, restore, policy, exemption, hold, erase). It holds
--     no personal data, has no FK so it outlives the workspace, and cannot be updated or deleted by the application roles.
--  3. storage_purge_queue: object-store keys owed a purge after an erase (the cascade removes the rows that point at the files).
--  4. financial_records_archive: the platform's own sales records (`orders`) outlive an erase, because tax law requires them for years.
--     What is kept is the money and the tax facts; the buyer's name, email, company and address are not copied. A daily job removes a
--     row once its `retain_until` passes. No FK, platform-only.
--  5. organizations.deleted_at: when the owner deleted the workspace themselves (`status = 'deleted'`, set by the settings screen). Such a
--     workspace was never purged; the sweep now erases it 30 days after the owner's deletion. The owner asked for it, so no reminders,
--     and the operator's never-delete switch does not stop it; only a legal hold does.
--  6. Only the worker role may DELETE an organization.

ALTER TABLE organizations
  ADD COLUMN last_activity_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN archived_at      timestamptz,
  ADD COLUMN archive_after_days integer,
  ADD COLUMN delete_after_days  integer,
  ADD COLUMN retention_exempt        boolean NOT NULL DEFAULT false,
  ADD COLUMN retention_exempt_reason text,
  ADD COLUMN retention_exempt_until  timestamptz,
  ADD COLUMN retention_exempt_by     text,
  ADD COLUMN retention_exempt_at     timestamptz,
  ADD COLUMN legal_hold boolean NOT NULL DEFAULT false,
  ADD COLUMN deleted_at timestamptz,
  ADD CONSTRAINT chk_organizations_archive_days
    CHECK (archive_after_days IS NULL OR archive_after_days BETWEEN 60 AND 3650),
  ADD CONSTRAINT chk_organizations_delete_days
    CHECK (delete_after_days IS NULL OR delete_after_days BETWEEN 120 AND 7300),
  ADD CONSTRAINT chk_organizations_exempt_reason
    CHECK (NOT retention_exempt OR length(btrim(coalesce(retention_exempt_reason, ''))) >= 5),
  ADD CONSTRAINT chk_organizations_archived_at
    CHECK ((status = 'archived') = (archived_at IS NOT NULL));

-- Workspaces the owner deleted before this migration have no stamp: their last change is the best date there is.
UPDATE organizations SET deleted_at = updated_at WHERE status = 'deleted';

CREATE INDEX idx_orgs_owner_deleted ON organizations (deleted_at) WHERE status = 'deleted' AND legal_hold = false;

-- The sweep scans by last activity; only workspaces it can still act on.
CREATE INDEX idx_orgs_lifecycle_scan ON organizations (last_activity_at)
  WHERE retention_exempt = false AND legal_hold = false AND status IN ('active', 'archived');

CREATE TABLE org_lifecycle_log (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id           bigint NOT NULL,
  org_uuid         uuid   NOT NULL,
  -- reminder_sent | archived | restored | deleted | exemption_set | exemption_cleared | policy_changed |
  -- legal_hold_set | legal_hold_cleared | delete_blocked
  event_type       text   NOT NULL,
  stage            text,
  reminder_no      smallint,
  -- The last_activity_at this event belongs to: a reminder is unique per (workspace, stage, number, cycle), so a re-run cannot send
  -- twice, and a workspace that comes back and goes idle again gets a fresh ladder.
  inactivity_cycle timestamptz,
  days_inactive    integer,
  actor_type       text   NOT NULL DEFAULT 'system',
  actor_ref        text,
  details          jsonb  NOT NULL DEFAULT '{}',
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_org_lifecycle_log_stage CHECK (stage IS NULL OR stage IN ('archive', 'delete'))
);

CREATE UNIQUE INDEX org_lifecycle_log_reminder_once
  ON org_lifecycle_log (org_id, stage, reminder_no, inactivity_cycle) WHERE event_type = 'reminder_sent';
CREATE INDEX idx_org_lifecycle_log_org  ON org_lifecycle_log (org_id, created_at DESC);
CREATE INDEX idx_org_lifecycle_log_uuid ON org_lifecycle_log (org_uuid, created_at DESC);

CREATE TABLE storage_purge_queue (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id       bigint NOT NULL,
  org_uuid     uuid NOT NULL,
  storage_key  text NOT NULL,
  attempts     integer NOT NULL DEFAULT 0,
  last_error   text,
  purged_at    timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_storage_purge_pending ON storage_purge_queue (id) WHERE purged_at IS NULL;

-- The platform's own sales records, kept after the workspace is gone. Copied from `orders` at erase time, without the buyer's identity.
CREATE TABLE financial_records_archive (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_uuid          uuid NOT NULL,
  order_uuid        uuid NOT NULL,
  order_number      text NOT NULL UNIQUE,
  kind              text,
  status            text NOT NULL,
  currency          text NOT NULL,
  amount            numeric(12,2) NOT NULL,
  discount_amount   numeric(12,4) NOT NULL,
  tax_rate          numeric(5,2) NOT NULL,
  tax_amount        numeric(12,4) NOT NULL,
  total_amount      numeric(12,4) NOT NULL,
  billing_country   text,
  billing_tax_id    text,
  gateway_slug      text,
  gateway_order_id  text,
  gateway_payment_id text,
  paid_at           timestamptz,
  order_created_at  timestamptz NOT NULL,
  archived_at       timestamptz NOT NULL DEFAULT now(),
  retain_until      timestamptz NOT NULL
);
CREATE INDEX idx_financial_archive_expiry ON financial_records_archive (retain_until);

-- Platform tables, not tenant data: privileged transactions only.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['org_lifecycle_log', 'storage_purge_queue', 'financial_records_archive'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY platform_only ON %I FOR ALL USING (app_is_privileged()) WITH CHECK (app_is_privileged())', t);
  END LOOP;
END $$;

REVOKE UPDATE, DELETE ON org_lifecycle_log FROM crm_app, crm_worker;
-- No table-level REVOKE on the two queues: the platform_only policy above already shows crm_app nothing without the privileged flag,
-- and the key-rotation CLI scans every table as the app role, so a table it cannot read would break it.
GRANT DELETE ON organizations TO crm_worker;

COMMENT ON TABLE org_lifecycle_log IS
  'Append-only compliance record of workspace lifecycle decisions. No personal data. Survives workspace erasure by design.';
