-- wadev: connect a personal WhatsApp number (docs/specs/personal-whatsapp-connect.md sections 6, 8, 9, 10; BL-095 phase 1).
-- Why this migration exists:
--  1. `devices.status` (connected | disconnected | needs_pair) stays exactly as it is: the sender resolver, the dashboards, the operator
--     counts, the warmer and the public API read it. A person watching a pairing needs more than that (waiting for a scan is not
--     "needs re-pair", a blink is not a re-pair either: spec R3, R9), so the runtime now writes `connection_state`, `state_reason` and
--     `state_changed_at` in the same UPDATE as `status`. The API never writes a state other than `created` (the browser can never
--     assert "connected").
--  2. `phone_digits` + a partial unique index: WaDesk had no uniqueness on edit and a check-then-insert race on add. The digits are
--     maintained by the API (country code + local number, the same reduction the runtime's `senderDigits` uses). Rows that already
--     share digits keep NULL here, so the index can always be built and legacy duplicates are not silently merged.
--  3. `device_risk_acknowledgements`: who accepted which version of the risk notice, when, and a hash of the exact English text shown.
--     Append-only: a trigger refuses UPDATE and DELETE (a foreign key's own action, a workspace or user removal, runs one trigger level
--     deeper and is let through, as in wallet_append_only_cascade). `devices.consent_id` points at the acknowledgement that led to a
--     device.
--  4. Capability keys `wa.devices.*` (category whatsapp, no record scope: a device is a workspace resource like waba.numbers.*). The
--     trigger on permission_defs (20261013100000) gives every new key to the Owner and Admin presets of every existing workspace and
--     provisioning gives it to new ones; Manager, Agent and Viewer get nothing by default (owner decision D2: workspace admins only).

SELECT set_config('app.privileged', 'on', true);

-- --- the acknowledgement trail -----------------------------------------------------------------------------------------------------
CREATE TABLE device_risk_acknowledgements (
  org_id         bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid           uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id        bigint,
  -- A snapshot: the record must still name the person after the user row is gone.
  user_name      text NOT NULL,
  policy_version text NOT NULL,
  -- SHA-256 (hex) of the canonical English text of that version (`personalWaNoticeCanonicalText()` in @crm/contracts).
  text_sha256    text NOT NULL,
  locale         text NOT NULL DEFAULT 'en',
  -- The device this acknowledgement first led to; a plain uuid copy so it survives the device's deletion. NULL when accepted ahead of any device.
  device_uuid    uuid,
  accepted_at    timestamptz NOT NULL DEFAULT now(),
  user_agent     text,
  -- A hash of the caller's address, never the address.
  ip_hash        text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_device_risk_ack_user FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT chk_device_risk_ack_sha CHECK (text_sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT chk_device_risk_ack_user_agent CHECK (user_agent IS NULL OR char_length(user_agent) <= 255),
  CONSTRAINT chk_device_risk_ack_version CHECK (char_length(policy_version) BETWEEN 1 AND 32)
);
CREATE INDEX idx_device_risk_ack_user_version ON device_risk_acknowledgements (org_id, user_id, policy_version);

ALTER TABLE device_risk_acknowledgements ENABLE ROW LEVEL SECURITY;
ALTER TABLE device_risk_acknowledgements FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON device_risk_acknowledgements FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE OR REPLACE FUNCTION device_risk_ack_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- pg_trigger_depth() > 1: the database is applying a foreign key (user removed -> user_id set null, workspace removed -> cascade).
  IF pg_trigger_depth() > 1 THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  -- A privileged session (the operator console's sanctioned escape hatch) may remove rows; nobody may edit one.
  IF TG_OP = 'DELETE' AND app_is_privileged() THEN RETURN OLD; END IF;
  RAISE EXCEPTION 'device_risk_acknowledgements is append-only' USING ERRCODE = 'integrity_constraint_violation';
END $$;

CREATE TRIGGER trg_device_risk_ack_append_only BEFORE UPDATE OR DELETE ON device_risk_acknowledgements
  FOR EACH ROW EXECUTE FUNCTION device_risk_ack_append_only();

-- --- devices ---------------------------------------------------------------------------------------------------------------------
ALTER TABLE devices
  ADD COLUMN connection_state  text NOT NULL DEFAULT 'created',
  ADD COLUMN state_reason      text,
  ADD COLUMN state_changed_at  timestamptz,
  ADD COLUMN phone_digits      text,
  ADD COLUMN consent_id        bigint,
  ADD CONSTRAINT chk_devices_connection_state CHECK (connection_state IN
    ('created', 'awaiting_qr', 'awaiting_pairing_code', 'connecting', 'connected', 'disconnected', 'logged_out', 'error')),
  ADD CONSTRAINT chk_devices_state_reason CHECK (state_reason IS NULL OR char_length(state_reason) <= 64),
  ADD CONSTRAINT fk_devices_consent FOREIGN KEY (org_id, consent_id)
    REFERENCES device_risk_acknowledgements (org_id, id) ON DELETE SET NULL (consent_id);

-- The row trigger bumps row_version and updated_at: a backfill is not an edit.
ALTER TABLE devices DISABLE TRIGGER trg_devices_touch;

-- connected -> connected; disconnected with a saved session of at least 3 rows -> disconnected; everything else (never paired, or a
-- half-finished pairing) -> created (spec section 9).
UPDATE devices d
   SET connection_state = CASE
         WHEN d.status = 'connected' THEN 'connected'
         WHEN d.status = 'disconnected'
              AND (SELECT count(*) FROM device_auth_state a WHERE a.org_id = d.org_id AND a.device_id = d.id) >= 3 THEN 'disconnected'
         ELSE 'created' END;
UPDATE devices SET state_changed_at = coalesce(last_seen_at, updated_at) WHERE connection_state <> 'created';

-- phone_digits as the runtime's senderDigits(): local digits; a typed leading '+' means the local part already carries its country code;
-- otherwise the country code is put in front unless the local number already begins with it. The first row of a group keeps the digits.
WITH calc AS (
  SELECT org_id, id,
         regexp_replace(coalesce(phone_number, ''), '\D', '', 'g') AS local_digits,
         regexp_replace(coalesce(country_code, ''), '\D', '', 'g') AS cc,
         left(btrim(coalesce(phone_number, '')), 1) = '+' AS plus
    FROM devices
), digits AS (
  SELECT org_id, id,
         CASE WHEN local_digits = '' THEN NULL
              WHEN plus THEN local_digits
              WHEN cc <> '' AND left(local_digits, length(cc)) <> cc THEN cc || local_digits
              ELSE local_digits END AS d
    FROM calc
), ranked AS (
  SELECT org_id, id, d, row_number() OVER (PARTITION BY org_id, d ORDER BY id) AS rn FROM digits WHERE d IS NOT NULL
)
UPDATE devices x SET phone_digits = r.d FROM ranked r WHERE r.org_id = x.org_id AND r.id = x.id AND r.rn = 1;

ALTER TABLE devices ENABLE TRIGGER trg_devices_touch;

-- One personal number once per workspace. Cross-workspace uniqueness is a later decision (a lookup must not reveal that another
-- workspace has the number).
CREATE UNIQUE INDEX uq_devices_org_phone_digits ON devices (org_id, phone_digits) WHERE phone_digits IS NOT NULL;
CREATE INDEX idx_devices_connection_state ON devices (org_id, connection_state);

