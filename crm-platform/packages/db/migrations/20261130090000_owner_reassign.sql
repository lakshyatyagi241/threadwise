-- Reassign on demand, with an opt-in restore (BL-112 phase 2, docs/specs/contact-owner-leave-and-delegation.md section 10).
--
-- A manager moves the contacts (and open deals) of a person who is away to somebody else as ONE batch, and may ask for them to come back
-- on the day the person returns. "Come back" must only touch what nobody else touched since, so the question "was this owner changed
-- by somebody else after the batch?" has to be answered by the data, whatever code path changed it (single edit, bulk, import, merge,
-- auto-assignment, a flow). A trigger does it: whenever `owner_id` of a contact (or `owner_user_id` of a deal) changes, the row records
-- WHEN and BY WHICH BATCH (the batch code announces itself with the transaction setting `app.owner_batch_id`; every other path leaves it
-- empty and so clears the stamp). Restore then selects exactly the rows whose stamp is still this batch.

CREATE TABLE owner_reassign_batches (
  org_id            bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid              uuid NOT NULL DEFAULT gen_random_uuid(),
  from_user_id      bigint NOT NULL,
  -- user: one person; delegate: the from-user's delegate at the time; team: round robin over the team's available members.
  to_kind           text NOT NULL,
  to_user_id        bigint,
  to_team_id        bigint,
  include_deals     boolean NOT NULL DEFAULT true,
  reason            text,
  -- The day the person is back: the sweep restores on this day (workspace calendar). NULL = no automatic return (the default).
  restore_on        date,
  status            text NOT NULL DEFAULT 'applied',
  moved_contacts    integer NOT NULL DEFAULT 0,
  moved_deals       integer NOT NULL DEFAULT 0,
  restored_contacts integer NOT NULL DEFAULT 0,
  restored_deals    integer NOT NULL DEFAULT 0,
  -- Contacts and deals that stayed where they were at restore: changed by somebody else since, or deleted.
  not_restored      integer NOT NULL DEFAULT 0,
  -- Rows the batch could not take in this run (the per-run cap): run it again for the rest.
  remaining         integer NOT NULL DEFAULT 0,
  undo_until        timestamptz NOT NULL,
  restored_at       timestamptz,
  restored_by       bigint,
  created_by        bigint,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  row_version       integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, from_user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, to_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (to_user_id),
  FOREIGN KEY (org_id, to_team_id) REFERENCES teams (org_id, id) ON DELETE SET NULL (to_team_id),
  FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  FOREIGN KEY (org_id, restored_by) REFERENCES users (org_id, id) ON DELETE SET NULL (restored_by),
  CONSTRAINT chk_owner_reassign_kind CHECK (to_kind IN ('user', 'delegate', 'team')),
  CONSTRAINT chk_owner_reassign_status CHECK (status IN ('applied', 'restored', 'restore_blocked')),
  CONSTRAINT chk_owner_reassign_reason CHECK (reason IS NULL OR char_length(reason) <= 500)
);
CREATE INDEX idx_owner_reassign_from ON owner_reassign_batches (org_id, from_user_id, created_at DESC);
-- The sweep spans every workspace, so no org_id prefix.
CREATE INDEX idx_owner_reassign_sweep ON owner_reassign_batches (restore_on) WHERE status = 'applied' AND restore_on IS NOT NULL;

ALTER TABLE owner_reassign_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE owner_reassign_batches FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON owner_reassign_batches FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_owner_reassign_batches_touch BEFORE UPDATE ON owner_reassign_batches
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- The stamp on the records. Nullable, no default: adding them rewrites nothing.
ALTER TABLE contacts
  ADD COLUMN owner_changed_at timestamptz,
  ADD COLUMN owner_batch_id bigint,
  ADD FOREIGN KEY (org_id, owner_batch_id) REFERENCES owner_reassign_batches (org_id, id) ON DELETE SET NULL (owner_batch_id);
ALTER TABLE deals
  ADD COLUMN owner_changed_at timestamptz,
  ADD COLUMN owner_batch_id bigint,
  ADD FOREIGN KEY (org_id, owner_batch_id) REFERENCES owner_reassign_batches (org_id, id) ON DELETE SET NULL (owner_batch_id);
CREATE INDEX idx_contacts_owner_batch ON contacts (org_id, owner_batch_id) WHERE owner_batch_id IS NOT NULL;
CREATE INDEX idx_deals_owner_batch ON deals (org_id, owner_batch_id) WHERE owner_batch_id IS NOT NULL;

CREATE FUNCTION stamp_owner_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  old_owner bigint;
  new_owner bigint;
  batch text := nullif(current_setting('app.owner_batch_id', true), '');
BEGIN
  IF TG_TABLE_NAME = 'deals' THEN
    old_owner := OLD.owner_user_id; new_owner := NEW.owner_user_id;
  ELSE
    old_owner := OLD.owner_id; new_owner := NEW.owner_id;
  END IF;
  IF new_owner IS DISTINCT FROM old_owner THEN
    NEW.owner_changed_at := now();
    NEW.owner_batch_id := batch::bigint;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_contacts_owner_stamp BEFORE UPDATE OF owner_id ON contacts
  FOR EACH ROW EXECUTE FUNCTION stamp_owner_change();
CREATE TRIGGER trg_deals_owner_stamp BEFORE UPDATE OF owner_user_id ON deals
  FOR EACH ROW EXECUTE FUNCTION stamp_owner_change();
