-- workspace_addon_activation: a workspace's own switch on an add-on it is entitled to (docs/specs/addons-lifecycle-and-permissions.md, phase 1).
-- Why this migration exists: "may this workspace have the add-on" (the plan's offer, a purchase, an override) and "is it on for this workspace right
-- now" were one thing. An add-on the plan includes could not be turned off by the workspace, and uninstalling an included app changed nothing.
-- One row per (workspace, add-on) once the workspace has chosen: state 'disabled' is an opt-out (the features the add-on grants stop applying to that
-- workspace and, in phase 2, the plan does not install it again); 'active' keeps the history after it is switched back on. No row = active.
-- It covers plain add-ons (Smart routing, Teams and permissions...) and the add-on of a Marketplace app (the app's install and uninstall write it).
--
-- Also registers the permission `addons.activation.manage` (turn an included add-on on or off), held by Owner and Admin.
-- Nothing about any plan, offer, installation or role changes. Idempotent. Expand-only.

CREATE TABLE IF NOT EXISTS workspace_addon_activation (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  -- the add-on's row in the plan catalogue (kind = 'addon'): a global table, so a plain foreign key is right
  addon_id    bigint NOT NULL REFERENCES plans (id) ON DELETE CASCADE,
  state       text NOT NULL DEFAULT 'disabled',
  source      text NOT NULL DEFAULT 'user',
  changed_by  bigint,
  changed_at  timestamptz NOT NULL DEFAULT now(),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, addon_id),
  CONSTRAINT chk_workspace_addon_activation_state CHECK (state IN ('active', 'disabled')),
  CONSTRAINT chk_workspace_addon_activation_source CHECK (source IN ('user', 'operator', 'system')),
  FOREIGN KEY (org_id, changed_by) REFERENCES users (org_id, id)
);

ALTER TABLE workspace_addon_activation ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_addon_activation FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON workspace_addon_activation FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_workspace_addon_activation_touch BEFORE UPDATE ON workspace_addon_activation
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- "which workspaces switched this add-on off" (the operator's view, the add-on's removal) walks the other side of the key.
CREATE INDEX IF NOT EXISTS idx_workspace_addon_activation_addon ON workspace_addon_activation (addon_id);

-- --- the permission -------------------------------------------------------------------------------------------------------------------

INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('addons.activation.manage', 'Turn included add-ons on or off', 'addons', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label, category = EXCLUDED.category, supports_scope = EXCLUDED.supports_scope;

INSERT INTO workspace_preset_baseline (preset_key, permission_key, record_scope)
VALUES
  ('admin', 'addons.activation.manage', 'all'),
  ('workspace_admin', 'addons.activation.manage', 'all')
ON CONFLICT (preset_key, permission_key) DO NOTHING;

