-- line: channel-line data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's channel line features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: line_channels, line_flow_sessions, line_rich_menus, line_broadcasts, line_broadcast_recipients

-- WaDesk `line_channels` (tenant; 0 rows in the reference DB)
CREATE TABLE line_channels (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  connected_by bigint,
  channel_access_token text NOT NULL,  -- encrypted
  channel_secret text NOT NULL,  -- encrypted
  assertion_kid text,
  assertion_private_key text,  -- encrypted
  rotating_token text,  -- encrypted
  rotating_token_key_id text,  -- encrypted
  rotating_token_expires_at timestamptz,
  webhook_token text NOT NULL,
  line_channel_id text,
  basic_id text,
  display_name text,
  picture_url text,
  active boolean NOT NULL DEFAULT true,
  connected_at timestamptz,
  last_inbound_at timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_line_channels_webhook_token UNIQUE (webhook_token),
  CONSTRAINT fk_line_channels_connected_by FOREIGN KEY (org_id, connected_by) REFERENCES users (org_id, id) ON DELETE SET NULL (connected_by)
);
CREATE INDEX idx_line_channels_active ON line_channels (org_id, active);
CREATE INDEX idx_line_channels_line_channel_id ON line_channels (org_id, line_channel_id);

ALTER TABLE line_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE line_channels FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON line_channels FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_line_channels_touch BEFORE UPDATE ON line_channels
  FOR EACH ROW EXECUTE FUNCTION touch_row();

