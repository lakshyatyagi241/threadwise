-- chat: the channel registry (plan-inbox-chat.md sections 2 row 1, 3.2 and 3.3).
-- Why this migration exists: Reference points a conversation at `device_id` and has to pin a `provider` beside it, because `devices.id` and
-- `wa_provider_configs.id` are two id spaces. A channel is the one thing a conversation, a send and a webhook all name: a row per connected
-- way of talking to customers (the dev simulator today, a WhatsApp Cloud number next, a web chat widget later), with the provider's
-- credentials sealed by the application vault (CryptoService, AES-GCM) so a database dump is not a working set of API keys.
--
-- Secrets: `credentials_enc` holds one sealed JSON document (access token, app secret, ...). `webhook_token_hash` holds only the SHA-256 of
-- the token the provider's verification challenge must echo (shown once, on create and on rotate); a webhook that needs a signing secret
-- keeps it inside the sealed credentials. The list and read queries never select either column.
--
-- `conversations.channel_id` gets its composite foreign key to this table in 20261014100500_chat_channel_fks.sql (ON DELETE RESTRICT: a
-- channel with threads cannot be deleted, its threads would lose their provider).

CREATE TABLE channels (
  org_id                    bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                        bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                      uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Which adapter speaks for it: simulator, whatsapp_cloud, ... The set is the adapter registry's, not the database's, so a new channel
  -- type is a code change and not a migration; the check only keeps the value a plain token.
  kind                      text NOT NULL,
  name                      text NOT NULL,
  -- connected: may send. disconnected: kept but silent (credentials not verified yet, or switched off by a person). error: the provider
  -- refused our credentials.
  status                    text NOT NULL DEFAULT 'disconnected',
  -- The provider's own handle for the account (WhatsApp phone number id), for display and uniqueness.
  external_id               text,
  -- What a person recognises it by (the phone number).
  display_address           text,
  credentials_enc           text,
  -- The last four characters of each secret inside it ({"accessToken": "1a2b"}), kept beside it so a list can say which token is
  -- connected without opening the vault.
  credential_hints          jsonb NOT NULL DEFAULT '{}'::jsonb,
  webhook_token_hash        text,
  webhook_token_rotated_at  timestamptz,
  -- Per-channel overrides of what the adapter reports (a verified number that cannot send templates). Empty = the adapter's defaults.
  capabilities              jsonb NOT NULL DEFAULT '{}'::jsonb,
  settings                  jsonb NOT NULL DEFAULT '{}'::jsonb,
  last_event_at             timestamptz,
  created_by                bigint,
  created_at                timestamptz NOT NULL DEFAULT now(),
  updated_at                timestamptz NOT NULL DEFAULT now(),
  row_version               integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- A provider account is connected once per workspace (several simulators have no external id and never collide: NULLs are distinct).
  UNIQUE (org_id, kind, external_id),
  -- Composite so a channel can never be created by a user of another workspace; the channel outlives a removed user.
  FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_channels_kind CHECK (kind ~ '^[a-z][a-z0-9_]{1,31}$'),
  CONSTRAINT chk_channels_name CHECK (btrim(name) <> '' AND char_length(name) <= 120),
  CONSTRAINT chk_channels_status CHECK (status IN ('connected', 'disconnected', 'error')),
  -- Plaintext can never be stored by mistake: the vault's output starts with its version tag.
  CONSTRAINT chk_channels_credentials_sealed CHECK (credentials_enc IS NULL OR credentials_enc ~ '^v[0-9]+:'),
  CONSTRAINT chk_channels_webhook_token_hash CHECK (webhook_token_hash IS NULL OR webhook_token_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT chk_channels_capabilities CHECK (jsonb_typeof(capabilities) = 'object'),
  CONSTRAINT chk_channels_settings CHECK (jsonb_typeof(settings) = 'object'),
  CONSTRAINT chk_channels_credential_hints CHECK (jsonb_typeof(credential_hints) = 'object')
);

CREATE INDEX idx_channels_org_created ON channels (org_id, created_at, id);
CREATE INDEX idx_channels_created_by ON channels (org_id, created_by);

ALTER TABLE channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE channels FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON channels FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_channels_touch BEFORE UPDATE ON channels
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- the public webhook lookup ---------------------------------------------------------------------------------------------------------
-- A provider's webhook arrives with only the channel uuid in the URL, so there is no tenant yet and the row that names the tenant is behind
-- row-level security. Lifting RLS in application code for a public route is what the tenancy rules forbid, so the lookup is a SECURITY
-- DEFINER function that returns two ids for one uuid and nothing else (same pattern as wgt_widget_lookup). After it answers, the channel is
-- read, its signature verified and the message enqueued under the normal tenant context.
CREATE OR REPLACE FUNCTION chat_channel_lookup(p_uuid uuid)
RETURNS TABLE (channel_id bigint, channel_org_id bigint)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT c.id, c.org_id FROM channels c WHERE c.uuid = p_uuid;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION chat_channel_lookup(uuid) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION chat_channel_lookup(uuid) TO crm_app_user;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_worker_user') THEN
    GRANT EXECUTE ON FUNCTION chat_channel_lookup(uuid) TO crm_worker_user;
  END IF;
END
$$;
