-- deal: the lost-reason catalogue and the per-workspace deal settings.
-- Why this migration exists (TW-DEAL-043, D-08): Reference kept the lost reason as free text that no screen collected, so there
-- was nothing to report on. A workspace now keeps a short list of reasons a rep picks from, and can require one. The deal keeps
-- the reason's NAME as text too (deals.lost_reason): reports and history survive a reason being renamed or deleted, and the
-- API's free-text `reason` keeps working.

CREATE TABLE deal_lost_reasons (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_deal_lost_reasons_name CHECK (btrim(name) <> '' AND char_length(name) <= 191)
);
CREATE UNIQUE INDEX uq_deal_lost_reasons_org_lower_name ON deal_lost_reasons (org_id, lower(btrim(name)));
CREATE INDEX idx_deal_lost_reasons_order ON deal_lost_reasons (org_id, sort_order, id);

ALTER TABLE deal_lost_reasons ENABLE ROW LEVEL SECURITY;
ALTER TABLE deal_lost_reasons FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON deal_lost_reasons FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_deal_lost_reasons_touch BEFORE UPDATE ON deal_lost_reasons
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE deals
  ADD CONSTRAINT fk_deals_lost_reason_id FOREIGN KEY (org_id, lost_reason_id)
    REFERENCES deal_lost_reasons (org_id, id) ON DELETE SET NULL (lost_reason_id);

-- One row per workspace, created on first write.
CREATE TABLE deal_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  lost_reason_required boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id)
);

ALTER TABLE deal_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE deal_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON deal_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_deal_settings_touch BEFORE UPDATE ON deal_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();
