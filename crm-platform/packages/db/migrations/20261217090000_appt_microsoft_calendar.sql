-- appt: Outlook / Microsoft 365 calendar as a second provider behind the calendar port (BL-035, part 1).
-- Why this migration exists: a workspace could connect one Google account (appointment_calendar_connections). The calendar port now has a second
-- adapter, so (1) the Microsoft grant gets a table of its own with the same shape and the same sealing (refresh token under the credentials key),
-- (2) a workspace that has both connected says which one bookings are WRITTEN to (busy time is read from every connected calendar, events are
-- written to exactly one, so a booking is never duplicated), and (3) an appointment remembers which provider holds its event, so a change of
-- provider rewrites the event instead of patching an id that means nothing to the new calendar.
-- Microsoft rotates refresh tokens (a refresh returns a new one), unlike Google: `refresh_token_enc` is replaced on refresh.

CREATE TABLE appointment_microsoft_connections (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  -- The admin who confirmed the connection. SET NULL: the grant belongs to the workspace, not to that person's seat.
  connected_by bigint,
  account_email text,
  -- The Microsoft directory object id (`oid`/Graph `id`): a reconnect with another account must not keep the old account's calendar choice.
  account_sub text,
  refresh_token_enc text NOT NULL,   -- AES-GCM ciphertext (credentials key); never plain text
  access_token_enc text,             -- cached short-lived token, same sealing
  access_token_expires_at timestamptz,
  scopes text,
  -- `primary` = the account's default calendar (Graph `/me/calendar`); otherwise a Graph calendar id the admin picked.
  calendar_id text NOT NULL DEFAULT 'primary',
  calendar_name text,
  status text NOT NULL DEFAULT 'active',
  status_reason text,
  status_at timestamptz NOT NULL DEFAULT now(),
  connected_at timestamptz NOT NULL DEFAULT now(),
  last_error_code text,
  last_error_at timestamptz,
  last_used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- One Microsoft account per workspace, as for Google.
  CONSTRAINT uq_appointment_microsoft_connections_org UNIQUE (org_id),
  CONSTRAINT chk_appointment_microsoft_connections_status CHECK (status IN ('active', 'needs_reconnect')),
  CONSTRAINT chk_appointment_microsoft_connections_last_error CHECK ((last_error_code IS NULL) = (last_error_at IS NULL)),
  CONSTRAINT fk_appointment_microsoft_connections_connected_by FOREIGN KEY (org_id, connected_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (connected_by)
);
CREATE INDEX idx_appointment_microsoft_connections_connected_by ON appointment_microsoft_connections (org_id, connected_by);

ALTER TABLE appointment_microsoft_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointment_microsoft_connections FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON appointment_microsoft_connections FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_appointment_microsoft_connections_touch BEFORE UPDATE ON appointment_microsoft_connections
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Which connected calendar bookings are written to. No row = automatic: Google when it is usable, else Microsoft (what a workspace that only
-- ever had Google already did). A row is an admin's explicit choice and is honoured while that provider is usable.
CREATE TABLE appointment_calendar_preferences (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider text NOT NULL,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_appointment_calendar_preferences_org UNIQUE (org_id),
  CONSTRAINT chk_appointment_calendar_preferences_provider CHECK (provider IN ('google', 'microsoft')),
  CONSTRAINT fk_appointment_calendar_preferences_updated_by FOREIGN KEY (org_id, updated_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (updated_by)
);
CREATE INDEX idx_appointment_calendar_preferences_updated_by ON appointment_calendar_preferences (org_id, updated_by);

ALTER TABLE appointment_calendar_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointment_calendar_preferences FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON appointment_calendar_preferences FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_appointment_calendar_preferences_touch BEFORE UPDATE ON appointment_calendar_preferences
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Which provider holds an appointment's event. NULL with an event id means Google (every event written before this migration): no UPDATE of
-- existing rows here, because a write to `appointments` bumps `row_version` and would hand every open editor a 409.
ALTER TABLE appointments
  ADD COLUMN calendar_provider text,
  ADD CONSTRAINT chk_appointments_calendar_provider CHECK (calendar_provider IS NULL OR calendar_provider IN ('google', 'microsoft'));
