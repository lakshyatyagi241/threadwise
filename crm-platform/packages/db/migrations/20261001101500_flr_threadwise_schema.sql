-- flr: flow-runtime-engine data model, ported from Reference
-- Why this migration exists: the tables Reference's flow runtime engine features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: flow_subscribers, flow_retry_logs

-- Reference `flow_subscribers` (child; 0 rows in the reference DB)
CREATE TABLE flow_subscribers (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_id bigint NOT NULL,
  contact_id bigint NOT NULL,
  enrolled_at timestamptz,
  completed_at timestamptz,
  failed_at timestamptz,
  failure_reason text,
  status text NOT NULL DEFAULT 'active',
  retry_count integer NOT NULL DEFAULT 0,
  last_retried_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_flow_subscribers_flow_id_contact_id UNIQUE (org_id, flow_id, contact_id),
  CONSTRAINT fk_flow_subscribers_flow_id FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_flow_subscribers_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_flow_subscribers_contact_id ON flow_subscribers (org_id, contact_id);
CREATE INDEX idx_flow_subscribers_flow_id_status ON flow_subscribers (org_id, flow_id, status);

ALTER TABLE flow_subscribers ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_subscribers FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_subscribers FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_flow_subscribers_touch BEFORE UPDATE ON flow_subscribers
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `flow_retry_logs` (tenant; 0 rows in the reference DB)
CREATE TABLE flow_retry_logs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_id bigint NOT NULL,
  flow_subscriber_id bigint NOT NULL,
  contact_id bigint,
  retried_by_user_id bigint,
  previous_status text,
  previous_failure_reason text,
  outcome text NOT NULL DEFAULT 'queued',
  outcome_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_flow_retry_logs_flow_id FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_flow_retry_logs_flow_subscriber_id FOREIGN KEY (org_id, flow_subscriber_id) REFERENCES flow_subscribers (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_flow_retry_logs_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_flow_retry_logs_retried_by_user_id FOREIGN KEY (org_id, retried_by_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (retried_by_user_id)
);
CREATE INDEX idx_flow_retry_logs_flow_id ON flow_retry_logs (org_id, flow_id);
CREATE INDEX idx_flow_retry_logs_flow_subscriber_id ON flow_retry_logs (org_id, flow_subscriber_id);
CREATE INDEX idx_flow_retry_logs_outcome ON flow_retry_logs (org_id, outcome);
CREATE INDEX idx_flow_retry_logs_created_at ON flow_retry_logs (org_id, created_at);

ALTER TABLE flow_retry_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_retry_logs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_retry_logs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_flow_retry_logs_touch BEFORE UPDATE ON flow_retry_logs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
