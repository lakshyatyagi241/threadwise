-- Bootstrap partitions (previous month, current, next two) and a catch-all so a gap in partition
-- maintenance degrades into rows landing in _default instead of failed writes. Add each parent to
-- PARTITIONED_TABLES in apps/api/src/workers/partition-maintenance.service.ts.
DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('hubspot_integration_logs', m);
    PERFORM ensure_monthly_partition('slack_integration_logs', m);
    PERFORM ensure_monthly_partition('trello_integration_logs', m);
    PERFORM ensure_monthly_partition('webhook_deliveries', m);
  END LOOP;
END $$;
CREATE TABLE hubspot_integration_logs_default PARTITION OF hubspot_integration_logs DEFAULT;
CREATE TABLE slack_integration_logs_default PARTITION OF slack_integration_logs DEFAULT;
CREATE TABLE trello_integration_logs_default PARTITION OF trello_integration_logs DEFAULT;
CREATE TABLE webhook_deliveries_default PARTITION OF webhook_deliveries DEFAULT;
