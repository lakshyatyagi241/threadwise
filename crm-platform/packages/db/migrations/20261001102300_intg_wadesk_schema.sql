-- intg: integrations-hubspot-slack-trello-google-webhooks data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's integrations hubspot slack trello google webhooks features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: hubspot_integrations, hubspot_integration_logs, incoming_webhooks, incoming_webhook_events, slack_integrations, slack_integration_logs, trello_integrations, trello_integration_logs, webhooks, webhook_deliveries

-- WaDesk `hubspot_integrations` (tenant; 0 rows in the reference DB)
CREATE TABLE hubspot_integrations (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  portal_id text,
  portal_name text,
  portal_email text,
  access_token text NOT NULL,  -- encrypted
  refresh_token text NOT NULL,  -- encrypted
  access_token_expires_at timestamptz,
  scopes text,
  status text NOT NULL DEFAULT 'active',
  metadata jsonb,
  last_verified_at timestamptz,
  connected_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_hubspot_integrations_portal_id UNIQUE (org_id, portal_id),
  CONSTRAINT fk_hubspot_integrations_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_hubspot_integrations_user_id ON hubspot_integrations (org_id, user_id);

ALTER TABLE hubspot_integrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE hubspot_integrations FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON hubspot_integrations FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_hubspot_integrations_touch BEFORE UPDATE ON hubspot_integrations
  FOR EACH ROW EXECUTE FUNCTION touch_row();

