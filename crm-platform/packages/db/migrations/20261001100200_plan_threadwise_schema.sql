-- Reference `subscriptions` (tenant; 0 rows in the reference DB)
CREATE TABLE subscriptions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  package_id bigint,
  plan_id text,
  gateway text NOT NULL,
  gateway_subscription_id text,
  gateway_plan_id text,
  gateway_customer_id text,
  billing_cycle text NOT NULL DEFAULT 'monthly',
  status text NOT NULL DEFAULT 'pending',
  amount numeric(12,2) NOT NULL DEFAULT 0.00,
  currency text NOT NULL DEFAULT 'USD',
  current_period_end timestamptz,
  renewals_count integer NOT NULL DEFAULT 0,
  meta jsonb,
  canceled_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_subscriptions_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_subscriptions_package_id FOREIGN KEY (package_id) REFERENCES packages (id) ON DELETE SET NULL
);
CREATE INDEX idx_subscriptions_gateway_gateway_subscription_id ON subscriptions (org_id, gateway, gateway_subscription_id);
CREATE INDEX idx_subscriptions_gateway_subscription_id ON subscriptions (org_id, gateway_subscription_id);
