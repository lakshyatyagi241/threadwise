-- wgt: the images a flow bot's widget carries (its logo and its popup picture), uploaded in the Customize tab.
-- Why this migration exists: a website widget can only show an image its visitors' browsers can fetch, and a link to somebody
-- else's server is gone the day they move it. The upload is kept here (the same interim storage the workspace logo uses, small
-- and replaced in place) and served from a public address that names the flow, not the tenant. One row per flow and slot, so
-- replacing a picture overwrites it and a deleted flow takes its pictures with it. The public read goes through a narrow
-- SECURITY DEFINER lookup (like `wgt_widget_lookup`) because the request arrives with no tenant; the lookup returns the one
-- picture asked for and nothing else.
CREATE TABLE flow_widget_assets (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_id     bigint NOT NULL,
  slot        text NOT NULL,
  mime        text NOT NULL,
  bytes       bytea NOT NULL,
  etag        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, flow_id, slot),
  FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_flow_widget_assets_slot CHECK (slot IN ('logo', 'popup')),
  CONSTRAINT chk_flow_widget_assets_mime CHECK (mime IN ('image/png', 'image/jpeg', 'image/webp', 'image/gif')),
  CONSTRAINT chk_flow_widget_assets_size CHECK (octet_length(bytes) <= 1048576)
);

ALTER TABLE flow_widget_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_widget_assets FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_widget_assets FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_flow_widget_assets_touch BEFORE UPDATE ON flow_widget_assets
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE OR REPLACE FUNCTION wgt_asset_lookup(p_flow uuid, p_slot text)
RETURNS TABLE (asset_mime text, asset_bytes bytea, asset_etag text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT a.mime, a.bytes, a.etag
      FROM flow_widget_assets a
      JOIN flows f ON f.org_id = a.org_id AND f.id = a.flow_id
     WHERE f.uuid = p_flow AND a.slot = p_slot;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION wgt_asset_lookup(uuid, text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION wgt_asset_lookup(uuid, text) TO crm_app_user;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_worker_user') THEN
    GRANT EXECUTE ON FUNCTION wgt_asset_lookup(uuid, text) TO crm_worker_user;
  END IF;
END
$$;
