-- paygw: the bytes of an offline-payment proof (TW-PAYGW-013) and the lookups the subscription lifecycle needs (TW-PAYGW-029/030).
-- Why a table for the proof: Reference wrote the receipt to a public media disk and the admin opened a guessable URL. Until an
-- object-store adapter is wired for private files, the bytes live next to the order, inside the tenant's row-level security, and are
-- served only through authenticated routes (the buyer's own order, or an operator). One proof per order: a re-upload replaces the
-- bytes (Reference left the old file orphaned). 4 MB is the hard cap, enforced again here.
-- Why the indexes: a provider notification names only the provider's subscription id, so it must be found across workspaces
-- (through PaygwStore); the existing indexes start with org_id and cannot serve that.

CREATE TABLE order_proof_blobs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  order_id bigint NOT NULL,
  mime text NOT NULL,
  byte_size integer NOT NULL,
  bytes bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_order_proof_blobs_order_id UNIQUE (org_id, order_id),
  CONSTRAINT chk_order_proof_blobs_size CHECK (byte_size BETWEEN 1 AND 4194304),
  CONSTRAINT chk_order_proof_blobs_mime CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  CONSTRAINT fk_order_proof_blobs_order_id FOREIGN KEY (org_id, order_id) REFERENCES orders (org_id, id) ON DELETE CASCADE
);

ALTER TABLE order_proof_blobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_proof_blobs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON order_proof_blobs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_order_proof_blobs_touch BEFORE UPDATE ON order_proof_blobs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A notification finds its subscription by (gateway, provider subscription id); the first charge also by our order number.
CREATE INDEX idx_subscriptions_gateway_sub_global ON subscriptions (gateway, gateway_subscription_id)
  WHERE gateway_subscription_id IS NOT NULL;
CREATE INDEX idx_subscriptions_gateway_plan_global ON subscriptions (gateway, gateway_plan_id)
  WHERE gateway_plan_id IS NOT NULL;
CREATE INDEX idx_subscriptions_order_number ON subscriptions ((meta ->> 'order_number'))
  WHERE meta ->> 'order_number' IS NOT NULL;
-- One pending subscription per order and gateway (a retried checkout reuses it instead of piling up rows).
CREATE UNIQUE INDEX uq_subscriptions_pending_order ON subscriptions (org_id, gateway, (meta ->> 'order_number'))
  WHERE status = 'pending' AND meta ->> 'order_number' IS NOT NULL;
