-- chat: the inbound/outbound ledger and the per-message event log (plan-inbox-chat.md sections 3.3 and 3.4).
-- Why this migration exists: `messages` is partitioned by month, and a partitioned table can only enforce a unique key that contains
-- the partition column, so "this provider message id was already stored" cannot be a constraint on `messages` itself. The ledger is
-- the small, flat table that can. It does two jobs:
--   1. Idempotency authority. Ingest does `INSERT ... ON CONFLICT DO NOTHING RETURNING` here first; no row back means a duplicate
--      delivery and the pipeline stops (a redelivery after the queue's own job-id memory expired, two concurrent deliveries, a client
--      retry of the same Idempotency-Key). BullMQ's job id is only an optimisation in front of this.
--   2. Receipt routing. A delivery receipt carries only the provider's id; the ledger row says which message (and which partition, via
--      `message_created_at`) it belongs to, so the status update is a primary-key lookup instead of a scan of every partition.
-- Because the message does not exist yet when the ledger row is written, the pipeline allocates the message id and timestamp first
-- (`nextval('messages_id_seq')`, `statement_timestamp()`) in the same transaction and inserts the message with them.
--
-- `message_events` keeps every state change and every receipt, including the ones the summary columns ignore because they arrived out
-- of order, so the history is complete even when `messages.status` (monotonic) is not. Retention is about 180 days
-- (architecture/messaging.md); the ledger is swept after about 60 days (`created_at` index).
--
-- Foreign keys: the ledger points at the conversation (cascade) and, in 20261014100500, at the channel. It does not point at
-- `messages` (a stream; the ledger outlives nothing it needs to protect). `message_events` is a stream with no foreign keys, like
-- `conversation_events`.

CREATE TABLE message_ledger (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  channel_id bigint NOT NULL,
  -- provider_id: the channel's message id (inbound message, or an outbound message once the channel accepted it).
  -- client_id: the sender's own id (clientMessageId / Idempotency-Key) for an outbound message.
  kind text NOT NULL,
  key text NOT NULL,
  message_id bigint NOT NULL,
  message_created_at timestamptz NOT NULL,
  conversation_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  CONSTRAINT uq_message_ledger_key UNIQUE (org_id, channel_id, kind, key),
  CONSTRAINT chk_message_ledger_kind CHECK (kind IN ('provider_id', 'client_id')),
  CONSTRAINT chk_message_ledger_key CHECK (length(key) BETWEEN 1 AND 512),
  CONSTRAINT fk_message_ledger_conversation_id FOREIGN KEY (org_id, conversation_id) REFERENCES conversations (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_message_ledger_message ON message_ledger (org_id, message_id);
CREATE INDEX idx_message_ledger_conversation ON message_ledger (org_id, conversation_id);
-- The sweep deletes old rows across every workspace, so it is not org-prefixed.
CREATE INDEX idx_message_ledger_created ON message_ledger (created_at);

ALTER TABLE message_ledger ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_ledger FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON message_ledger FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- Event log, one row per state change or receipt of a message. `created_at` is the time the event happened (and the partition key).
CREATE SEQUENCE message_events_id_seq;
CREATE TABLE message_events (
  id bigint NOT NULL DEFAULT nextval('message_events_id_seq'),
  org_id bigint NOT NULL,
  message_id bigint NOT NULL,
  message_created_at timestamptz NOT NULL,
  event text NOT NULL,
  detail jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at),
  CONSTRAINT chk_message_events_event CHECK (event IN ('queued', 'attempt', 'retry', 'sent', 'delivered', 'read', 'failed'))
) PARTITION BY RANGE (created_at);
-- Reading a message's history by id; `message_created_at` lets the planner prune to the message's own partition.
CREATE INDEX idx_message_events_message ON message_events (org_id, message_id, message_created_at);

ALTER TABLE message_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON message_events FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('message_events', m);
  END LOOP;
END $$;
CREATE TABLE message_events_default PARTITION OF message_events DEFAULT;
SELECT inherit_partition_rls('message_events_default');
GRANT SELECT, INSERT, UPDATE, DELETE ON message_events_default TO crm_app, crm_worker;
