-- tib2: team-inbox-routing-sla data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's team inbox routing sla features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: agent_statuses, routing_rules, sla_policies, sla_breaches

-- WaDesk `agent_statuses` (tenant; 1 rows in the reference DB)
CREATE TABLE agent_statuses (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  status text NOT NULL DEFAULT 'online',
  status_message text,
  last_seen_at timestamptz,
  current_load integer NOT NULL DEFAULT 0,
  today_replies integer NOT NULL DEFAULT 0,
  today_resolutions integer NOT NULL DEFAULT 0,
  counters_date date,
  preferences jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_agent_statuses_user_id UNIQUE (org_id, user_id),
  CONSTRAINT fk_agent_statuses_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_agent_statuses_last_seen_at ON agent_statuses (org_id, last_seen_at);

ALTER TABLE agent_statuses ENABLE ROW LEVEL SECURITY;
ALTER TABLE agent_statuses FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON agent_statuses FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_agent_statuses_touch BEFORE UPDATE ON agent_statuses
  FOR EACH ROW EXECUTE FUNCTION touch_row();

