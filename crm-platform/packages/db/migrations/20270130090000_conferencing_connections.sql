-- conferencing: a person's own Zoom or Microsoft Teams account (BL-360).
-- Why this migration exists: a meeting scheduled on a contact can carry a video link. Zoom and Teams links are made in the SCHEDULER's account
-- (the host of the call), not in one account shared by the workspace, so unlike the workspace calendar grant (appointment_calendar_connections,
-- one row per workspace) this grant is one row per person per provider. The workspace installs the Marketplace listing first (consent and
-- availability); each person then connects their own account. Google Meet needs no row here: Google makes the room when the meeting is put on
-- the workspace's connected Google Calendar, and Teams may also be made by the Microsoft 365 calendar.
-- Tokens are sealed with the credentials key (AES-GCM, as appointment_calendar_connections); Microsoft and Zoom both rotate refresh tokens, so
-- `refresh_token_enc` is replaced on every refresh. Not personal data of a contact: it is the staff member's own account (privacy allowlist).

CREATE TABLE conferencing_connections (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL,
  provider text NOT NULL,
  account_email text,
  -- The provider's stable id of the account (Zoom user id, Microsoft directory object id): a reconnect with another account is visible.
  account_sub text,
  refresh_token_enc text NOT NULL,   -- AES-GCM ciphertext (credentials key); never plain text
  access_token_enc text,             -- cached short-lived token, same sealing
  access_token_expires_at timestamptz,
  scopes text,
  status text NOT NULL DEFAULT 'active',
  status_reason text,
  status_at timestamptz NOT NULL DEFAULT now(),
  connected_at timestamptz NOT NULL DEFAULT now(),
  last_error_code text,
  last_error_at timestamptz,
  last_used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- One account per person per provider: connecting again replaces the grant.
  CONSTRAINT uq_conferencing_connections_user_provider UNIQUE (org_id, user_id, provider),
  CONSTRAINT chk_conferencing_connections_provider CHECK (provider IN ('zoom', 'teams')),
  CONSTRAINT chk_conferencing_connections_status CHECK (status IN ('active', 'needs_reconnect')),
  CONSTRAINT chk_conferencing_connections_last_error CHECK ((last_error_code IS NULL) = (last_error_at IS NULL)),
  -- A person who leaves takes their connections with them: the grant is theirs, not the workspace's.
  CONSTRAINT fk_conferencing_connections_user FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);

ALTER TABLE conferencing_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE conferencing_connections FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON conferencing_connections FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_conferencing_connections_touch BEFORE UPDATE ON conferencing_connections
  FOR EACH ROW EXECUTE FUNCTION touch_row();
