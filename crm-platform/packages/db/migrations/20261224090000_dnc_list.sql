-- Do-Not-Call list (BL-181, spec docs/specs/privacy-and-data-governance.md section 11.11) and the DPDP consent manager's registration id.
--
-- Why. A workspace that calls or texts people for marketing must be able to say "never this number", whatever the ledger says: the person
-- may have asked on the phone, may be on a national registry the workspace is entitled to download, or may sit on a list the business
-- keeps itself. The Compliance center only stored a note about a registry (BL-176/177). This is the workspace's own list, and the
-- ConsentGate reads it: marketing on the `voice` and `sms` channels to a listed number is denied (reason `on_dnc_list`).
--
--   dnc_entries    one row per number per workspace. `phone` is E.164 with its plus; `phone_digits` is the same number without it and is what
--                  the gate matches on (a contact's stored number may carry the plus or not). `source` says where the entry came from:
--                  `manual` (a person typed or pasted it), `import` (a CSV), `contact_request` (the person asked the workspace), or
--                  `registry_export` (an extract the workspace downloaded from a registry it is entitled to use). NO registry is called
--                  from here; that needs a licence and credentials (BL-221).
--
--   compliance_settings.consent_manager_registration   the registration number of the DPDP Consent Manager the workspace uses (a note;
--                  the inbound hook is a contract only, BL-222).
--
-- Additive: nothing is backfilled and no existing statement is touched.

CREATE TABLE dnc_entries (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  phone           text NOT NULL,
  phone_digits    text GENERATED ALWAYS AS (regexp_replace(phone, '[^0-9]', '', 'g')) STORED,
  source          text NOT NULL DEFAULT 'manual',
  note            text,
  added_by        bigint,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- One entry per number: adding a number twice is a no-op, not a second row.
  UNIQUE (org_id, phone_digits),
  CONSTRAINT fk_dnc_added_by FOREIGN KEY (org_id, added_by) REFERENCES users (org_id, id) ON DELETE SET NULL (added_by),
  CONSTRAINT ck_dnc_phone CHECK (phone ~ '^\+[1-9][0-9]{6,14}$'),
  CONSTRAINT ck_dnc_source CHECK (source IN ('manual', 'import', 'contact_request', 'registry_export')),
  CONSTRAINT ck_dnc_note CHECK (note IS NULL OR char_length(note) <= 300)
);
-- The list screen: newest first, per workspace.
CREATE INDEX idx_dnc_entries_created ON dnc_entries (org_id, created_at DESC, id DESC);

ALTER TABLE dnc_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE dnc_entries FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON dnc_entries FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

ALTER TABLE compliance_settings
  ADD COLUMN consent_manager_registration text NOT NULL DEFAULT '',
  ADD CONSTRAINT ck_compliance_cm_registration CHECK (char_length(consent_manager_registration) <= 60);
