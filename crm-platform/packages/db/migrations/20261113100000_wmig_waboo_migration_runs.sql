-- wmig: operator-run Waboo -> WaDesk migration (platform table, not a WaDesk feature).
-- One row per run of the existing migration pipeline. Holds the client key, the database NAME, the step timeline and the final
-- report numbers. It never holds a credential, token or connection string (the pipeline reads those from its own environment).
-- Platform (operator) table: no tenant column of its own; org_id is only the workspace the load created.

CREATE TABLE waboo_migration_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  source_client text NOT NULL,
  source_db text NOT NULL,
  org_id bigint REFERENCES organizations (id) ON DELETE SET NULL,
  mode text NOT NULL DEFAULT 'dry',
  status text NOT NULL DEFAULT 'queued',
  -- [{name,status,startedAt,finishedAt,counts,message}]
  steps jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- {green,unaccounted,integrityErrors,alarms,summary}
  report jsonb,
  error text,
  created_by bigint,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_wmig_client CHECK (source_client ~ '^[a-z0-9_-]{1,64}$'),
  CONSTRAINT chk_wmig_db CHECK (source_db ~ '^[A-Za-z0-9_]{1,128}$'),
  CONSTRAINT chk_wmig_mode CHECK (mode IN ('dry', 'load')),
  CONSTRAINT chk_wmig_status CHECK (status IN ('queued', 'running', 'completed', 'failed', 'cancelled')),
  CONSTRAINT chk_wmig_steps CHECK (jsonb_typeof(steps) = 'array')
);

-- Only ONE active run per client.
CREATE UNIQUE INDEX uq_wmig_active_client ON waboo_migration_runs (source_client)
  WHERE status IN ('queued', 'running');
-- Recovery sweep and the runs list.
CREATE INDEX idx_wmig_status ON waboo_migration_runs (status, started_at);
CREATE INDEX idx_wmig_created ON waboo_migration_runs (created_at DESC);

ALTER TABLE waboo_migration_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE waboo_migration_runs FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON waboo_migration_runs FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_waboo_migration_runs_touch BEFORE UPDATE ON waboo_migration_runs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
