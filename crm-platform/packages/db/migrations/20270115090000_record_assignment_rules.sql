-- On for the plans that carry SLA policies (the higher tier), off for every other plan. A plan that already lists the key keeps its value
-- (an operator's choice is never overwritten). `plans` is platform-owned with forced row-level security, hence the privileged flag.
UPDATE plans
SET features = features || jsonb_build_object('record_assignment', coalesce(features ->> 'inbox_sla', 'false') = 'true'),
    updated_at = now()
WHERE kind = 'plan' AND NOT (features ? 'record_assignment');
