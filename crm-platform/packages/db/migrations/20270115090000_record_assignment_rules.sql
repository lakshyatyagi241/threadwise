-- Record assignment rules (BL-340..BL-345): the contact and deal auto-assignment of 20261130090100 grows into rules for contacts, COMPANIES and
-- deals, with a field-by-field condition tree instead of flat keyword lists, a run log that says why a record went where it went, optional
-- reassign-on-update, and a plan gate of its own that only the higher plans carry.
--
--  * assignment_rules: subject 'company' is allowed; `rules` holds the condition tree (the segment tree: AND / OR groups over the fields of
--    the module). NULL = no condition, which is the fallback rule. The old flat `conditions` column stays for rules saved before this
--    migration (the engine reads them as the tree `legacyConditionsToRules` makes of them) and is emptied the first time a rule is edited.
--    `reassign_on_update` (default off), `description` and `updated_by` (last modified by) are new.
--  * companies.owner_changed_at + trigger: the same "a person decided this owner" stamp contacts and deals have, so the engine never
--    overrules an owner somebody set (the shared stamp function writes batch columns companies do not have, so companies get their own).
--  * assignment_runs: one row per decision (assigned, reassigned, skipped) with the rule, the person, the method and a trace of every rule
--    tried. It holds ids only, never a name or a phone number: the screen reads the record's current name when it lists the log, so erasing
--    a person leaves nothing personal here. Kept 90 days (swept by the worker).
--  * plan feature `record_assignment`: switched on only for the plans that already carry SLA policies (the higher tier), explicitly off
--    for every other plan. The registry default is false, so a plan created later is off until the operator ticks it.

-- --- rules ------------------------------------------------------------------------------------------------------------------------

ALTER TABLE assignment_rules DROP CONSTRAINT chk_assignment_rules_subject;
ALTER TABLE assignment_rules
  ADD CONSTRAINT chk_assignment_rules_subject CHECK (subject IN ('contact', 'company', 'deal'));

ALTER TABLE assignment_rules
  ADD COLUMN description        text NOT NULL DEFAULT '',
  ADD COLUMN rules              jsonb,
  ADD COLUMN reassign_on_update boolean NOT NULL DEFAULT false,
  ADD COLUMN updated_by         bigint,
  ADD CONSTRAINT chk_assignment_rules_description CHECK (char_length(description) <= 500),
  ADD CONSTRAINT fk_assignment_rules_updated_by FOREIGN KEY (org_id, updated_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (updated_by);

-- --- companies: who decided the owner ----------------------------------------------------------------------------------------------

ALTER TABLE companies ADD COLUMN owner_changed_at timestamptz;

CREATE FUNCTION stamp_company_owner_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.owner_id IS DISTINCT FROM OLD.owner_id THEN
    NEW.owner_changed_at := now();
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_companies_owner_stamp BEFORE UPDATE OF owner_id ON companies
  FOR EACH ROW EXECUTE FUNCTION stamp_company_owner_change();

-- --- the run log -------------------------------------------------------------------------------------------------------------------

CREATE TABLE assignment_runs (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  subject     text NOT NULL,
  -- The record's internal id. No foreign key: the record may be deleted or erased while the decision stays in the log.
  record_id   bigint NOT NULL,
  rule_id     bigint,
  -- The rule's name when it ran (the rule may be renamed or deleted later).
  rule_name   text,
  outcome     text NOT NULL,
  reason      text NOT NULL,
  owner_id    bigint,
  method      text,
  origin      text NOT NULL DEFAULT 'manual',
  trigger     text NOT NULL DEFAULT 'created',
  -- Every active rule in the order it was tried: [{ruleId, name, matched, nobody, broken}].
  trace       jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- The record's owner_changed_at right after the engine wrote the owner: a later change of owner (by a person) no longer equals it,
  -- which is how reassign-on-update tells "still the engine's pick" from "somebody took over".
  owner_stamp timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, rule_id) REFERENCES assignment_rules (org_id, id) ON DELETE SET NULL (rule_id),
  FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_id),
  CONSTRAINT chk_assignment_runs_subject CHECK (subject IN ('contact', 'company', 'deal')),
  CONSTRAINT chk_assignment_runs_outcome CHECK (outcome IN ('assigned', 'reassigned', 'skipped')),
  CONSTRAINT chk_assignment_runs_trigger CHECK (trigger IN ('created', 'updated'))
);
CREATE INDEX idx_assignment_runs_recent ON assignment_runs (org_id, created_at DESC, id DESC);
CREATE INDEX idx_assignment_runs_record ON assignment_runs (org_id, subject, record_id, id DESC);
CREATE INDEX idx_assignment_runs_rule ON assignment_runs (org_id, rule_id, id DESC) WHERE rule_id IS NOT NULL;
ALTER TABLE assignment_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE assignment_runs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON assignment_runs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

