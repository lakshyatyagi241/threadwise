-- cpn: one row per redeemed order, so counting a redemption can never happen twice.
-- Why this migration exists (WD-CPN-008): WaDesk bumped `coupons.uses_count` inside its "finalize order" step and relied on that
-- step returning early for an order that was already paid. Here the count is also bumped by an outbox consumer (at-least-once
-- delivery) and by the checkout's own paid transition, so the guarantee has to live in the data: UNIQUE (org_id, order_id) turns
-- a second attempt into a no-op, and only the attempt that inserts the row increments the counter.
-- The coupon code is kept as a snapshot because deleting a coupon must not erase the history of what it was redeemed for.
-- A redemption belongs to the workspace that paid the order, so this is an ordinary tenant table (the coupon itself is platform
-- data; the consumer and the checkout reach the coupon row through the platform door).

CREATE TABLE coupon_redemptions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  order_id bigint NOT NULL,
  coupon_id bigint REFERENCES coupons (id) ON DELETE SET NULL,
  coupon_code text NOT NULL,
  user_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_coupon_redemptions_order UNIQUE (org_id, order_id),
  CONSTRAINT fk_coupon_redemptions_order FOREIGN KEY (org_id, order_id) REFERENCES orders (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_coupon_redemptions_coupon ON coupon_redemptions (coupon_id);

ALTER TABLE coupon_redemptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE coupon_redemptions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON coupon_redemptions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_coupon_redemptions_touch BEFORE UPDATE ON coupon_redemptions
  FOR EACH ROW EXECUTE FUNCTION touch_row();
