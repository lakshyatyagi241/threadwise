-- 2042_wallet_legacy_invoices
-- Why this migration exists (not what it does — the SQL says that):
--
-- A wallet top-up paid in the old system has an invoice there (kept by its billing provider, fetched when the person clicks
-- Download Invoice). A top-up paid in this application has an order, and the order has the invoice; a migrated top-up has no order
-- and must not get a made-up one (it would count as new revenue and would invent a tax breakdown). The migration fetches each
-- invoice as the provider issued it and keeps it here, one row per provider invoice, so the wallet can offer Download invoice for a
-- migrated top-up too. The page shows the HTML in a sandboxed frame; nothing here is ever executed.
-- Additive: a new table nothing reads until the wallet looks a ledger row's invoice id up in it.

CREATE TABLE wallet_legacy_invoices (
  org_id         bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid           uuid NOT NULL DEFAULT gen_random_uuid(),
  -- the provider's own id (what the ledger row's meta.legacy.waboo.invoice holds) and the number printed on the invoice
  invoice_id     text NOT NULL,
  invoice_number text,
  invoice_date   date,
  currency       text,
  total          numeric(14, 4),
  status         text,
  -- the invoice as the provider rendered it
  html           text NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  row_version    integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, invoice_id),
  CONSTRAINT ck_wallet_legacy_invoices_html CHECK (length(html) BETWEEN 1 AND 2000000)
);

ALTER TABLE wallet_legacy_invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE wallet_legacy_invoices FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wallet_legacy_invoices FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_wallet_legacy_invoices_touch BEFORE UPDATE ON wallet_legacy_invoices
  FOR EACH ROW EXECUTE FUNCTION touch_row();
