-- wadev: whatsapp-devices-baileys data model, ported from Reference
-- Why this migration exists: the tables Reference's whatsapp devices baileys features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: devices, wa_provider_configs

-- Reference `devices` (tenant; 5 rows in the reference DB)
CREATE TABLE devices (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  assigned_user_id bigint,
  device_name text NOT NULL,
  country_code text,
  phone_number text NOT NULL,
  region text,
  active boolean NOT NULL DEFAULT false,
  activate_after_pairing boolean NOT NULL DEFAULT true,
  status text NOT NULL DEFAULT 'disconnected',
  proxy_enabled boolean NOT NULL DEFAULT false,
  proxy_type text,
  proxy_host text,
  proxy_port smallint,
  proxy_username text,
  proxy_password text,  -- encrypted
  proxy_status text,
  proxy_egress_ip text,
  proxy_checked_at timestamptz,
  sent_24h integer NOT NULL DEFAULT 0,
  failed_24h integer NOT NULL DEFAULT 0,
  warmer_config jsonb,
  warm_day date,
  warm_day_count integer NOT NULL DEFAULT 0,
  last_seen_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_devices_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_devices_assigned_user_id FOREIGN KEY (org_id, assigned_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (assigned_user_id)
);
CREATE INDEX idx_devices_active ON devices (org_id, active);
CREATE INDEX idx_devices_assigned_user_id ON devices (org_id, assigned_user_id);
CREATE INDEX idx_devices_region ON devices (org_id, region);
CREATE INDEX idx_devices_status ON devices (org_id, status);
CREATE INDEX idx_devices_user_id_active ON devices (org_id, user_id, active);

ALTER TABLE devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE devices FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON devices FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_devices_touch BEFORE UPDATE ON devices
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `wa_provider_configs` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_provider_configs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  calling_enabled boolean NOT NULL DEFAULT false,
  calling_enabled_at timestamptz,
  calling_enabled_meta jsonb,
  credentials_json text,  -- encrypted
  meta_json jsonb,
  phone_number text,
  display_label text,
  is_primary boolean NOT NULL DEFAULT false,
  connected_at timestamptz,
  last_health_at timestamptz,
  warmer_config jsonb,
  warm_day date,
  warm_day_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid)
);
CREATE INDEX idx_wa_provider_configs_provider_status ON wa_provider_configs (org_id, provider, status);
CREATE INDEX idx_wa_provider_configs_is_primary ON wa_provider_configs (org_id, is_primary);

ALTER TABLE wa_provider_configs ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_provider_configs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_provider_configs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_provider_configs_touch BEFORE UPDATE ON wa_provider_configs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
