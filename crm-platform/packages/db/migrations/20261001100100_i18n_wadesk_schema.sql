-- i18n: localization-translation data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's localization translation features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: languages, translation_providers, translation_usage

-- WaDesk `languages` (global_read; 21 rows in the reference DB)
CREATE TABLE languages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  name text NOT NULL,
  code text NOT NULL,
  native_name text,
  direction text NOT NULL DEFAULT 'ltr',
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_languages_direction CHECK (direction IN ('ltr', 'rtl')),
  CONSTRAINT uq_languages_code UNIQUE (code)
);

ALTER TABLE languages ENABLE ROW LEVEL SECURITY;
ALTER TABLE languages FORCE  ROW LEVEL SECURITY;
CREATE POLICY read_all ON languages FOR SELECT USING (true);
CREATE POLICY operator_write ON languages FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_languages_touch BEFORE UPDATE ON languages
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `translation_providers` (platform_only; 5 rows in the reference DB)
CREATE TABLE translation_providers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  slug text NOT NULL,
  name text NOT NULL,
  description text,
  is_active boolean NOT NULL DEFAULT false,
  is_default boolean NOT NULL DEFAULT false,
  credentials text,  -- encrypted
  extra_config jsonb,
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_translation_providers_slug UNIQUE (slug)
);
CREATE INDEX idx_translation_providers_is_active_is_default_sort_order ON translation_providers (is_active, is_default, sort_order);

ALTER TABLE translation_providers ENABLE ROW LEVEL SECURITY;
ALTER TABLE translation_providers FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON translation_providers FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_translation_providers_touch BEFORE UPDATE ON translation_providers
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `translation_usage` (stream; 0 rows in the reference DB)
CREATE SEQUENCE translation_usage_id_seq;
CREATE TABLE translation_usage (
  id bigint NOT NULL DEFAULT nextval('translation_usage_id_seq'),
  org_id bigint NOT NULL,
  provider_slug text NOT NULL,
  source_lang text NOT NULL,
  target_lang text NOT NULL,
  chars_in integer NOT NULL DEFAULT 0,
  chars_out integer NOT NULL DEFAULT 0,
  cost_micros bigint NOT NULL DEFAULT 0,
  was_fallback boolean NOT NULL DEFAULT false,
  called_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_translation_usage_called_at ON translation_usage (org_id, called_at);
CREATE INDEX idx_translation_usage_provider_slug_called_at ON translation_usage (org_id, provider_slug, called_at);

ALTER TABLE translation_usage ENABLE ROW LEVEL SECURITY;
ALTER TABLE translation_usage FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON translation_usage FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- Bootstrap partitions (previous month, current, next two) and a catch-all so a gap in partition
-- maintenance degrades into rows landing in _default instead of failed writes. Add each parent to
-- PARTITIONED_TABLES in apps/api/src/workers/partition-maintenance.service.ts.
DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('translation_usage', m);
  END LOOP;
END $$;
CREATE TABLE translation_usage_default PARTITION OF translation_usage DEFAULT;
