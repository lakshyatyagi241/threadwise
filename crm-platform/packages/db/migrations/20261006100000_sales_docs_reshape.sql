-- sales-docs: reshape the drafted Reference `sales_docs` table into the proposals / estimates engine (TW-PROP / TW-EST).
-- Why this migration exists: the table drafted by 20261001104500_sales_threadwise_schema.sql is a literal copy of Reference's
-- (one JSON column for the lines, a plaintext bearer token, no unique number, a status vocabulary with no check). The port
-- decisions it settles (docs/threadwise-port/inventory/sales-proposals-estimates.md, "Port decisions"):
--   D-02/D-06  numbers come from a locked per-org per-type counter and are unique, never reused; the prefix is configurable;
--   D-03       lines are rows (qty, unit price, per-line discount and tax rate); the document has its own discount;
--   D-04/D-05  `viewed` is a status, expiry is a sweep, a public link can expire and be revoked, and only its SHA-256 is looked up;
--   D-11/D-15  every transition and every buyer decision is an append-only event row (signer, IP, user agent, signature);
--   D-29       a sent document is revised through numbered revisions that keep the earlier lines.
-- The table has never been written by any code (0 rows), so the old JSON column and plaintext token are dropped, not migrated;
-- the defensive backfills below only matter on a database somebody filled by hand.

-- --- the document -----------------------------------------------------------------------------------------------------------

UPDATE sales_docs SET status = 'declined' WHERE status = 'rejected';
UPDATE sales_docs SET status = 'converted' WHERE status = 'invoiced';

WITH numbered AS (
  SELECT org_id, id, row_number() OVER (PARTITION BY org_id, doc_type ORDER BY id) AS rn FROM sales_docs
)
UPDATE sales_docs d
   SET seq = n.rn,
       number = COALESCE(NULLIF(d.number, ''),
                         CASE d.doc_type WHEN 'estimate' THEN 'EST-' ELSE 'PRO-' END || lpad(n.rn::text, 4, '0'))
  FROM numbered n WHERE d.org_id = n.org_id AND d.id = n.id;

ALTER TABLE sales_docs
  ADD COLUMN source              text    NOT NULL DEFAULT 'manual',
  ADD COLUMN terms               text,
  ADD COLUMN revision            integer NOT NULL DEFAULT 1,
  ADD COLUMN accepted_revision   integer,
  ADD COLUMN duplicated_from_id  bigint,
  ADD COLUMN discount_kind       text    NOT NULL DEFAULT 'none',
  ADD COLUMN discount_value      bigint  NOT NULL DEFAULT 0,
  ADD COLUMN public_token_hash   text,
  ADD COLUMN public_token_cipher text,
  ADD COLUMN token_expires_at    timestamptz,
  ADD COLUMN token_revoked_at    timestamptz,
  ADD COLUMN first_viewed_at     timestamptz,
  ADD COLUMN last_viewed_at      timestamptz,
  ADD COLUMN view_count          integer NOT NULL DEFAULT 0;

-- The plaintext token becomes a lookup hash; a row that already had one keeps a working link (the link cannot be shown again).
UPDATE sales_docs SET public_token_hash = encode(sha256(convert_to(public_token, 'UTF8')), 'hex')
 WHERE public_token IS NOT NULL;

-- The old JSON lines become rows; tax stays on the document rate (the old shape had no per-line tax).
CREATE TABLE sales_doc_items (
  org_id           bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  doc_id           bigint NOT NULL,
  position         integer NOT NULL,
  description      text NOT NULL,
  -- numeric, not float: 0.3333 hours is a legal quantity and must multiply exactly (the math is bigint in the API)
  qty              numeric(18,4) NOT NULL,
  unit_price_minor bigint NOT NULL,
  discount_kind    text NOT NULL DEFAULT 'none',
  discount_value   bigint NOT NULL DEFAULT 0,
  -- null = the line follows the document's default rate
  tax_rate_bp      integer,
  gross_minor      bigint NOT NULL DEFAULT 0,
  discount_minor   bigint NOT NULL DEFAULT 0,
  net_minor        bigint NOT NULL DEFAULT 0,
  tax_minor        bigint NOT NULL DEFAULT 0,
  created_at       timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  CONSTRAINT fk_sales_doc_items_doc FOREIGN KEY (org_id, doc_id) REFERENCES sales_docs (org_id, id) ON DELETE CASCADE,
  CONSTRAINT uq_sales_doc_items_position UNIQUE (org_id, doc_id, position),
  CONSTRAINT chk_sales_doc_items_qty CHECK (qty >= 0 AND qty < 100000000000),
  CONSTRAINT chk_sales_doc_items_money CHECK (
    unit_price_minor >= 0 AND gross_minor >= 0 AND discount_minor >= 0 AND net_minor >= 0 AND tax_minor >= 0
    AND discount_minor <= gross_minor AND net_minor = gross_minor - discount_minor
  ),
  CONSTRAINT chk_sales_doc_items_discount CHECK (
    discount_kind IN ('none', 'percent', 'amount') AND discount_value >= 0
    AND (discount_kind <> 'percent' OR discount_value <= 10000)
    AND (discount_kind <> 'none' OR discount_value = 0)
  ),
  CONSTRAINT chk_sales_doc_items_tax CHECK (tax_rate_bp IS NULL OR tax_rate_bp BETWEEN 0 AND 10000)
);

INSERT INTO sales_doc_items (org_id, doc_id, position, description, qty, unit_price_minor, gross_minor, net_minor)
SELECT d.org_id, d.id, e.ord - 1, COALESCE(NULLIF(e.item ->> 'description', ''), 'Item'),
       COALESCE((e.item ->> 'qty')::numeric, 1), COALESCE((e.item ->> 'unit_price_minor')::bigint, 0),
       COALESCE((e.item ->> 'line_total_minor')::bigint, 0), COALESCE((e.item ->> 'line_total_minor')::bigint, 0)
  FROM sales_docs d
  CROSS JOIN LATERAL jsonb_array_elements(COALESCE(d.items_json, '[]'::jsonb)) WITH ORDINALITY AS e(item, ord)
 WHERE jsonb_typeof(d.items_json) = 'array';

ALTER TABLE sales_docs
  DROP COLUMN items_json,
  DROP COLUMN public_token,
  ALTER COLUMN number SET NOT NULL,
  ALTER COLUMN seq DROP DEFAULT,
  ALTER COLUMN doc_type DROP DEFAULT,
  ADD CONSTRAINT fk_sales_docs_duplicated_from FOREIGN KEY (org_id, duplicated_from_id)
    REFERENCES sales_docs (org_id, id) ON DELETE SET NULL (duplicated_from_id),
  ADD CONSTRAINT uq_sales_docs_type_seq UNIQUE (org_id, doc_type, seq),
  ADD CONSTRAINT uq_sales_docs_number UNIQUE (org_id, number),
  ADD CONSTRAINT uq_sales_docs_token_hash UNIQUE (public_token_hash),
  ADD CONSTRAINT chk_sales_docs_type CHECK (doc_type IN ('proposal', 'estimate')),
  ADD CONSTRAINT chk_sales_docs_status CHECK (
    status IN ('draft', 'sent', 'viewed', 'accepted', 'declined', 'expired', 'converted')
  ),
  ADD CONSTRAINT chk_sales_docs_source CHECK (source IN ('manual', 'ai', 'api')),
  ADD CONSTRAINT chk_sales_docs_currency CHECK (currency ~ '^[A-Z]{3}$' AND currency_exponent BETWEEN 0 AND 3),
  ADD CONSTRAINT chk_sales_docs_tax_rate CHECK (tax_rate_bp BETWEEN 0 AND 10000),
  ADD CONSTRAINT chk_sales_docs_discount CHECK (
    discount_kind IN ('none', 'percent', 'amount') AND discount_value >= 0
    AND (discount_kind <> 'percent' OR discount_value <= 10000)
    AND (discount_kind <> 'none' OR discount_value = 0)
  ),
  -- total = subtotal - discount + tax: the database refuses a row whose totals do not add up
  ADD CONSTRAINT chk_sales_docs_totals CHECK (
    subtotal_minor >= 0 AND discount_minor >= 0 AND tax_minor >= 0 AND total_minor >= 0
    AND discount_minor <= subtotal_minor AND total_minor = subtotal_minor - discount_minor + tax_minor
  ),
  ADD CONSTRAINT chk_sales_docs_revision CHECK (revision >= 1 AND (accepted_revision IS NULL OR accepted_revision <= revision)),
  -- the stamps agree with the status (a decided document has a decision time; an open one has been sent)
  ADD CONSTRAINT chk_sales_docs_stamps CHECK (
    (status NOT IN ('accepted', 'declined', 'converted') OR decided_at IS NOT NULL)
    AND (status NOT IN ('sent', 'viewed') OR sent_at IS NOT NULL)
    AND (status <> 'viewed' OR first_viewed_at IS NOT NULL)
  );

DROP INDEX IF EXISTS idx_sales_docs_doc_type_status;
