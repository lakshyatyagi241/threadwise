CREATE INDEX idx_sales_docs_status ON sales_docs (org_id, status, doc_type);
CREATE INDEX idx_sales_docs_owner ON sales_docs (org_id, owner_id);
CREATE INDEX idx_sales_docs_invoice ON sales_docs (org_id, invoice_id) WHERE invoice_id IS NOT NULL;
-- the expiry sweep reads only open documents with a valid-until date
CREATE INDEX idx_sales_docs_expiry ON sales_docs (valid_until) WHERE status IN ('sent', 'viewed') AND valid_until IS NOT NULL;
CREATE INDEX idx_sales_docs_title_trgm ON sales_docs USING gin (title gin_trgm_ops);
CREATE INDEX idx_sales_docs_number_trgm ON sales_docs USING gin (number gin_trgm_ops);

CREATE INDEX idx_sales_doc_items_doc ON sales_doc_items (org_id, doc_id, position);

-- --- revisions: the lines a document had before it was revised ---------------------------------------------------------------

CREATE TABLE sales_doc_revisions (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  doc_id      bigint NOT NULL,
  revision    integer NOT NULL,
  status      text NOT NULL,
  -- the whole content of that revision: terms, notes (as stored, encrypted), discount, tax rate, lines and totals
  snapshot    jsonb NOT NULL,
  total_minor bigint NOT NULL,
  created_by  bigint,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_sales_doc_revisions_doc FOREIGN KEY (org_id, doc_id) REFERENCES sales_docs (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_sales_doc_revisions_user FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT uq_sales_doc_revisions UNIQUE (org_id, doc_id, revision)
);

-- --- events: the timeline and the audit trail of every decision ---------------------------------------------------------------

CREATE TABLE sales_doc_events (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  doc_id        bigint NOT NULL,
  type          text NOT NULL,
  actor_kind    text NOT NULL,
  actor_user_id bigint,
  from_status   text,
  to_status     text,
  revision      integer NOT NULL DEFAULT 1,
  channel       text,
  -- buyer-supplied evidence: encrypted at rest (AES-GCM through CryptoService), never copied to an audit row or an outbox event
  signer_name   text,
  signer_email  text,
  signature     text,
  comment       text,
  ip            text,
  user_agent    text,
  meta          jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_sales_doc_events_doc FOREIGN KEY (org_id, doc_id) REFERENCES sales_docs (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_sales_doc_events_user FOREIGN KEY (org_id, actor_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (actor_user_id),
  CONSTRAINT chk_sales_doc_events_actor CHECK (actor_kind IN ('user', 'buyer', 'system')),
  CONSTRAINT chk_sales_doc_events_type CHECK (type IN (
    'created', 'edited', 'duplicated', 'sent', 'viewed', 'accepted', 'declined', 'expired', 'revised',
    'extended', 'converted_invoice', 'converted_deal', 'link_regenerated', 'link_revoked'
  ))
);
CREATE INDEX idx_sales_doc_events_doc ON sales_doc_events (org_id, doc_id, created_at, id);

-- Append-only: the only update the table accepts is the foreign key clearing `actor_user_id` when a user is deleted.
CREATE FUNCTION sales_doc_events_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) - 'actor_user_id') IS DISTINCT FROM (to_jsonb(OLD) - 'actor_user_id') THEN
    RAISE EXCEPTION 'sales_doc_events is append-only' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_sales_doc_events_append_only BEFORE UPDATE ON sales_doc_events
  FOR EACH ROW EXECUTE FUNCTION sales_doc_events_append_only();

-- --- numbering ---------------------------------------------------------------------------------------------------------------

-- One row per org and type. The allocator is `INSERT .. ON CONFLICT DO UPDATE .. RETURNING`: the row lock serialises concurrent
-- creators until the creating transaction ends, a rollback gives the number back, and nothing ever lowers `last_seq`, so a number
-- is never handed out twice and deleting the newest document does not free its number (Reference used max(seq) + 1: both happened).
CREATE TABLE sales_doc_counters (
  org_id   bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  doc_type text NOT NULL,
  last_seq bigint NOT NULL,
  PRIMARY KEY (org_id, doc_type),
  CONSTRAINT chk_sales_doc_counters_type CHECK (doc_type IN ('proposal', 'estimate')),
  CONSTRAINT chk_sales_doc_counters_seq CHECK (last_seq >= 0)
);
INSERT INTO sales_doc_counters (org_id, doc_type, last_seq)
SELECT org_id, doc_type, max(seq) FROM sales_docs GROUP BY org_id, doc_type;

-- Per-organization settings of the module. A row is created on first write; absent means the defaults below.
CREATE TABLE sales_doc_settings (
  org_id            bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  proposal_prefix   text NOT NULL DEFAULT 'PRO',
  estimate_prefix   text NOT NULL DEFAULT 'EST',
  number_padding    smallint NOT NULL DEFAULT 4,
  -- the first number handed out; ignored once the counter exists
  proposal_start    bigint NOT NULL DEFAULT 1,
  estimate_start    bigint NOT NULL DEFAULT 1,
  -- documents created without a valid-until date get today + this many days (null: no date)
  default_valid_days integer,
  -- a public link stops working this many days after the document is sent (null: it lives as long as the document is open)
  link_ttl_days     integer,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  row_version       integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT chk_sales_doc_settings_prefix CHECK (
    proposal_prefix ~ '^[A-Za-z0-9]{1,10}$' AND estimate_prefix ~ '^[A-Za-z0-9]{1,10}$'
  ),
  CONSTRAINT chk_sales_doc_settings_padding CHECK (number_padding BETWEEN 1 AND 10),
  CONSTRAINT chk_sales_doc_settings_start CHECK (proposal_start >= 1 AND estimate_start >= 1),
  CONSTRAINT chk_sales_doc_settings_days CHECK (
    (default_valid_days IS NULL OR default_valid_days BETWEEN 1 AND 3650)
    AND (link_ttl_days IS NULL OR link_ttl_days BETWEEN 1 AND 3650)
  )
);

-- --- templates for the default terms and notes -------------------------------------------------------------------------------

CREATE TABLE sales_doc_templates (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  doc_type    text NOT NULL,
  name        text NOT NULL,
  terms       text,
  notes       text,
  valid_days  integer,
  is_default  boolean NOT NULL DEFAULT false,
  created_by  bigint,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_sales_doc_templates_user FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_sales_doc_templates_type CHECK (doc_type IN ('proposal', 'estimate')),
  CONSTRAINT chk_sales_doc_templates_name CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT chk_sales_doc_templates_days CHECK (valid_days IS NULL OR valid_days BETWEEN 1 AND 3650)
);
CREATE UNIQUE INDEX uq_sales_doc_templates_name ON sales_doc_templates (org_id, doc_type, lower(name));
-- at most one default per type: the template a new document starts from
CREATE UNIQUE INDEX uq_sales_doc_templates_default ON sales_doc_templates (org_id, doc_type) WHERE is_default;

-- --- RLS on every new table, and touch_row where the table is edited in place ------------------------------------------------

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['sales_doc_items', 'sales_doc_revisions', 'sales_doc_events', 'sales_doc_counters',
                           'sales_doc_settings', 'sales_doc_templates']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I FOR ALL USING (org_id = current_org_id() OR app_is_privileged()) WITH CHECK (org_id = current_org_id() OR app_is_privileged())',
      t);
  END LOOP;
END $$;

CREATE TRIGGER trg_sales_doc_settings_touch BEFORE UPDATE ON sales_doc_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_sales_doc_templates_touch BEFORE UPDATE ON sales_doc_templates
  FOR EACH ROW EXECUTE FUNCTION touch_row();
