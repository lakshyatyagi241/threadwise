-- tchat: the bytes of a message attachment (TW-TCHAT-010).
-- Why this migration exists: Reference wrote attachments to a public media disk (SET domain, not built here) and anyone with the
-- URL could read them. Until the object-store adapter lands, the bytes live next to the message, inside the tenant's row-level
-- security, and are served only through an authenticated route that checks channel access. Rows go with their message
-- (ON DELETE CASCADE), so deleting a message no longer leaves an orphan file behind. 20 MB is the hard cap (enforced in the API).
CREATE TABLE team_chat_attachment_blobs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  message_id bigint NOT NULL,
  bytes bytea NOT NULL,
  byte_size integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_team_chat_attachment_blobs_message_id UNIQUE (org_id, message_id),
  CONSTRAINT chk_team_chat_attachment_blobs_size CHECK (byte_size BETWEEN 1 AND 20971520),
  CONSTRAINT fk_team_chat_attachment_blobs_message_id FOREIGN KEY (org_id, message_id) REFERENCES team_chat_messages (org_id, id) ON DELETE CASCADE
);

ALTER TABLE team_chat_attachment_blobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE team_chat_attachment_blobs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON team_chat_attachment_blobs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_team_chat_attachment_blobs_touch BEFORE UPDATE ON team_chat_attachment_blobs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
