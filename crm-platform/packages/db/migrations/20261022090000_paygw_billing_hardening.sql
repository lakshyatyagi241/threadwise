-- paygw: recurring add-ons, a reusable provider plan, and the grace-period default.
-- Why: (1) an add-on (extra seat pack) can renew by autopay like a plan, so `plans.billing_mode` says whether a pack is bought once
-- or subscribed to, and a `subscriptions` row says whether it renews a plan or an add-on (and which purchase). (2) Razorpay (and
-- others) make a provider plan per checkout; `gateway_plan_cache` remembers the plan id per gateway account, price and interval, so
-- the provider account stops collecting orphan plans. It is platform-level (no tenant), operator/privileged only, like payment_gateways.
-- (3) `billing.grace_days`: how long a paid plan or add-on stays active after its period ends while autopay is still retrying.
-- Additive only.

ALTER TABLE plans
  ADD COLUMN billing_mode text NOT NULL DEFAULT 'one_time',
  ADD CONSTRAINT chk_plans_billing_mode CHECK (billing_mode IN ('one_time', 'recurring')),
  ADD CONSTRAINT chk_plans_recurring_addon CHECK (billing_mode = 'one_time' OR (kind = 'addon' AND NOT is_free AND NOT is_lifetime));

ALTER TABLE subscriptions
  ADD COLUMN kind text NOT NULL DEFAULT 'plan',
  ADD COLUMN workspace_addon_id bigint,
  ADD CONSTRAINT chk_subscriptions_kind CHECK (kind IN ('plan', 'addon')),
  ADD CONSTRAINT chk_subscriptions_addon_link CHECK (kind = 'plan' OR plan_id IS NOT NULL),
  ADD CONSTRAINT fk_subscriptions_workspace_addon FOREIGN KEY (org_id, workspace_addon_id)
    REFERENCES workspace_addons (org_id, id) ON DELETE SET NULL (workspace_addon_id);
CREATE INDEX idx_subscriptions_org_kind_status ON subscriptions (org_id, kind, status);

CREATE TABLE gateway_plan_cache (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gateway text NOT NULL,
  -- sha256 of the account's key id: a test key and a live key never share a plan.
  account_hash text NOT NULL,
  currency text NOT NULL,
  amount_minor bigint NOT NULL,
  interval_unit text NOT NULL,
  interval_count integer NOT NULL,
  gateway_plan_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_gateway_plan_cache UNIQUE (gateway, account_hash, currency, amount_minor, interval_unit, interval_count),
  CONSTRAINT chk_gateway_plan_cache_amount CHECK (amount_minor > 0 AND interval_count > 0)
);
ALTER TABLE gateway_plan_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE gateway_plan_cache FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON gateway_plan_cache FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());

INSERT INTO platform_settings (key, value) VALUES ('billing.grace_days', '7'::jsonb)
ON CONFLICT (key) DO NOTHING;
