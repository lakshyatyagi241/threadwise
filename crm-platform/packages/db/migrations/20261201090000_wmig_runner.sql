-- wmig: the hand-over between the panel's worker and the runner agent (platform tables, not a WaDesk feature).
-- Waboo's database only answers over the Geta VPN, so the migration pipeline cannot run inside the API's own container. A small agent
-- on a VPN-connected machine claims the job of a RUNNING run, starts the pipeline and reports its events back; the worker reads them.
-- Additive to 20261113100000 / 20261114100000 / 20261128090000. No credential, token or connection string is ever stored here: the
-- agent's token is an environment value on both sides and never reaches a table.
-- Platform (operator) tables: no tenant column.

CREATE TABLE waboo_migration_runner_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- the run this job executes (waboo_migration_runs.uuid); one job per run
  run_uuid uuid NOT NULL UNIQUE,
  -- {sourceClient, sourceDb, mode}: exactly what the pipeline is started with; the agent re-validates every field
  args jsonb NOT NULL,
  status text NOT NULL DEFAULT 'queued',
  runner text,
  -- the pipeline's validated, scrubbed step/report events in the order they were printed
  events jsonb NOT NULL DEFAULT '[]'::jsonb,
  stderr_tail text NOT NULL DEFAULT '',
  exit_code integer,
  timed_out boolean NOT NULL DEFAULT false,
  -- set when the worker gives up on the job (nobody claimed it, the agent went silent, the timeout); the agent kills the pipeline
  cancel_requested boolean NOT NULL DEFAULT false,
  claimed_at timestamptz,
  last_seen_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_wmigj_status CHECK (status IN ('queued', 'claimed', 'done', 'abandoned')),
  CONSTRAINT chk_wmigj_args CHECK (jsonb_typeof(args) = 'object'),
  CONSTRAINT chk_wmigj_events CHECK (jsonb_typeof(events) = 'array'),
  CONSTRAINT chk_wmigj_runner CHECK (runner IS NULL OR runner ~ '^[A-Za-z0-9._-]{1,64}$')
);
CREATE INDEX idx_wmigj_status ON waboo_migration_runner_jobs (status, id);

-- one row per agent that ever asked for work; the panel shows "runner online" from last_seen_at
CREATE TABLE waboo_migration_runners (
  name text PRIMARY KEY,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_wmigr_name CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$')
);

