-- marketplace: the platform-owned catalogue of mini apps and integrations (spec docs/specs/marketplace-mini-apps-and-integrations.md, M-01).
-- Why this migration exists: the product has no way for a workspace to add or connect anything itself. WaDesk's answer was a ZIP of code
-- loaded into the one running application (the extension registry), which cannot be offered to tenants of a multi-tenant SaaS. The
-- Marketplace is data: a listing, versions that each carry a declarative manifest (and, for an integration, a connector recipe), and
-- per-workspace installations (next migration). Nothing in a listing is code that runs in the API process.
--
--  1. marketplace_categories, marketplace_apps, marketplace_app_versions: platform-owned, NOT tenant data (no org_id). They follow how
--     whatsapp_providers is protected (forced RLS, writes only on the privileged path = the operator API) with one difference: a
--     workspace must be able to browse them, so a SELECT policy lets a tenant read what is published, and what it has installed (a
--     listing the platform later hides or kills must still show on the workspace's own Installed page). A tenant cannot write them.
--  2. Statuses: an app is draft | in_review | published | hidden | killed; a version is draft | in_review | approved | rejected |
--     published | retired. Only `published` appears in browse and search. `killed` is the platform kill switch.
--  3. `current_version_id` is the published version a new installation gets. `install_count` is kept by the trigger of the installations
--     table (a SECURITY DEFINER function, since a tenant cannot update a platform row) so Popular can sort without counting across tenants.
--  4. `scopes` is a copy of the manifest's scope list on the version row, so the re-consent rule is a set comparison in SQL.

CREATE TABLE marketplace_categories (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  kind        text NOT NULL,
  slug        text NOT NULL,
  name        text NOT NULL,
  description text,
  icon        text,
  sort_order  integer NOT NULL DEFAULT 100,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_marketplace_categories_kind_slug UNIQUE (kind, slug),
  CONSTRAINT chk_marketplace_categories_kind CHECK (kind IN ('mini_app', 'integration')),
  CONSTRAINT chk_marketplace_categories_slug CHECK (slug ~ '^[a-z][a-z0-9-]{1,47}$')
);
CREATE TRIGGER trg_marketplace_categories_touch BEFORE UPDATE ON marketplace_categories
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE marketplace_apps (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                   uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  slug                   text NOT NULL UNIQUE,
  kind                   text NOT NULL,
  category_id            bigint NOT NULL REFERENCES marketplace_categories (id) ON DELETE RESTRICT,
  name                   text NOT NULL,
  tagline                text NOT NULL DEFAULT '',
  status                 text NOT NULL DEFAULT 'draft',
  first_party            boolean NOT NULL DEFAULT false,
  featured               boolean NOT NULL DEFAULT false,
  -- The plan feature (counting billing add-ons) a workspace needs to install it; null = every plan.
  plan_feature           text,
  sort_order             integer NOT NULL DEFAULT 100,
  -- Integrations: which of the five connector mechanisms, copied from the published manifest for filters and the usage report.
  connector_type         text,
  -- Long description, screenshots, highlights, data-processing disclosure (validated by marketListingSchema).
  listing                jsonb NOT NULL DEFAULT '{}'::jsonb,
  current_version_id     bigint,
  install_count          integer NOT NULL DEFAULT 0,
  published_at           timestamptz,
  killed_at              timestamptz,
  kill_reason            text,
  created_by_operator_id bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  row_version            integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_marketplace_apps_slug CHECK (slug ~ '^[a-z][a-z0-9-]{1,47}$'),
  CONSTRAINT chk_marketplace_apps_kind CHECK (kind IN ('mini_app', 'integration')),
  CONSTRAINT chk_marketplace_apps_status CHECK (status IN ('draft', 'in_review', 'published', 'hidden', 'killed')),
  CONSTRAINT chk_marketplace_apps_connector CHECK (
    connector_type IS NULL OR connector_type IN ('oauth', 'push', 'pull', 'email_parse', 'webhook_relay')),
  CONSTRAINT chk_marketplace_apps_connector_kind CHECK (connector_type IS NULL OR kind = 'integration'),
  -- A published app has a version to install.
  CONSTRAINT chk_marketplace_apps_published_version CHECK (status <> 'published' OR current_version_id IS NOT NULL),
  CONSTRAINT chk_marketplace_apps_install_count CHECK (install_count >= 0)
);
CREATE INDEX idx_marketplace_apps_browse ON marketplace_apps (kind, category_id, status);
CREATE INDEX idx_marketplace_apps_published_at ON marketplace_apps (published_at DESC, id DESC) WHERE status = 'published';
CREATE INDEX idx_marketplace_apps_popular ON marketplace_apps (install_count DESC, id DESC) WHERE status = 'published';
-- A counter change (install_count, written by the installations trigger) is not an edit: it must not move row_version, or an
-- operator's optimistic write would conflict every time a workspace installs the app.
CREATE TRIGGER trg_marketplace_apps_touch BEFORE UPDATE ON marketplace_apps
  FOR EACH ROW WHEN (OLD.install_count = NEW.install_count) EXECUTE FUNCTION touch_row();

CREATE TABLE marketplace_app_versions (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid                    uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  app_id                  bigint NOT NULL REFERENCES marketplace_apps (id) ON DELETE CASCADE,
  version                 text NOT NULL,
  status                  text NOT NULL DEFAULT 'draft',
  -- Manifest v1 and, for an integration, the connector recipe (both validated by the API before they are stored).
  manifest                jsonb NOT NULL,
  recipe                  jsonb,
  scopes                  text[] NOT NULL DEFAULT '{}',
  changelog               text NOT NULL DEFAULT '',
  review_note             text,
  submitted_at            timestamptz,
  reviewed_at             timestamptz,
  reviewed_by_operator_id bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  published_at            timestamptz,
  created_by_operator_id  bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  row_version             integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_marketplace_app_versions_version UNIQUE (app_id, version),
  CONSTRAINT chk_marketplace_app_versions_status CHECK (
    status IN ('draft', 'in_review', 'approved', 'rejected', 'published', 'retired')),
  CONSTRAINT chk_marketplace_app_versions_version CHECK (version ~ '^[0-9]{1,4}\.[0-9]{1,4}\.[0-9]{1,4}(-[0-9a-z.]{1,20})?$')
);
CREATE INDEX idx_marketplace_app_versions_app ON marketplace_app_versions (app_id, created_at DESC, id DESC);
CREATE TRIGGER trg_marketplace_app_versions_touch BEFORE UPDATE ON marketplace_app_versions
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE marketplace_apps
  ADD CONSTRAINT fk_marketplace_apps_current_version FOREIGN KEY (current_version_id)
    REFERENCES marketplace_app_versions (id) ON DELETE SET NULL (current_version_id);

-- --- row-level security ----------------------------------------------------------------------------------------------------------
-- Writes: only the privileged path (the operator API through PlatformStore). Reads by a workspace: published rows, plus what the
-- workspace has installed. The installations table does not exist yet, so its policies are added by the next migration.

ALTER TABLE marketplace_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_categories FORCE  ROW LEVEL SECURITY;
CREATE POLICY privileged_all ON marketplace_categories FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE POLICY tenant_read_active ON marketplace_categories FOR SELECT
  USING (is_active);

ALTER TABLE marketplace_apps ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_apps FORCE  ROW LEVEL SECURITY;
CREATE POLICY privileged_all ON marketplace_apps FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE POLICY tenant_read_published ON marketplace_apps FOR SELECT
  USING (status = 'published');

ALTER TABLE marketplace_app_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_app_versions FORCE  ROW LEVEL SECURITY;
CREATE POLICY privileged_all ON marketplace_app_versions FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
-- `retired` versions were published once: their changelog is the app page's "what changed".
CREATE POLICY tenant_read_published ON marketplace_app_versions FOR SELECT
  USING (status IN ('published', 'retired'));

GRANT SELECT, INSERT, UPDATE, DELETE ON marketplace_categories, marketplace_apps, marketplace_app_versions TO crm_app, crm_worker;
