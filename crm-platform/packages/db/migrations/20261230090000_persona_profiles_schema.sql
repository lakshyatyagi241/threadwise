-- persona profiles, phase 0: the schema (docs/specs/persona-profiles.md, sections 4.1 and 4.2; backlog BL-280).
-- Not a Reference feature (product extension): Reference has no notion of a business type.
--
-- Why this migration exists: one product has to serve many kinds of business (a clinic, a sales team, a shop) without a fork. A persona
-- is a named, versioned definition in a PLATFORM catalog (which words, which modules, which starter setup); each workspace points at one
-- and may carry two override layers (the platform operator's and its own). This migration only creates the places to keep that. Nothing
-- reads them to change what a screen shows yet, and every existing workspace is put on the `generic` persona (next migration), which
-- hides nothing.
--
--   personas, persona_versions     platform catalog (no org_id). Anyone may read a persona and its PUBLISHED versions; only the
--                                  privileged path (the operator console) writes. A draft is never visible to a tenant. A published
--                                  version is immutable: it can only be marked superseded.
--   workspace_persona              one row per workspace: which persona and version it follows, team size, solo mode, "Show more
--                                  modules", the two override documents, the onboarding state and `rev`. `rev` is bumped by EVERY
--                                  change (trigger), so a cache keyed by it can never serve a stale answer. The operator columns
--                                  can only be written on the privileged path (trigger: RLS cannot restrict columns).
--   workspace_persona_applied      the ledger of starter-pack rows already created, so re-applying never duplicates or overwrites.
--   workspace_persona_log          append-only history of persona changes. Operator-layer rows are invisible to the workspace.
--
-- No personal data lives here: only keys, versions, module ids, label overrides and ids of the people who made a change.

-- ---------------------------------------------------------------------------------------------------------------------
-- Platform catalog
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE personas (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid            uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  -- lower-case by the pattern, so plain text is enough; a key is never reused (archive instead of delete)
  key             text NOT NULL UNIQUE,
  status          text NOT NULL DEFAULT 'active',
  is_system       boolean NOT NULL DEFAULT false,
  sort_order      integer NOT NULL DEFAULT 0,
  -- the latest PUBLISHED version; null until the first publish
  current_version integer,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_personas_key CHECK (key ~ '^[a-z][a-z0-9_]{1,39}$'),
  CONSTRAINT chk_personas_status CHECK (status IN ('active', 'archived')),
  -- the persona every workspace falls back to cannot go away
  CONSTRAINT chk_personas_system_active CHECK (NOT is_system OR status = 'active'),
  CONSTRAINT chk_personas_current_version CHECK (current_version IS NULL OR current_version > 0)
);

ALTER TABLE personas ENABLE ROW LEVEL SECURITY;
ALTER TABLE personas FORCE  ROW LEVEL SECURITY;
-- names and keys are not secret: every workspace may list them (the onboarding picker, the Settings screen)
CREATE POLICY read_all ON personas FOR SELECT USING (true);
CREATE POLICY operator_write ON personas FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_personas_touch BEFORE UPDATE ON personas
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE persona_versions (
  persona_id   bigint NOT NULL REFERENCES personas (id) ON DELETE CASCADE,
  version      integer NOT NULL,
  status       text NOT NULL DEFAULT 'draft',
  -- the document of docs/specs/persona-profiles.md section 4.3 (zod: personaDefinitionSchema in @crm/contracts)
  definition   jsonb NOT NULL,
  -- built at publish: the per-locale vocabulary overlay and the resolved module map
  compiled     jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- diff against the previous version, with `appliesToExisting` per hide
  changes      jsonb NOT NULL DEFAULT '[]'::jsonb,
  note         text,
  created_by   bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  published_by bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  PRIMARY KEY (persona_id, version),
  CONSTRAINT chk_persona_versions_version CHECK (version > 0),
  CONSTRAINT chk_persona_versions_status CHECK (status IN ('draft', 'published', 'superseded')),
  CONSTRAINT chk_persona_versions_published CHECK ((status = 'draft') = (published_at IS NULL))
);
-- one draft per persona
CREATE UNIQUE INDEX uq_persona_versions_one_draft ON persona_versions (persona_id) WHERE status = 'draft';

ALTER TABLE persona_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE persona_versions FORCE  ROW LEVEL SECURITY;
-- a workspace reads the published and superseded versions (it may be pinned to an old one), never a draft
CREATE POLICY read_published ON persona_versions FOR SELECT
  USING (status <> 'draft' OR app_is_privileged());
CREATE POLICY operator_write ON persona_versions FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());

-- A published version is immutable: the only change it accepts is published -> superseded. A draft may be edited and deleted. The one
-- other thing allowed is the foreign keys to platform_operators clearing created_by / published_by when an operator is deleted (that runs
-- as a nested trigger action, pg_trigger_depth() > 1); without it deleting an operator would fail on the versions they published.
CREATE FUNCTION persona_versions_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'draft' THEN
      RAISE EXCEPTION 'persona_versions: a published version cannot be deleted' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.status <> 'draft' THEN
    IF NEW.persona_id = OLD.persona_id AND NEW.version = OLD.version
       AND NEW.definition = OLD.definition AND NEW.compiled = OLD.compiled AND NEW.changes = OLD.changes
       AND NEW.note IS NOT DISTINCT FROM OLD.note
       AND NEW.created_at = OLD.created_at
       AND NEW.published_at IS NOT DISTINCT FROM OLD.published_at
       AND (NEW.status = OLD.status OR (OLD.status = 'published' AND NEW.status = 'superseded'))
       AND (NEW.created_by IS NOT DISTINCT FROM OLD.created_by OR (NEW.created_by IS NULL AND pg_trigger_depth() > 1))
       AND (NEW.published_by IS NOT DISTINCT FROM OLD.published_by OR (NEW.published_by IS NULL AND pg_trigger_depth() > 1)) THEN
      RETURN NEW;
    END IF;
    RAISE EXCEPTION 'persona_versions: a published version is immutable' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_persona_versions_guard BEFORE UPDATE OR DELETE ON persona_versions
  FOR EACH ROW EXECUTE FUNCTION persona_versions_guard();

