CREATE TABLE workspace_persona (
  org_id              bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  persona_key         text NOT NULL DEFAULT 'generic' REFERENCES personas (key),
  -- the version the workspace has accepted; with `pinned` false it follows the latest published one
  persona_version     integer NOT NULL DEFAULT 1,
  pinned              boolean NOT NULL DEFAULT false,
  -- same five values as the onboarding team size
  team_size           text,
  solo_ui             text NOT NULL DEFAULT 'auto',
  show_all_modules    boolean NOT NULL DEFAULT false,
  -- both documents: `{ "v": 1, "modules": {...}, "vocab": {...}, ... }` (zod: workspaceOverridesSchema / operatorOverridesSchema)
  workspace_overrides jsonb NOT NULL DEFAULT '{}'::jsonb,
  operator_overrides  jsonb NOT NULL DEFAULT '{}'::jsonb,
  operator_note       text,
  operator_updated_by bigint REFERENCES platform_operators (id) ON DELETE SET NULL,
  operator_updated_at timestamptz,
  -- `{ "steps": {...}, "skippedAt": ..., "completedAt": ... }`
  onboarding          jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- bumped by EVERY change to this row (trigger): the key of every cache of the resolved view
  rev                 integer NOT NULL DEFAULT 1,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  row_version         integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT chk_workspace_persona_version CHECK (persona_version > 0),
  CONSTRAINT chk_workspace_persona_team_size CHECK (team_size IS NULL OR team_size IN ('1', '2-5', '6-20', '21-100', '100+')),
  CONSTRAINT chk_workspace_persona_solo_ui CHECK (solo_ui IN ('auto', 'on', 'off')),
  CONSTRAINT chk_workspace_persona_overrides CHECK (
    jsonb_typeof(workspace_overrides) = 'object' AND jsonb_typeof(operator_overrides) = 'object' AND jsonb_typeof(onboarding) = 'object'
  )
);
CREATE INDEX idx_workspace_persona_key ON workspace_persona (persona_key);

ALTER TABLE workspace_persona ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_persona FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON workspace_persona FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- Row-level security cannot restrict columns, so this trigger does it: only the privileged path (the operator console) may set or change
-- the operator_* columns (the one exception: the foreign key to platform_operators clearing operator_updated_by when an operator is
-- deleted, a nested trigger action). It also bumps `rev` on every update, whatever the statement says, so no writer can forget it or lower it.
CREATE FUNCTION workspace_persona_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF NOT app_is_privileged() THEN
    IF TG_OP = 'INSERT' THEN
      IF NEW.operator_overrides <> '{}'::jsonb OR NEW.operator_note IS NOT NULL
         OR NEW.operator_updated_by IS NOT NULL OR NEW.operator_updated_at IS NOT NULL THEN
        RAISE EXCEPTION 'workspace_persona: operator columns are written by the platform operator only' USING ERRCODE = 'insufficient_privilege';
      END IF;
    ELSIF NEW.operator_overrides IS DISTINCT FROM OLD.operator_overrides
       OR NEW.operator_note IS DISTINCT FROM OLD.operator_note
       OR NEW.operator_updated_at IS DISTINCT FROM OLD.operator_updated_at
       OR (NEW.operator_updated_by IS DISTINCT FROM OLD.operator_updated_by
           AND NOT (NEW.operator_updated_by IS NULL AND pg_trigger_depth() > 1)) THEN
      RAISE EXCEPTION 'workspace_persona: operator columns are written by the platform operator only' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  IF TG_OP = 'UPDATE' THEN
    NEW.rev := OLD.rev + 1;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_workspace_persona_guard BEFORE INSERT OR UPDATE ON workspace_persona
  FOR EACH ROW EXECUTE FUNCTION workspace_persona_guard();
CREATE TRIGGER trg_workspace_persona_touch BEFORE UPDATE ON workspace_persona
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A workspace cannot delete its own row (that would drop the operator's overrides); it goes away with the organization (cascade).
REVOKE DELETE ON workspace_persona FROM crm_app, crm_worker;

