CREATE TABLE workspace_persona_log (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  layer      text NOT NULL,
  actor_kind text NOT NULL,
  -- a workspace user id or a platform operator id, as `actor_kind` says
  actor_id   bigint,
  action     text NOT NULL,
  item_id    text,
  before     jsonb,
  after      jsonb,
  reason     text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  CONSTRAINT chk_workspace_persona_log_layer CHECK (layer IN ('persona_change', 'workspace', 'operator')),
  CONSTRAINT chk_workspace_persona_log_actor CHECK (actor_kind IN ('user', 'operator')),
  CONSTRAINT chk_workspace_persona_log_layer_actor CHECK (layer <> 'operator' OR actor_kind = 'operator'),
  -- whoever acts as the operator says why (the same shape as retention_exempt_reason)
  CONSTRAINT chk_workspace_persona_log_reason CHECK (actor_kind <> 'operator' OR length(btrim(coalesce(reason, ''))) >= 5)
);
CREATE INDEX idx_workspace_persona_log_org_created ON workspace_persona_log (org_id, created_at DESC);

ALTER TABLE workspace_persona_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_persona_log FORCE  ROW LEVEL SECURITY;
-- A workspace reads its own history, but nothing the operator did (owner decision 10: it sees "set by your account team", never the
-- notes), and it can only append rows as itself: a tenant cannot write an operator-layer or operator-actor row.
CREATE POLICY tenant_read ON workspace_persona_log FOR SELECT
  USING ((org_id = current_org_id() AND layer <> 'operator' AND actor_kind <> 'operator') OR app_is_privileged());
CREATE POLICY tenant_append ON workspace_persona_log FOR INSERT
  WITH CHECK (
    (org_id = current_org_id() AND layer <> 'operator' AND actor_kind <> 'operator' AND actor_id IS NOT DISTINCT FROM current_actor_id())
    OR app_is_privileged()
  );
-- a workspace's rows are stamped by the database, not by the writer: no backdating
CREATE FUNCTION workspace_persona_log_guard() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF NOT app_is_privileged() THEN
    NEW.created_at := now();
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_workspace_persona_log_guard BEFORE INSERT ON workspace_persona_log
  FOR EACH ROW EXECUTE FUNCTION workspace_persona_log_guard();
-- append-only: no role may change or remove a row (the organization's deletion cascades regardless)
REVOKE UPDATE, DELETE ON workspace_persona_log FROM crm_app, crm_worker;
