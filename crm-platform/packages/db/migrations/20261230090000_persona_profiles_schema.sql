  CONSTRAINT chk_workspace_persona_applied_kind CHECK (preset_kind IN ('booking_type', 'lifecycle_stage', 'pipeline', 'template', 'setting')),
  CONSTRAINT fk_workspace_persona_applied_by FOREIGN KEY (org_id, applied_by) REFERENCES users (org_id, id) ON DELETE SET NULL (applied_by)
