-- marketplace: the delivery inbox of portal connections, and the windowed state of pull connections
-- (docs/specs/lead-portals-feasibility.md, section "Recommended build order" 1 to 3; spec M-05, M-06).
-- Why this migration exists: the Indian lead portals give us two kinds of door and both need state the first migrations did not have.
--
--  1. A PUSH portal (IndiaMART, JustDial, 99acres, MagicBricks, Shiksha, Sulekha) posts to our address and turns itself off after a day or
--     two of errors (IndiaMART: a 10 second timeout, deactivated after 48 hours of refusals), so the address must answer 200 fast and never
--     lose what it was given. marketplace_inbound_events is the durable copy of each delivery, written BEFORE the answer and processed
--     afterwards by the worker (map, hand to the lead pipeline, retry from the stored copy). The raw body is kept only until the delivery
--     is processed (it holds a person's phone and name; the lead pipeline keeps its own raw event under its own retention); a delivery that
--     could not be read or processed keeps it so support can look at what the portal really sent. Rows are trimmed after 30 days.
--  2. A PULL portal (IndiaMART, Housing.com, TradeIndia) is asked for "the leads between two times". The connection already keeps a cursor
--     (poll_cursor); a windowed poll also needs to know when it last asked (the portals limit how often: IndiaMART one request every five
--     minutes, a key blocked for 15 minutes beyond five a minute), how wide a window the portal could answer last time (a window that holds
--     more leads than one answer can carry is asked again in halves) and how many leads the last poll found, for the connection page.
--
-- Table privileges are inherited from the default privileges; RLS is not, so it is enabled, forced and given its policy here.

CREATE TABLE marketplace_inbound_events (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  connection_id   bigint NOT NULL,
  -- How it arrived: the HTTP method and the format the body was read as (json, form, xml, or query for a GET).
  method          text NOT NULL,
  format          text NOT NULL,
  content_type    text,
  -- The raw body (or the raw query string of a GET), as text. NULL once the delivery is processed.
  body            text,
  -- A few harmless headers (user agent, content type). Never an authentication header.
  headers         jsonb NOT NULL DEFAULT '{}'::jsonb,
  source_ip       text,
  status          text NOT NULL DEFAULT 'received',
  attempts        integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  claimed_at      timestamptz,
  error           text,
  leads_received  integer NOT NULL DEFAULT 0,
  leads_accepted  integer NOT NULL DEFAULT 0,
  leads_duplicate integer NOT NULL DEFAULT 0,
  leads_rejected  integer NOT NULL DEFAULT 0,
  received_at     timestamptz NOT NULL DEFAULT now(),
  processed_at    timestamptz,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_marketplace_inbound_events_status CHECK (
    status IN ('received', 'processing', 'processed', 'rejected', 'failed')),
  CONSTRAINT chk_marketplace_inbound_events_method CHECK (method IN ('POST', 'GET')),
  CONSTRAINT chk_marketplace_inbound_events_format CHECK (format IN ('json', 'form', 'xml', 'query')),
  CONSTRAINT fk_marketplace_inbound_events_connection FOREIGN KEY (org_id, connection_id)
    REFERENCES marketplace_connections (org_id, id) ON DELETE CASCADE
);
-- The worker's sweep: deliveries nobody has picked up yet, or whose retry is due.
CREATE INDEX idx_marketplace_inbound_events_due ON marketplace_inbound_events (next_attempt_at)
  WHERE status IN ('received', 'failed');
-- A worker that died mid-delivery leaves it 'processing'; the sweep takes it over after a while.
CREATE INDEX idx_marketplace_inbound_events_stuck ON marketplace_inbound_events (claimed_at)
  WHERE status = 'processing';
CREATE INDEX idx_marketplace_inbound_events_recent ON marketplace_inbound_events (org_id, connection_id, received_at DESC, id DESC);
-- The retention sweep.
CREATE INDEX idx_marketplace_inbound_events_age ON marketplace_inbound_events (received_at);

ALTER TABLE marketplace_inbound_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_inbound_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON marketplace_inbound_events FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- --- pull state ---------------------------------------------------------------------------------------------------------------------

ALTER TABLE marketplace_connections
  -- When a request was last made to the portal (a poll, successful or not): the portal's minimum interval is kept against it, and so is
  -- a manual "Sync now".
  ADD COLUMN last_poll_at       timestamptz,
  -- How wide the next window may be, when the last one held more leads than an answer can carry. NULL: the recipe's own width.
  ADD COLUMN poll_window_seconds integer,
  -- How many leads the last successful poll found (for the connection page); NULL before the first.
  ADD COLUMN last_poll_leads    integer,
  ADD CONSTRAINT chk_marketplace_connections_window CHECK (poll_window_seconds IS NULL OR poll_window_seconds > 0);
