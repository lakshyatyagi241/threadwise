-- Conversation handoff and assignment, phase 1 (BL-396..BL-404, docs/specs/conversation-handoff-and-assignment.md).
--
-- Why this migration exists: a bot (flow, AI agent) had no way to say "a person must take this", a conversation had no field saying who
-- handles it (bot, a queue, a person), and the assignment engine left no trace of why somebody was picked or skipped. This adds:
--
--   conversations.handling         NULL | with_bot | waiting | with_person. NULL = "not tracked": every existing row and every thread that
--                                  no handoff ever touched; it behaves exactly as before. A separate column on purpose: `status`
--                                  (open/snoozed/resolved/closed/spam), the kanban and every inbox filter are untouched.
--   conversations.handling_since   when the thread entered its current handling (queue age).
--   conversations.assigned_source  who set the current assignee (manual, claim, handoff_named, rule, owner, sticky, sync, system):
--                                  the owner sync only ever moves a thread an automatic source assigned, never one a person took.
--   conversation_handoffs          one row per handoff: the card the agent reads (reason, summary, collected answers) AND the run log
--                                  (trace of who was considered and why someone was skipped). Unique idempotency key.
--   workspace_settings.handoff_*   the workspace switches of section 4.6 of the spec; every default keeps the behaviour of today.
--
-- Expand-only (blue-green): new nullable columns, a new table, columns with defaults. The CHECKs on conversations are added NOT VALID (a
-- brief lock) and validated by the next migration. No permission is added (claim reuses inbox.conversation.assign_self), so no locked
-- preset role has to be unlocked. No data is rewritten: a table-wide UPDATE of conversations is exactly what this avoids.

-- --- conversations ---------------------------------------------------------------------------------------------------------------

ALTER TABLE conversations
  ADD COLUMN handling        text,
  ADD COLUMN handling_since  timestamptz,
  ADD COLUMN assigned_source text,
  ADD CONSTRAINT chk_conversations_handling
    CHECK (handling IS NULL OR handling IN ('with_bot', 'waiting', 'with_person')) NOT VALID,
  ADD CONSTRAINT chk_conversations_assigned_source
    CHECK (assigned_source IS NULL OR assigned_source IN
      ('manual', 'claim', 'handoff_named', 'rule', 'owner', 'sticky', 'sync', 'system')) NOT VALID;

-- --- the handoff card and run log ------------------------------------------------------------------------------------------------

CREATE TABLE conversation_handoffs (
  org_id               bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                   bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                 uuid NOT NULL DEFAULT gen_random_uuid(),
  conversation_id      bigint NOT NULL,
  -- flow | ai_agent | keyword | bot_failure | manual
  source               text NOT NULL,
  reason               text NOT NULL DEFAULT 'other',
  reason_text          text,
  summary              text,
  -- The flow variables the author chose to pass on ({name: value}), capped by the service. Deleted with the conversation.
  answers              jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- person | team | rules
  destination_kind     text NOT NULL,
  destination_team_id  bigint,
  destination_user_id  bigint,
  priority             text,
  -- waiting | assigned | returned | resolved | cancelled
  status               text NOT NULL DEFAULT 'waiting',
  -- assigned | waiting | unavailable: the three ports of the flow node
  outcome              text NOT NULL DEFAULT 'waiting',
  assigned_user_id     bigint,
  assigned_team_id     bigint,
  -- Ordered lines {step, who?, result, why}: who was considered, who was skipped and why, who was chosen.
  trace                jsonb NOT NULL DEFAULT '[]'::jsonb,
  idempotency_key      text,
  flow_run_id          bigint,
  node_id              text,
  requested_by         bigint,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  completed_at         timestamptz,
  row_version          integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_conversation_handoffs_conversation FOREIGN KEY (org_id, conversation_id)
    REFERENCES conversations (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_conversation_handoffs_dest_team FOREIGN KEY (org_id, destination_team_id)
    REFERENCES teams (org_id, id) ON DELETE SET NULL (destination_team_id),
  CONSTRAINT fk_conversation_handoffs_dest_user FOREIGN KEY (org_id, destination_user_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (destination_user_id),
  CONSTRAINT fk_conversation_handoffs_assigned_user FOREIGN KEY (org_id, assigned_user_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (assigned_user_id),
  CONSTRAINT fk_conversation_handoffs_assigned_team FOREIGN KEY (org_id, assigned_team_id)
    REFERENCES teams (org_id, id) ON DELETE SET NULL (assigned_team_id),
  CONSTRAINT fk_conversation_handoffs_requested_by FOREIGN KEY (org_id, requested_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (requested_by),
  CONSTRAINT chk_conversation_handoffs_source
    CHECK (source IN ('flow', 'ai_agent', 'keyword', 'bot_failure', 'manual')),
  CONSTRAINT chk_conversation_handoffs_destination
    CHECK (destination_kind IN ('person', 'team', 'rules')),
  CONSTRAINT chk_conversation_handoffs_status
    CHECK (status IN ('waiting', 'assigned', 'returned', 'resolved', 'cancelled')),
  CONSTRAINT chk_conversation_handoffs_outcome
    CHECK (outcome IN ('assigned', 'waiting', 'unavailable')),
  CONSTRAINT chk_conversation_handoffs_texts
    CHECK (char_length(coalesce(reason_text, '')) <= 500 AND char_length(coalesce(summary, '')) <= 2000)
);

-- One live handoff per conversation: a repeat is absorbed by the service, never a second card.
CREATE UNIQUE INDEX uq_conversation_handoffs_live
  ON conversation_handoffs (org_id, conversation_id) WHERE status IN ('waiting', 'assigned');
CREATE UNIQUE INDEX uq_conversation_handoffs_idem
  ON conversation_handoffs (org_id, idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX idx_conversation_handoffs_conv ON conversation_handoffs (org_id, conversation_id, created_at DESC);

ALTER TABLE conversation_handoffs ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversation_handoffs FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON conversation_handoffs FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_conversation_handoffs_touch BEFORE UPDATE ON conversation_handoffs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- workspace settings ----------------------------------------------------------------------------------------------------------

-- Every default is the behaviour of today: automatic assignment stays on (it only ever ran when the plan has inbox_routing), no mode, no window.
ALTER TABLE workspace_settings
  ADD COLUMN handoff_auto_assign              boolean NOT NULL DEFAULT true,
  ADD COLUMN handoff_claim_sets_owner         boolean NOT NULL DEFAULT false,
  ADD COLUMN handoff_owner_mode               text NOT NULL DEFAULT 'independent',
  ADD COLUMN handoff_continuity_days          integer,
  ADD COLUMN handoff_prompt_owner_on_reassign boolean NOT NULL DEFAULT false,
  ADD COLUMN handoff_notify_queue             boolean NOT NULL DEFAULT true,
  ADD CONSTRAINT chk_workspace_settings_handoff_owner_mode
    CHECK (handoff_owner_mode IN ('independent', 'owner_first', 'keep_in_sync')),
  ADD CONSTRAINT chk_workspace_settings_handoff_continuity
    CHECK (handoff_continuity_days IS NULL OR handoff_continuity_days BETWEEN 1 AND 365);

-- --- teams -----------------------------------------------------------------------------------------------------------------------

-- The round robin cursor of a team's own method (the id of the person who took the last turn), read and moved under a row lock on the
-- team, as a routing rule's cursor is. Nullable: no team has taken a turn yet.
ALTER TABLE teams ADD COLUMN assignment_cursor bigint;
