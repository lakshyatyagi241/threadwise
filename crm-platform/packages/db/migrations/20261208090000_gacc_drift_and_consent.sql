-- gacc: (1) a bounded reconcile of booked appointments against their Google events, and (2) a server-side record for each Google consent.
--
-- (1) Google is NOT the source of truth for an appointment. A scheduled job looks at the upcoming appointments that have a Google event and
-- notices when the event was deleted, cancelled, moved or had its guests changed. It never changes or cancels the appointment: it records
-- the drift here, shows a badge, tells the owner once, and a person chooses "push our time back to Google" or "accept Google's change".
-- `google_pushed_*` is what WE last wrote to the event (time, guest, Google's etag): a difference between the event and that snapshot is
-- Google-side drift, while a difference between the appointment and the snapshot just means our own push is still on its way (an echo
-- of our own change must never count as drift).
-- `appointment_calendar_connections` gets the schedule of that job (next run, failures for the back-off).
--
-- (2) The consent confirmation. The OAuth callback runs on the API's origin and cannot see the person's session, so it parks what Google
-- returned (sealed) in `google_consent_requests`, keyed by the signed state's nonce, and sends the browser to a page of the app where the
-- same signed-in person confirms "connect <google email> to <workspace> for <permissions>". The grant is stored only on that confirmation,
-- once, by that person, in that workspace; a forwarded consent link, a replay, an expiry or a cancel stores nothing.

ALTER TABLE appointments
  ADD COLUMN google_sync_state text,
  ADD COLUMN google_sync_reason text,
  ADD COLUMN google_drift_detected_at timestamptz,
  ADD COLUMN google_drift_starts_at timestamptz,
  ADD COLUMN google_drift_ends_at timestamptz,
  ADD COLUMN google_event_etag text,
  ADD COLUMN google_pushed_at timestamptz,
  ADD COLUMN google_pushed_starts_at timestamptz,
  ADD COLUMN google_pushed_ends_at timestamptz,
  ADD COLUMN google_pushed_attendee text,
  ADD COLUMN google_checked_at timestamptz,
  ADD CONSTRAINT chk_appointments_google_sync_state CHECK (google_sync_state IS NULL OR google_sync_state IN ('in_sync', 'drifted', 'unreadable')),
  ADD CONSTRAINT chk_appointments_google_sync_reason CHECK (
    (google_sync_state IN ('drifted', 'unreadable')) = (google_sync_reason IS NOT NULL)
    AND (google_sync_reason IS NULL OR google_sync_reason IN ('event_deleted', 'event_missing', 'time_changed', 'attendees_changed', 'event_forbidden', 'event_unreadable'))
  );

-- `unreadable`: Google answered "forbidden" or "bad request" for THIS event (not an outage): it is marked looked-at with a reason, never
-- reported as drift, and the pass goes on to the next appointment.

-- The monitoring columns (sync state, drift, etag, last look) are written by the hourly reconcile. They must not bump `row_version` or
-- `updated_at`: a person editing an appointment would otherwise get a spurious 409 ROW_VERSION_CONFLICT every hour. Any change to another
-- column bumps the version exactly as `touch_row()` does.
CREATE OR REPLACE FUNCTION touch_appointment() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  monitoring text[] := ARRAY['google_sync_state', 'google_sync_reason', 'google_drift_detected_at', 'google_drift_starts_at',
                             'google_drift_ends_at', 'google_event_etag', 'google_checked_at', 'updated_at', 'row_version'];
BEGIN
  IF TG_OP = 'UPDATE' AND (to_jsonb(NEW) - monitoring) = (to_jsonb(OLD) - monitoring) THEN
    NEW.updated_at := OLD.updated_at;
    NEW.row_version := OLD.row_version;
    RETURN NEW;
  END IF;
  NEW.updated_at := now();
  IF TG_OP = 'UPDATE' THEN
    NEW.row_version := OLD.row_version + 1;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER trg_appointments_touch ON appointments;
CREATE TRIGGER trg_appointments_touch BEFORE UPDATE ON appointments
  FOR EACH ROW EXECUTE FUNCTION touch_appointment();

-- The reconcile reads the next 60 days of appointments that have an event: a partial index keeps that cheap on a large table.
CREATE INDEX idx_appointments_google_reconcile ON appointments (org_id, starts_at)
  WHERE calendar_event_id IS NOT NULL AND status IN ('pending', 'confirmed');

ALTER TABLE appointment_calendar_connections
  ADD COLUMN next_reconcile_at timestamptz,
  ADD COLUMN last_reconcile_at timestamptz,
  ADD COLUMN reconcile_failures integer NOT NULL DEFAULT 0;

CREATE TABLE google_consent_requests (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  -- sha256 of the signed state's nonce: the state is a bearer of this row, so the row never holds the nonce itself.
  nonce_hash text NOT NULL,
  -- The admin who pressed Connect: the only person who may confirm.
  user_id bigint NOT NULL,
  capabilities text[] NOT NULL,
  return_to text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  expires_at timestamptz NOT NULL,
  -- Filled by the callback (status awaiting_confirm): who Google said consented, what it granted, and the sealed tokens.
  account_email text,
  account_sub text,
  scopes text,
  missing_scopes text[],
  refresh_token_enc text,
  access_token_enc text,
  access_token_expires_at timestamptz,
  decided_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_google_consent_requests_nonce UNIQUE (nonce_hash),
  CONSTRAINT chk_google_consent_requests_status CHECK (
    status IN ('pending', 'awaiting_confirm', 'confirmed', 'cancelled', 'rejected', 'expired')
  ),
  CONSTRAINT chk_google_consent_requests_capabilities CHECK (
    capabilities <@ ARRAY['calendar', 'sheets', 'docs', 'forms', 'drive_listing']::text[] AND cardinality(capabilities) > 0
  ),
  CONSTRAINT fk_google_consent_requests_user FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_google_consent_requests_user ON google_consent_requests (org_id, user_id);
CREATE INDEX idx_google_consent_requests_expiry ON google_consent_requests (expires_at) WHERE status IN ('pending', 'awaiting_confirm');

ALTER TABLE google_consent_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE google_consent_requests FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON google_consent_requests FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_google_consent_requests_touch BEFORE UPDATE ON google_consent_requests
  FOR EACH ROW EXECUTE FUNCTION touch_row();
