-- tg: channel-telegram data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's channel telegram features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: telegram_accounts, telegram_bots, telegram_broadcasts, telegram_broadcast_recipients, telegram_flow_sessions

-- WaDesk `telegram_accounts` (tenant; 0 rows in the reference DB)
CREATE TABLE telegram_accounts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  connected_by bigint,
  session text,
  tg_user_id text,
  username text,
  first_name text,
  phone text,
  last_error text,
  last_checked_at timestamptz,
  connected_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_telegram_accounts_tg_user_id UNIQUE (org_id, tg_user_id),
  CONSTRAINT fk_telegram_accounts_connected_by FOREIGN KEY (org_id, connected_by) REFERENCES users (org_id, id) ON DELETE SET NULL (connected_by)
);

ALTER TABLE telegram_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE telegram_accounts FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON telegram_accounts FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_telegram_accounts_touch BEFORE UPDATE ON telegram_accounts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

