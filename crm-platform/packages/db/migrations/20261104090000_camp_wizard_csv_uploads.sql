-- camp: the broadcast wizard's "Broadcast via CSV" audience.
-- Why this migration exists: the audience step lets a person upload a CSV of phone numbers. The server parses and validates it once
-- (E.164, duplicates, invalid rows with their line numbers) and keeps the result so the count, the sample and the launch all read
-- the SAME list the person previewed, instead of re-parsing a file that is gone. One row per upload (camp_wizard_csv) and one per file
-- line (camp_wizard_csv_rows: valid, duplicate or invalid). `expires_at` is the retention: an upload nobody launched is deleted by the
-- worker after a week; a recurring broadcast pins its upload (expires_at NULL) because every run reads it again.

CREATE TABLE camp_wizard_csv (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  file_name text NOT NULL,
  total_rows integer NOT NULL DEFAULT 0,
  valid_count integer NOT NULL DEFAULT 0,
  duplicate_count integer NOT NULL DEFAULT 0,
  invalid_count integer NOT NULL DEFAULT 0,
  created_by bigint,
  -- NULL: kept until the broadcast that uses it is gone (a recurring series).
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_camp_wizard_csv_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_camp_wizard_csv_expiry ON camp_wizard_csv (expires_at) WHERE expires_at IS NOT NULL;

ALTER TABLE camp_wizard_csv ENABLE ROW LEVEL SECURITY;
ALTER TABLE camp_wizard_csv FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON camp_wizard_csv FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_camp_wizard_csv_touch BEFORE UPDATE ON camp_wizard_csv
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE camp_wizard_csv_rows (
  org_id bigint NOT NULL,
  upload_id bigint NOT NULL,
  -- The line in the file, header included (the first data row is line 2).
  line integer NOT NULL,
  kind text NOT NULL,
  -- The phone cell as written (what the error list shows).
  raw_value text,
  -- E.164 with the plus, and its digits, for a valid row.
  phone text,
  digits text,
  name text,
  -- missing_phone | invalid_phone | duplicate, for a row that is not valid.
  reason text,
  PRIMARY KEY (org_id, upload_id, line),
  CONSTRAINT ck_camp_wizard_csv_rows_kind CHECK (kind IN ('valid', 'duplicate', 'invalid')),
  CONSTRAINT fk_camp_wizard_csv_rows_upload FOREIGN KEY (org_id, upload_id)
    REFERENCES camp_wizard_csv (org_id, id) ON DELETE CASCADE
);
-- The audience reads the valid numbers of one upload, and matches them to contacts by digits.
CREATE INDEX idx_camp_wizard_csv_rows_valid ON camp_wizard_csv_rows (org_id, upload_id, digits) WHERE kind = 'valid';

ALTER TABLE camp_wizard_csv_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE camp_wizard_csv_rows FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON camp_wizard_csv_rows FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
