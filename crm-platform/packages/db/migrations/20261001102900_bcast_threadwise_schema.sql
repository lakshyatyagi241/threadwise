-- bcast: broadcasts data model, ported from Reference
-- Why this migration exists: the tables Reference's broadcasts features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: broadcasts, broadcast_contacts, wa_link_clicks

-- Reference `broadcasts` (tenant; 3 rows in the reference DB)
CREATE TABLE broadcasts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  device_id bigint,
  template_id bigint,
  template_overrides jsonb,
  name text NOT NULL,
  timezone text,
  status text NOT NULL DEFAULT 'scheduled',
  send_attempts smallint NOT NULL DEFAULT 0,
  next_attempt_at timestamptz,
  pinned boolean NOT NULL DEFAULT false,
  archived boolean NOT NULL DEFAULT false,
  scheduled_at timestamptz,
  completed_at timestamptz,
  node_schedule_id text,
  total_recipients integer NOT NULL DEFAULT 0,
  success_count integer NOT NULL DEFAULT 0,
  delivered_count integer NOT NULL DEFAULT 0,
  read_count integer NOT NULL DEFAULT 0,
  clicked_count integer NOT NULL DEFAULT 0,
  fail_count integer NOT NULL DEFAULT 0,
  provider text,
  temp_caption text,
  messages_log jsonb,
  template_type text,
  temp_image text,
  button_text jsonb,
  latitude text,
  longitude text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_broadcasts_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_broadcasts_template_id FOREIGN KEY (org_id, template_id) REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (template_id)
);
CREATE INDEX idx_broadcasts_archived ON broadcasts (org_id, archived);
CREATE INDEX idx_broadcasts_device_id ON broadcasts (org_id, device_id);
CREATE INDEX idx_broadcasts_provider ON broadcasts (org_id, provider);
CREATE INDEX idx_broadcasts_scheduled_at ON broadcasts (org_id, scheduled_at);
CREATE INDEX idx_broadcasts_status ON broadcasts (org_id, status);
CREATE INDEX idx_broadcasts_template_id ON broadcasts (org_id, template_id);
CREATE INDEX idx_broadcasts_user_id_status ON broadcasts (org_id, user_id, status);

ALTER TABLE broadcasts ENABLE ROW LEVEL SECURITY;
ALTER TABLE broadcasts FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON broadcasts FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_broadcasts_touch BEFORE UPDATE ON broadcasts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

