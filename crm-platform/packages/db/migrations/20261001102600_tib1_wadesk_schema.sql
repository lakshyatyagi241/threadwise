-- tib1: team-inbox-conversations data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's team inbox conversations features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: conversation_tag, inbox_messages, outbound_webhooks, saved_replies

-- --- additions to tables this repo already has ----------------------------------------
-- tags: WaDesk tags carry a free-text description next to name and colour.
ALTER TABLE tags ADD COLUMN description text;

-- WaDesk `conversation_tag` (child; 0 rows in the reference DB)
CREATE TABLE conversation_tag (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  conversation_id bigint NOT NULL,
  tag_id bigint NOT NULL,
  added_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_conversation_tag_conversation_id_tag_id UNIQUE (org_id, conversation_id, tag_id),
  CONSTRAINT fk_conversation_tag_tag_id FOREIGN KEY (org_id, tag_id) REFERENCES tags (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_conversation_tag_added_by FOREIGN KEY (org_id, added_by) REFERENCES users (org_id, id) ON DELETE SET NULL (added_by)
);
CREATE INDEX idx_conversation_tag_tag_id ON conversation_tag (org_id, tag_id);

ALTER TABLE conversation_tag ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversation_tag FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON conversation_tag FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_conversation_tag_touch BEFORE UPDATE ON conversation_tag
  FOR EACH ROW EXECUTE FUNCTION touch_row();

