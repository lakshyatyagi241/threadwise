-- cms: marketing-site-cms data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's marketing site cms features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: announcements, blog_categories, blog_posts, contact_messages, frontend_content, guidebook_articles, legal_pages, pricing_faqs

-- WaDesk `announcements` (global_read; 0 rows in the reference DB)
CREATE TABLE announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  text text NOT NULL,
  link_url text,
  link_label text,
  tone text NOT NULL DEFAULT 'info',
  is_active boolean NOT NULL DEFAULT true,
  dismissible boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  starts_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1
);
CREATE INDEX idx_announcements_is_active_sort_order ON announcements (is_active, sort_order);
CREATE INDEX idx_announcements_starts_at_expires_at ON announcements (starts_at, expires_at);

ALTER TABLE announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements FORCE  ROW LEVEL SECURITY;
CREATE POLICY read_all ON announcements FOR SELECT USING (true);
CREATE POLICY operator_write ON announcements FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_announcements_touch BEFORE UPDATE ON announcements
  FOR EACH ROW EXECUTE FUNCTION touch_row();

