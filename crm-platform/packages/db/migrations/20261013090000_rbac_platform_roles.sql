  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A locked role (Super Admin) keeps its name, its description and every permission it has, and cannot be deleted. Enforced here, not by
-- hiding a button: a Super Admin that could strip itself locks the console out of its own platform.
CREATE OR REPLACE FUNCTION protect_locked_platform_role() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME = 'platform_roles' THEN
    IF TG_OP = 'DELETE' AND OLD.is_locked THEN
      RAISE EXCEPTION 'platform role is locked and cannot be deleted' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.is_locked AND (NEW.name <> OLD.name OR NEW.is_locked = false) THEN
      RAISE EXCEPTION 'platform role is locked and cannot be renamed or unlocked' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN COALESCE(NEW, OLD);
  END IF;
  -- platform_role_permissions: removing a grant from a locked role is refused; adding one is allowed (a new key reaches Super Admin).
  IF EXISTS (SELECT 1 FROM platform_roles r WHERE r.id = OLD.role_id AND r.is_locked) THEN
    RAISE EXCEPTION 'platform role is locked: its permissions cannot be removed' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE TRIGGER trg_platform_roles_protect BEFORE UPDATE OR DELETE ON platform_roles
  FOR EACH ROW EXECUTE FUNCTION protect_locked_platform_role();
CREATE TRIGGER trg_platform_role_permissions_protect BEFORE DELETE ON platform_role_permissions
  FOR EACH ROW EXECUTE FUNCTION protect_locked_platform_role();

