-- rbac: platform-staff roles and the permission catalogue behind the operator console (/admin/roles, /admin/permissions).
-- Why this migration exists (TW-RBAC-001, 003, 005..013, 021): Reference keeps SaaS-operator roles and permission names in global Spatie
-- tables. They have no per-organization meaning here, so they get their own platform-layer tables (no org_id, privileged only) and
-- never touch the per-org roles/role_grants of the workspace RBAC. Seeded once: 101 permission keys and the six Reference roles. The
-- seeder's "overwrite on re-run" behaviour is NOT ported (D-RBAC-01): this migration runs once and later keys arrive by migration.
--
-- Deliberate differences, recorded in docs/threadwise-port/parity/roles-permissions.md:
--   * Super Admin is locked in the database (no rename, no strip, no delete); Reference only blocked deletion.
--   * The 16 enforced platform.* keys are system keys and cannot be deleted; Reference let any key go, which disabled the check for everyone.

CREATE TABLE platform_roles (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  -- citext: Reference's MySQL collation made role names case-insensitive ("manager" collides with "Manager").
  name        citext NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  is_locked   boolean NOT NULL DEFAULT false,
  -- Shown as the "System role" badge (Reference: Super Admin and Admin); every other role reads "Custom role".
  is_system   boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_platform_roles_name CHECK (length(btrim(name::text)) BETWEEN 1 AND 191)
);

CREATE TABLE platform_permissions (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid       uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  name       citext NOT NULL UNIQUE,
  -- true for the keys code checks (platform.*): refusing their deletion is what keeps the check from failing closed for everybody.
  is_system  boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_platform_permissions_name CHECK (length(btrim(name::text)) BETWEEN 1 AND 191)
);

CREATE TABLE platform_role_permissions (
  role_id       bigint NOT NULL REFERENCES platform_roles (id) ON DELETE CASCADE,
  permission_id bigint NOT NULL REFERENCES platform_permissions (id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX idx_platform_role_permissions_perm ON platform_role_permissions (permission_id);

CREATE TABLE platform_operator_roles (
  operator_id bigint NOT NULL REFERENCES platform_operators (id) ON DELETE CASCADE,
  role_id     bigint NOT NULL REFERENCES platform_roles (id) ON DELETE CASCADE,
  PRIMARY KEY (operator_id, role_id)
);
CREATE INDEX idx_platform_operator_roles_role ON platform_operator_roles (role_id);

DO $$
DECLARE
  t text;
  platform_tables text[] := ARRAY['platform_roles', 'platform_permissions', 'platform_role_permissions', 'platform_operator_roles'];
BEGIN
  FOREACH t IN ARRAY platform_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY privileged_only ON %I FOR ALL
        USING      (app_is_privileged())
        WITH CHECK (app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
  END LOOP;
END $$;

