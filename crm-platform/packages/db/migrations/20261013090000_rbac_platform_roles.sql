-- An operator is created by the installer, the CLI, a seed or a test, none of which know about roles. The tier column therefore
-- keeps the matching seeded role in step: a new operator gets it, and a tier change swaps the old tier's role for the new one.
-- Roles an operator was given on top are left alone.
CREATE OR REPLACE FUNCTION sync_operator_tier_role() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  role_for text[] := ARRAY['super_admin', 'Super Admin', 'support', 'Platform Support', 'auditor', 'Auditor'];
  new_name text := role_for[array_position(role_for, NEW.role) + 1];
  old_name text;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    old_name := role_for[array_position(role_for, OLD.role) + 1];
    DELETE FROM platform_operator_roles
      WHERE operator_id = NEW.id AND role_id = (SELECT id FROM platform_roles WHERE name = old_name);
  END IF;
  INSERT INTO platform_operator_roles (operator_id, role_id)
    SELECT NEW.id, id FROM platform_roles WHERE name = new_name
    ON CONFLICT DO NOTHING;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_platform_operators_tier_role AFTER INSERT ON platform_operators
  FOR EACH ROW EXECUTE FUNCTION sync_operator_tier_role();
CREATE TRIGGER trg_platform_operators_tier_role_upd AFTER UPDATE OF role ON platform_operators
  FOR EACH ROW WHEN (OLD.role IS DISTINCT FROM NEW.role) EXECUTE FUNCTION sync_operator_tier_role();

