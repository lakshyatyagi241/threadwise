-- alib: the API Library (saved HTTP API calls a workspace builds once and reuses from flows).
-- Why this migration exists: the old console had an "API Library" (name, method, URL with variable chips, headers, JSON or form-data
-- payload, an optional JavaScript function that reshapes the payload, a mapping of response fields into contact properties, a log of
-- every call). The owner asked for it in the new platform. It is not a WaDesk port (WaDesk has no such screen).
--
--  1. api_library_apis  one saved API. `headers` is [{key, value, secret}]: the value of a secret header is stored ENCRYPTED (the API
--                       encrypts it with the credentials key before the write and decrypts it only to send), so the column never holds a
--                       readable token. `variables` declares every {{token}} the url, header values and body use, with its default.
--  2. api_library_logs  every run (a test from the form, a flow node), append-only, partitioned monthly, no foreign keys (a stream). The
--                       request is stored with secrets MASKED, never the real value. Kept 30 days by a daily sweep (the worker); a
--                       deleted API leaves its log behind (api_name is a snapshot).

CREATE TABLE api_library_apis (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Letters, digits, underscore. Permanent: flows read the answer as {{Name.field}}. Unique per workspace ignoring case.
  name text NOT NULL,
  method text NOT NULL,
  url text NOT NULL,
  payload_type text NOT NULL DEFAULT 'application/json',
  variables jsonb NOT NULL DEFAULT '[]'::jsonb,
  headers jsonb NOT NULL DEFAULT '[]'::jsonb,
  body jsonb,
  function_code text,
  -- [{path, contactProperty, defaultValue}]: response field -> contact property.
  mapping_config jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- ["data.id", "items[].name"]: response paths a flow reads as {{Name.<path>}}.
  response_variables jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_api_library_apis_name CHECK (name ~ '^[A-Za-z0-9_]{1,64}$'),
  CONSTRAINT chk_api_library_apis_method CHECK (method IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE')),
  CONSTRAINT chk_api_library_apis_payload CHECK (payload_type IN ('application/json', 'multipart/form-data')),
  CONSTRAINT chk_api_library_apis_url CHECK (btrim(url) <> '' AND char_length(url) <= 2048),
  CONSTRAINT chk_api_library_apis_variables CHECK (jsonb_typeof(variables) = 'array'),
  CONSTRAINT chk_api_library_apis_headers CHECK (jsonb_typeof(headers) = 'array'),
  CONSTRAINT chk_api_library_apis_mapping CHECK (jsonb_typeof(mapping_config) = 'array'),
  CONSTRAINT chk_api_library_apis_resp_vars CHECK (jsonb_typeof(response_variables) = 'array'),
  CONSTRAINT chk_api_library_apis_body CHECK (body IS NULL OR jsonb_typeof(body) IN ('object', 'array')),
  CONSTRAINT chk_api_library_apis_function CHECK (function_code IS NULL OR char_length(function_code) <= 20000),
  CONSTRAINT fk_api_library_apis_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE UNIQUE INDEX uq_api_library_apis_name ON api_library_apis (org_id, lower(name));
CREATE INDEX idx_api_library_apis_recent ON api_library_apis (org_id, created_at DESC, id DESC);
CREATE INDEX idx_api_library_apis_created_by ON api_library_apis (org_id, created_by) WHERE created_by IS NOT NULL;

ALTER TABLE api_library_apis ENABLE ROW LEVEL SECURITY;
ALTER TABLE api_library_apis FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON api_library_apis FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_api_library_apis_touch BEFORE UPDATE ON api_library_apis
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- The run log. A stream: no foreign key (the API, the user, the flow and the contact are remembered by id or uuid, and the row outlives
-- any of them), keyed by (id, created_at) because Postgres wants the partition key in the primary key.
CREATE SEQUENCE api_library_logs_id_seq;
CREATE TABLE api_library_logs (
  id bigint NOT NULL DEFAULT nextval('api_library_logs_id_seq'),
  org_id bigint NOT NULL,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  -- Null when the run was a test of a definition that was never saved.
  api_uuid uuid,
  api_name text NOT NULL DEFAULT '',
  source text NOT NULL,
  method text NOT NULL,
  -- After substitution, with secret-looking query parameters masked.
  url text NOT NULL,
  -- Secret headers read ******** here; nothing in this table is the real value.
  request_headers jsonb NOT NULL DEFAULT '{}'::jsonb,
  request_body text,
  status_code integer,
  ok boolean NOT NULL DEFAULT false,
  duration_ms integer NOT NULL DEFAULT 0,
  error_kind text,
  error text,
  response_headers jsonb NOT NULL DEFAULT '{}'::jsonb,
  response_body text,
  response_truncated boolean NOT NULL DEFAULT false,
  user_id bigint,
  contact_uuid uuid,
  flow_id bigint,
  flow_run_uuid uuid,
  flow_node_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at),
  CONSTRAINT chk_api_library_logs_source CHECK (source IN ('test', 'flow', 'automation')),
  CONSTRAINT chk_api_library_logs_kind CHECK (
    error_kind IS NULL OR error_kind IN ('blocked', 'function', 'timeout', 'network', 'status', 'invalid'))
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_api_library_logs_recent ON api_library_logs (org_id, created_at DESC, id DESC);
CREATE INDEX idx_api_library_logs_api ON api_library_logs (org_id, api_uuid, created_at DESC);
CREATE INDEX idx_api_library_logs_uuid ON api_library_logs (org_id, uuid);

ALTER TABLE api_library_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE api_library_logs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON api_library_logs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('api_library_logs', m);
  END LOOP;
END $$;

CREATE TABLE api_library_logs_default PARTITION OF api_library_logs DEFAULT;
SELECT inherit_partition_rls('api_library_logs_default');
GRANT SELECT, INSERT, UPDATE, DELETE ON api_library_logs_default TO crm_app, crm_worker;
