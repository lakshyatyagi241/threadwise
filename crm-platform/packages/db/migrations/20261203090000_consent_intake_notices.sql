-- consent intake (BL-167, spec docs/specs/privacy-and-data-governance.md section 4.3.2): where a person can agree to marketing, and what
-- they were shown when they did.
--
--   1. The ledger learns three sources: `widget` (the website chat widget's pre-chat consent line), `booking` (the booking page's consent
--      line) and `commerce` (a store's own marketing consent, Shopify / WooCommerce). The constraint is dropped and re-created with the
--      full list; no row changes, no applied migration is edited.
--   2. `consent_notices`: the wording of each intake point, versioned. One row per version, never updated: a change to the text, the
--      link or the on/off state appends the next version, so the ledger's `noticeVersion` evidence always names a wording that can be
--      read back. Scope and reference say which intake point: ('widget', widget uuid), ('booking', booking type uuid) or
--      ('commerce', 'shopify:<integration uuid>' / 'woocommerce:<integration uuid>'). No personal data lives here.

ALTER TABLE contact_consent_events DROP CONSTRAINT ck_consent_events_source;
ALTER TABLE contact_consent_events ADD CONSTRAINT ck_consent_events_source CHECK (
  source IN ('form', 'keyword', 'manual', 'import', 'api', 'flow', 'inbound_message', 'contact_request', 'legacy', 'widget', 'booking', 'commerce')
);

CREATE TABLE consent_notices (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  scope text NOT NULL,
  scope_ref text NOT NULL,
  version integer NOT NULL,
  enabled boolean NOT NULL,
  -- Kept when the line is switched off, so switching it on again starts from the last wording.
  text text NOT NULL DEFAULT '',
  url text,
  -- Stores only: the extra channel the store's marketing checkbox is worded to cover (see contracts consent/notice.ts).
  channels text[] NOT NULL DEFAULT '{}',
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, scope, scope_ref, version),
  CONSTRAINT fk_consent_notices_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT ck_consent_notices_scope CHECK (scope IN ('widget', 'booking', 'commerce')),
  CONSTRAINT ck_consent_notices_ref CHECK (char_length(scope_ref) BETWEEN 1 AND 80),
  CONSTRAINT ck_consent_notices_version CHECK (version >= 1),
  CONSTRAINT ck_consent_notices_text CHECK (char_length(text) <= 1000 AND (NOT enabled OR btrim(text) <> '')),
  CONSTRAINT ck_consent_notices_channels CHECK (channels <@ ARRAY['whatsapp', 'sms', 'email']::text[]),
  CONSTRAINT ck_consent_notices_url CHECK (url IS NULL OR (char_length(url) <= 500 AND url ~* '^https://[^[:space:]]+$'))
);
CREATE INDEX idx_consent_notices_current ON consent_notices (org_id, scope, scope_ref, version DESC);

ALTER TABLE consent_notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE consent_notices FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON consent_notices FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- A published wording is never edited (the ledger names its version). The only change the database makes itself is `created_by`
-- going NULL when the author is erased.
CREATE FUNCTION consent_notices_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) - 'created_by') IS NOT DISTINCT FROM (to_jsonb(OLD) - 'created_by') THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'consent_notices is append-only: a version cannot be changed' USING ERRCODE = 'integrity_constraint_violation';
END $$;

CREATE TRIGGER trg_consent_notices_immutable BEFORE UPDATE ON consent_notices
  FOR EACH ROW EXECUTE FUNCTION consent_notices_immutable();
