-- chk: checkout-orders-merchant-payments data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's checkout orders merchant payments features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: wa_coupons, wa_merchant_gateways, wa_orders, wa_order_items, wa_pending_orders

-- WaDesk `wa_coupons` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_coupons (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  storefront_id bigint,
  code text NOT NULL,
  type text NOT NULL DEFAULT 'percent',
  amount bigint NOT NULL DEFAULT 0,
  min_subtotal_minor bigint,
  max_discount_minor bigint,
  free_shipping boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  starts_at timestamptz,
  expires_at timestamptz,
  usage_limit integer,
  used_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_coupons_code UNIQUE (org_id, code),
  CONSTRAINT fk_wa_coupons_storefront_id FOREIGN KEY (org_id, storefront_id) REFERENCES wa_storefronts (org_id, id) ON DELETE SET NULL (storefront_id)
);

ALTER TABLE wa_coupons ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_coupons FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_coupons FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_coupons_touch BEFORE UPDATE ON wa_coupons
  FOR EACH ROW EXECUTE FUNCTION touch_row();

