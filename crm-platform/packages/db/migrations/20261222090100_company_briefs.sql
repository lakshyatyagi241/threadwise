-- companies: the "Generate brief" card (BL-194).
-- Why this table exists: a brief is written by an AI model from what the person who asked may see (their record scopes decide which
-- contacts, deals, tasks and conversations are counted), so it belongs to that person, not to the company: a colleague with a narrower
-- scope must never be shown a summary of records they cannot open. One row per (company, person) is also the cache: asking again with
-- the same facts and within a day returns this row without calling a model, and asking to regenerate overwrites it.
--
-- `content` is the structured brief (sections of bullet points), never the facts that were sent. `input_hash` is a digest of those facts,
-- so a change in the CRM (a deal moved, a task added) is known without keeping them. The row is removed with its company or its person.

CREATE TABLE company_briefs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  company_id bigint NOT NULL,
  user_id bigint NOT NULL,
  input_hash text NOT NULL,
  content jsonb NOT NULL,
  provider text NOT NULL,
  model text NOT NULL,
  prompt_tokens integer NOT NULL DEFAULT 0,
  completion_tokens integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_company_briefs_company_user UNIQUE (org_id, company_id, user_id),
  CONSTRAINT fk_company_briefs_company FOREIGN KEY (org_id, company_id)
    REFERENCES companies (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_company_briefs_user FOREIGN KEY (org_id, user_id)
    REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_company_briefs_user ON company_briefs (org_id, user_id);

ALTER TABLE company_briefs ENABLE ROW LEVEL SECURITY;
ALTER TABLE company_briefs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON company_briefs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_company_briefs_touch BEFORE UPDATE ON company_briefs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
