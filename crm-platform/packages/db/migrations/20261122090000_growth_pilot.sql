-- growth pilot: more ways to use what lead scoring already knows (engagement, chat readings, campaign receipts). Not a Reference feature.
--
-- Everything here is a pilot of the demo workspace (slug demo-interakt): the API and the workers read `growth_settings` and do nothing for a
-- workspace that has no row or is not in the pilot list, and the only DATA statements in this file are limited to that slug. The tables
-- themselves are inert elsewhere.
--
--   growth_settings            one row per pilot workspace: which parts are on (`features`) and their thresholds and rules (`config`).
--   growth_actions             the "Growth inbox": things a person should look at or approve (a hot lead, an unanswered buying question, a
--                              contact who asked to stop, a lapsed customer, a registration problem...). One open action per dedupe key.
--   contact_propensity         the model's score of how likely a contact is to convert, with the features behind it.
--   growth_models              what a workspace's models learned (the conversion model).
--   growth_daily_digests       one stored summary of the workspace per day.
--   contact_enrichment         what a third-party enrichment returned for a contact (company size, industry...), when a key is configured.
--   lifecycle_stage_suggestions  gets a `source` (chat or engagement) and the statuses `auto_applied` and `undone` for the guarded auto mode.
--   lead_chat_digests          gets the language of the chat and the kind of problem the contact reported.

CREATE TABLE growth_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  -- {feature_key: boolean}; a key that is absent is off.
  features jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Overrides of the defaults in code (thresholds, rules, the phrase table, extra masked words); absent keys use the default.
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id)
);
ALTER TABLE growth_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE growth_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON growth_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_growth_settings_touch BEFORE UPDATE ON growth_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- growth_actions
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE growth_actions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  type text NOT NULL,
  contact_id bigint NOT NULL,
  conversation_id bigint,
  digest_id bigint,
  severity text NOT NULL DEFAULT 'info',
  -- A short line for the list, and what a person is asked to do; both written from masked or structured data.
  title text NOT NULL,
  detail text,
  -- Type specific facts (the suggested assignee, the reply to send, the days since...). Never the text of a message.
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'open',
  -- One open action per key (for example `hot_lead:<contact>`): detecting the same thing again does not pile up rows.
  dedupe_key text NOT NULL,
  decided_by bigint,
  decided_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, conversation_id) REFERENCES conversations (org_id, id) ON DELETE SET NULL (conversation_id),
  FOREIGN KEY (org_id, digest_id) REFERENCES lead_chat_digests (org_id, id) ON DELETE SET NULL (digest_id),
  FOREIGN KEY (org_id, decided_by) REFERENCES users (org_id, id) ON DELETE SET NULL (decided_by),
  CONSTRAINT ck_growth_actions_type CHECK (type IN (
    'hot_lead', 'unanswered_intent', 'registration_issue', 'purchase_route', 'opt_out', 'lapsed', 'service_due', 'status_reply'
  )),
  CONSTRAINT ck_growth_actions_severity CHECK (severity IN ('info', 'attention', 'urgent')),
  CONSTRAINT ck_growth_actions_status CHECK (status IN ('open', 'done', 'dismissed', 'expired'))
);
CREATE UNIQUE INDEX uq_growth_actions_open ON growth_actions (org_id, dedupe_key) WHERE status = 'open';
CREATE INDEX idx_growth_actions_list ON growth_actions (org_id, status, created_at DESC);
CREATE INDEX idx_growth_actions_contact ON growth_actions (org_id, contact_id);
CREATE INDEX idx_growth_actions_time ON growth_actions (created_at);
ALTER TABLE growth_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE growth_actions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON growth_actions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_growth_actions_touch BEFORE UPDATE ON growth_actions
  FOR EACH ROW EXECUTE FUNCTION touch_row();

