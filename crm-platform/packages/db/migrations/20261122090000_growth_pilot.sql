-- "Last Activity" for the contacts of the demo workspace that have chatted: the newest message of their threads. A bump of that column
-- alone is not an edit (contacts_touch), so no version moves.
UPDATE contacts c SET last_activity_at = x.t
FROM (
  SELECT cv.org_id, cv.contact_id, max(cv.last_message_at) AS t
  FROM conversations cv JOIN organizations o ON o.id = cv.org_id
  WHERE o.slug = 'demo-interakt' AND cv.contact_id IS NOT NULL AND cv.last_message_at IS NOT NULL
  GROUP BY cv.org_id, cv.contact_id
) x
WHERE c.org_id = x.org_id AND c.id = x.contact_id AND (c.last_activity_at IS NULL OR c.last_activity_at < x.t);
