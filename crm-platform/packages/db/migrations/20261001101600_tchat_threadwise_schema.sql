-- tchat: team-chat data model, ported from Reference
-- Why this migration exists: the tables Reference's team chat features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: team_chat_channels, team_chat_invitations, team_chat_messages, team_chat_reactions, team_chat_reads, team_chat_channel_members

-- Reference `team_chat_channels` (tenant; 0 rows in the reference DB)
CREATE TABLE team_chat_channels (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  slug text NOT NULL,
  description text,
  type text NOT NULL DEFAULT 'public',
  created_by_user_id bigint,
  last_message_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_team_chat_channels_type CHECK (type IN ('public', 'private', 'dm')),
  CONSTRAINT uq_team_chat_channels_slug UNIQUE (org_id, slug),
  CONSTRAINT fk_team_chat_channels_created_by_user_id FOREIGN KEY (org_id, created_by_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by_user_id)
);
CREATE INDEX idx_team_chat_channels_created_by_user_id ON team_chat_channels (org_id, created_by_user_id);
CREATE INDEX idx_team_chat_channels_type ON team_chat_channels (org_id, type);

ALTER TABLE team_chat_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE team_chat_channels FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON team_chat_channels FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_team_chat_channels_touch BEFORE UPDATE ON team_chat_channels
  FOR EACH ROW EXECUTE FUNCTION touch_row();

