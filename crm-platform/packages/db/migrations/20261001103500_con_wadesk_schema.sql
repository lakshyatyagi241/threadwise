-- con: contacts-attributes-tags data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's contacts attributes tags features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: contact_groups, csat_responses, contact_group_members

-- --- additions to tables this repo already has ----------------------------------------
-- contacts: WaDesk contact fields that have no column yet. WaDesk `mobile` is `phone`, `custom_attributes` is `data`,
-- `user_id` is `owner_id` and `contact_group` becomes contact_group_members (below); `mobile_hash` is not needed because
-- PII is stored plain under RLS here (see docs/wadesk-port/schema/README.md, decision P1).
ALTER TABLE contacts
  ADD COLUMN title           text,
  ADD COLUMN middle_name     text,
  ADD COLUMN language        text,
  ADD COLUMN address         text,
  ADD COLUMN country_code    text,
  ADD COLUMN channel         text,
  ADD COLUMN channel_uid     text,
  ADD COLUMN image_url       text,
  ADD COLUMN subject         text,
  ADD COLUMN message         text,
  ADD COLUMN is_unsubscribed boolean NOT NULL DEFAULT false,
  ADD COLUMN unsubscribed_at timestamptz;
-- A channel user (telegram chat, line user, ...) is one contact per org. Partial: phone-only contacts have neither column.
CREATE UNIQUE INDEX uq_contacts_org_channel_uid ON contacts (org_id, channel, channel_uid)
  WHERE channel IS NOT NULL AND channel_uid IS NOT NULL;
CREATE INDEX idx_contacts_org_unsubscribed ON contacts (org_id) WHERE is_unsubscribed;

-- WaDesk `contact_groups` (tenant; 4 rows in the reference DB)
CREATE TABLE contact_groups (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  user_group text,
  note text,
  status boolean NOT NULL DEFAULT true,
  color text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_contact_groups_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_contact_groups_user_id ON contact_groups (org_id, user_id);

ALTER TABLE contact_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_groups FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_groups FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_contact_groups_touch BEFORE UPDATE ON contact_groups
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `csat_responses` (tenant; 0 rows in the reference DB)
CREATE TABLE csat_responses (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  conversation_id bigint NOT NULL,
  agent_user_id bigint,
  rating smallint,
  comment text,
  sent_at timestamptz,
  responded_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_csat_responses_agent_user_id FOREIGN KEY (org_id, agent_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (agent_user_id)
);
CREATE INDEX idx_csat_responses_agent_user_id ON csat_responses (org_id, agent_user_id);
CREATE INDEX idx_csat_responses_conversation_id ON csat_responses (org_id, conversation_id);

