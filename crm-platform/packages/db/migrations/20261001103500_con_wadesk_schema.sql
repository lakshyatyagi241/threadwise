-- WaDesk `contact_group_members` (tenant; 0 rows in the reference DB)
CREATE TABLE contact_group_members (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id bigint NOT NULL,
  group_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_contact_group_members_contact_id_group_id UNIQUE (org_id, contact_id, group_id),
  CONSTRAINT fk_contact_group_members_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_contact_group_members_group_id FOREIGN KEY (org_id, group_id) REFERENCES contact_groups (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_contact_group_members_group_id ON contact_group_members (org_id, group_id);

