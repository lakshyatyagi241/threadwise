-- appt: iCal (ICS) calendars as a read-only busy-time source, and a subscribable ICS feed of a person's bookings (BL-035, part 2).
-- Why this migration exists:
--  (1) A workspace can subscribe to calendars it cannot connect with OAuth (an Apple or Fastmail calendar, a school or club timetable, a
--      Microsoft or Google calendar published as a secret ICS address). The feed is fetched by the worker every 15 minutes; its busy intervals
--      for the next ~180 days are stored in `calendar_ics_busy` so that the slot engine reads them from the database and never waits on a
--      remote calendar. The address is sealed (`url_enc`): a published-calendar address usually carries a secret token, so it is never shown
--      again and never logged; only its host is kept for display.
--  (2) A staff member can subscribe their own calendar app to their bookings. `appointment_feed_tokens` holds one bearer token per person (only
--      its hash is a lookup key; an encrypted copy lets the person copy the link again). What the feed shows is decided when it is read, from the
--      person's CURRENT record scope, so a removed or demoted person's feed empties and the link is worth nothing.

CREATE TABLE calendar_ics_feeds (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  url_enc text NOT NULL,             -- AES-GCM ciphertext (credentials key); the address may hold a secret token
  url_host text NOT NULL,            -- display only: never the path or the query
  url_hash text NOT NULL,            -- sha256 of the normalized address: one feed per address per workspace
  -- Whether an all-day event blocks its day (a holiday feed may not want to close the calendar).
  block_all_day boolean NOT NULL DEFAULT true,
  is_active boolean NOT NULL DEFAULT true,
  status text NOT NULL DEFAULT 'pending',
  last_error_code text,
  last_fetched_at timestamptz,
  last_success_at timestamptz,
  next_fetch_at timestamptz NOT NULL DEFAULT now(),
  consecutive_failures integer NOT NULL DEFAULT 0,
  -- Conditional GET: a feed that did not change costs one small request.
  etag text,
  last_modified text,
  calendar_name text,
  event_count integer NOT NULL DEFAULT 0,
  busy_count integer NOT NULL DEFAULT 0,
  warnings jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_calendar_ics_feeds_url UNIQUE (org_id, url_hash),
  CONSTRAINT chk_calendar_ics_feeds_status CHECK (status IN ('pending', 'ok', 'error')),
  CONSTRAINT chk_calendar_ics_feeds_name CHECK (char_length(name) BETWEEN 1 AND 80),
  CONSTRAINT chk_calendar_ics_feeds_error CHECK ((status = 'error') = (last_error_code IS NOT NULL)),
  CONSTRAINT fk_calendar_ics_feeds_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_calendar_ics_feeds_created_by ON calendar_ics_feeds (org_id, created_by);
-- The scheduler's claim: active feeds that are due, across workspaces.
CREATE INDEX idx_calendar_ics_feeds_due ON calendar_ics_feeds (next_fetch_at) WHERE is_active;

ALTER TABLE calendar_ics_feeds ENABLE ROW LEVEL SECURITY;
ALTER TABLE calendar_ics_feeds FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON calendar_ics_feeds FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
-- The refresh job writes the monitoring columns (status, last fetch, counts, the conditional-GET tags) every 15 minutes. They must not bump
-- `row_version` or `updated_at`: an admin editing a feed would otherwise get a spurious 409 ROW_VERSION_CONFLICT after every refresh. Any change
-- to another column bumps the version exactly as `touch_row()` does.
CREATE FUNCTION touch_calendar_ics_feed() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  monitoring text[] := ARRAY['status', 'last_error_code', 'last_fetched_at', 'last_success_at', 'next_fetch_at', 'consecutive_failures',
                             'etag', 'last_modified', 'calendar_name', 'event_count', 'busy_count', 'warnings', 'updated_at', 'row_version'];
BEGIN
  IF TG_OP = 'UPDATE' AND (to_jsonb(NEW) - monitoring) = (to_jsonb(OLD) - monitoring) THEN
    NEW.updated_at := OLD.updated_at;
    NEW.row_version := OLD.row_version;
    RETURN NEW;
  END IF;
  NEW.updated_at := now();
  IF TG_OP = 'UPDATE' THEN
    NEW.row_version := OLD.row_version + 1;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_calendar_ics_feeds_touch BEFORE UPDATE ON calendar_ics_feeds
  FOR EACH ROW EXECUTE FUNCTION touch_calendar_ics_feed();

-- The busy intervals of a feed: replaced as a whole by each successful refresh (a feed holds at most 5,000).
CREATE TABLE calendar_ics_busy (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  feed_id bigint NOT NULL,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  PRIMARY KEY (org_id, id),
  CONSTRAINT chk_calendar_ics_busy_range CHECK (ends_at > starts_at),
  CONSTRAINT fk_calendar_ics_busy_feed FOREIGN KEY (org_id, feed_id)
    REFERENCES calendar_ics_feeds (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_calendar_ics_busy_feed ON calendar_ics_busy (org_id, feed_id);
CREATE INDEX idx_calendar_ics_busy_window ON calendar_ics_busy (org_id, starts_at, ends_at);

ALTER TABLE calendar_ics_busy ENABLE ROW LEVEL SECURITY;
ALTER TABLE calendar_ics_busy FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON calendar_ics_busy FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- One token per person for their own bookings feed. The public route finds the person by the token's hash, before the workspace is known.
CREATE TABLE appointment_feed_tokens (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL,
  token_hash text NOT NULL,          -- sha256 of the 256-bit token; the lookup key
  token_enc text NOT NULL,           -- AES-GCM ciphertext (credentials key): lets the person copy the link again
  last_used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_appointment_feed_tokens_user UNIQUE (org_id, user_id),
  CONSTRAINT uq_appointment_feed_tokens_hash UNIQUE (token_hash),
  CONSTRAINT fk_appointment_feed_tokens_user FOREIGN KEY (org_id, user_id)
    REFERENCES users (org_id, id) ON DELETE CASCADE
);

ALTER TABLE appointment_feed_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointment_feed_tokens FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON appointment_feed_tokens FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_appointment_feed_tokens_touch BEFORE UPDATE ON appointment_feed_tokens
  FOR EACH ROW EXECUTE FUNCTION touch_row();
