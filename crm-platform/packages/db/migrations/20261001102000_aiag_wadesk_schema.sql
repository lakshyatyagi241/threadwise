-- aiag: ai-agents-training data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's ai agents training features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: ai_chat_assistants, ai_training_sources, ai_agents

-- WaDesk `ai_chat_assistants` (tenant; 0 rows in the reference DB)
CREATE TABLE ai_chat_assistants (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  name text NOT NULL,
  slug text NOT NULL,
  greeting text,
  system_prompt text,
  tone text NOT NULL DEFAULT 'helpful',
  language text NOT NULL DEFAULT 'en',
  ai_provider text NOT NULL DEFAULT 'openai',
  ai_model text NOT NULL DEFAULT 'gpt-4o-mini',
  reply_max_tokens smallint NOT NULL DEFAULT 400,
  temperature numeric(4,2) NOT NULL DEFAULT 0.70,
  fallback_message text,
  handoff_enabled boolean NOT NULL DEFAULT true,
  handoff_keyword text,
  handoff_message text,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_ai_chat_assistants_slug UNIQUE (org_id, slug),
  CONSTRAINT fk_ai_chat_assistants_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_ai_chat_assistants_user_id ON ai_chat_assistants (org_id, user_id);
CREATE INDEX idx_ai_chat_assistants_status ON ai_chat_assistants (org_id, status);

ALTER TABLE ai_chat_assistants ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_chat_assistants FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_chat_assistants FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_ai_chat_assistants_touch BEFORE UPDATE ON ai_chat_assistants
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `ai_training_sources` (tenant; 0 rows in the reference DB)
CREATE TABLE ai_training_sources (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  assistant_id bigint,
  user_id bigint,
  kind text NOT NULL,
  label text NOT NULL,
  url text,
  file_path text,
  content text,
  question text,
  answer text,
  status text NOT NULL DEFAULT 'ready',
  tokens_estimate integer,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_ai_training_sources_assistant_id FOREIGN KEY (org_id, assistant_id) REFERENCES ai_chat_assistants (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_ai_training_sources_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
