-- WaDesk `ai_agents` (tenant; 0 rows in the reference DB)
CREATE TABLE ai_agents (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  provider text NOT NULL DEFAULT 'openai',
  model text NOT NULL DEFAULT 'gpt-4o-mini',
  knowledge_assistant_id bigint,
  system_prompt text,
  tone text NOT NULL DEFAULT 'professional',
  avatar_color text NOT NULL DEFAULT '#6366f1',
  auto_respond boolean NOT NULL DEFAULT true,
  max_tokens smallint NOT NULL DEFAULT 512,
  temperature smallint NOT NULL DEFAULT 7,
  max_replies_per_conversation smallint NOT NULL DEFAULT 10,
  handoff_keywords jsonb,
  handoff_low_score_threshold smallint NOT NULL DEFAULT 0,
  handoff_low_score_window smallint NOT NULL DEFAULT 3,
  handoff_enabled boolean NOT NULL DEFAULT true,
  use_saved_replies boolean NOT NULL DEFAULT false,
  voice_note_enabled boolean NOT NULL DEFAULT false,
  voice_call_enabled boolean NOT NULL DEFAULT false,
  voice_provider text,
  voice_id text,
  voice_language text NOT NULL DEFAULT 'en',
  asr_provider text,
  asr_language text,
  max_voice_notes_per_day integer NOT NULL DEFAULT 200,
  is_active boolean NOT NULL DEFAULT true,
  device_ids jsonb,
  messages_sent bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_ai_agents_knowledge_assistant_id FOREIGN KEY (org_id, knowledge_assistant_id) REFERENCES ai_chat_assistants (org_id, id) ON DELETE SET NULL (knowledge_assistant_id)
);
CREATE INDEX idx_ai_agents_knowledge_assistant_id ON ai_agents (org_id, knowledge_assistant_id);

ALTER TABLE ai_agents ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_agents FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_agents FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_ai_agents_touch BEFORE UPDATE ON ai_agents
  FOR EACH ROW EXECUTE FUNCTION touch_row();
