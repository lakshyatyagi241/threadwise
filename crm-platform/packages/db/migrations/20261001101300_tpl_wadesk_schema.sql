-- tpl: message-templates data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's message templates features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: chat_templates, wa_templates

-- WaDesk `chat_templates` (child; 8 rows in the reference DB)
CREATE TABLE chat_templates (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  title text NOT NULL,
  category text NOT NULL,
  tone text,
  body text NOT NULL,
  media_path text,
  media_type text,
  status text NOT NULL DEFAULT 'approved',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_chat_templates_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_chat_templates_category ON chat_templates (org_id, category);
CREATE INDEX idx_chat_templates_status ON chat_templates (org_id, status);
CREATE INDEX idx_chat_templates_user_id ON chat_templates (org_id, user_id);

ALTER TABLE chat_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_templates FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON chat_templates FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_chat_templates_touch BEFORE UPDATE ON chat_templates
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `wa_templates` (tenant; 12 rows in the reference DB)
CREATE TABLE wa_templates (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  template_name text NOT NULL,
  header text,
  header_location jsonb,
  template_body text NOT NULL,
  footer text,
  code_expiration_minutes smallint,
  buttons jsonb,
  carousel_data jsonb,
  variable_map jsonb,
  rejection_reason text,
  rejection_reason_code text,
  category text NOT NULL DEFAULT 'utility',
  meta_category text,
  template_type text NOT NULL DEFAULT 'standard',
  attachment_type text,
  attachment_file text,
  header_sample_url text,
  language text NOT NULL DEFAULT 'en_US',
  parameter_format text NOT NULL DEFAULT 'POSITIONAL',
  status text NOT NULL DEFAULT 'pending',
  approved_at timestamptz,
  submitted_at timestamptz,
  last_synced_at timestamptz,
  paused_until timestamptz,
  provider_config_id bigint,
  meta_template_id text,
  twilio_content_sid text,
  meta_status text,
  channel text,
  quality_score text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_templates_meta_template_id UNIQUE (meta_template_id),
  CONSTRAINT fk_wa_templates_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_wa_templates_provider_config_id FOREIGN KEY (org_id, provider_config_id) REFERENCES wa_provider_configs (org_id, id) ON DELETE SET NULL (provider_config_id)
);
CREATE INDEX idx_wa_templates_category_status ON wa_templates (org_id, category, status);
CREATE INDEX idx_wa_templates_provider_config_id_meta_status ON wa_templates (org_id, provider_config_id, meta_status);
CREATE INDEX idx_wa_templates_channel ON wa_templates (org_id, channel);
CREATE INDEX idx_wa_templates_meta_status ON wa_templates (org_id, meta_status);
CREATE INDEX idx_wa_templates_status ON wa_templates (org_id, status);
CREATE INDEX idx_wa_templates_twilio_content_sid ON wa_templates (org_id, twilio_content_sid);
CREATE INDEX idx_wa_templates_user_id_status ON wa_templates (org_id, user_id, status);

ALTER TABLE wa_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_templates FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_templates FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_templates_touch BEFORE UPDATE ON wa_templates
  FOR EACH ROW EXECUTE FUNCTION touch_row();
