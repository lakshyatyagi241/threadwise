-- appt: the workspace's connected Google Calendar (TW-APPT-028, 029; decision D-08).
-- Why this migration exists: Reference kept the Google grant inside the workspace's encrypted `appointment_settings` JSON, one blob that
-- also held every other setting and was rewritten whole on each token refresh. The calendar port now has a real adapter, so the grant
-- gets a table of its own: one row per workspace, the refresh token sealed with the credentials key (never plain text), the account it
-- belongs to, which calendar bookings are written to, and a status that says whether Google still honours the grant. `needs_reconnect`
-- is set when Google answers `invalid_grant` so the settings card can ask for a new consent instead of every booking failing quietly.

CREATE TABLE appointment_calendar_connections (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider text NOT NULL DEFAULT 'google',
  -- The admin who completed the consent screen. SET NULL: the grant belongs to the workspace, not to that person's seat.
  connected_by bigint,
  account_email text,
  -- Google's stable account id (`sub`): a reconnect with another account must not keep the old account's calendar choice.
  account_sub text,
  refresh_token_enc text NOT NULL,   -- AES-GCM ciphertext (credentials key); never plain text
  access_token_enc text,             -- cached short-lived token, same sealing
  access_token_expires_at timestamptz,
  scopes text,
  calendar_id text NOT NULL DEFAULT 'primary',
  calendar_name text,
  status text NOT NULL DEFAULT 'active',
  status_reason text,
  status_at timestamptz NOT NULL DEFAULT now(),
  connected_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- One Google account per workspace (Reference: one `google_oauth` block per workspace).
  CONSTRAINT uq_appointment_calendar_connections_org UNIQUE (org_id),
  CONSTRAINT chk_appointment_calendar_connections_provider CHECK (provider IN ('google')),
  CONSTRAINT chk_appointment_calendar_connections_status CHECK (status IN ('active', 'needs_reconnect')),
  CONSTRAINT fk_appointment_calendar_connections_connected_by FOREIGN KEY (org_id, connected_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (connected_by)
);
CREATE INDEX idx_appointment_calendar_connections_connected_by ON appointment_calendar_connections (org_id, connected_by);

ALTER TABLE appointment_calendar_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointment_calendar_connections FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON appointment_calendar_connections FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_appointment_calendar_connections_touch BEFORE UPDATE ON appointment_calendar_connections
  FOR EACH ROW EXECUTE FUNCTION touch_row();
