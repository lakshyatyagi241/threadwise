-- ecom_invoice_handoffs
-- Why: a store's paid-order webhook is handed to invoicing (TW-ECOM-035). The store redelivers (Shopify retries, WooCommerce
-- re-sends) and the worker may run a job twice, so each delivery id is claimed once per source, in the same transaction that
-- bills the order. Reference kept this in a platform-wide table with no workspace; here it is tenant data (RLS, composite keys) and
-- the unique key is (org, source, delivery id). The invoice itself is also idempotent on the order (invoices.wa_order_id), so a
-- DIFFERENT delivery of an order that is already invoiced, or whose invoice was voided, never makes a second document: this table
-- is what remembers a replayed delivery after the invoice is gone.

CREATE TABLE ecom_invoice_handoffs (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  source      text NOT NULL,
  delivery_id text NOT NULL,
  topic       text,
  wa_order_id bigint NOT NULL,
  invoice_id  bigint,
  outcome     text NOT NULL DEFAULT 'pending',
  reason      text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_ecom_invoice_handoffs_delivery UNIQUE (org_id, source, delivery_id),
  CONSTRAINT chk_ecom_invoice_handoffs_source CHECK (source IN ('shopify', 'woocommerce')),
  CONSTRAINT chk_ecom_invoice_handoffs_outcome CHECK (outcome IN ('pending', 'invoiced', 'existing', 'skipped')),
  FOREIGN KEY (org_id, wa_order_id) REFERENCES wa_orders (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, invoice_id) REFERENCES invoices (org_id, id) ON DELETE SET NULL (invoice_id)
);
CREATE INDEX idx_ecom_invoice_handoffs_order ON ecom_invoice_handoffs (org_id, wa_order_id);

ALTER TABLE ecom_invoice_handoffs ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecom_invoice_handoffs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ecom_invoice_handoffs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_ecom_invoice_handoffs_touch BEFORE UPDATE ON ecom_invoice_handoffs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
