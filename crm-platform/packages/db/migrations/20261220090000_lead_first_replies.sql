-- lead: speed-to-lead (BL-014, spec L-16): the automatic first message to a new lead, one row per lead.
--
-- Why a table and not a flag on `lead_events`: the message has a life of its own. It waits out a delay of up to an hour, may be held for
-- quiet hours or business hours, can be retried by a worker, and ends in one of several states (sent, blocked by the ConsentGate, skipped
-- for lack of a sender, failed) that the lead screen and the contact's timeline must show. A worker claims due rows with
-- FOR UPDATE SKIP LOCKED, so the table is also the queue.
--
-- Idempotency ("never twice"): UNIQUE (org_id, lead_event_id). A redelivered outbox event, a second worker and an admin's retry of the
-- lead all meet the same row; only the first insert schedules a message. The row holds no message text and no address: the message is
-- rendered at send time from the source's template and the contact, so nothing personal is copied here.

CREATE TABLE lead_first_replies (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  lead_event_id bigint NOT NULL,
  -- The contact the lead became. Cleared when the contact is deleted (the row stays as the record of what was decided).
  contact_id bigint,
  channel text NOT NULL,
  status text NOT NULL DEFAULT 'scheduled',
  -- A stable code (quiet_hours, no_consent, ...): see LEAD_FIRST_REPLY_REASONS. Never provider text, which can carry a phone number.
  reason text,
  -- When it may go (the delay), moved forward while it is held.
  due_at timestamptz NOT NULL,
  -- After this a held message is dropped as `failed / expired`: a "speed to lead" message that arrives a day late is not one.
  expires_at timestamptz NOT NULL,
  -- Counts claims by a worker. A WhatsApp message is safe to try again (the conversation ledger dedupes on this row's uuid); an SMS or
  -- an email is not (the provider has no idempotency key), so a claim that never finished ends `failed / interrupted` instead.
  attempts integer NOT NULL DEFAULT 0,
  claimed_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_lead_first_replies_lead_event UNIQUE (org_id, lead_event_id),
  CONSTRAINT chk_lead_first_replies_channel CHECK (channel IN ('whatsapp', 'sms', 'email')),
  CONSTRAINT chk_lead_first_replies_status CHECK (status IN ('scheduled', 'sending', 'held', 'sent', 'blocked', 'skipped', 'failed')),
  CONSTRAINT fk_lead_first_replies_lead_event FOREIGN KEY (org_id, lead_event_id)
    REFERENCES lead_events (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_lead_first_replies_contact FOREIGN KEY (org_id, contact_id)
    REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id)
);
-- The worker's pick, across workspaces (it runs privileged): what is waiting, earliest first. Final rows are not in it.
CREATE INDEX idx_lead_first_replies_due ON lead_first_replies (due_at)
  WHERE status IN ('scheduled', 'held', 'sending');
CREATE INDEX idx_lead_first_replies_contact ON lead_first_replies (org_id, contact_id) WHERE contact_id IS NOT NULL;

ALTER TABLE lead_first_replies ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_first_replies FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_first_replies FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_lead_first_replies_touch BEFORE UPDATE ON lead_first_replies
  FOR EACH ROW EXECUTE FUNCTION touch_row();
