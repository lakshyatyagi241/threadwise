-- Owner-enabled appointment channels and the predefined message library (BL-350..BL-354).
--
-- Why: the booking-type editor showed WhatsApp as if it were always usable. The workspace owner now decides which channels may carry
-- appointment messages (email, WhatsApp, SMS; voice is reserved), a booking type lists only the channels that are enabled AND connected,
-- and the owner adopts predefined templates (confirmation, reminder, reschedule, cancellation, after-visit follow-up) with one click.
-- An email template lives in the app; a WhatsApp template is a normal `wa_templates` row submitted to Meta, and only an APPROVED one can
-- be chosen. A workspace that exists today keeps working exactly as it does: email, WhatsApp and SMS are switched on for it (source
-- `legacy_default`), and what is not connected simply stays unusable. A workspace created from now on has no row: the owner chooses.
--
-- Voice: the channel id `voice` and the shape of its data are reserved (a row may exist but cannot be enabled; a library template may
-- hold a call script; a reminder rule and a run may name it) so that the outbound reminder call arrives later without a migration.

-- --- the workspace's channel choice -----------------------------------------------------------------------------------------------

CREATE TABLE appointment_channel_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  channel text NOT NULL,
  enabled boolean NOT NULL DEFAULT false,
  -- The sender to use when the workspace has more than one: whatsapp = wa_provider_configs.id of a Cloud API number, sms =
  -- wa_provider_configs.id of the SMS sender, email = mail_mailboxes.id of a shared mailbox. Null = the first connected one.
  -- Not a foreign key (three different tables); the service checks it and the sender falls back when it is gone or disconnected.
  default_sender_id bigint,
  -- Channel-specific settings. Reserved for voice (call window, attempts, script template); empty for the others.
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Who decided: the owner, or the migration that kept today's behaviour for a workspace that already existed.
  source text NOT NULL DEFAULT 'owner',
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_appointment_channel_settings_channel UNIQUE (org_id, channel),
  CONSTRAINT chk_appointment_channel_settings_channel CHECK (channel IN ('email', 'whatsapp', 'sms', 'voice')),
  CONSTRAINT chk_appointment_channel_settings_source CHECK (source IN ('owner', 'legacy_default')),
  -- The Voice bot does not exist yet: the channel can be listed and cannot be switched on.
  CONSTRAINT chk_appointment_channel_settings_voice_off CHECK (channel <> 'voice' OR enabled = false),
  CONSTRAINT fk_appointment_channel_settings_updated_by FOREIGN KEY (org_id, updated_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (updated_by)
);
ALTER TABLE appointment_channel_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointment_channel_settings FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON appointment_channel_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_appointment_channel_settings_touch BEFORE UPDATE ON appointment_channel_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Workspaces that exist today keep today's behaviour. `organizations` is under FORCE ROW LEVEL SECURITY, so the privileged flag is raised.
SELECT set_config('app.privileged', 'on', true);
INSERT INTO appointment_channel_settings (org_id, channel, enabled, source)
SELECT o.id, c.channel, true, 'legacy_default'
  FROM organizations o CROSS JOIN (VALUES ('email'), ('whatsapp'), ('sms')) AS c(channel)
ON CONFLICT (org_id, channel) DO NOTHING;

-- --- the message library ------------------------------------------------------------------------------------------------------

-- One row per message the workspace can use. `body` is the text with {{placeholders}}. For an email it is the message; for a WhatsApp
-- template it is the pattern the linked `wa_templates` row was made from (the live status, the Meta id and a rejection reason are read
-- from that row, so the library can never show a stale "approved"); for voice it is the call script. The row holds the business's own
-- words, never a contact's data.
CREATE TABLE appointment_message_templates (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  kind text NOT NULL,
  channel text NOT NULL,
  language text NOT NULL,
  name text NOT NULL,
  subject text,
  body text NOT NULL,
  -- The placeholders the body uses, in first-use order (WhatsApp fills {{1}}.. from the booking in this order).
  variables text[] NOT NULL DEFAULT ARRAY[]::text[],
  -- WhatsApp only: the template that was submitted to Meta for this message.
  wa_template_id bigint,
  -- The predefined message this was adopted from (a key of the built-in set), or null for the owner's own.
  predefined_key text,
  is_active boolean NOT NULL DEFAULT true,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_appointment_message_templates_kind CHECK (kind IN ('confirmation', 'reminder', 'reschedule', 'cancellation', 'follow_up')),
  CONSTRAINT chk_appointment_message_templates_channel CHECK (channel IN ('email', 'whatsapp', 'sms', 'voice')),
  CONSTRAINT chk_appointment_message_templates_text CHECK (
    char_length(name) BETWEEN 1 AND 120 AND char_length(body) BETWEEN 1 AND 4000
    AND (subject IS NULL OR char_length(subject) <= 191) AND language ~ '^[a-z]{2,3}(_[A-Z]{2})?$'),
  CONSTRAINT chk_appointment_message_templates_wa CHECK (channel = 'whatsapp' OR wa_template_id IS NULL),
  CONSTRAINT uq_appointment_message_templates_name UNIQUE (org_id, kind, channel, language, name),
  CONSTRAINT fk_appointment_message_templates_wa_template_id FOREIGN KEY (org_id, wa_template_id)
    REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (wa_template_id),
  CONSTRAINT fk_appointment_message_templates_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_appointment_message_templates_wa ON appointment_message_templates (org_id, wa_template_id);
CREATE INDEX idx_appointment_message_templates_created_by ON appointment_message_templates (org_id, created_by);
-- A predefined message is adopted once per channel and language.
CREATE UNIQUE INDEX uq_appointment_message_templates_predefined
  ON appointment_message_templates (org_id, predefined_key, channel, language) WHERE predefined_key IS NOT NULL;
ALTER TABLE appointment_message_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointment_message_templates FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON appointment_message_templates FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_appointment_message_templates_touch BEFORE UPDATE ON appointment_message_templates
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- a booking type chooses a library message per kind and channel -------------------------------------------------------------

ALTER TABLE booking_templates
