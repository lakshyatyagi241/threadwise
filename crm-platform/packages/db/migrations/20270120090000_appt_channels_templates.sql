  ADD CONSTRAINT chk_booking_templates_channel CHECK (
    channel IN ('whatsapp', 'email', 'sms', 'voice', 'telegram', 'instagram', 'facebook'));

-- --- voice is reserved on the reminder rule and its runs -----------------------------------------------------------------------

ALTER TABLE booking_reminders DROP CONSTRAINT chk_booking_reminders_channels;
ALTER TABLE booking_reminders
  ADD CONSTRAINT chk_booking_reminders_channels CHECK (
    cardinality(channels) BETWEEN 1 AND 4 AND channels <@ ARRAY['whatsapp', 'sms', 'email', 'voice']::text[]);

ALTER TABLE appointment_reminder_runs DROP CONSTRAINT chk_appointment_reminder_runs_channel;
ALTER TABLE appointment_reminder_runs
  ADD CONSTRAINT chk_appointment_reminder_runs_channel CHECK (
    channel IS NULL OR channel IN ('whatsapp', 'sms', 'email', 'voice'));

-- --- permissions --------------------------------------------------------------------------------------------------------------
-- Owner and Admin decide which channels the workspace uses and manage the library (submitting a WhatsApp template to Meta also needs
-- `tpl.templates.create` and `tpl.templates.sync`, which the service checks). Reading what is on is `record.booking-types.read`.

INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('appointments.channels.manage',  'Choose which channels carry appointment messages and their default sender', 'crm', false),
  ('appointments.templates.manage', 'Adopt, edit and submit the appointment message templates',                  'crm', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label, category = EXCLUDED.category, supports_scope = EXCLUDED.supports_scope;

INSERT INTO workspace_preset_baseline (preset_key, permission_key)
SELECT p.preset, k.key
FROM (VALUES ('admin'), ('workspace_admin')) AS p(preset)
CROSS JOIN (VALUES ('appointments.channels.manage'), ('appointments.templates.manage')) AS k(key)
ON CONFLICT (preset_key, permission_key) DO NOTHING;

SELECT set_config('app.privileged', 'on', true);
SELECT apply_workspace_preset_baseline(id) FROM organizations;
UPDATE organizations SET roles_version = roles_version + 1;
