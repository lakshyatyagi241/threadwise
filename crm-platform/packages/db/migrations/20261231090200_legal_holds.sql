-- Legal hold (BL-295, docs/specs/legal-hold.md). Erasure is not absolute: a person asks to be erased, but the business must keep the data
-- for a legal obligation, a dispute, a regulator's request or an investigation. A hold freezes erasure and every purge for one contact, one
-- lead or a whole workspace; a rights case for a held person is RESTRICTED (kept, locked) and resumes when the hold ends.
--
--   legal_holds                      one row per hold: scope, reason category, case reference, review and expiry dates, who placed and
--                                    released it. One ACTIVE hold per subject (partial unique indexes).
--   is_subject_held(org, type, id)   the single question every purge path asks (true for a workspace hold, a hold on the subject or on the
--                                    person it is linked to, or the platform operator's own workspace hold).
--   org_has_active_legal_hold(org)   any active hold at all: wholesale wipes (plan lapse, workspace erase) ask this one.
--   trg_*_legal_hold_guard           the database net under the application guard: a direct DELETE of a held contact or lead is refused.
--   privacy_requests.restricted_*    the rights case state "restricted: legal hold", and the confirmation recorded when someone tried to
--                                    execute the erasure while the hold was active (the worker resumes it after the release).
--   privacy_settings.legal_hold_requester_notice   the workspace's own wording of the answer to the person (counsel's text), or NULL.
--
-- Additive: nothing is backfilled and no existing statement changes behaviour unless a hold exists.

CREATE TABLE legal_holds (
  org_id             bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid               uuid NOT NULL DEFAULT gen_random_uuid(),
  scope              text NOT NULL,
  contact_id         bigint,
  lead_id            bigint,
  -- A masked text (initials and last digits) or 'Whole workspace': never the person's name, number or address.
  subject_label      text NOT NULL,
  reason_category    text NOT NULL,
  case_ref           text NOT NULL,
  note               text,
  review_at          timestamptz,
  expires_at         timestamptz,
  status             text NOT NULL DEFAULT 'active',
  placed_by          bigint,
  placed_at          timestamptz NOT NULL DEFAULT now(),
  last_reviewed_by   bigint,
  last_reviewed_at   timestamptz,
  released_by        bigint,
  released_at        timestamptz,
  release_note       text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  row_version        integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- SET NULL: a released hold outlives the person it delayed the erasure of (the register keeps the masked label); an active hold cannot lose
  -- its subject because the delete triggers below refuse the delete.
  CONSTRAINT fk_legal_holds_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_legal_holds_lead FOREIGN KEY (org_id, lead_id) REFERENCES leads (org_id, id) ON DELETE SET NULL (lead_id),
  CONSTRAINT fk_legal_holds_placed_by FOREIGN KEY (org_id, placed_by) REFERENCES users (org_id, id) ON DELETE SET NULL (placed_by),
  CONSTRAINT fk_legal_holds_reviewed_by FOREIGN KEY (org_id, last_reviewed_by) REFERENCES users (org_id, id) ON DELETE SET NULL (last_reviewed_by),
  CONSTRAINT fk_legal_holds_released_by FOREIGN KEY (org_id, released_by) REFERENCES users (org_id, id) ON DELETE SET NULL (released_by),
  CONSTRAINT ck_legal_holds_scope CHECK (scope IN ('contact', 'lead', 'workspace')),
  CONSTRAINT ck_legal_holds_subject CHECK (
    status <> 'active'
    OR (scope = 'contact' AND contact_id IS NOT NULL AND lead_id IS NULL)
    OR (scope = 'lead' AND lead_id IS NOT NULL AND contact_id IS NULL)
    OR (scope = 'workspace' AND contact_id IS NULL AND lead_id IS NULL)),
  CONSTRAINT ck_legal_holds_reason CHECK (reason_category IN
    ('legal_obligation', 'legal_claim', 'regulator_request', 'internal_investigation')),
  CONSTRAINT ck_legal_holds_status CHECK (status IN ('active', 'released', 'expired')),
  CONSTRAINT ck_legal_holds_label CHECK (char_length(subject_label) BETWEEN 1 AND 120),
  CONSTRAINT ck_legal_holds_case_ref CHECK (char_length(case_ref) BETWEEN 1 AND 120),
  CONSTRAINT ck_legal_holds_note CHECK (note IS NULL OR char_length(note) <= 500),
  CONSTRAINT ck_legal_holds_release_note CHECK (release_note IS NULL OR char_length(release_note) <= 500),
  CONSTRAINT ck_legal_holds_released CHECK ((status = 'active') = (released_at IS NULL)),
  CONSTRAINT ck_legal_holds_dates CHECK (expires_at IS NULL OR expires_at > placed_at)
);

-- One active hold per subject: a second matter is added to the first one's case reference (extend), not stacked.
CREATE UNIQUE INDEX uq_legal_holds_active_contact ON legal_holds (org_id, contact_id) WHERE status = 'active' AND scope = 'contact';
CREATE UNIQUE INDEX uq_legal_holds_active_lead ON legal_holds (org_id, lead_id) WHERE status = 'active' AND scope = 'lead';
CREATE UNIQUE INDEX uq_legal_holds_active_workspace ON legal_holds (org_id) WHERE status = 'active' AND scope = 'workspace';
-- The guard function and the sweeps read only active holds: a tiny partial index keeps the "is anything held" test free for workspaces with none.
CREATE INDEX idx_legal_holds_active ON legal_holds (org_id, scope) WHERE status = 'active';
-- The register: newest first, per workspace; the expiry sweep looks at active holds with an end date.
CREATE INDEX idx_legal_holds_list ON legal_holds (org_id, placed_at DESC, id DESC);
CREATE INDEX idx_legal_holds_expiry ON legal_holds (expires_at) WHERE status = 'active' AND expires_at IS NOT NULL;

ALTER TABLE legal_holds ENABLE ROW LEVEL SECURITY;
ALTER TABLE legal_holds FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON legal_holds FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_legal_holds_touch BEFORE UPDATE ON legal_holds
  FOR EACH ROW EXECUTE FUNCTION touch_row();

