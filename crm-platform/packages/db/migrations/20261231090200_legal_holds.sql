-- The rights case under a hold. `status` keeps its values; a case is "restricted: legal hold" while `restricted_at` is set.
-- `erasure_confirmed_*` is the person who typed the confirmation phrase while the hold was active: the worker executes that erasure after the
-- hold ends without asking again.
ALTER TABLE privacy_requests
  ADD COLUMN restricted_at         timestamptz,
  ADD COLUMN restricted_hold_id    bigint,
  ADD COLUMN erasure_confirmed_by  bigint,
  ADD COLUMN erasure_confirmed_at  timestamptz,
  ADD CONSTRAINT fk_privacy_requests_restricted_hold FOREIGN KEY (org_id, restricted_hold_id)
    REFERENCES legal_holds (org_id, id) ON DELETE SET NULL (restricted_hold_id),
  ADD CONSTRAINT fk_privacy_requests_confirmed_by FOREIGN KEY (org_id, erasure_confirmed_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (erasure_confirmed_by),
  ADD CONSTRAINT ck_privacy_requests_restricted CHECK (restricted_hold_id IS NULL OR restricted_at IS NOT NULL);
-- The resume sweep: confirmed erasures that are no longer restricted.
CREATE INDEX idx_privacy_requests_resume ON privacy_requests (erasure_confirmed_at)
  WHERE status = 'in_progress' AND request_type = 'erasure' AND erasure_confirmed_at IS NOT NULL AND restricted_at IS NULL;
CREATE INDEX idx_privacy_requests_restricted ON privacy_requests (org_id, restricted_hold_id) WHERE restricted_at IS NOT NULL;

ALTER TABLE privacy_settings
  ADD COLUMN legal_hold_requester_notice text,
  ADD CONSTRAINT ck_privacy_settings_hold_notice CHECK (legal_hold_requester_notice IS NULL OR char_length(legal_hold_requester_notice) <= 1500);
