-- Is this subject held? STABLE, SECURITY INVOKER: it runs under the caller's row-level security, so a tenant only ever sees its own holds and a
-- privileged sweep sees every workspace's. A hold is active while its status is 'active' AND it has not passed its end date (the worker moves
-- an expired one to 'expired' so its unique slot frees up, but the answer never waits for the worker).
--   p_type  'contact' | 'lead'
--   p_id    may be NULL (a row with no known person): only a workspace-wide hold then answers true.
CREATE FUNCTION is_subject_held(p_org bigint, p_type text, p_id bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM legal_holds h
     WHERE h.org_id = p_org AND h.status = 'active' AND (h.expires_at IS NULL OR h.expires_at > now())
       AND (h.scope = 'workspace'
            OR (p_id IS NOT NULL AND p_type = 'contact' AND (
                  (h.scope = 'contact' AND h.contact_id = p_id)
                  OR (h.scope = 'lead' AND h.lead_id IN (SELECT l.id FROM leads l WHERE l.org_id = p_org AND l.contact_id = p_id))))
            OR (p_id IS NOT NULL AND p_type = 'lead' AND (
                  (h.scope = 'lead' AND h.lead_id = p_id)
                  OR (h.scope = 'contact' AND h.contact_id = (SELECT l.contact_id FROM leads l WHERE l.org_id = p_org AND l.id = p_id))))))
  OR EXISTS (SELECT 1 FROM organizations o WHERE o.id = p_org AND o.legal_hold)
$$;

-- Any active hold at all in the workspace (a wholesale wipe would delete the held records too).
CREATE FUNCTION org_has_active_legal_hold(p_org bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM legal_holds h
     WHERE h.org_id = p_org AND h.status = 'active' AND (h.expires_at IS NULL OR h.expires_at > now()))
  OR EXISTS (SELECT 1 FROM organizations o WHERE o.id = p_org AND o.legal_hold)
$$;

-- The net under the application guard: any code path that deletes a held contact or lead directly is refused. A delete that arrives through a
-- foreign-key cascade (pg_trigger_depth() > 1: the operator erasing a whole workspace) is not a tenant act and is decided where it starts.
CREATE FUNCTION legal_hold_delete_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF pg_trigger_depth() <= 1 AND is_subject_held(OLD.org_id, TG_ARGV[0], OLD.id) THEN
    RAISE EXCEPTION 'LEGAL_HOLD_ACTIVE: this record is protected and cannot be deleted' USING ERRCODE = '55000';
  END IF;
  RETURN OLD;
END $$;
CREATE TRIGGER trg_contacts_legal_hold_guard BEFORE DELETE ON contacts
  FOR EACH ROW EXECUTE FUNCTION legal_hold_delete_guard('contact');
CREATE TRIGGER trg_leads_legal_hold_guard BEFORE DELETE ON leads
  FOR EACH ROW EXECUTE FUNCTION legal_hold_delete_guard('lead');

