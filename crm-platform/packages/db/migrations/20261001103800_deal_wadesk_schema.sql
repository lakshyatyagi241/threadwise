-- deal: deals-pipelines data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's deals pipelines features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: pipelines, pipeline_stages, deals, deal_activities

-- WaDesk `pipelines` (tenant; 0 rows in the reference DB)
CREATE TABLE pipelines (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  is_default boolean NOT NULL DEFAULT false,
  currency text NOT NULL DEFAULT 'INR',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid)
);
CREATE INDEX idx_pipelines_is_default ON pipelines (org_id, is_default);

ALTER TABLE pipelines ENABLE ROW LEVEL SECURITY;
ALTER TABLE pipelines FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON pipelines FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_pipelines_touch BEFORE UPDATE ON pipelines
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `pipeline_stages` (tenant; 0 rows in the reference DB)
