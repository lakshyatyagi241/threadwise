-- WaDesk `deals` (tenant; 0 rows in the reference DB)
CREATE TABLE deals (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  pipeline_id bigint NOT NULL,
  stage_id bigint NOT NULL,
  contact_id bigint,
  company_id bigint,
  conversation_id bigint,
  title text NOT NULL,
  value_minor bigint NOT NULL DEFAULT 0,
  currency text NOT NULL DEFAULT 'INR',
  owner_user_id bigint,
  owner_team_id bigint,
  expected_close_date date,
  status text NOT NULL DEFAULT 'open',
  lost_reason text,
  source text NOT NULL DEFAULT 'manual',
  sort_order integer NOT NULL DEFAULT 0,
  notes text,
  meta jsonb,
  won_at timestamptz,
  lost_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_deals_pipeline_id FOREIGN KEY (org_id, pipeline_id) REFERENCES pipelines (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_deals_stage_id FOREIGN KEY (org_id, stage_id) REFERENCES pipeline_stages (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_deals_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_deals_company_id FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_deals_conversation_id FOREIGN KEY (org_id, conversation_id) REFERENCES conversations (org_id, id) ON DELETE SET NULL (conversation_id),
  CONSTRAINT fk_deals_owner_user_id FOREIGN KEY (org_id, owner_user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_user_id)
);
CREATE INDEX idx_deals_company_id ON deals (org_id, company_id);
CREATE INDEX idx_deals_contact_id ON deals (org_id, contact_id);
CREATE INDEX idx_deals_owner_user_id ON deals (org_id, owner_user_id);
CREATE INDEX idx_deals_pipeline_id_stage_id ON deals (org_id, pipeline_id, stage_id);
CREATE INDEX idx_deals_status ON deals (org_id, status);

ALTER TABLE deals ENABLE ROW LEVEL SECURITY;
ALTER TABLE deals FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON deals FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_deals_touch BEFORE UPDATE ON deals
  FOR EACH ROW EXECUTE FUNCTION touch_row();

