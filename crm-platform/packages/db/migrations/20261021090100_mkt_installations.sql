CREATE OR REPLACE FUNCTION market_requests_bump_votes() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  IF TG_OP = 'INSERT' THEN
    UPDATE market_requests SET vote_count = vote_count + 1 WHERE id = NEW.request_id;
  ELSIF TG_OP = 'DELETE' THEN
    UPDATE market_requests SET vote_count = GREATEST(vote_count - 1, 0) WHERE id = OLD.request_id;
  END IF;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION market_requests_bump_votes() FROM PUBLIC;
CREATE TRIGGER trg_market_request_votes_count AFTER INSERT OR DELETE ON market_request_votes
  FOR EACH ROW EXECUTE FUNCTION market_requests_bump_votes();
