-- marketplace: per-workspace installations, consent records, connector connections, delivery log and integration requests
-- (spec docs/specs/marketplace-mini-apps-and-integrations.md, M-03, M-04, M-05, M-16).
-- Why this migration exists: the catalogue (previous migration) says what can be installed; these tables say what each workspace
-- HAS installed, what it consented to, how it is connected and whether it is healthy, and what it has asked us to build.
--
--  1. workspace_app_installations: one row per (workspace, app). Forced RLS, composite (org_id, id) key, composite foreign keys to the
--     tenant tables it references (users). `granted_scopes` is what the admin consented to; `pending_version_id` is a newer published
--     version that asks for MORE scopes and waits for a new consent (the installation keeps running on the old version meanwhile).
--     `credentials_enc` is one sealed CryptoService envelope of the secret fields the admin entered; only the last four characters of
--     each are kept in the clear (`credential_hints`) so the page can say "set" without decrypting. Uninstalling deletes the row (access
--     ends in the same transaction); the keep/delete-data choice is kept in marketplace_consents.
--  2. marketplace_consents: append-only ledger of install, re-consent and uninstall (who, which version, which scopes, the data choice).
--  3. marketplace_connections: what an integration installation talks through (push, pull, webhook relay, ...): a public key that names
--     its delivery address, the sealed secret that authenticates deliveries, poll schedule and state for pull connectors, health and
--     counters. One connection per installation in v1.
--  4. marketplace_connection_events: one row per delivery id (the sender's own lead id, or a hash of the delivery), the idempotency
--     guard at the door and the "recent events" list. It holds no lead data: the lead pipeline stores the raw event. Trimmed by the worker.
--  5. market_requests / market_request_votes: "request an integration". A request is one row per normalised name across the platform
--     (so asking twice is a vote), a workspace counts once per request. The count is kept by a SECURITY DEFINER trigger so a workspace
--     can see how many others asked without being able to see who.
--  6. marketplace_connection_lookup: the public delivery address names no tenant, and the row that does is behind RLS, so the lookup is a
--     SECURITY DEFINER function that returns two ids and nothing else (the same pattern as ecom_store_lookup).

CREATE TABLE workspace_app_installations (
  org_id               bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                   bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                 uuid NOT NULL DEFAULT gen_random_uuid(),
  app_id               bigint NOT NULL REFERENCES marketplace_apps (id) ON DELETE RESTRICT,
  installed_version_id bigint NOT NULL REFERENCES marketplace_app_versions (id) ON DELETE RESTRICT,
  pending_version_id   bigint REFERENCES marketplace_app_versions (id) ON DELETE SET NULL,
  status               text NOT NULL DEFAULT 'active',
  granted_scopes       text[] NOT NULL DEFAULT '{}',
  config               jsonb NOT NULL DEFAULT '{}'::jsonb,
  credentials_enc      text,
  credential_hints     jsonb NOT NULL DEFAULT '{}'::jsonb,
  health_status        text NOT NULL DEFAULT 'unknown',
  health_checked_at    timestamptz,
  last_error           text,
  last_error_at        timestamptz,
  installed_by         bigint,
  installed_at         timestamptz NOT NULL DEFAULT now(),
  disabled_at          timestamptz,
  killed_at            timestamptz,
  kill_reason          text,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  row_version          integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_workspace_app_installations_app UNIQUE (org_id, app_id),
  CONSTRAINT chk_workspace_app_installations_status CHECK (status IN ('active', 'disabled', 'killed')),
  CONSTRAINT chk_workspace_app_installations_health CHECK (
    health_status IN ('unknown', 'healthy', 'degraded', 'error', 'needs_reauth')),
  CONSTRAINT fk_workspace_app_installations_installed_by FOREIGN KEY (org_id, installed_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (installed_by)
);
-- The kill switch and the publish-time upgrade walk every installation of one app across workspaces.
CREATE INDEX idx_workspace_app_installations_app ON workspace_app_installations (app_id, status);
CREATE INDEX idx_workspace_app_installations_org_status ON workspace_app_installations (org_id, status);
CREATE INDEX idx_workspace_app_installations_installed_by ON workspace_app_installations (org_id, installed_by);
CREATE TRIGGER trg_workspace_app_installations_touch BEFORE UPDATE ON workspace_app_installations
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE workspace_app_installations ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_app_installations FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON workspace_app_installations FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- A workspace reads the listing and the versions of what it has installed even after the platform hides or kills the app.
CREATE POLICY tenant_read_installed ON marketplace_apps FOR SELECT
  USING (EXISTS (SELECT 1 FROM workspace_app_installations i
                  WHERE i.org_id = current_org_id() AND i.app_id = marketplace_apps.id));
CREATE POLICY tenant_read_installed ON marketplace_app_versions FOR SELECT
  USING (EXISTS (SELECT 1 FROM workspace_app_installations i
                  WHERE i.org_id = current_org_id()
                    AND (i.installed_version_id = marketplace_app_versions.id OR i.pending_version_id = marketplace_app_versions.id)));

-- install_count of the app follows its installations. SECURITY DEFINER: the catalogue is not writable by a workspace.
CREATE OR REPLACE FUNCTION marketplace_bump_install_count() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  IF TG_OP = 'INSERT' THEN
    UPDATE marketplace_apps SET install_count = install_count + 1 WHERE id = NEW.app_id;
  ELSIF TG_OP = 'DELETE' THEN
    UPDATE marketplace_apps SET install_count = GREATEST(install_count - 1, 0) WHERE id = OLD.app_id;
  END IF;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION marketplace_bump_install_count() FROM PUBLIC;
CREATE TRIGGER trg_workspace_app_installations_count AFTER INSERT OR DELETE ON workspace_app_installations
  FOR EACH ROW EXECUTE FUNCTION marketplace_bump_install_count();

-- --- consent ledger ----------------------------------------------------------------------------------------------------------------

CREATE TABLE marketplace_consents (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  installation_id bigint,
  app_id          bigint NOT NULL REFERENCES marketplace_apps (id) ON DELETE RESTRICT,
  version_id      bigint NOT NULL REFERENCES marketplace_app_versions (id) ON DELETE RESTRICT,
  action          text NOT NULL,
  scopes          text[] NOT NULL DEFAULT '{}',
  previous_scopes text[] NOT NULL DEFAULT '{}',
  data_choice     text,
  consented_by    bigint,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_marketplace_consents_action CHECK (action IN ('install', 'reconsent', 'uninstall')),
  CONSTRAINT chk_marketplace_consents_data_choice CHECK (
    (action = 'uninstall' AND data_choice IN ('keep', 'delete')) OR (action <> 'uninstall' AND data_choice IS NULL)),
  -- The ledger outlives the installation it describes.
  CONSTRAINT fk_marketplace_consents_installation FOREIGN KEY (org_id, installation_id)
    REFERENCES workspace_app_installations (org_id, id) ON DELETE SET NULL (installation_id),
  CONSTRAINT fk_marketplace_consents_user FOREIGN KEY (org_id, consented_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (consented_by)
);
CREATE INDEX idx_marketplace_consents_installation ON marketplace_consents (org_id, installation_id, created_at DESC);
CREATE INDEX idx_marketplace_consents_app ON marketplace_consents (org_id, app_id, created_at DESC);
CREATE INDEX idx_marketplace_consents_version ON marketplace_consents (version_id);
CREATE INDEX idx_marketplace_consents_user ON marketplace_consents (org_id, consented_by);

ALTER TABLE marketplace_consents ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_consents FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON marketplace_consents FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
-- A ledger row is never edited.
CREATE POLICY ledger_no_update ON marketplace_consents AS RESTRICTIVE FOR UPDATE
  USING (false);

-- --- connections ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE marketplace_connections (
  org_id                bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                    bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                  uuid NOT NULL DEFAULT gen_random_uuid(),
  installation_id       bigint NOT NULL,
  connector_type        text NOT NULL,
  -- 32 hex characters: names the connection in its delivery address. Not a secret by itself (every delivery must also authenticate).
  public_key            text NOT NULL,
  -- CryptoService envelope of the secret that authenticates deliveries; the last four characters in the clear.
  secret_enc            text,
  secret_hint           text,
  status                text NOT NULL DEFAULT 'active',
  poll_interval_seconds integer,
  next_poll_at          timestamptz,
  poll_cursor           text,
  -- The lead pipeline's source for this connection, once it has provisioned one (no foreign key: the pipeline's tables are another domain's).
  lead_source_id        bigint,
  last_event_at         timestamptz,
  last_success_at       timestamptz,
  last_error            text,
  last_error_at         timestamptz,
  consecutive_failures  integer NOT NULL DEFAULT 0,
  received_count        bigint NOT NULL DEFAULT 0,
  accepted_count        bigint NOT NULL DEFAULT 0,
  duplicate_count       bigint NOT NULL DEFAULT 0,
  failed_count          bigint NOT NULL DEFAULT 0,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  row_version           integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_marketplace_connections_installation UNIQUE (org_id, installation_id),
  CONSTRAINT uq_marketplace_connections_public_key UNIQUE (public_key),
  CONSTRAINT chk_marketplace_connections_type CHECK (
    connector_type IN ('oauth', 'push', 'pull', 'email_parse', 'webhook_relay')),
  CONSTRAINT chk_marketplace_connections_status CHECK (status IN ('active', 'paused', 'error', 'disabled')),
  CONSTRAINT chk_marketplace_connections_public_key CHECK (public_key ~ '^[0-9a-f]{32}$'),
  CONSTRAINT fk_marketplace_connections_installation FOREIGN KEY (org_id, installation_id)
    REFERENCES workspace_app_installations (org_id, id) ON DELETE CASCADE
);
-- The pull worker's sweep: active pull connections that are due.
CREATE INDEX idx_marketplace_connections_due ON marketplace_connections (next_poll_at)
  WHERE connector_type = 'pull' AND status = 'active';
CREATE TRIGGER trg_marketplace_connections_touch BEFORE UPDATE ON marketplace_connections
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE marketplace_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_connections FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON marketplace_connections FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE OR REPLACE FUNCTION marketplace_connection_lookup(p_public_key text)
RETURNS TABLE (conn_org_id bigint, conn_id bigint)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY SELECT c.org_id, c.id FROM marketplace_connections c WHERE c.public_key = p_public_key;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;
REVOKE ALL ON FUNCTION marketplace_connection_lookup(text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION marketplace_connection_lookup(text) TO crm_app_user;
  END IF;
END
$$;

-- --- deliveries -----------------------------------------------------------------------------------------------------------------------

CREATE TABLE marketplace_connection_events (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  connection_id bigint NOT NULL,
  external_id   text NOT NULL,
  status        text NOT NULL,
  error         text,
  -- How many times this delivery id arrived (2 or more = the sender repeated itself).
  seen_count    integer NOT NULL DEFAULT 1,
  received_at   timestamptz NOT NULL DEFAULT now(),
  last_seen_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_marketplace_connection_events_external UNIQUE (org_id, connection_id, external_id),
  CONSTRAINT chk_marketplace_connection_events_status CHECK (status IN ('accepted', 'failed', 'rejected')),
  CONSTRAINT chk_marketplace_connection_events_external CHECK (length(external_id) BETWEEN 1 AND 200),
  CONSTRAINT fk_marketplace_connection_events_connection FOREIGN KEY (org_id, connection_id)
    REFERENCES marketplace_connections (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_marketplace_connection_events_recent ON marketplace_connection_events (org_id, connection_id, received_at DESC, id DESC);
-- The retention sweep.
CREATE INDEX idx_marketplace_connection_events_age ON marketplace_connection_events (received_at);

ALTER TABLE marketplace_connection_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE marketplace_connection_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON marketplace_connection_events FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- --- requests -----------------------------------------------------------------------------------------------------------------------

CREATE TABLE market_requests (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid               uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  name               text NOT NULL,
  -- The name with case, spaces and punctuation removed: "Just Dial" and "JustDial" are one request.
  name_key           text NOT NULL,
  kind               text NOT NULL DEFAULT 'integration',
  category_slug      text,
  website            text,
  status             text NOT NULL DEFAULT 'open',
  vote_count         integer NOT NULL DEFAULT 0,
  operator_note      text,
  created_by_org_id  bigint REFERENCES organizations (id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  row_version        integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_market_requests_name_key UNIQUE (kind, name_key),
  CONSTRAINT chk_market_requests_kind CHECK (kind IN ('mini_app', 'integration')),
  CONSTRAINT chk_market_requests_status CHECK (status IN ('open', 'planned', 'building', 'shipped', 'declined')),
  CONSTRAINT chk_market_requests_votes CHECK (vote_count >= 0)
);
CREATE INDEX idx_market_requests_votes ON market_requests (vote_count DESC, id DESC);
CREATE INDEX idx_market_requests_created ON market_requests (created_at DESC, id DESC);
CREATE INDEX idx_market_requests_org ON market_requests (created_by_org_id);
-- vote_count is written by the votes trigger; like install_count it is not an edit and must not move row_version.
CREATE TRIGGER trg_market_requests_touch BEFORE UPDATE ON market_requests
  FOR EACH ROW WHEN (OLD.vote_count = NEW.vote_count) EXECUTE FUNCTION touch_row();

ALTER TABLE market_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE market_requests FORCE  ROW LEVEL SECURITY;
-- Everyone sees the names and counts (demand is shared); a workspace can add a request as itself; only the operator changes one.
CREATE POLICY privileged_all ON market_requests FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE POLICY tenant_read ON market_requests FOR SELECT
  USING (true);
CREATE POLICY tenant_insert ON market_requests FOR INSERT
  WITH CHECK (created_by_org_id = current_org_id());
GRANT SELECT, INSERT, UPDATE, DELETE ON market_requests TO crm_app, crm_worker;

