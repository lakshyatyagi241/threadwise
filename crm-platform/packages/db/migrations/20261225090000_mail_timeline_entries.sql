-- mail timeline (E-19): which mail already has an entry on a contact's timeline.
-- Why this migration exists: the Email channel writes one `contact_activities` row per mail (inbound and outbound) so the contact's Activity
-- Timeline shows the correspondence. A mail can be seen more than once (a redelivered sync, a send retried after the provider already accepted
-- it), and `contact_activities` is another domain's append-only table with no column to dedupe on. This table is the Email channel's own
-- ledger of what it wrote: `dedupe_key` is `<mailbox uuid>:in:<provider message id>` or `<mailbox uuid>:out:<Message-ID>`, unique per
-- workspace, and the INSERT ... ON CONFLICT DO NOTHING on it is what makes the write idempotent. It holds no person's data (ids only).
-- Deleting the activity (or its contact, which cascades to it) deletes the ledger row.
CREATE TABLE mail_timeline_entries (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  dedupe_key  text NOT NULL,
  activity_id bigint NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, dedupe_key),
  CONSTRAINT chk_mail_timeline_entries_key CHECK (char_length(dedupe_key) BETWEEN 1 AND 500),
  CONSTRAINT fk_mail_timeline_entries_activity FOREIGN KEY (org_id, activity_id)
    REFERENCES contact_activities (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_mail_timeline_entries_activity ON mail_timeline_entries (org_id, activity_id);

ALTER TABLE mail_timeline_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE mail_timeline_entries FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON mail_timeline_entries FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
