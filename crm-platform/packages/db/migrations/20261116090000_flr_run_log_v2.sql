-- flr: a per-node execution log that stays small, and 30 days of it (TW-FLR-054, 055, 083)
-- Why this migration exists: a run used to copy the whole compiled graph into flow_runs.graph, so ten thousand runs of one flow stored
-- ten thousand copies, and the step log kept only a node id and a free-text note, so once a user edited a node nobody could tell what
-- it had been. Now a graph is stored once per distinct version (content hash) and a run points at it; every step row carries the node's
-- label and a short summary of what it did, how long it took and which branch it took, so the log still reads correctly after the
-- flow is edited or the node is deleted. Runs that ended more than 30 days ago are deleted by a daily sweep (steps cascade).
--
-- Old runs keep their embedded graph (graph stays non-null for them); new runs leave it null and read the shared version.

CREATE TABLE flow_graph_versions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  flow_id bigint NOT NULL,
  -- sha256 of the compiled graph: the same graph is never stored twice for a flow.
  hash text NOT NULL,
  graph jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, flow_id, hash),
  CONSTRAINT fk_flow_graph_versions_flow_id FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE
);

ALTER TABLE flow_graph_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_graph_versions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_graph_versions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

ALTER TABLE flow_runs ALTER COLUMN graph DROP NOT NULL;
ALTER TABLE flow_runs ADD COLUMN graph_version_id bigint;
ALTER TABLE flow_runs ADD CONSTRAINT fk_flow_runs_graph_version_id
  FOREIGN KEY (org_id, graph_version_id) REFERENCES flow_graph_versions (org_id, id) ON DELETE SET NULL (graph_version_id);
-- Totals kept on the run so the list never counts the step table.
ALTER TABLE flow_runs ADD COLUMN node_count integer NOT NULL DEFAULT 0;
ALTER TABLE flow_runs ADD COLUMN error_count integer NOT NULL DEFAULT 0;
ALTER TABLE flow_runs ADD COLUMN duration_ms integer NOT NULL DEFAULT 0;
CREATE INDEX idx_flow_runs_graph_version ON flow_runs (org_id, graph_version_id) WHERE graph_version_id IS NOT NULL;
-- The retention sweep reads finished runs by age, across every workspace.
CREATE INDEX idx_flow_runs_ended ON flow_runs (ended_at) WHERE ended_at IS NOT NULL;

-- One row per node execution. node_label and summary are copied at run time: they are what the node was, whatever the flow says now.
ALTER TABLE flow_run_steps ADD COLUMN node_label text;
ALTER TABLE flow_run_steps ADD COLUMN outcome text
  CHECK (outcome IN ('ok', 'error', 'skipped', 'waiting', 'timeout'));
-- The exit the run left the node by (1 is the normal exit; a Condition's yes is 1 and no is 2).
ALTER TABLE flow_run_steps ADD COLUMN port integer;
ALTER TABLE flow_run_steps ADD COLUMN duration_ms integer;
-- Which visit of the node this was (a loop runs a node more than once).
ALTER TABLE flow_run_steps ADD COLUMN attempt integer;
ALTER TABLE flow_run_steps ADD COLUMN summary text;
ALTER TABLE flow_run_steps ADD COLUMN error_code text;
