-- notif: per-person notification preferences and the retention indexes (docs/specs/realtime-notifications.md sections 5, 6 and 16 D5,
-- BL-096 phase 2).
-- Why this migration exists: a person must be able to switch the bell row, the toast and the ping of each notification type on or
-- off for themselves (resolution: their setting, then the workspace owner's toggle, then the default), and the feed must stop growing
-- for ever (WaDesk never pruned it; 194k rows were seen live).
--
-- notification_user_prefs is sparse: one row per (person, type) the person ever changed, and a NULL channel means "inherit", so a later
-- change of a default or of the owner's toggle still reaches everyone who never chose. It is a plain tenant table: forced RLS, composite
-- key and foreign key, touch_row for optimistic locking. A removed user takes their preferences along (ON DELETE CASCADE).
--
-- The two partial indexes serve the retention job's batch deletes (read rows older than the read cutoff; unread rows older than the
-- unread cutoff) as an index range scan from the oldest row, instead of a scan of the whole feed.

CREATE TABLE notification_user_prefs (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id     bigint NOT NULL,
  type        text NOT NULL,
  bell        boolean,
  toast       boolean,
  sound       boolean,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_notification_user_prefs_user_type UNIQUE (org_id, user_id, type),
  CONSTRAINT chk_notification_user_prefs_type CHECK (char_length(type) BETWEEN 1 AND 64),
  CONSTRAINT fk_notification_user_prefs_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);

ALTER TABLE notification_user_prefs ENABLE ROW LEVEL SECURITY;
ALTER TABLE notification_user_prefs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON notification_user_prefs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_notification_user_prefs_touch BEFORE UPDATE ON notification_user_prefs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE INDEX idx_inbox_notifications_prune_read
  ON inbox_notifications (created_at) WHERE read_at IS NOT NULL;
CREATE INDEX idx_inbox_notifications_prune_unread
  ON inbox_notifications (created_at) WHERE read_at IS NULL;
