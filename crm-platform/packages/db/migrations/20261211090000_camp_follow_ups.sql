-- camp: follow-up steps after a campaign message (the guided campaign's "Add a follow-up").
-- Why this migration exists: after the campaign message goes out, a recipient's reply or read (or silence) can trigger another message
-- or start a flow, up to three steps in a row. The steps themselves live in the campaign's wizard draft; this adds where each recipient
-- stands in the chain, a log with one row per (recipient, step) that makes a step happen at most once, and the lookup that lets the
-- delivery report of a follow-up message find its campaign (the wallet charges a message once its delivery is reported).

ALTER TABLE wpcampaigns
  ADD COLUMN follow_up_count smallint NOT NULL DEFAULT 0,
  ADD CONSTRAINT ck_wpcampaigns_follow_up_count CHECK (follow_up_count BETWEEN 0 AND 3);

-- null: not in a chain yet. active: the next step to look at is `follow_up_next`, measured from `follow_up_base_at` (when the
-- message before it was sent); `follow_up_check_at` is when the worker looks at it next. done: the chain ended (last step done, or a step was skipped or lapsed, or the recipient opted out).
ALTER TABLE wp_campaign_contacts
  ADD COLUMN follow_up_state text,
  ADD COLUMN follow_up_next smallint,
  ADD COLUMN follow_up_base_at timestamptz,
  ADD COLUMN follow_up_check_at timestamptz,
  ADD CONSTRAINT ck_wp_campaign_contacts_follow_up_state CHECK (follow_up_state IS NULL OR follow_up_state IN ('active', 'done')),
  ADD CONSTRAINT ck_wp_campaign_contacts_follow_up_chain CHECK (
    (follow_up_state = 'active') = (follow_up_next IS NOT NULL AND follow_up_base_at IS NOT NULL AND follow_up_check_at IS NOT NULL)
  );

CREATE INDEX idx_wp_campaign_contacts_follow_up_active
  ON wp_campaign_contacts (follow_up_check_at) WHERE follow_up_state = 'active';
CREATE INDEX idx_wpcampaigns_follow_up ON wpcampaigns (org_id, id) WHERE follow_up_count > 0;

CREATE TABLE camp_follow_up_attempts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  campaign_id bigint NOT NULL,
  recipient_id bigint NOT NULL,
  -- 1 is the first follow-up.
  step_no smallint NOT NULL,
  trigger text NOT NULL,
  action_kind text NOT NULL,
  -- When the step became due (or, for a watching step, the moment it fired or ran out).
  scheduled_for timestamptz NOT NULL,
  executed_at timestamptz NOT NULL DEFAULT now(),
  -- claimed: written BEFORE the provider is called, so a crash in between never sends it twice.
  outcome text NOT NULL,
  -- The delivery of the message the step sent, from the provider's reports.
  delivery_status text,
  delivered_at timestamptz,
  read_at timestamptz,
  provider_message_id text,
  error_code text,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_camp_follow_up_attempts_step UNIQUE (org_id, recipient_id, step_no),
  CONSTRAINT ck_camp_follow_up_attempts_trigger CHECK (trigger IN ('replied', 'read', 'not_replied', 'not_read')),
  CONSTRAINT ck_camp_follow_up_attempts_action CHECK (action_kind IN ('template', 'flow')),
  CONSTRAINT ck_camp_follow_up_attempts_outcome CHECK (outcome IN ('claimed', 'sent', 'flow_started', 'failed', 'skipped', 'lapsed')),
  CONSTRAINT ck_camp_follow_up_attempts_delivery CHECK (delivery_status IS NULL OR delivery_status IN ('sent', 'delivered', 'read', 'failed')),
  CONSTRAINT fk_camp_follow_up_attempts_campaign FOREIGN KEY (org_id, campaign_id)
    REFERENCES wpcampaigns (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_camp_follow_up_attempts_recipient FOREIGN KEY (org_id, recipient_id)
    REFERENCES wp_campaign_contacts (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_camp_follow_up_attempts_campaign ON camp_follow_up_attempts (org_id, campaign_id, step_no);
CREATE INDEX idx_camp_follow_up_attempts_message ON camp_follow_up_attempts (provider_message_id) WHERE provider_message_id IS NOT NULL;

ALTER TABLE camp_follow_up_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE camp_follow_up_attempts FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON camp_follow_up_attempts FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_camp_follow_up_attempts_touch BEFORE UPDATE ON camp_follow_up_attempts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A delivery report arrives without a tenant and names a message id: this narrow SECURITY DEFINER lookup says which follow-up
-- attempt it belongs to; everything after that runs under the normal tenant context (same shape as camp_receipt_lookup).
CREATE OR REPLACE FUNCTION camp_follow_up_receipt_lookup(p_message_id text)
RETURNS TABLE (receipt_org_id bigint, receipt_campaign_id bigint, receipt_contact_id bigint, receipt_attempt_id bigint)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT a.org_id, a.campaign_id, r.contact_id, a.id
    FROM camp_follow_up_attempts a
    JOIN wp_campaign_contacts r ON r.org_id = a.org_id AND r.id = a.recipient_id
    WHERE a.provider_message_id = p_message_id
    ORDER BY a.id DESC LIMIT 1;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION camp_follow_up_receipt_lookup(text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION camp_follow_up_receipt_lookup(text) TO crm_app_user;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_worker_user') THEN
    GRANT EXECUTE ON FUNCTION camp_follow_up_receipt_lookup(text) TO crm_worker_user;
  END IF;
END
$$;
