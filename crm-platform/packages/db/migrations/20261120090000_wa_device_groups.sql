-- wadev groups: the WhatsApp groups of a PERSONAL number (unofficial engine, channel kind whatsapp_qr).
-- Why this migration exists: Reference kept groups in the device-agnostic `wa_groups` / `wa_group_members` (unique on the group jid alone, the
-- phone as a plain string), which cannot say which of a workspace's several numbers a group belongs to, whether that number is an admin, or
-- that it left. This is the per-device directory the Groups tab lists and edits (docs/threadwise-port/plan/whatsapp-personal-groups-build.md,
-- decisions D5, D6, D7). The legacy tables stay for the storefront's group-code ordering.
--
-- group_jid holds the BARE group id (no '@g.us'); the same string is the inbox thread key `g:<id>`. A group the number left, or was removed
-- from, is KEPT with left_at set (D5), so its thread stays readable. Deleting the DEVICE deletes its groups (ON DELETE CASCADE): the number is
-- gone, nothing can read or write them any more, and the inbox threads are separate rows that stay.
-- invite_code is a bearer secret (anyone with it can join): never returned to a client or logged; the API only says `hasInviteLink`.
-- participants is the cached roster ({jid, phone, lid, name, admin}), personal data, written capped; join_requests is the pending list
-- (recovery path for a missed `group.join-request` event). Both are served only to wa.groups.manage holders.

CREATE TABLE wa_device_groups (
  org_id             bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid               uuid NOT NULL DEFAULT gen_random_uuid(),
  device_id          bigint NOT NULL,
  group_jid          text NOT NULL,
  subject            text,
  description        text,
  size               integer NOT NULL DEFAULT 0,
  -- Is OUR number an admin (or the owner) of the group: gates every change.
  is_admin           boolean NOT NULL DEFAULT false,
  -- Only admins may send / only admins may edit the group info / new members need an admin's approval / who may add members.
  announce           boolean NOT NULL DEFAULT false,
  restrict_info      boolean NOT NULL DEFAULT false,
  join_approval      boolean NOT NULL DEFAULT false,
  member_add_mode    text NOT NULL DEFAULT 'all_member_add',
  owner_jid          text,
  addressing_mode    text,
  invite_code        text,
  picture_url        text,
  creation_at        timestamptz,
  synced_at          timestamptz,
  left_at            timestamptz,
  participants       jsonb NOT NULL DEFAULT '[]'::jsonb,
  join_requests      jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_by_user_id bigint,
  meta_json          jsonb,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  row_version        integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_device_groups_device_jid UNIQUE (org_id, device_id, group_jid),
  CONSTRAINT fk_wa_device_groups_device_id FOREIGN KEY (org_id, device_id)
    REFERENCES devices (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_wa_device_groups_created_by_user_id FOREIGN KEY (org_id, created_by_user_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by_user_id),
  CONSTRAINT ck_wa_device_groups_member_add_mode CHECK (member_add_mode IN ('all_member_add', 'admin_add')),
  CONSTRAINT ck_wa_device_groups_participants CHECK (jsonb_typeof(participants) = 'array' AND jsonb_array_length(participants) <= 2048),
  CONSTRAINT ck_wa_device_groups_join_requests CHECK (jsonb_typeof(join_requests) = 'array' AND jsonb_array_length(join_requests) <= 1000)
);

-- The list is newest first for one number, by keyset (created_at, id). The number's filter is mandatory on the list.
CREATE INDEX idx_wa_device_groups_list ON wa_device_groups (org_id, device_id, created_at DESC, id DESC);

ALTER TABLE wa_device_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_device_groups FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_device_groups FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_device_groups_touch BEFORE UPDATE ON wa_device_groups
  FOR EACH ROW EXECUTE FUNCTION touch_row();
