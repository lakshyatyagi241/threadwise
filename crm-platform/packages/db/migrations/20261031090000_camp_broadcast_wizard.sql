-- camp: the broadcast wizard's data (a draft, a recurring series, frequency-cap retries, test sends).
-- Why this migration exists: the four-step "Create broadcast" wizard saves ONE draft that becomes a campaign, and adds three things the
-- WaDesk campaign model keeps in a single row: (1) a recurring broadcast is a SERIES with one child campaign per occurrence, so every run
-- has its own recipients, counters and history (WaDesk re-queued the same row, which loses the past runs); (2) retries for Meta's
-- frequency-capping failure (131049) run at exactly 24-hour spacing until an end date, tracked per recipient with an attempt log, so a
-- retry can be proved to have run once and never for a message that already went through; (3) a test send is recorded and charged like a
-- real one. The existing campaign tables are extended (not copied) so the sender, the receipts and the screens keep working unchanged.

-- ---------------------------------------------------------------------------------------------------- series
CREATE TABLE camp_series (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  -- The recurrence rule (frequency, interval, weekdays, start date, time of day, zone, end): packages/contracts campaigns/recurrence.ts.
  rule jsonb NOT NULL,
  -- The wizard draft every run is built from (template, audience, variables, retries), frozen at launch.
  blueprint jsonb NOT NULL,
  template_id bigint,
  provider text NOT NULL,
  device_id bigint,
  -- The 0-based occurrence the planner will create next, and when it is due. NULL next_run_at: the rule has ended.
  next_index integer NOT NULL DEFAULT 0,
  next_run_at timestamptz,
  occurrences_created integer NOT NULL DEFAULT 0,
  -- Occurrences a long outage made stale: stepped over, never sent late in a burst.
  occurrences_skipped integer NOT NULL DEFAULT 0,
  last_occurrence_at timestamptz,
  ended_at timestamptz,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT ck_camp_series_status CHECK (status IN ('active', 'paused', 'ended', 'cancelled')),
  CONSTRAINT fk_camp_series_template FOREIGN KEY (org_id, template_id)
    REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (template_id),
  CONSTRAINT fk_camp_series_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
-- The planner's scan: active series that are due.
CREATE INDEX idx_camp_series_due ON camp_series (next_run_at) WHERE status = 'active' AND next_run_at IS NOT NULL;
CREATE INDEX idx_camp_series_org_status ON camp_series (org_id, status, id DESC);

ALTER TABLE camp_series ENABLE ROW LEVEL SECURITY;
ALTER TABLE camp_series FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON camp_series FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_camp_series_touch BEFORE UPDATE ON camp_series
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------- campaigns
-- `wizard` is { draft, launch? }: the wizard draft as the person last saved it, and what was true at launch (skipped contacts, the
-- estimate). NULL on a campaign the classic builder made, which is how the rest of the app tells the two apart.
ALTER TABLE wpcampaigns
  ADD COLUMN wizard jsonb,
  ADD COLUMN series_id bigint,
  ADD COLUMN occurrence_no integer,
  -- When this run is (was) due, as an instant. The send date and time columns hold the same moment on the zone's clock for the sweeper.
  ADD COLUMN run_at timestamptz,
  ADD COLUMN retry_enabled boolean NOT NULL DEFAULT false,
  -- The instant the retry window closes (the start of the day after the person's end date, in their zone).
  ADD COLUMN retry_until timestamptz;

ALTER TABLE wpcampaigns
  ADD CONSTRAINT fk_wpcampaigns_series FOREIGN KEY (org_id, series_id)
    REFERENCES camp_series (org_id, id) ON DELETE SET NULL (series_id),
  ADD CONSTRAINT ck_wpcampaigns_wizard_series CHECK ((series_id IS NULL) = (occurrence_no IS NULL));
-- One run per occurrence: the planner can be retried or run twice and still create it once.
CREATE UNIQUE INDEX uq_wpcampaigns_series_occurrence ON wpcampaigns (org_id, series_id, occurrence_no) WHERE series_id IS NOT NULL;
CREATE INDEX idx_wpcampaigns_wizard ON wpcampaigns (org_id, id DESC) WHERE wizard IS NOT NULL;
CREATE INDEX idx_wpcampaigns_retry ON wpcampaigns (retry_enabled) WHERE retry_enabled;

-- ---------------------------------------------------------------------------------------------------- recipients
-- retry_state: scheduled (waiting for retry_next_at), sending (claimed by the retry job), sent (a retry was accepted by the provider,
-- outcome pending), recovered (a retry was delivered), exhausted (no more retries: end date reached, another error, or the job died
-- mid-send: a message that may have gone out is never sent again).
ALTER TABLE wp_campaign_contacts
  ADD COLUMN error_code text,
  ADD COLUMN retry_state text,
  ADD COLUMN retry_count smallint NOT NULL DEFAULT 0,
  -- The anchor: when the first send was accepted. Retry k is due exactly k x 24 h after it, however late a run actually was.
  ADD COLUMN retry_first_sent_at timestamptz,
  ADD COLUMN retry_next_at timestamptz;
ALTER TABLE wp_campaign_contacts
  ADD CONSTRAINT ck_wp_campaign_contacts_retry_state
    CHECK (retry_state IS NULL OR retry_state IN ('scheduled', 'sending', 'sent', 'recovered', 'exhausted'));
CREATE INDEX idx_wp_campaign_contacts_retry_due ON wp_campaign_contacts (retry_next_at) WHERE retry_state = 'scheduled';
CREATE INDEX idx_wp_campaign_contacts_retry_open ON wp_campaign_contacts (org_id, campaign_id) WHERE retry_state IN ('scheduled', 'sending', 'sent');

-- One row per retry actually executed: the proof that a retry ran once, and when.
CREATE TABLE camp_retry_attempts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  campaign_id bigint NOT NULL,
  recipient_id bigint NOT NULL,
  -- 1 is the first retry.
  attempt_no smallint NOT NULL,
  scheduled_for timestamptz NOT NULL,
  executed_at timestamptz NOT NULL DEFAULT now(),
  outcome text NOT NULL,
  provider_message_id text,
  error_code text,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- The same retry cannot be recorded twice: a second claim of it fails here, whatever else goes wrong.
  CONSTRAINT uq_camp_retry_attempts_recipient_attempt UNIQUE (org_id, recipient_id, attempt_no),
  CONSTRAINT ck_camp_retry_attempts_outcome CHECK (outcome IN ('sent', 'frequency_cap', 'failed')),
  CONSTRAINT fk_camp_retry_attempts_campaign FOREIGN KEY (org_id, campaign_id)
    REFERENCES wpcampaigns (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_camp_retry_attempts_recipient FOREIGN KEY (org_id, recipient_id)
    REFERENCES wp_campaign_contacts (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_camp_retry_attempts_campaign ON camp_retry_attempts (org_id, campaign_id, executed_at);

ALTER TABLE camp_retry_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE camp_retry_attempts FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON camp_retry_attempts FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_camp_retry_attempts_touch BEFORE UPDATE ON camp_retry_attempts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

