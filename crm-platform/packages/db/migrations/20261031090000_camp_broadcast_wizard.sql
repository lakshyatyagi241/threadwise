-- A delivery report names a provider message id and no tenant. Same shape as camp_receipt_lookup: a narrow SECURITY DEFINER lookup says
-- which organization a test message belongs to; everything after it runs under the normal tenant context.
CREATE OR REPLACE FUNCTION camp_test_receipt_lookup(p_message_id text)
RETURNS TABLE (test_org_id bigint, test_id bigint)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT t.org_id, t.id FROM camp_test_sends t WHERE t.provider_message_id = p_message_id ORDER BY t.id DESC LIMIT 1;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;
REVOKE ALL ON FUNCTION camp_test_receipt_lookup(text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION camp_test_receipt_lookup(text) TO crm_app_user;
  END IF;
END
$$;
