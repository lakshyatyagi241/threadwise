-- con: the CSV of a contacts export is kept for 30 days so anyone who may export can download it again.
-- Why this migration exists: the Import and export history listed who exported what and when, but the file only went to the
-- browser that asked for it, so a teammate (or the same person on another device) had to run the export again. The file is
-- stored gzipped on the row; `uuid` is also written into the export's audit entry, which is how the history finds its file.
-- Expired rows are deleted by the next export of the same workspace.

CREATE TABLE contact_exports (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  created_by bigint,
  file_name text NOT NULL,
  row_count integer NOT NULL DEFAULT 0,
  byte_size integer NOT NULL DEFAULT 0,
  csv_gz bytea NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_contact_exports_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_contact_exports_org_expires ON contact_exports (org_id, expires_at);

ALTER TABLE contact_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_exports FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_exports FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_contact_exports_touch BEFORE UPDATE ON contact_exports
  FOR EACH ROW EXECUTE FUNCTION touch_row();
