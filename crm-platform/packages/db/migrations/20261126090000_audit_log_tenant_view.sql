-- audit: the tenant-facing audit log (list, detail, filters, asynchronous CSV export). Not a Reference feature one-to-one: Reference's
-- Activity Log reads its own `audit_logs`; here the same screen reads `audit_log` (docs/specs/audit-log-tenant.md).
--
-- Permission keys (Owner and Admin only; Manager does NOT get them, the trail names every person and every change):
--   audit.log.read    open Settings > Audit log, read entries and the masked field changes
--   audit.log.export  prepare a CSV of the filtered window (built by the worker, kept 7 days, announced by email)
-- Owner and Admin presets get every new key by the trigger on `permission_defs` (20261013100000); `workspace_preset_baseline` makes
-- sure a workspace provisioned later gets them too.

INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('audit.log.read',   'View the workspace audit log',  'settings', false),
  ('audit.log.export', 'Export the workspace audit log', 'settings', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label,
      category = EXCLUDED.category,
      supports_scope = EXCLUDED.supports_scope;

INSERT INTO workspace_preset_baseline (preset_key, permission_key)
SELECT p.preset, k.key
FROM (VALUES ('admin'), ('workspace_admin')) AS p(preset)
CROSS JOIN (VALUES ('audit.log.read'), ('audit.log.export')) AS k(key)
ON CONFLICT (preset_key, permission_key) DO NOTHING;

SELECT set_config('app.privileged', 'on', true);
SELECT apply_workspace_preset_baseline(id) FROM organizations;
UPDATE organizations SET roles_version = roles_version + 1;

-- The list is "newest first inside one workspace and one time window"; the existing indexes lead with (org_id, module, record_id) or
-- (org_id, actor_id), so an unfiltered or module-less read had to sort. Created on the partitioned parent: every partition (and every
-- later monthly partition) gets its own copy, and a query bounded by `at` only touches the partitions of its window.
CREATE INDEX idx_audit_org_at ON audit_log (org_id, at DESC, id DESC);
-- "Everything one request did" (the request id shown on every row).
CREATE INDEX idx_audit_org_request ON audit_log (org_id, request_id, at DESC) WHERE request_id IS NOT NULL;

-- One row per requested export. Same shape as `contact_consent_exports`; the row stays (status `expired`) after the file is deleted.
CREATE TABLE audit_log_exports (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  requested_by  bigint NOT NULL,
  -- Where the "your export is ready" mail went; kept so the page can say it even after the user changes address.
  emailed_to    text,
  -- The window and filters the file is built with (an AuditLogFilters document, ISO dates already resolved).
  filters       jsonb NOT NULL DEFAULT '{}'::jsonb,
  status        text NOT NULL DEFAULT 'queued',
  row_count     integer,
  file_name     text,
  file_bytes    integer,
  file_gz       bytea,
  error         text,
  requested_at  timestamptz NOT NULL DEFAULT now(),
  started_at    timestamptz,
  completed_at  timestamptz,
  expires_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, requested_by) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_audit_log_exports_status CHECK (status IN ('queued', 'running', 'ready', 'failed', 'expired'))
);
CREATE INDEX idx_audit_log_exports_org ON audit_log_exports (org_id, requested_at DESC);
-- The daily sweep finds files past their time and exports whose worker died.
CREATE INDEX idx_audit_log_exports_expiry ON audit_log_exports (expires_at) WHERE status = 'ready';
CREATE INDEX idx_audit_log_exports_running ON audit_log_exports (started_at) WHERE status = 'running';

ALTER TABLE audit_log_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log_exports FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON audit_log_exports FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_audit_log_exports_touch BEFORE UPDATE ON audit_log_exports
  FOR EACH ROW EXECUTE FUNCTION touch_row();
