-- 0014_add_contact_tags_and_views
-- Phase 11 (docs/phase-plan.md) — Contacts list/view/bulk surface: tags,
-- their membership on contacts, and saved/shared list views. Design in
-- docs/contacts-schema-design.dbml lines 162-215.

CREATE TABLE tags (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  name        citext NOT NULL,
  color       text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- citext is already case-insensitive, so a plain unique index dedups
  -- "VIP" and "vip" without a lower() expression index.
  UNIQUE (org_id, name)
);

-- Pure membership: a contact either has a tag or doesn't. No row_version,
-- no uuid — never addressed individually, only ever as the (contact, tag) pair.
CREATE TABLE contact_tags (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  contact_id bigint NOT NULL,
  tag_id     bigint NOT NULL,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, contact_id, tag_id),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, tag_id)     REFERENCES tags     (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, created_by) REFERENCES users    (org_id, id) ON DELETE SET NULL
);
CREATE INDEX idx_contact_tags_contact ON contact_tags (org_id, contact_id);
CREATE INDEX idx_contact_tags_tag     ON contact_tags (org_id, tag_id);

CREATE TABLE contact_views (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  name        text NOT NULL,
  -- AND/OR condition tree over contacts columns + Tier-2 fields.
  filter      jsonb NOT NULL DEFAULT '{}',
  position    integer NOT NULL DEFAULT 0,
  -- false = only the creator sees it; true = every org member does.
  is_shared   boolean NOT NULL DEFAULT false,
  created_by  bigint,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL
);
CREATE INDEX idx_contact_views_created_by ON contact_views (org_id, created_by);

-- Pure membership: favoriting a view is per-viewer. No row_version, no uuid.
CREATE TABLE contact_view_favorites (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  view_id    bigint NOT NULL,
  user_id    bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, view_id, user_id),
  FOREIGN KEY (org_id, view_id) REFERENCES contact_views (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, user_id) REFERENCES users          (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_contact_view_favorites_view ON contact_view_favorites (org_id, view_id);

DO $$
DECLARE
  t text;
  new_tables text[] := ARRAY['tags', 'contact_tags', 'contact_views', 'contact_view_favorites'];
BEGIN
  FOREACH t IN ARRAY new_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
        FOR ALL
        USING      (org_id = current_org_id() OR app_is_privileged())
        WITH CHECK (org_id = current_org_id() OR app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
  END LOOP;
END $$;

CREATE TRIGGER trg_tags_touch          BEFORE UPDATE ON tags          FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_contact_views_touch BEFORE UPDATE ON contact_views FOR EACH ROW EXECUTE FUNCTION touch_row();
