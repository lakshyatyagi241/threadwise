-- flb: publishing a flow also pushes the workspace's bot live on the Geta console (an addition beyond WaDesk).
-- Why this migration exists: after the local publish commits, a worker makes two calls to the Geta console (a configuration update,
-- then publish-bot). Two tenant tables hold what that needs and what happened:
--
--   flb_geta_publish_settings  one row per workspace: base URL, optional origin, the two header tokens and the Geta chatbot record
--                              (the three secrets are sealed by the application with CryptoService; a database dump is not a working
--                              set of console credentials).
--   flb_geta_publish_syncs     one row per flow: the remote state of its last publish (pending | live | failed), the step it stopped
--                              at, a sanitised error, when it was attempted and which bot id was used. `publish_version` counts
--                              publishes of the flow and makes the worker idempotent: an event for an older version, or for a
--                              version that is already live, does nothing. The row can also carry a per-flow chatbot record (sealed)
--                              that replaces the workspace one; such a row is `idle` until the flow is first pushed.
--
-- The new key is a workspace toggle; it reaches the locked Owner preset and the Admin preset through the grant trigger on permission_defs.
-- Publishing and retrying keep riding `flb.flows.publish`; reading the state rides `flb.flows.read`.

INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('flb.geta.manage', 'Manage the Geta console publishing credentials', 'flows', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label,
      category = EXCLUDED.category,
      supports_scope = EXCLUDED.supports_scope;

CREATE TABLE flb_geta_publish_settings (
  org_id             bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid               uuid NOT NULL DEFAULT gen_random_uuid(),
  base_url           text,
  origin             text,
  authorization_enc  text,
  geta_host_enc      text,
  chatbot_record_enc text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  row_version        integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id)
);

ALTER TABLE flb_geta_publish_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE flb_geta_publish_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flb_geta_publish_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_flb_geta_publish_settings_touch BEFORE UPDATE ON flb_geta_publish_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE flb_geta_publish_syncs (
  org_id                       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                           bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                         uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_id                      bigint NOT NULL,
  publish_version              integer NOT NULL DEFAULT 0,
  state                        text NOT NULL DEFAULT 'idle',
  step                         text,
  failed_step                  text,
  last_error                   text,
  attempted_at                 timestamptz,
  bot_id                       text,
  -- The publish version whose configuration update already succeeded: a retry of that version resumes at publish-bot.
  configuration_updated_version integer NOT NULL DEFAULT 0,
  chatbot_override_enc         text,
  created_at                   timestamptz NOT NULL DEFAULT now(),
  updated_at                   timestamptz NOT NULL DEFAULT now(),
  row_version                  integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, flow_id),
  FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_flb_geta_syncs_state CHECK (state IN ('idle', 'pending', 'live', 'failed')),
  CONSTRAINT chk_flb_geta_syncs_step CHECK (step IS NULL OR step IN ('configuration_update', 'publish_bot')),
  CONSTRAINT chk_flb_geta_syncs_failed_step CHECK (failed_step IS NULL OR failed_step IN ('configuration_update', 'publish_bot'))
);

ALTER TABLE flb_geta_publish_syncs ENABLE ROW LEVEL SECURITY;
ALTER TABLE flb_geta_publish_syncs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flb_geta_publish_syncs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_flb_geta_publish_syncs_touch BEFORE UPDATE ON flb_geta_publish_syncs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
