-- waba: whatsapp-cloud-api-waba data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's whatsapp cloud api waba features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: waba_groups, wa_customer_profiles

-- WaDesk `waba_groups` (tenant; 0 rows in the reference DB)
CREATE TABLE waba_groups (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider_config_id bigint NOT NULL,
  group_id text NOT NULL,
  subject text,
  description text,
  invite_link text,
  join_approval_mode text,
  participant_count integer NOT NULL DEFAULT 0,
  suspended boolean NOT NULL DEFAULT false,
  creation_timestamp timestamptz,
  synced_at timestamptz,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_waba_groups_provider_config_id_group_id UNIQUE (org_id, provider_config_id, group_id),
  CONSTRAINT fk_waba_groups_provider_config_id FOREIGN KEY (org_id, provider_config_id) REFERENCES wa_provider_configs (org_id, id) ON DELETE CASCADE
);

ALTER TABLE waba_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE waba_groups FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON waba_groups FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_waba_groups_touch BEFORE UPDATE ON waba_groups
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `wa_customer_profiles` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_customer_profiles (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  phone text NOT NULL,
  name text,
  company text,
  address text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_customer_profiles_phone UNIQUE (org_id, phone)
);

ALTER TABLE wa_customer_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_customer_profiles FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_customer_profiles FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_customer_profiles_touch BEFORE UPDATE ON wa_customer_profiles
  FOR EACH ROW EXECUTE FUNCTION touch_row();
