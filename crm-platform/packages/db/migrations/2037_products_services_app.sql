-- Products and services: a first-party Marketplace app that gives the workspace a price list of things it sells (step 1 of
-- docs/specs/crm-deal-estimate-invoice-products.md section 5).
-- Why this migration exists: invoice and estimate lines are free text (a `sku` text at most), so a price has to be typed again on every
-- document. A workspace that sells things wants them once, with a price and a default tax, and kept apart from the store's catalogue
-- (`wa_products`, the WhatsApp storefront). It is an add-on: nothing is visible or reachable until the app is owned.
--
--  1. sales_items       one product or service: kind, name, sku, description, unit, unit price (minor units) and currency, a default tax
--                       rate (percent), an active flag. `wa_product_id` is a nullable link to the store product it was imported from; step 1
--                       only stores it. Nothing else points at this table yet: documents get a nullable `sales_item_id` in a later step, so
--                       nothing that exists can break.
--  2. permissions       `record.sales-items.*` (category `products`), kept out of the Roles editor of a workspace without the app
--                       (`plan_feature`, `app_slug`). Owner and Admin get them by the trigger on permission_defs; Manager gets read, create
--                       and update here.
--  3. the listing       `products-services` is seeded as a DRAFT paid mini app (price NOT set: the operator prices it in the console and
--                       publishing is refused until then), not included in any plan, granting the plan feature `products_services`.
--                       Same recipe as Forms (20261031100200). Nobody has data yet, so nothing is comped.
--  4. every plan row gets `products_services: false` explicitly.

CREATE TABLE sales_items (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  kind text NOT NULL DEFAULT 'product',
  name text NOT NULL,
  sku text,
  description text,
  -- What one unit is called on a document: pcs, kg, hour, month. Free text, short.
  unit text,
  unit_price_minor bigint NOT NULL DEFAULT 0,
  currency text NOT NULL,
  -- The tax a new line starts with, in percent (18 = 18%); NULL = no default tax.
  tax_rate_percent numeric(7,4),
  is_active boolean NOT NULL DEFAULT true,
  -- The store product this item was made from; stored only in step 1.
  wa_product_id bigint,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_sales_items_kind CHECK (kind IN ('product', 'service')),
  CONSTRAINT chk_sales_items_name CHECK (btrim(name) <> '' AND char_length(name) <= 191),
  CONSTRAINT chk_sales_items_sku CHECK (sku IS NULL OR (btrim(sku) <> '' AND char_length(sku) <= 64)),
  CONSTRAINT chk_sales_items_unit CHECK (unit IS NULL OR (btrim(unit) <> '' AND char_length(unit) <= 24)),
  CONSTRAINT chk_sales_items_description CHECK (description IS NULL OR char_length(description) <= 2000),
  CONSTRAINT chk_sales_items_price CHECK (unit_price_minor >= 0),
  CONSTRAINT chk_sales_items_currency CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_sales_items_tax CHECK (tax_rate_percent IS NULL OR (tax_rate_percent >= 0 AND tax_rate_percent <= 100)),
  CONSTRAINT fk_sales_items_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT fk_sales_items_wa_product FOREIGN KEY (org_id, wa_product_id)
    REFERENCES wa_products (org_id, id) ON DELETE SET NULL (wa_product_id)
);
-- A sku is unique within the workspace, whatever the case; an item without one is not constrained.
CREATE UNIQUE INDEX uq_sales_items_sku ON sales_items (org_id, lower(sku)) WHERE sku IS NOT NULL;
CREATE INDEX idx_sales_items_list ON sales_items (org_id, lower(name), id);
CREATE INDEX idx_sales_items_kind ON sales_items (org_id, kind, is_active);
CREATE INDEX idx_sales_items_wa_product ON sales_items (org_id, wa_product_id) WHERE wa_product_id IS NOT NULL;

ALTER TABLE sales_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE sales_items FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON sales_items FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_sales_items_touch BEFORE UPDATE ON sales_items
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Capability keys.
INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('record.sales-items.read',   'View products and services',            'products', false),
  ('record.sales-items.create', 'Add products and services',             'products', false),
  ('record.sales-items.update', 'Edit and deactivate products and services', 'products', false),
  ('record.sales-items.delete', 'Delete products and services',          'products', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label,
      category = EXCLUDED.category,
      supports_scope = EXCLUDED.supports_scope;

UPDATE permission_defs SET plan_feature = 'products_services', app_slug = 'products-services'
WHERE key LIKE 'record.sales-items.%';

SELECT set_config('app.privileged', 'on', true);

INSERT INTO role_grants (org_id, role_id, permission_key, effect, record_scope)
  SELECT r.org_id, r.id, k.key, 'allow', 'all'
  FROM roles r
  CROSS JOIN (VALUES
    ('record.sales-items.read'), ('record.sales-items.create'), ('record.sales-items.update')
  ) AS k(key)
  WHERE r.system_key = 'manager'
ON CONFLICT (org_id, role_id, permission_key) DO NOTHING;

UPDATE organizations SET roles_version = roles_version + 1;

