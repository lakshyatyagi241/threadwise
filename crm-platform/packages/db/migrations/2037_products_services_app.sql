INSERT INTO marketplace_apps
  (slug, kind, category_id, name, tagline, status, first_party, featured, sort_order, listing,
   pricing_model, trial_days, purchasable, grants_plan_features, grandfather_existing)
SELECT 'products-services', 'mini_app', c.id, 'Products and services',
       'A price list of what you sell, ready for your quotes and invoices.',
       'draft', true, false, 70,
       $l${"longDescription":"Keep the products and services you sell in one list, each with a price, a unit and a default tax. Paid per month; the price is set by the platform.","highlights":["Products and services in one list","Price, unit and default tax for each","Active and inactive items, searchable by name or SKU"]}$l$::jsonb,
       'paid_monthly', 0, true, ARRAY['products_services'], false
FROM marketplace_categories c WHERE c.kind = 'mini_app' AND c.slug = 'sales-tools'
ON CONFLICT (slug) DO NOTHING;

INSERT INTO marketplace_app_versions (app_id, version, status, manifest, scopes, changelog)
SELECT a.id, '1.0.0', 'draft',
       $m${"manifestVersion":1,"id":"products-services","name":"Products and services","kind":"mini_app","category":"sales-tools","version":"1.0.0","description":"A price list of the products and services you sell.","scopes":["sales-items.read","sales-items.write"],"surfaces":[{"type":"settings_page","key":"products-services","label":"Products and services"}],"pricing":{"model":"addon","note":"Priced by the platform operator."},"support":{}}$m$::jsonb,
       ARRAY['sales-items.read','sales-items.write'], 'First version: the price list.'
FROM marketplace_apps a WHERE a.slug = 'products-services'
  AND NOT EXISTS (SELECT 1 FROM marketplace_app_versions v WHERE v.app_id = a.id);

UPDATE plans SET features = features || '{"products_services": false}'::jsonb WHERE kind = 'plan';
