-- tib1: the inbox's remaining storage needs (plan-inbox-chat.md section 4.2, routes 9, 18 and 21).
--
-- 1. `conversation_notes.mentions` is a list of user uuids (plan section 3.3). WaDesk stored `[{user_id, name}]` and never checked the
--    user belonged to the workspace; the API now validates every mention against the workspace's members, so the column is always an
--    array of uuid strings. NOT NULL with a default of `[]` and a CHECK keep a reader from handling null, an object or a scalar.
--
-- 2. Trigram indexes on the conversation columns the list search looks at (title, peer name, number, last-message preview). The search is
--    `ILIKE '%text%'`, which a btree cannot serve; pg_trgm (already installed for the message bodies) can. The org prefix is applied by
--    the planner first, so each index only has to cut down one workspace's rows.
--
-- 3. `conversation_media_uploads`: a file an agent attached in the composer before pressing send. The file itself goes to the media store
--    (never to Postgres); this row is the reference the send names (`mediaId`). It belongs to the workspace and to the agent who uploaded
--    it, expires after a day, and is stamped when a message uses it. A table, and not just a signed token, so a reference can be checked
--    for tenant, owner and expiry in the database and so an abandoned upload can be found and removed later.

SELECT set_config('app.privileged', 'on', true);

-- 1. notes ----------------------------------------------------------------------------------------------------------------------------
UPDATE conversation_notes SET mentions = '[]'::jsonb WHERE mentions IS NULL OR jsonb_typeof(mentions) <> 'array';
ALTER TABLE conversation_notes
  ALTER COLUMN mentions SET DEFAULT '[]'::jsonb,
  ALTER COLUMN mentions SET NOT NULL,
  ADD CONSTRAINT chk_conversation_notes_mentions CHECK (jsonb_typeof(mentions) = 'array'),
  ADD CONSTRAINT chk_conversation_notes_body CHECK (length(body) BETWEEN 1 AND 8000);

-- 2. search ---------------------------------------------------------------------------------------------------------------------------
CREATE INDEX idx_conversations_title_trgm ON conversations USING gin (title gin_trgm_ops);
CREATE INDEX idx_conversations_peer_name_trgm ON conversations USING gin (peer_name gin_trgm_ops);
CREATE INDEX idx_conversations_peer_key_trgm ON conversations USING gin (peer_key gin_trgm_ops);
CREATE INDEX idx_conversations_preview_trgm ON conversations USING gin (preview gin_trgm_ops);

-- 3. uploads --------------------------------------------------------------------------------------------------------------------------
CREATE TABLE conversation_media_uploads (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id     bigint,
  -- The media store's object key (chat/<org>/<yyyy>/<mm>/<random>.<ext>): a locator, never a URL.
  media_key   text NOT NULL,
  kind        text NOT NULL,
  mime        text NOT NULL,
  size_bytes  bigint NOT NULL,
  name        text NOT NULL,
  sha256      text NOT NULL,
  expires_at  timestamptz NOT NULL,
  -- Set when a message used the file. A used upload cannot be used by a second message.
  used_at     timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_conversation_media_uploads_kind CHECK (kind IN ('image', 'video', 'audio', 'document')),
  CONSTRAINT chk_conversation_media_uploads_size CHECK (size_bytes >= 0),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
-- The sweep that removes abandoned uploads runs across every workspace, so this index is not org-prefixed.
CREATE INDEX idx_conversation_media_uploads_expiry ON conversation_media_uploads (expires_at) WHERE used_at IS NULL;

ALTER TABLE conversation_media_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversation_media_uploads FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON conversation_media_uploads FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
