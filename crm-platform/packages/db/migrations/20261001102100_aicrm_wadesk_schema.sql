-- aicrm: ai-copilot-lead-finder data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's ai copilot lead finder features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: ai_crm_actions, crm_briefs, leads

-- WaDesk `ai_crm_actions` (stream; 0 rows in the reference DB)
CREATE SEQUENCE ai_crm_actions_id_seq;
CREATE TABLE ai_crm_actions (
  id bigint NOT NULL DEFAULT nextval('ai_crm_actions_id_seq'),
  org_id bigint NOT NULL,
  user_id bigint,
  channel text NOT NULL DEFAULT 'dashboard',
  tool text NOT NULL,
  kind text NOT NULL DEFAULT 'read',
  status text NOT NULL DEFAULT 'ok',
  params jsonb,
  result_summary text,
  provider text,
  model text,
  tokens integer NOT NULL DEFAULT 0,
  subject_type text,
  subject_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_ai_crm_actions_tool ON ai_crm_actions (org_id, tool);
CREATE INDEX idx_ai_crm_actions_user_id ON ai_crm_actions (org_id, user_id);
CREATE INDEX idx_ai_crm_actions_created_at ON ai_crm_actions (org_id, created_at);

ALTER TABLE ai_crm_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_crm_actions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_crm_actions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- WaDesk `crm_briefs` (tenant; 0 rows in the reference DB)
CREATE TABLE crm_briefs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  created_by bigint,
  subject_type text NOT NULL,
  subject_id bigint NOT NULL,
  title text NOT NULL,
  html text NOT NULL,
  summary text,
  public_token text NOT NULL,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_crm_briefs_public_token UNIQUE (public_token),
  CONSTRAINT fk_crm_briefs_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_crm_briefs_subject_type_subject_id ON crm_briefs (org_id, subject_type, subject_id);

ALTER TABLE crm_briefs ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_briefs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON crm_briefs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_crm_briefs_touch BEFORE UPDATE ON crm_briefs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `leads` (tenant; 0 rows in the reference DB)
CREATE TABLE leads (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  source text NOT NULL DEFAULT 'osm',
  external_id text,
  name text,
  category text,
  phone text,
  phone_e164 text,
  email text,
  website text,
  address text,
  lat numeric(10,7),
  lng numeric(10,7),
  rating numeric(3,2),
  in_crm boolean NOT NULL DEFAULT false,
  contact_id bigint,
  raw jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_leads_source_external_id UNIQUE (org_id, source, external_id),
  CONSTRAINT fk_leads_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_leads_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id)
);

ALTER TABLE leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE leads FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON leads FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_leads_touch BEFORE UPDATE ON leads
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Bootstrap partitions (previous month, current, next two) and a catch-all so a gap in partition
-- maintenance degrades into rows landing in _default instead of failed writes. Add each parent to
-- PARTITIONED_TABLES in apps/api/src/workers/partition-maintenance.service.ts.
DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('ai_crm_actions', m);
  END LOOP;
END $$;
CREATE TABLE ai_crm_actions_default PARTITION OF ai_crm_actions DEFAULT;
