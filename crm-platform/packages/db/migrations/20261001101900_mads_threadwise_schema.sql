-- mads: meta-ads data model, ported from Reference
-- Why this migration exists: the tables Reference's meta ads features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: meta_campaigns

-- Reference `meta_campaigns` (tenant; 5 rows in the reference DB)
CREATE TABLE meta_campaigns (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  facebook_id text,
  meta_adset_id text,
  meta_creative_id text,
  meta_ad_id text,
  meta_image_hash text,
  meta_last_error text,
  meta_synced_at timestamptz,
  name text NOT NULL,
  creative_title text,
  creative_body text,
  creative_link_url text,
  ctwa_phone text,
  ctwa_message text,
  targeting jsonb,
  objective text NOT NULL DEFAULT 'OUTCOME_TRAFFIC',
  optimization_goal text NOT NULL DEFAULT 'LINK_CLICKS',
  status text NOT NULL DEFAULT 'PAUSED',
  type text NOT NULL DEFAULT 'campaign',
  ctwa_cta text,
  ctwa_enabled boolean NOT NULL DEFAULT false,
  daily_budget numeric(12,2) NOT NULL DEFAULT 0.00,
  lifetime_budget numeric(12,2),
  budget_level text NOT NULL DEFAULT 'adset',
  bid_strategy text,
  bid_amount bigint,
  special_ad_categories jsonb,
  insights jsonb,
  ad_set_count smallint NOT NULL DEFAULT 1,
  ad_count smallint NOT NULL DEFAULT 1,
  creative_image text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_meta_campaigns_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_meta_campaigns_facebook_id ON meta_campaigns (org_id, facebook_id);
CREATE INDEX idx_meta_campaigns_status ON meta_campaigns (org_id, status);
CREATE INDEX idx_meta_campaigns_user_id_meta_ad_id ON meta_campaigns (org_id, user_id, meta_ad_id);
CREATE INDEX idx_meta_campaigns_user_id_optimization_goal ON meta_campaigns (org_id, user_id, optimization_goal);
CREATE INDEX idx_meta_campaigns_user_id_status ON meta_campaigns (org_id, user_id, status);

ALTER TABLE meta_campaigns ENABLE ROW LEVEL SECURITY;
ALTER TABLE meta_campaigns FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON meta_campaigns FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_meta_campaigns_touch BEFORE UPDATE ON meta_campaigns
  FOR EACH ROW EXECUTE FUNCTION touch_row();
