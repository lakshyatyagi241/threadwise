-- WaDesk `storefront_cart_recoveries` (tenant; 0 rows in the reference DB)
CREATE TABLE storefront_cart_recoveries (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  storefront_id bigint NOT NULL,
  customer_phone text NOT NULL,
  customer_name text,
  items_json jsonb,
  subtotal_minor bigint NOT NULL DEFAULT 0,
  currency_code text NOT NULL DEFAULT 'INR',
  scheduled_ids jsonb,
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_storefront_cart_recoveries_storefront_id FOREIGN KEY (org_id, storefront_id) REFERENCES wa_storefronts (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_storefront_cart_recoveries_customer_phone ON storefront_cart_recoveries (org_id, customer_phone);
CREATE INDEX idx_storefront_cart_recoveries_storefront_id ON storefront_cart_recoveries (org_id, storefront_id);

