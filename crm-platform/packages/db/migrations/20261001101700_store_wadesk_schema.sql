  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_storefront_views_storefront_id_day UNIQUE (org_id, storefront_id, day),
  CONSTRAINT fk_wa_storefront_views_storefront_id FOREIGN KEY (org_id, storefront_id) REFERENCES wa_storefronts (org_id, id) ON DELETE CASCADE
