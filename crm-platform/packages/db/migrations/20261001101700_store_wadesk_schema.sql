-- store: storefront-builder data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's storefront builder features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: wa_storefronts, wa_storefront_views, storefront_cart_recoveries

-- WaDesk `wa_storefronts` (tenant; 0 rows in the reference DB)
CREATE TABLE wa_storefronts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  device_id bigint,
  shop_name text,
  slug text NOT NULL,
  custom_domain text,
  custom_domain_verified boolean NOT NULL DEFAULT false,
  theme_key text NOT NULL DEFAULT 'aurora',
  enabled boolean NOT NULL DEFAULT true,
  settings_json jsonb,
  shipping_json jsonb,
  payment_provider text,
  payment_config_json jsonb,
  currency_code text NOT NULL DEFAULT 'INR',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_wa_storefronts_custom_domain UNIQUE (custom_domain),
  CONSTRAINT uq_wa_storefronts_slug UNIQUE (slug),
  CONSTRAINT fk_wa_storefronts_device_id FOREIGN KEY (org_id, device_id) REFERENCES devices (org_id, id) ON DELETE SET NULL (device_id)
);
CREATE INDEX idx_wa_storefronts_device_id ON wa_storefronts (org_id, device_id);

ALTER TABLE wa_storefronts ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_storefronts FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_storefronts FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_storefronts_touch BEFORE UPDATE ON wa_storefronts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `wa_storefront_views` (child; 0 rows in the reference DB)
CREATE TABLE wa_storefront_views (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  storefront_id bigint NOT NULL,
  day date NOT NULL,
  views integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
