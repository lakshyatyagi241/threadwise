-- seg: segments, saved rules over contacts that fill themselves.
-- Why this migration exists (product extension, docs/wadesk-port/parity/product-extensions.md): WaDesk has only static groups.
-- A segment is a rule tree (rules jsonb: AND/OR groups of conditions over contact fields) that the API turns into SQL with the
-- same builder the contacts list uses, so membership is never stored: it is always the answer of the rule right now. What IS
-- stored is a cached member count (member_count_cache / member_count_at, 5 minute TTL, refreshed by a worker sweep for
-- segments someone used recently, last_used_at) so a list of segments never counts a huge set on the request path.

CREATE TABLE segments (
  org_id             bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid               uuid NOT NULL DEFAULT gen_random_uuid(),
  name               text NOT NULL,
  description        text,
  color              text,
  -- private: the owner and admins. shared: every member who can read segments.
  visibility         text NOT NULL DEFAULT 'private',
  owner_id           bigint,
  rules              jsonb NOT NULL,
  rules_version      integer NOT NULL DEFAULT 1,
  member_count_cache integer,
  member_count_at    timestamptz,
  last_used_at       timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  row_version        integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- Composite, so a segment can never be owned by a user of another workspace. SET NULL on the owner column only: the segment
  -- outlives a removed user (admins still see it and can hand it over).
  FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_id),
  CONSTRAINT chk_segments_name CHECK (btrim(name) <> '' AND char_length(name) <= 191),
  CONSTRAINT chk_segments_description CHECK (description IS NULL OR char_length(description) <= 1000),
  CONSTRAINT chk_segments_color CHECK (color IS NULL OR color ~ '^#[0-9A-Fa-f]{6}$'),
  CONSTRAINT chk_segments_visibility CHECK (visibility IN ('private', 'shared')),
  CONSTRAINT chk_segments_rules CHECK (jsonb_typeof(rules) = 'object' AND rules ->> 'type' = 'group'),
  CONSTRAINT chk_segments_rules_version CHECK (rules_version >= 1),
  CONSTRAINT chk_segments_count CHECK (member_count_cache IS NULL OR member_count_cache >= 0)
);

-- One segment per name per workspace, whatever the case; two simultaneous creates cannot both win.
CREATE UNIQUE INDEX uq_segments_org_lower_name ON segments (org_id, lower(name));
CREATE INDEX idx_segments_org_created ON segments (org_id, created_at DESC, id DESC);
CREATE INDEX idx_segments_owner ON segments (org_id, owner_id);
-- The count sweep: segments used lately, across workspaces.
CREATE INDEX idx_segments_last_used ON segments (last_used_at DESC) WHERE last_used_at IS NOT NULL;

ALTER TABLE segments ENABLE ROW LEVEL SECURITY;
ALTER TABLE segments FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON segments FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- touch_row() for this table, except that bookkeeping writes (the cached count and the usage stamp) do not bump row_version or
-- updated_at: otherwise someone refreshing a count, or a worker sweeping, would make the editor's next save a 409.
CREATE FUNCTION segments_touch() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) - ARRAY['member_count_cache', 'member_count_at', 'last_used_at', 'updated_at', 'row_version'])
     = (to_jsonb(OLD) - ARRAY['member_count_cache', 'member_count_at', 'last_used_at', 'updated_at', 'row_version']) THEN
    NEW.updated_at := OLD.updated_at;
    NEW.row_version := OLD.row_version;
    RETURN NEW;
  END IF;
  NEW.updated_at := now();
  NEW.row_version := OLD.row_version + 1;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_segments_touch BEFORE UPDATE ON segments
  FOR EACH ROW EXECUTE FUNCTION segments_touch();

-- Rule evaluation reads custom property values out of contacts.data (jsonb text). A value that is not a number or a date
-- ("n/a", "2026-02-31", an old import) must make that contact not match, never fail the whole query with a cast error, so the
-- casts live in functions that swallow the error and answer NULL.
CREATE FUNCTION segment_safe_numeric(v text) RETURNS numeric
  LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
BEGIN
  IF v IS NULL OR v !~ '^\s*-?[0-9]+(\.[0-9]+)?\s*$' THEN RETURN NULL; END IF;
  RETURN v::numeric;
EXCEPTION WHEN others THEN
  RETURN NULL;
END $$;

CREATE FUNCTION segment_safe_timestamptz(v text) RETURNS timestamptz
  LANGUAGE plpgsql STABLE PARALLEL SAFE AS $$
BEGIN
  IF v IS NULL OR v !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' THEN RETURN NULL; END IF;
  -- A bare day (a date property) is that day in UTC whatever the session time zone is.
  IF v ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN RETURN (v::date)::timestamp AT TIME ZONE 'UTC'; END IF;
  RETURN v::timestamptz;
EXCEPTION WHEN others THEN
  RETURN NULL;
END $$;
