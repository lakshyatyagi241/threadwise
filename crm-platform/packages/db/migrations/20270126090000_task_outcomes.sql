-- task: the outcome catalogue and the outcome of a task.
-- Why this migration exists: Waboo kept a workspace list of task outcomes (Interested, Left message, No response, Not able to reach, ...)
-- that a person picks when they complete or log a task, with a position and a visible flag per entry (contact_task_config, action
-- "task_outcomes") and the chosen outcome on the task. Desk had neither, so the five outcomes of a migrated workspace had nowhere to go.
--
--   task_outcomes        one row per outcome: name (unique per workspace, case-insensitive), order, active flag. A hidden (inactive) outcome
--                        is no longer offered in pickers but stays on the tasks that carry it, as Waboo's "visible: false" did.
--   tasks.outcome_id     the outcome a task ended with, or NULL. The foreign key does NOT clear on delete: Waboo refused to delete an
--                        outcome that a task uses, and so does the API (409 TASK_OUTCOME_IN_USE); the database is the net under it.
--
-- Additive: no row changes and no existing statement behaves differently until an outcome exists.

CREATE TABLE task_outcomes (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_task_outcomes_name CHECK (btrim(name) <> '' AND char_length(name) <= 191)
);
CREATE UNIQUE INDEX uq_task_outcomes_org_lower_name ON task_outcomes (org_id, lower(btrim(name)));
CREATE INDEX idx_task_outcomes_order ON task_outcomes (org_id, sort_order, id);

ALTER TABLE task_outcomes ENABLE ROW LEVEL SECURITY;
ALTER TABLE task_outcomes FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON task_outcomes FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_task_outcomes_touch BEFORE UPDATE ON task_outcomes
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE tasks ADD COLUMN outcome_id bigint;
ALTER TABLE tasks
  ADD CONSTRAINT fk_tasks_outcome_id FOREIGN KEY (org_id, outcome_id)
    REFERENCES task_outcomes (org_id, id);
-- "How many tasks use this outcome" (the delete guard and the count on the settings screen) and the outcome filter of the task list.
CREATE INDEX idx_tasks_outcome ON tasks (org_id, outcome_id) WHERE outcome_id IS NOT NULL;
