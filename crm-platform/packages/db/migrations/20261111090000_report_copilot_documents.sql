-- report-copilot: the document library of the AI report assistant, and the two capability keys that gate it.
-- Why this migration exists: the assistant (CopilotKit) reads the documents people add on the workspace Dashboard and on the platform
-- operator's Overview, together with the screen's live numbers, and builds a report. The extracted text is stored once at upload (it is
-- what the model reads; the original file is not kept), so a chat never re-parses a PDF.
--
-- Two tables, because the two screens have different owners:
--   report_documents           a workspace's library; a tenant table (org_id, RLS tenant_isolation).
--   platform_report_documents  the operator's library; no org_id, readable and writable only through the platform door
--                              (app_is_privileged()), exactly like admin_ai_keys.
-- Extracted text can hold anything a customer or the operator uploaded, so it is never joined into another table and never leaves the
-- API except through the assistant's own tools, scoped to the library of the caller.

-- --- the workspace library ---------------------------------------------------------------------------------------------------------------
CREATE TABLE report_documents (
  org_id         bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid           uuid NOT NULL DEFAULT gen_random_uuid(),
  name           text NOT NULL,
  extension      text NOT NULL,
  mime           text,
  size_bytes     integer NOT NULL CHECK (size_bytes >= 0),
  char_count     integer NOT NULL DEFAULT 0 CHECK (char_count >= 0),
  truncated      boolean NOT NULL DEFAULT false,
  status         text NOT NULL DEFAULT 'ready' CHECK (status IN ('ready', 'failed')),
  failure_reason text,
  extracted_text text NOT NULL DEFAULT '',
  created_by     bigint,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  row_version    integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- Composite, so a document can never name an author of another workspace. The author may leave; the document stays.
  CONSTRAINT fk_report_documents_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_report_documents_created_at ON report_documents (org_id, created_at DESC, id DESC);
CREATE INDEX idx_report_documents_created_by ON report_documents (org_id, created_by);

ALTER TABLE report_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE report_documents FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON report_documents FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_report_documents_touch BEFORE UPDATE ON report_documents
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- the operator's library --------------------------------------------------------------------------------------------------------------
CREATE TABLE platform_report_documents (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid           uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  name           text NOT NULL,
  extension      text NOT NULL,
  mime           text,
  size_bytes     integer NOT NULL CHECK (size_bytes >= 0),
  char_count     integer NOT NULL DEFAULT 0 CHECK (char_count >= 0),
  truncated      boolean NOT NULL DEFAULT false,
  status         text NOT NULL DEFAULT 'ready' CHECK (status IN ('ready', 'failed')),
  failure_reason text,
  extracted_text text NOT NULL DEFAULT '',
  created_by     bigint,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  row_version    integer NOT NULL DEFAULT 1,
  CONSTRAINT fk_platform_report_documents_created_by FOREIGN KEY (created_by) REFERENCES platform_operators (id) ON DELETE SET NULL
);
CREATE INDEX idx_platform_report_documents_created_at ON platform_report_documents (created_at DESC, id DESC);
CREATE INDEX idx_platform_report_documents_created_by ON platform_report_documents (created_by);

ALTER TABLE platform_report_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform_report_documents FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON platform_report_documents FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_platform_report_documents_touch BEFORE UPDATE ON platform_report_documents
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- --- capability keys ---------------------------------------------------------------------------------------------------------------------
-- `read` opens the assistant (list the documents, chat); `manage` adds and removes documents. Both live next to the dashboard keys.
INSERT INTO permission_defs (key, label, category, supports_scope) VALUES
  ('dash.reports.read',   'Use the AI report assistant on the dashboard', 'dashboard', false),
  ('dash.reports.manage', 'Add and remove the report assistant''s documents', 'dashboard', false)
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label,
      category = EXCLUDED.category,
      supports_scope = EXCLUDED.supports_scope;

-- Owner and Admin receive every new key from the trigger on permission_defs (20261013100000). The Manager holds the other dashboard
-- keys, so it holds both of these; the Agent and the Viewer hold no dashboard key, so they hold neither. The baseline table is the
-- declared way to add a preset grant (20261014090000): it reaches new organizations at provisioning and, below, the existing ones.
INSERT INTO workspace_preset_baseline (preset_key, permission_key, record_scope) VALUES
  ('manager', 'dash.reports.read',   'all'),
  ('manager', 'dash.reports.manage', 'all')
ON CONFLICT (preset_key, permission_key) DO NOTHING;

SELECT set_config('app.privileged', 'on', true);
SELECT apply_workspace_preset_baseline(id) FROM organizations;
UPDATE organizations SET roles_version = roles_version + 1;
