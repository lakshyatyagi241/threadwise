-- kb: one knowledge base per AI agent, searched by meaning, with the FAQ folded in as a text source.
--
-- Three changes in one step, because they only make sense together:
--   1. Knowledge belongs to one agent. Entries that belonged to the whole workspace (assistant_id NULL, only ever imported from
--      Reference) are copied to every agent of that workspace, so four agents no longer share one pool.
--   2. ai_training_chunks: every ready entry is cut into small passages, each with a pgvector embedding, so an agent reads the few
--      passages that match the customer's message instead of the whole base. Same storage choice as the FAQ engine (halfvec(3072),
--      exact scan on (org_id, assistant_id), no ANN index until a single agent holds ~50k passages).
--   3. FAQs become one text entry "FAQ" per agent. The FAQ engine's own answering (settings, thresholds, second check, link to a step)
--      is retired in code; the faq_* tables are KEPT here as an archive and dropped by a later migration once this one is verified.
--
-- What does NOT carry over: an FAQ whose answer was "go to a step" (no text to keep) and paused FAQs. Both are counted in a NOTICE.

-- A workspace that has FAQs but no agent gets one first, so the FAQ answers, and any workspace-wide entries it holds, have an agent to live on.
INSERT INTO ai_chat_assistants (org_id, name, slug, greeting)
SELECT DISTINCT f.org_id, 'FAQ assistant', 'faq-assistant', 'Hi! Ask me anything.'
FROM faqs f
WHERE NOT EXISTS (SELECT 1 FROM ai_chat_assistants a WHERE a.org_id = f.org_id)
ON CONFLICT DO NOTHING;

-- ---------------------------------------------------------------------------------------------------------------------
-- 1. Workspace-wide entries -> one copy per agent
-- ---------------------------------------------------------------------------------------------------------------------
WITH shared AS (
  SELECT * FROM ai_training_sources WHERE assistant_id IS NULL
), per_agent AS (
  SELECT s.*, a.id AS target_id,
         row_number() OVER (PARTITION BY s.id ORDER BY a.id) AS rn
  FROM shared s
  JOIN ai_chat_assistants a ON a.org_id = s.org_id
)
INSERT INTO ai_training_sources
  (org_id, assistant_id, user_id, kind, label, url, file_path, content, question, answer, status, tokens_estimate, error)
SELECT org_id, target_id, user_id, kind, label, url,
       -- The stored file belongs to exactly one copy, so deleting that copy removes it and no other copy loses it by accident.
       CASE WHEN rn = 1 THEN file_path END,
       content, question, answer, status, tokens_estimate, error
FROM per_agent;

-- Only entries that were copied are removed; a workspace with no agent keeps its rows (nothing can read them, nothing is lost).
DELETE FROM ai_training_sources s
WHERE s.assistant_id IS NULL
  AND EXISTS (SELECT 1 FROM ai_chat_assistants a WHERE a.org_id = s.org_id);

-- ---------------------------------------------------------------------------------------------------------------------
-- 2. Passages with embeddings
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE ai_training_chunks (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  source_id bigint NOT NULL,
  -- Copied from the entry so a search is one indexed read; the entry's agent never changes (a duplicate is a new entry).
  assistant_id bigint NOT NULL,
  position integer NOT NULL,
  text text NOT NULL,
  -- pending: needs (re-)embedding; ready: embedding belongs to embedding_model; failed: gave up after embed_attempts.
  embed_state text NOT NULL DEFAULT 'pending',
  embedding halfvec(3072),
  embedding_model text,
  embedded_at timestamptz,
  embed_attempts smallint NOT NULL DEFAULT 0,
  embed_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  CONSTRAINT uq_ai_training_chunks_position UNIQUE (org_id, source_id, position),
  CONSTRAINT ck_ai_training_chunks_state CHECK (embed_state IN ('pending', 'ready', 'failed')),
  CONSTRAINT ck_ai_training_chunks_ready CHECK (embed_state <> 'ready' OR (embedding IS NOT NULL AND embedding_model IS NOT NULL)),
  CONSTRAINT fk_ai_training_chunks_source FOREIGN KEY (org_id, source_id) REFERENCES ai_training_sources (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_ai_training_chunks_assistant FOREIGN KEY (org_id, assistant_id) REFERENCES ai_chat_assistants (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_ai_training_chunks_assistant ON ai_training_chunks (org_id, assistant_id, embed_state);
-- The embed worker's queue: only the rows that still need work.
CREATE INDEX idx_ai_training_chunks_pending ON ai_training_chunks (org_id, id) WHERE embed_state = 'pending';

ALTER TABLE ai_training_chunks ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_training_chunks FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_training_chunks FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_ai_training_chunks_touch BEFORE UPDATE ON ai_training_chunks
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- 3. FAQs -> one text entry "FAQ" per agent
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TEMP TABLE _faq_target ON COMMIT DROP AS
SELECT fl.org_id, fl.id AS flow_id,
       COALESCE(
         -- The agent the flow already talks through (its AI step stores the agent's uuid, or in an old flow its row id).
         (SELECT a.id FROM ai_chat_assistants a
           WHERE a.org_id = fl.org_id
             AND a.uuid::text = (jsonb_path_query_first(fl.flow_data, '$.**.assistant ? (@.type() == "string")') #>> '{}')),
         (SELECT a.id FROM ai_chat_assistants a
           WHERE a.org_id = fl.org_id
             AND a.id::text = (jsonb_path_query_first(fl.flow_data, '$.**.assistant_id ? (@.type() == "number")') #>> '{}')),
         -- Otherwise the workspace's first active agent.
         (SELECT a.id FROM ai_chat_assistants a WHERE a.org_id = fl.org_id AND a.status = 'active' ORDER BY a.id LIMIT 1),
         (SELECT a.id FROM ai_chat_assistants a WHERE a.org_id = fl.org_id ORDER BY a.id LIMIT 1)
       ) AS assistant_id
FROM flows fl
WHERE EXISTS (SELECT 1 FROM faqs f WHERE f.org_id = fl.org_id AND f.owner_flow_id = fl.id);

CREATE TEMP TABLE _faq_text ON COMMIT DROP AS
SELECT t.org_id, t.assistant_id,
       left(string_agg(
         'Q: ' || btrim(f.question) || E'\n'
         || COALESCE(
              (SELECT E'Also asked as: ' || string_agg(btrim(v.text), ' | ' ORDER BY v.id) || E'\n'
                 FROM faq_variations v
                WHERE v.org_id = f.org_id AND v.faq_id = f.id AND v.source <> 'question'),
              '')
         || 'A: ' || btrim(f.answer_text),
         E'\n\n' ORDER BY f.id), 200000) AS body
FROM faqs f
JOIN _faq_target t ON t.org_id = f.org_id AND t.flow_id = f.owner_flow_id
WHERE f.status = 'active' AND f.answer_type = 'text' AND t.assistant_id IS NOT NULL
GROUP BY t.org_id, t.assistant_id;

INSERT INTO ai_training_sources (org_id, assistant_id, kind, label, content, status, tokens_estimate)
SELECT org_id, assistant_id, 'text', 'FAQ', body, 'ready', ceil(length(body) / 4.0)::int
FROM _faq_text
WHERE body <> '';

DO $$
DECLARE kept int; skipped int;
BEGIN
  SELECT count(*) INTO kept FROM faqs WHERE status = 'active' AND answer_type = 'text';
  SELECT count(*) INTO skipped FROM faqs WHERE status <> 'active' OR answer_type <> 'text';
  RAISE NOTICE 'kb merge: % FAQs moved into text entries, % not moved (paused or "go to a step")', kept, skipped;
END $$;

