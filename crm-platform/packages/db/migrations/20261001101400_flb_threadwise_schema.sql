-- flb: flow-builder-editor data model, ported from Reference
-- Why this migration exists: the tables Reference's flow builder editor features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: flows, flow_connected_devices, flow_templates

-- Reference `flows` (tenant; 0 rows in the reference DB)
CREATE TABLE flows (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  flow_name text NOT NULL,
  flow_data jsonb,
  flow_file_path text,
  category text,
  trigger_kind text NOT NULL DEFAULT 'keyword',
  trigger_value bigint,
  trigger_keywords text,
  trigger_device_id bigint,
  is_published boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  published_at timestamptz,
  provider text NOT NULL DEFAULT 'baileys',
  flow_type text NOT NULL DEFAULT 'chat',
  instaflow_flow_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_flows_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_flows_category ON flows (org_id, category);
CREATE INDEX idx_flows_flow_type ON flows (org_id, flow_type);
CREATE INDEX idx_flows_instaflow_flow_id ON flows (org_id, instaflow_flow_id);
CREATE INDEX idx_flows_trigger_kind_trigger_value ON flows (org_id, trigger_kind, trigger_value);
CREATE INDEX idx_flows_user_id_is_active ON flows (org_id, user_id, is_active);
CREATE INDEX idx_flows_provider ON flows (org_id, provider);

ALTER TABLE flows ENABLE ROW LEVEL SECURITY;
ALTER TABLE flows FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flows FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_flows_touch BEFORE UPDATE ON flows
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `flow_connected_devices` (child; 0 rows in the reference DB)
CREATE TABLE flow_connected_devices (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_id bigint NOT NULL,
  device_number text NOT NULL,
  device_name text,
  status text NOT NULL DEFAULT 'active',
  connected_at timestamptz,
  last_active_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_flow_connected_devices_flow_id FOREIGN KEY (org_id, flow_id) REFERENCES flows (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_flow_connected_devices_flow_id_status ON flow_connected_devices (org_id, flow_id, status);

ALTER TABLE flow_connected_devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_connected_devices FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON flow_connected_devices FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_flow_connected_devices_touch BEFORE UPDATE ON flow_connected_devices
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `flow_templates` (global_read; 0 rows in the reference DB)
CREATE TABLE flow_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  name text NOT NULL,
  description text,
  flow_type text NOT NULL DEFAULT 'chat',
  category text,
  flow_data jsonb NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_by bigint,
  clone_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1
);
CREATE INDEX idx_flow_templates_category ON flow_templates (category);
CREATE INDEX idx_flow_templates_flow_type ON flow_templates (flow_type);
CREATE INDEX idx_flow_templates_is_active ON flow_templates (is_active);

ALTER TABLE flow_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE flow_templates FORCE  ROW LEVEL SECURITY;
CREATE POLICY read_all ON flow_templates FOR SELECT USING (true);
CREATE POLICY operator_write ON flow_templates FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_flow_templates_touch BEFORE UPDATE ON flow_templates
  FOR EACH ROW EXECUTE FUNCTION touch_row();
