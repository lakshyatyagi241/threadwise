-- mail: Gmail mailboxes connected to the team inbox (TW-MAIL-019 to 023, 028; docs/threadwise-port/plan/channel-email-build.md).
-- Why this migration exists: Reference has no mail engine (it bridges to MailTrixy and mirrors a row in workspace_email_accounts). The port
-- speaks to Gmail itself, so a workspace needs somewhere to keep each connected Google account: who it is, the sealed OAuth tokens (never
-- plain text), where the incremental sync stands (Gmail's history id) and why the last sync failed. One row per (workspace, address); a
-- disconnect keeps the row (tokens wiped, status 'disconnected') so the conversations that came through it stay attached and a reconnect of
-- the same address picks the row up again. `channel_uuid` is the inbox channel the mailbox feeds (kind 'email', external id = this uuid).
-- `owner_user_id` is empty for now: a personal mailbox (TW-MAIL-035) is a later scope, `scope` says which kind a row is.

CREATE TABLE mail_mailboxes (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider text NOT NULL DEFAULT 'google',
  -- Case-insensitive: Gmail addresses are, and a reconnect with different casing must find the same row.
  address citext NOT NULL,
  -- Google's stable account id: a reconnect by another Google account is refused even when it reads the same name.
  account_sub text,
  display_name text NOT NULL,
  status text NOT NULL DEFAULT 'connected',
  scope text NOT NULL DEFAULT 'shared',
  owner_user_id bigint,
  refresh_token_enc text,            -- AES-GCM ciphertext (credentials key); NULL after a disconnect
  access_token_enc text,             -- cached short-lived token, same sealing
  access_token_expires_at timestamptz,
  scopes text,
  history_id text,                   -- Gmail's mailbox history cursor; NULL = not synced yet (the next sync backfills)
  last_synced_at timestamptz,
  last_error text,
  connected_by bigint,
  connected_at timestamptz,
  channel_uuid uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_mail_mailboxes_address UNIQUE (org_id, address),
  CONSTRAINT chk_mail_mailboxes_provider CHECK (provider IN ('google')),
  CONSTRAINT chk_mail_mailboxes_status CHECK (status IN ('connected', 'needs_reauth', 'error', 'disconnected')),
  CONSTRAINT chk_mail_mailboxes_scope CHECK (scope IN ('shared', 'personal')),
  CONSTRAINT chk_mail_mailboxes_name CHECK (btrim(display_name) <> '' AND char_length(display_name) <= 80),
  CONSTRAINT chk_mail_mailboxes_tokens_sealed CHECK (refresh_token_enc IS NULL OR refresh_token_enc ~ '^v[0-9]+:'),
  CONSTRAINT fk_mail_mailboxes_owner FOREIGN KEY (org_id, owner_user_id)
    REFERENCES users (org_id, id) ON DELETE SET NULL (owner_user_id),
  CONSTRAINT fk_mail_mailboxes_connected_by FOREIGN KEY (org_id, connected_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (connected_by),
  CONSTRAINT fk_mail_mailboxes_channel FOREIGN KEY (org_id, channel_uuid)
    REFERENCES channels (org_id, uuid) ON DELETE SET NULL (channel_uuid)
);
CREATE INDEX idx_mail_mailboxes_owner ON mail_mailboxes (org_id, owner_user_id);
CREATE INDEX idx_mail_mailboxes_connected_by ON mail_mailboxes (org_id, connected_by);
CREATE INDEX idx_mail_mailboxes_channel ON mail_mailboxes (org_id, channel_uuid);
-- The sweeper looks for connected mailboxes across every workspace.
CREATE INDEX idx_mail_mailboxes_connected ON mail_mailboxes (status) WHERE status = 'connected';

ALTER TABLE mail_mailboxes ENABLE ROW LEVEL SECURITY;
ALTER TABLE mail_mailboxes FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON mail_mailboxes FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_mail_mailboxes_touch BEFORE UPDATE ON mail_mailboxes
  FOR EACH ROW EXECUTE FUNCTION touch_row();
