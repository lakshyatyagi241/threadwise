-- paygw: refunds of platform payments (the operator returns money through the provider, here Razorpay).
-- Why this migration exists: until now a refund was ledger-only (a note) and the money never went back through the gateway. A refund is a
-- financial record, so it is kept as its own row BEFORE the provider is called (status `pending`, counted against what was paid), then
-- updated with the provider's answer: a double click or a retry cannot refund more than was paid.
--
-- A refund belongs to a one-time ORDER (order_id) or to one charge of a SUBSCRIPTION (subscription_id, with the provider's payment id,
-- because a renewal has no order). At least one of the two is set. `gateway_payment_id` is the provider's payment: refunds of one
-- payment are summed to refuse more than the payment held.

CREATE TABLE order_refunds (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  order_id bigint,
  subscription_id bigint,
  gateway text NOT NULL,
  gateway_payment_id text NOT NULL,
  gateway_refund_id text,
  amount_minor bigint NOT NULL,
  currency text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  reason text NOT NULL,
  failure text,
  -- The platform operator who did it. Operators are platform data, not tenant rows, so there is no foreign key.
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_order_refunds_target CHECK (order_id IS NOT NULL OR subscription_id IS NOT NULL),
  CONSTRAINT chk_order_refunds_amount CHECK (amount_minor > 0),
  CONSTRAINT chk_order_refunds_currency CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_order_refunds_status CHECK (status IN ('pending', 'processed', 'failed')),
  CONSTRAINT fk_order_refunds_order FOREIGN KEY (org_id, order_id) REFERENCES orders (org_id, id),
  CONSTRAINT fk_order_refunds_subscription FOREIGN KEY (org_id, subscription_id) REFERENCES subscriptions (org_id, id)
);

CREATE INDEX idx_order_refunds_payment ON order_refunds (org_id, gateway, gateway_payment_id);
CREATE INDEX idx_order_refunds_order ON order_refunds (org_id, order_id) WHERE order_id IS NOT NULL;
CREATE INDEX idx_order_refunds_subscription ON order_refunds (org_id, subscription_id) WHERE subscription_id IS NOT NULL;

ALTER TABLE order_refunds ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_refunds FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON order_refunds FOR ALL
  USING (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_order_refunds_touch BEFORE UPDATE ON order_refunds
  FOR EACH ROW EXECUTE FUNCTION touch_row();
