-- inv: credit notes (owner direction; Reference: the words "credit note" in a PDF title, no code behind them).
-- Why this migration exists: a credit note is a numbered document that reduces what the buyer owes on ONE issued invoice. Money has to
-- stay consistent across three places (the invoice, the credit note, the payment ledger), so the database keeps it consistent:
--   * invoices.credited_minor is the sum of the invoice's ISSUED credit notes (a trigger maintains it, never the app);
--   * the invoice's payment status is a function of paid + credited against the total (one function now serves both the payment ledger
--     trigger and the credit note trigger), so a fully credited invoice reads paid and a partly credited one partially_paid;
--   * the credit notes of an invoice can never add up to more than the invoice (checked under the invoice row lock, so two concurrent
--     credit notes cannot both fit);
--   * an issued credit note is frozen; it can only be voided, and not once cash has been returned for it (the ledger refund stands).
-- Numbering: credit notes have their own series (credit_note_prefix, CRN by default) from the same locked allocator.

ALTER TABLE invoice_settings
  ADD COLUMN credit_note_prefix text NOT NULL DEFAULT 'CRN',
  ADD COLUMN sales_order_prefix text NOT NULL DEFAULT 'SO',
  DROP CONSTRAINT chk_invoice_settings_prefix,
  ADD CONSTRAINT chk_invoice_settings_prefix CHECK (
    numbering_prefix ~ '^[A-Za-z0-9]{1,10}$' AND proforma_prefix ~ '^[A-Za-z0-9]{1,10}$' AND receipt_prefix ~ '^[A-Za-z0-9]{1,10}$'
    AND credit_note_prefix ~ '^[A-Za-z0-9]{1,10}$' AND sales_order_prefix ~ '^[A-Za-z0-9]{1,10}$'
  );

-- --- the credit note --------------------------------------------------------------------------------------------------------------

CREATE TABLE credit_notes (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  invoice_id      bigint NOT NULL,
  series          text,
  credit_number   text,
  seq             integer,
  status          text NOT NULL DEFAULT 'draft',
  reason          text NOT NULL,
  note            text,
  settlement      text NOT NULL DEFAULT 'balance',
  currency        text NOT NULL,
  currency_exponent smallint NOT NULL DEFAULT 2,
  subtotal_minor  bigint NOT NULL DEFAULT 0,
  tax_minor       bigint NOT NULL DEFAULT 0,
  tax_added_minor bigint NOT NULL DEFAULT 0,
  total_minor     bigint NOT NULL DEFAULT 0,
  -- cash returned through the payment ledger for this credit note (the rest only reduces the invoice's balance)
  refunded_minor  bigint NOT NULL DEFAULT 0,
  tax_summary     jsonb,
  issue_date      date,
  issued_at       timestamptz,
  voided_at       timestamptz,
  void_reason     text,
  created_by      bigint,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_credit_notes_invoice FOREIGN KEY (org_id, invoice_id) REFERENCES invoices (org_id, id),
  CONSTRAINT fk_credit_notes_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT uq_credit_notes_number UNIQUE (org_id, credit_number),
  CONSTRAINT uq_credit_notes_series_seq UNIQUE (org_id, series, seq),
  CONSTRAINT chk_credit_notes_status CHECK (status IN ('draft', 'issued', 'void')),
  CONSTRAINT chk_credit_notes_reason CHECK (reason IN ('return', 'price_adjustment', 'billing_error', 'cancellation', 'goodwill', 'other')),
  CONSTRAINT chk_credit_notes_settlement CHECK (settlement IN ('balance', 'refund')),
  CONSTRAINT chk_credit_notes_currency CHECK (currency ~ '^[A-Z]{3}$' AND currency_exponent BETWEEN 0 AND 3),
  -- the totals add up, or the database refuses the row
  CONSTRAINT chk_credit_notes_totals CHECK (
    subtotal_minor >= 0 AND tax_minor >= 0 AND tax_added_minor >= 0 AND tax_added_minor <= tax_minor AND total_minor >= 0
    AND total_minor = subtotal_minor + tax_added_minor
    AND refunded_minor >= 0 AND refunded_minor <= total_minor
  ),
  CONSTRAINT chk_credit_notes_stamps CHECK (
    (status = 'draft' AND credit_number IS NULL AND seq IS NULL AND series IS NULL AND refunded_minor = 0)
    OR (status <> 'draft' AND credit_number IS NOT NULL AND seq IS NOT NULL AND series IS NOT NULL AND issued_at IS NOT NULL AND issue_date IS NOT NULL)
  ),
  CONSTRAINT chk_credit_notes_void CHECK ((status = 'void') = (voided_at IS NOT NULL) AND (status = 'void' OR void_reason IS NULL))
);
CREATE INDEX idx_credit_notes_invoice ON credit_notes (org_id, invoice_id);
CREATE INDEX idx_credit_notes_list ON credit_notes (org_id, created_at DESC, id DESC);

CREATE TABLE credit_note_items (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  credit_note_id  bigint NOT NULL,
  sort            smallint NOT NULL DEFAULT 0,
  invoice_item_id bigint,
  description     text NOT NULL,
  hsn_sac         text,
  qty             numeric(18,4) NOT NULL DEFAULT 1,
  unit_price_minor bigint NOT NULL DEFAULT 0,
  line_subtotal_minor bigint NOT NULL DEFAULT 0,
  tax_name        text,
  tax_type        text,
  tax_rate_percent numeric(7,4) NOT NULL DEFAULT 0,
  tax_inclusive   boolean NOT NULL DEFAULT false,
  tax_amount_minor bigint NOT NULL DEFAULT 0,
  line_total_minor bigint NOT NULL DEFAULT 0,
  tax_components  jsonb,
  currency        text NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_credit_note_items_note FOREIGN KEY (org_id, credit_note_id) REFERENCES credit_notes (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_credit_note_items_invoice_item FOREIGN KEY (org_id, invoice_item_id) REFERENCES invoice_items (org_id, id) ON DELETE SET NULL (invoice_item_id),
  CONSTRAINT uq_credit_note_items_sort UNIQUE (org_id, credit_note_id, sort),
  CONSTRAINT chk_credit_note_items_qty CHECK (qty > 0),
  CONSTRAINT chk_credit_note_items_money CHECK (
    unit_price_minor >= 0 AND line_subtotal_minor >= 0 AND tax_amount_minor >= 0 AND line_total_minor >= 0
    AND line_total_minor = line_subtotal_minor + CASE WHEN tax_inclusive THEN 0 ELSE tax_amount_minor END
  )
);
CREATE INDEX idx_credit_note_items_note ON credit_note_items (org_id, credit_note_id);
CREATE INDEX idx_credit_note_items_invoice_item ON credit_note_items (org_id, invoice_item_id) WHERE invoice_item_id IS NOT NULL;

-- --- the invoice side: credited_minor and a payment status that counts credit ---------------------------------------------------------

ALTER TABLE invoices
  ADD COLUMN credited_minor bigint NOT NULL DEFAULT 0,
  ADD CONSTRAINT chk_invoices_credited CHECK (credited_minor >= 0 AND credited_minor <= total_minor);

ALTER TABLE invoices DROP CONSTRAINT chk_invoices_paid;
ALTER TABLE invoices ADD CONSTRAINT chk_invoices_paid CHECK (
  paid_minor >= 0 AND refunded_minor >= 0
  AND (payment_status <> 'unpaid' OR (paid_minor = 0 AND credited_minor = 0))
  AND (payment_status <> 'partially_paid' OR (paid_minor + credited_minor > 0 AND paid_minor + credited_minor < total_minor))
  AND (payment_status <> 'paid' OR paid_minor + credited_minor >= total_minor)
  AND (status <> 'draft' OR (paid_minor = 0 AND credited_minor = 0 AND payment_status = 'unpaid'))
  AND (status <> 'void' OR (paid_minor = 0 AND credited_minor = 0))
);

-- One function derives the invoice's ledger cache from the ledger and the credit notes; both triggers call it.
CREATE FUNCTION invoice_refresh_payment_state(p_org bigint, p_invoice bigint, p_paid_at timestamptz) RETURNS void
  LANGUAGE plpgsql AS $$
BEGIN
  UPDATE invoices i
     SET paid_minor = s.paid,
         refunded_minor = s.refunded,
         credited_minor = c.credited,
         payment_status = CASE WHEN i.status <> 'issued' THEN i.payment_status
                               WHEN s.paid + c.credited >= i.total_minor THEN 'paid'
                               WHEN s.paid + c.credited > 0 THEN 'partially_paid'
                               ELSE 'unpaid' END,
         paid_at = CASE WHEN i.status = 'issued' AND s.paid + c.credited >= i.total_minor
                        THEN coalesce(i.paid_at, p_paid_at, now()) ELSE NULL END
    FROM (SELECT coalesce(sum(amount_minor), 0) AS paid,
                 coalesce(sum(-amount_minor) FILTER (WHERE kind = 'refund'), 0) AS refunded
            FROM payments WHERE org_id = p_org AND invoice_id = p_invoice) s,
         (SELECT coalesce(sum(total_minor), 0) AS credited
            FROM credit_notes WHERE org_id = p_org AND invoice_id = p_invoice AND status = 'issued') c
   WHERE i.org_id = p_org AND i.id = p_invoice;
END $$;

CREATE OR REPLACE FUNCTION payments_sync_invoice() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.invoice_id IS NOT NULL THEN
    PERFORM invoice_refresh_payment_state(NEW.org_id, NEW.invoice_id, NEW.paid_at);
  END IF;
  RETURN NULL;
END $$;

-- --- credit note triggers -------------------------------------------------------------------------------------------------------------

CREATE FUNCTION credit_notes_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  inv   invoices%ROWTYPE;
  other bigint;
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.status = 'issued' THEN
    IF NEW.status = 'void' THEN
      IF OLD.refunded_minor > 0 THEN
        RAISE EXCEPTION 'a credit note that returned cash cannot be voided: the refund stands in the payment ledger' USING ERRCODE = '55000';
      END IF;
      RETURN NEW;
    END IF;
    IF (NEW.status, NEW.invoice_id, NEW.credit_number, NEW.series, NEW.seq, NEW.currency, NEW.subtotal_minor, NEW.tax_minor,
        NEW.tax_added_minor, NEW.total_minor, NEW.reason, NEW.settlement, NEW.refunded_minor, NEW.issue_date)
       IS DISTINCT FROM
       (OLD.status, OLD.invoice_id, OLD.credit_number, OLD.series, OLD.seq, OLD.currency, OLD.subtotal_minor, OLD.tax_minor,
        OLD.tax_added_minor, OLD.total_minor, OLD.reason, OLD.settlement, OLD.refunded_minor, OLD.issue_date)
    THEN
      RAISE EXCEPTION 'an issued credit note is frozen' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.status = 'void' THEN
    RAISE EXCEPTION 'a void credit note cannot change' USING ERRCODE = '55000';
  END IF;
  IF NEW.status = 'issued' THEN
    -- the invoice row lock serialises credit notes (and payments) of one invoice
    SELECT * INTO inv FROM invoices WHERE org_id = NEW.org_id AND id = NEW.invoice_id FOR UPDATE;
    IF NOT FOUND OR inv.status <> 'issued' THEN
      RAISE EXCEPTION 'a credit note needs an issued invoice' USING ERRCODE = '23514';
    END IF;
    IF inv.currency <> NEW.currency THEN
      RAISE EXCEPTION 'the credit note currency % does not match the invoice currency %', NEW.currency, inv.currency USING ERRCODE = '23514';
    END IF;
    SELECT coalesce(sum(total_minor), 0) INTO other FROM credit_notes
     WHERE org_id = NEW.org_id AND invoice_id = NEW.invoice_id AND status = 'issued' AND id IS DISTINCT FROM NEW.id;
    IF other + NEW.total_minor > inv.total_minor THEN
      RAISE EXCEPTION 'credit notes would exceed the invoice (% already credited of %)', other, inv.total_minor USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_credit_notes_guard BEFORE INSERT OR UPDATE ON credit_notes
  FOR EACH ROW EXECUTE FUNCTION credit_notes_guard();

CREATE FUNCTION credit_notes_sync_invoice() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.status IS DISTINCT FROM OLD.status THEN
    PERFORM invoice_refresh_payment_state(NEW.org_id, NEW.invoice_id, NULL);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_credit_notes_sync AFTER INSERT OR UPDATE ON credit_notes
  FOR EACH ROW EXECUTE FUNCTION credit_notes_sync_invoice();

-- the lines of an issued credit note are frozen like an invoice's
CREATE FUNCTION credit_note_items_freeze() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  st text;
BEGIN
  SELECT status INTO st FROM credit_notes
   WHERE org_id = CASE WHEN TG_OP = 'DELETE' THEN OLD.org_id ELSE NEW.org_id END
     AND id = CASE WHEN TG_OP = 'DELETE' THEN OLD.credit_note_id ELSE NEW.credit_note_id END;
  IF st IS NOT NULL AND st <> 'draft' THEN
    RAISE EXCEPTION 'the lines of an issued credit note are frozen' USING ERRCODE = '55000';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER trg_credit_note_items_freeze BEFORE INSERT OR UPDATE OR DELETE ON credit_note_items
  FOR EACH ROW EXECUTE FUNCTION credit_note_items_freeze();

-- the invoice cannot be voided while credit notes stand against it (the invoice CHECK already refuses it; this says why)
CREATE OR REPLACE FUNCTION invoices_freeze() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'draft' THEN
    RETURN NEW;
  END IF;
  IF OLD.status = 'void' AND NEW.status <> 'void' THEN
    RAISE EXCEPTION 'a void invoice cannot be reopened' USING ERRCODE = '55000';
  END IF;
  IF NEW.status = 'draft' THEN
    RAISE EXCEPTION 'an issued invoice cannot go back to draft' USING ERRCODE = '55000';
  END IF;
  IF (NEW.invoice_number, NEW.series, NEW.seq, NEW.doc_type, NEW.currency, NEW.currency_exponent,
      NEW.subtotal_minor, NEW.discount_minor, NEW.shipping_minor, NEW.tax_minor, NEW.tax_added_minor,
      NEW.total_minor, NEW.discount_kind, NEW.discount_value, NEW.tax_inclusive, NEW.buyer_name, NEW.issued_at, NEW.issue_date,
      NEW.tax_regime, NEW.buyer_tax_id, NEW.buyer_country, NEW.place_of_supply, NEW.reverse_charge, NEW.seller_snapshot_json)
     IS DISTINCT FROM
     (OLD.invoice_number, OLD.series, OLD.seq, OLD.doc_type, OLD.currency, OLD.currency_exponent,
      OLD.subtotal_minor, OLD.discount_minor, OLD.shipping_minor, OLD.tax_minor, OLD.tax_added_minor,
      OLD.total_minor, OLD.discount_kind, OLD.discount_value, OLD.tax_inclusive, OLD.buyer_name, OLD.issued_at, OLD.issue_date,
      OLD.tax_regime, OLD.buyer_tax_id, OLD.buyer_country, OLD.place_of_supply, OLD.reverse_charge, OLD.seller_snapshot_json)
  THEN
    RAISE EXCEPTION 'an issued invoice is frozen: its number, parties, tax facts, currency and amounts cannot change'
      USING ERRCODE = '55000';
  END IF;
  IF NEW.status = 'void' AND NEW.credited_minor > 0 THEN
    RAISE EXCEPTION 'an invoice with credit notes against it cannot be voided' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END $$;

