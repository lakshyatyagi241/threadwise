-- lsc chat digest: AI lead scoring learns from the conversation, and suggests lifecycle stages. Not a Reference feature.
--
-- What it adds:
--   lead_scoring_settings.chat_digest / stage_suggestions: two more opt-ins of the workspace. Masked chat text goes to the AI vendor
--       for the first, so it is off until the workspace chooses, and the API only lets the pilot workspaces switch it on (see
--       CHAT_DIGEST_PILOT_SLUGS in the scorer's rules).
--   lead_chat_digests: one row per reading of a contact's conversation: the intent, the short summary, the signals, the score the model
--       gave, the stage it would suggest, which messages it relied on, and what the call cost. Append-only; the daily sweep deletes old
--       rows with the scoring log. `through_at` is the newest message it read, so the idle sweeper re-reads a contact only when
--       something newer has arrived.
--   lifecycle_stage_suggestions: a stage change the AI proposes and a person accepts or dismisses. One pending suggestion per contact.
--   lead_scoring_runs.trigger accepts 'chat' (a digest the idle sweeper started).
--
-- The demo workspace (slug demo-interakt) gets everything switched on at the end, so the feature can be shown end to end. Other
-- workspaces are untouched and cannot opt in until the pilot list grows.

ALTER TABLE lead_scoring_settings
  ADD COLUMN chat_digest boolean NOT NULL DEFAULT false,
  ADD COLUMN stage_suggestions boolean NOT NULL DEFAULT false;

ALTER TABLE lead_scoring_runs DROP CONSTRAINT ck_lead_scoring_runs_trigger;
ALTER TABLE lead_scoring_runs ADD CONSTRAINT ck_lead_scoring_runs_trigger
  CHECK (trigger IN ('created', 'updated', 'manual', 'backfill', 'chat'));

-- ---------------------------------------------------------------------------------------------------------------------
-- lead_chat_digests
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE lead_chat_digests (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- The newest message, by when it was said, that this digest read.
  through_at timestamptz NOT NULL,
  messages_read integer NOT NULL DEFAULT 0,
  inbound_read integer NOT NULL DEFAULT 0,
  -- 'ai': a model read the (masked) chat. 'rules': the phrase table classified button and keyword taps, no call was made.
  source text NOT NULL,
  intent text NOT NULL,
  -- {askedPrice, readyToBuy, objection, urgent}: booleans.
  signals jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- One or two sentences by the model, written from masked text; no names or numbers by instruction.
  summary text,
  score smallint,
  reasons jsonb,
  suggested_stage text,
  stage_confidence numeric(3,2),
  -- Message uuids the model named as the reason for its answer (checked against the messages it was shown).
  evidence jsonb NOT NULL DEFAULT '[]'::jsonb,
  model text,
  prompt_tokens integer NOT NULL DEFAULT 0,
  completion_tokens integer NOT NULL DEFAULT 0,
  cost_usd numeric(12,8) NOT NULL DEFAULT 0,
  cost_source text NOT NULL DEFAULT 'none',
  billed_against text NOT NULL DEFAULT 'none',
  duration_ms integer,
  -- chat (the idle sweeper) or manual (the Analyze chat button).
  trigger text NOT NULL,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  CONSTRAINT ck_lead_chat_digests_source CHECK (source IN ('ai', 'rules')),
  CONSTRAINT ck_lead_chat_digests_trigger CHECK (trigger IN ('chat', 'manual')),
  CONSTRAINT ck_lead_chat_digests_score CHECK (score IS NULL OR score BETWEEN 0 AND 100),
  CONSTRAINT ck_lead_chat_digests_conf CHECK (stage_confidence IS NULL OR stage_confidence BETWEEN 0 AND 1),
  CONSTRAINT ck_lead_chat_digests_billed CHECK (billed_against IN ('admin', 'workspace', 'none')),
  CONSTRAINT ck_lead_chat_digests_cost_source CHECK (cost_source IN ('vendor', 'estimate', 'none'))
);
CREATE INDEX idx_lead_chat_digests_contact ON lead_chat_digests (org_id, contact_id, through_at DESC);
-- The retention sweep deletes by time across workspaces.
CREATE INDEX idx_lead_chat_digests_time ON lead_chat_digests (created_at);

ALTER TABLE lead_chat_digests ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_chat_digests FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_chat_digests FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- ---------------------------------------------------------------------------------------------------------------------
-- lifecycle_stage_suggestions
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE lifecycle_stage_suggestions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id bigint NOT NULL,
  digest_id bigint,
  from_stage text NOT NULL,
  to_stage text NOT NULL,
  confidence numeric(3,2) NOT NULL,
  reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- pending: waiting for a person. accepted / dismissed: a person decided. superseded: a newer suggestion replaced it, or the contact
  -- already moved. expired: nobody decided in 30 days.
  status text NOT NULL DEFAULT 'pending',
  decided_by bigint,
  decided_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, digest_id) REFERENCES lead_chat_digests (org_id, id) ON DELETE SET NULL (digest_id),
  FOREIGN KEY (org_id, decided_by) REFERENCES users (org_id, id) ON DELETE SET NULL (decided_by),
  CONSTRAINT ck_lifecycle_stage_suggestions_status CHECK (status IN ('pending', 'accepted', 'dismissed', 'superseded', 'expired')),
  CONSTRAINT ck_lifecycle_stage_suggestions_conf CHECK (confidence BETWEEN 0 AND 1),
  CONSTRAINT ck_lifecycle_stage_suggestions_move CHECK (from_stage <> to_stage)
);
-- A contact has at most one open suggestion: a new one replaces it.
CREATE UNIQUE INDEX uq_lifecycle_stage_suggestions_pending ON lifecycle_stage_suggestions (org_id, contact_id) WHERE status = 'pending';
CREATE INDEX idx_lifecycle_stage_suggestions_status ON lifecycle_stage_suggestions (org_id, status, created_at DESC);
CREATE INDEX idx_lifecycle_stage_suggestions_time ON lifecycle_stage_suggestions (created_at);

ALTER TABLE lifecycle_stage_suggestions ENABLE ROW LEVEL SECURITY;
ALTER TABLE lifecycle_stage_suggestions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lifecycle_stage_suggestions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_lifecycle_stage_suggestions_touch BEFORE UPDATE ON lifecycle_stage_suggestions
  FOR EACH ROW EXECUTE FUNCTION touch_row();

