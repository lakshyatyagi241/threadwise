-- tt: channel-tiktok data model, ported from Reference
-- Why this migration exists: the tables Reference's channel tiktok features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: tiktok_accounts, tiktok_posts, tiktok_shops

-- Reference `tiktok_accounts` (tenant; 0 rows in the reference DB)
CREATE TABLE tiktok_accounts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  open_id text NOT NULL,
  union_id text,
  display_name text,
  username text,
  avatar_url text,
  bio text,
  is_verified boolean NOT NULL DEFAULT false,
  follower_count bigint,
  following_count bigint,
  likes_count bigint,
  video_count bigint,
  access_token text,  -- encrypted
  refresh_token text,  -- encrypted
  token_expires_at timestamptz,
  refresh_expires_at timestamptz,
  scopes jsonb,
  status text NOT NULL DEFAULT 'connected',
  connect_method text NOT NULL DEFAULT 'oauth',
  last_error text,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_tiktok_accounts_open_id UNIQUE (org_id, open_id),
  CONSTRAINT fk_tiktok_accounts_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);

ALTER TABLE tiktok_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE tiktok_accounts FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON tiktok_accounts FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_tiktok_accounts_touch BEFORE UPDATE ON tiktok_accounts
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `tiktok_posts` (tenant; 0 rows in the reference DB)
CREATE TABLE tiktok_posts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  tiktok_account_id bigint NOT NULL,
  user_id bigint,
  type text NOT NULL DEFAULT 'video',
  status text NOT NULL DEFAULT 'draft',
  caption text,
  media_json jsonb,
  publish_id text,
  tiktok_post_id text,
  scheduled_at timestamptz,
  published_at timestamptz,
  error text,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_tiktok_posts_tiktok_account_id FOREIGN KEY (org_id, tiktok_account_id) REFERENCES tiktok_accounts (org_id, id) ON DELETE CASCADE,
