-- ecom: shopify-woocommerce data model, ported from Reference
-- Why this migration exists: the tables Reference's shopify woocommerce features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: shopify_integrations, shopify_integration_events, shopify_integration_logs, shopify_stock_waitlist, woocommerce_integrations, woocommerce_integration_events, woocommerce_integration_logs, woocommerce_stock_waitlist, shopify_cart_recoveries, shopify_cod_confirmations, woocommerce_cart_recoveries, woocommerce_cod_confirmations

-- Reference `shopify_integrations` (tenant; 0 rows in the reference DB)
CREATE TABLE shopify_integrations (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  store_url text NOT NULL,
  store_name text,
  shop_id text,
  shop_email text,
  shop_owner text,
  shop_plan text,
  shop_currency text,
  shop_country text,
  access_token text NOT NULL,  -- encrypted
  scopes text,
  status text NOT NULL DEFAULT 'active',
  webhook_secret text NOT NULL,
  metadata jsonb,
  last_verified_at timestamptz,
  connected_at timestamptz,
  products_synced_at timestamptz,
  orders_synced_at timestamptz,
  customers_synced_at timestamptz,
  sync_stats jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_shopify_integrations_store_url UNIQUE (org_id, store_url),
  CONSTRAINT fk_shopify_integrations_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_shopify_integrations_user_id ON shopify_integrations (org_id, user_id);
CREATE INDEX idx_shopify_integrations_webhook_secret ON shopify_integrations (org_id, webhook_secret);

ALTER TABLE shopify_integrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE shopify_integrations FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON shopify_integrations FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_shopify_integrations_touch BEFORE UPDATE ON shopify_integrations
  FOR EACH ROW EXECUTE FUNCTION touch_row();

