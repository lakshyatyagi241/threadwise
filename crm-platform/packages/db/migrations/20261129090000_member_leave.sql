-- Member leave and delegate (BL-112, docs/specs/contact-owner-leave-and-delegation.md).
--
-- A person can be "on leave" for a date range, and can name one delegate who stands in for them while automatic assignment (routing of
-- conversations, auto-assignment of contacts and deals) would otherwise have to skip them. The two live in their own tables, not as
-- columns on `users`, so that the identity table stays untouched and a leave keeps its history after it ended.
--
-- Dates are plain `date`s in the WORKSPACE's time zone (organizations.settings.timezone, UTC when missing): "on leave until 20 Oct"
-- means the whole of the 20th. Whether somebody is on leave RIGHT NOW is always derived from the dates (`starts_on <= today <= ends_on`),
-- never from `status` alone, so routing is correct between two runs of the sweep; the sweep only flips `status` and announces the change.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE member_leaves (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id     bigint NOT NULL,
  starts_on   date NOT NULL,
  -- NULL = open-ended (a long absence); ended by hand.
  ends_on     date,
  -- Shown only to people who manage leave of others; colleagues see the dates.
  reason      text,
  -- scheduled: not started yet; active: the sweep saw it start; ended: its end date passed or it was ended early;
  -- cancelled: removed before it started.
  status      text NOT NULL DEFAULT 'scheduled',
  started_at  timestamptz,
  ended_at    timestamptz,
  created_by  bigint,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_member_leaves_status CHECK (status IN ('scheduled', 'active', 'ended', 'cancelled')),
  CONSTRAINT chk_member_leaves_range CHECK (ends_on IS NULL OR ends_on >= starts_on),
  CONSTRAINT chk_member_leaves_reason CHECK (reason IS NULL OR char_length(reason) <= 500),
  -- The data-level guarantee behind "one leave at a time per person": two leaves that still count (scheduled or active) can never
  -- share a day. A NULL end is infinity. The service checks first to give a clear answer; this holds under a race.
  CONSTRAINT excl_member_leaves_overlap EXCLUDE USING gist (
    org_id WITH =,
    user_id WITH =,
    daterange(starts_on, ends_on, '[]') WITH &&
  ) WHERE (status IN ('scheduled', 'active'))
);
-- At most one ACTIVE row per member (the exclusion above already makes two active rows impossible; this names the rule the
-- sweep and the screens rely on and gives them an index to look it up by).
CREATE UNIQUE INDEX uq_member_leaves_active ON member_leaves (org_id, user_id) WHERE status = 'active';
CREATE INDEX idx_member_leaves_user ON member_leaves (org_id, user_id, starts_on DESC);
-- The sweep spans every workspace, so no org_id prefix.
CREATE INDEX idx_member_leaves_sweep_start ON member_leaves (starts_on) WHERE status = 'scheduled';
CREATE INDEX idx_member_leaves_sweep_end ON member_leaves (ends_on) WHERE status = 'active' AND ends_on IS NOT NULL;

ALTER TABLE member_leaves ENABLE ROW LEVEL SECURITY;
ALTER TABLE member_leaves FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON member_leaves FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_member_leaves_touch BEFORE UPDATE ON member_leaves
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- One optional delegate per member. A person with no row has no delegate. The delegate must be another member of the SAME workspace
-- (composite FK); "active", "not yourself" and "no cycle" are the service's rules because they depend on state that changes.
CREATE TABLE member_delegates (
  org_id           bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid             uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id          bigint NOT NULL,
  delegate_user_id bigint NOT NULL,
  created_by       bigint,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  row_version      integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, user_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  -- A delegate who is removed from the workspace takes the arrangement with them.
  FOREIGN KEY (org_id, delegate_user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_member_delegates_not_self CHECK (user_id <> delegate_user_id)
);
CREATE INDEX idx_member_delegates_delegate ON member_delegates (org_id, delegate_user_id);

ALTER TABLE member_delegates ENABLE ROW LEVEL SECURITY;
ALTER TABLE member_delegates FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON member_delegates FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_member_delegates_touch BEFORE UPDATE ON member_delegates
  FOR EACH ROW EXECUTE FUNCTION touch_row();
