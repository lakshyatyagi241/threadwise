-- inv: invoicing data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's invoicing features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: invoices, invoice_items, invoice_logs, invoice_number_sequences, invoice_settings, invoice_tax_summary, invoice_webhook_events

-- WaDesk `invoices` (tenant; 0 rows in the reference DB)
CREATE TABLE invoices (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  source text NOT NULL,
  doc_type text NOT NULL DEFAULT 'tax_invoice',
  wa_order_id bigint,
  external_order_id text,
  external_order_number text,
  series text NOT NULL,
  invoice_number text NOT NULL,
  seq integer NOT NULL,
  status text NOT NULL DEFAULT 'issued',
  send_status text NOT NULL DEFAULT 'pending',
  send_attempts smallint NOT NULL DEFAULT 0,
  send_reason text,
  sent_at timestamptz,
  trigger text NOT NULL DEFAULT 'manual',
  issued_at timestamptz,
  due_at timestamptz,
  paid_at timestamptz,
  currency text NOT NULL DEFAULT 'USD',
  currency_exponent smallint NOT NULL DEFAULT 2,
  subtotal_minor bigint NOT NULL DEFAULT 0,
  discount_minor bigint NOT NULL DEFAULT 0,
  shipping_minor bigint NOT NULL DEFAULT 0,
  tax_minor bigint NOT NULL DEFAULT 0,
  total_minor bigint NOT NULL DEFAULT 0,
  tax_inclusive boolean NOT NULL DEFAULT false,
  buyer_name text,
  buyer_email text,
  buyer_phone text,
  billing_json jsonb,
  shipping_json jsonb,
  seller_snapshot_json jsonb,
  notes text,
  pdf_disk text,
  pdf_path text,
  pdf_sha256 text,
  pdf_bytes bigint,
  delivery_channel text,
  delivered_at timestamptz,
  wa_message_id text,
  send_error text,
  public_token text NOT NULL,
  meta_json jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_invoices_public_token UNIQUE (public_token),
  CONSTRAINT uq_invoices_source_external_order_id_doc_type UNIQUE (org_id, source, external_order_id, doc_type),
  CONSTRAINT uq_invoices_invoice_number UNIQUE (org_id, invoice_number),
  CONSTRAINT uq_invoices_series_seq UNIQUE (org_id, series, seq),
  CONSTRAINT fk_invoices_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_invoices_doc_type ON invoices (org_id, doc_type);
CREATE INDEX idx_invoices_send_status ON invoices (org_id, send_status);
CREATE INDEX idx_invoices_status ON invoices (org_id, status);
CREATE INDEX idx_invoices_wa_order_id ON invoices (org_id, wa_order_id);
CREATE INDEX idx_invoices_issued_at ON invoices (org_id, issued_at);

ALTER TABLE invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE invoices FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON invoices FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_invoices_touch BEFORE UPDATE ON invoices
  FOR EACH ROW EXECUTE FUNCTION touch_row();

