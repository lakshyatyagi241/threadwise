-- bsp: bsp-billing-engine data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's bsp billing engine features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: bsp_credit_allocations

-- WaDesk `bsp_credit_allocations` (tenant; 0 rows in the reference DB)
CREATE TABLE bsp_credit_allocations (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  waba_id text NOT NULL,
  allocation_config_id text,
  credit_source text,
  currency text NOT NULL DEFAULT 'USD',
  status text NOT NULL DEFAULT 'attached',
  last_error text,
  attached_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid)
);
CREATE INDEX idx_bsp_credit_allocations_waba_id ON bsp_credit_allocations (org_id, waba_id);

ALTER TABLE bsp_credit_allocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE bsp_credit_allocations FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON bsp_credit_allocations FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_bsp_credit_allocations_touch BEFORE UPDATE ON bsp_credit_allocations
  FOR EACH ROW EXECUTE FUNCTION touch_row();
