-- Sales activities settings (BL-370..BL-379): one registry of the workspace's activity types (Task, Meeting, Phone, Email, Reminder, SMS, Chat
-- and any the business adds), each with its own switches, an ordered list of "types" (task types) and an ordered list of "outcomes".
-- Why this migration exists: tasks, meetings and logged calls each had a fixed shape (a task has no type and no outcome, a meeting cannot be
-- completed or given an outcome, a call has seven built-in outcomes). The owner wants those lists and switches edited from one Settings page,
-- the same for every niche (the labels come from the workspace vocabulary, not from this schema).
--
--   activity_types           one row per activity. `key` is the stable id ('task', 'meeting', 'phone', 'email', 'reminder', 'sms', 'chat' for the
--                            defaults, 'custom_<slug>' for a custom one) and never changes. A default keeps `name` NULL: the screen shows its
--                            localised name, so the seed needs no language. `behaves_as` says which editor and which consumers an activity uses.
--   activity_type_options    the ordered task types and outcomes of an activity. Removing one stamps `deleted_at` (a removed outcome stays readable
--                            on every old record); the same name added again revives it. A default option keeps `name` NULL for the same reason.
--                            `counts_as` (phone outcomes only) is the built-in call outcome a custom outcome counts as in the call log's reports.
--   contact_meeting_outcomes the outcome and notes of a completed meeting, one row per meeting (a separate table so the meetings table stays as
--                            it is for the booking mirror).
--   tasks.task_type_id and call_log_entries.outcome_option_id point at the options. The outcome of a TASK is not kept here: it is the workspace's
--                            `task_outcomes` list (20270126090000, Settings > Task outcomes, `tasks.outcome_id`), which the Task activity links to
--                            instead of keeping a second list. New workspaces get the five default task outcomes below; existing ones are not touched. The task `kind` column ('task' | 'follow_up',
--                            lead handling) is untouched: existing follow-up tasks are given the seeded 'Follow up' type below.
--
-- The defaults are seeded for every existing workspace here and for every new one by a trigger on organizations (the same shape as the default
-- pipeline). Nothing about an existing workspace changes until someone edits the settings: the seeded switches reproduce today's behaviour (a
-- task can be completed, its done time cannot be edited, no mobile check-in) and the seeded phone outcomes are the seven the call log already had.

-- --- the registry -------------------------------------------------------------------------------------------------------------------

CREATE TABLE activity_types (
  org_id                 bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                     bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid                   uuid NOT NULL DEFAULT gen_random_uuid(),
  key                    text NOT NULL,
  -- NULL on a default activity (its localised name is shown); required on a custom one.
  name                   text,
  is_default             boolean NOT NULL DEFAULT false,
  behaves_as             text NOT NULL,
  icon                   text NOT NULL DEFAULT 'activity',
  position               integer NOT NULL DEFAULT 0,
  show_in_calendar       boolean NOT NULL DEFAULT false,
  allow_complete         boolean NOT NULL DEFAULT true,
  allow_edit_completed   boolean NOT NULL DEFAULT false,
  -- Stored and shown; the mobile app has no meeting check-in yet, so this has no effect until it does (docs/api/sales-activities.md).
  mobile_check_in        boolean NOT NULL DEFAULT false,
  outcomes_enabled       boolean NOT NULL DEFAULT true,
  archived_at            timestamptz,
  created_by             bigint,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  row_version            integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_activity_types_key UNIQUE (org_id, key),
  CONSTRAINT fk_activity_types_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT ck_activity_types_key CHECK (key ~ '^[a-z0-9_]{1,60}$'),
  CONSTRAINT ck_activity_types_name CHECK ((name IS NULL AND is_default) OR (name IS NOT NULL AND btrim(name) <> '' AND char_length(name) <= 80)),
  CONSTRAINT ck_activity_types_behaves CHECK (behaves_as IN ('task', 'meeting', 'phone', 'other')),
  CONSTRAINT ck_activity_types_icon CHECK (icon ~ '^[a-z_]{1,30}$'),
  CONSTRAINT ck_activity_types_position CHECK (position >= 0)
);
CREATE INDEX idx_activity_types_order ON activity_types (org_id, position, id) WHERE archived_at IS NULL;

CREATE TABLE activity_type_options (
  org_id            bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid              uuid NOT NULL DEFAULT gen_random_uuid(),
  activity_type_id  bigint NOT NULL,
  kind              text NOT NULL,
  key               text NOT NULL,
  name              text,
  is_system         boolean NOT NULL DEFAULT false,
  counts_as         text,
  position          integer NOT NULL DEFAULT 0,
  deleted_at        timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  row_version       integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_activity_type_options_key UNIQUE (org_id, activity_type_id, kind, key),
  CONSTRAINT fk_activity_type_options_type FOREIGN KEY (org_id, activity_type_id) REFERENCES activity_types (org_id, id) ON DELETE CASCADE,
  CONSTRAINT ck_activity_type_options_kind CHECK (kind IN ('type', 'outcome')),
  CONSTRAINT ck_activity_type_options_key CHECK (key ~ '^[a-z0-9_]{1,60}$'),
  CONSTRAINT ck_activity_type_options_name CHECK ((name IS NULL AND is_system) OR (name IS NOT NULL AND btrim(name) <> '' AND char_length(name) <= 80)),
  CONSTRAINT ck_activity_type_options_counts_as CHECK (
    counts_as IS NULL OR (kind = 'outcome' AND counts_as IN ('connected', 'no_answer', 'busy', 'left_voicemail', 'wrong_number', 'declined', 'failed'))),
  CONSTRAINT ck_activity_type_options_position CHECK (position >= 0)
);
CREATE INDEX idx_activity_type_options_order ON activity_type_options (org_id, activity_type_id, kind, position, id) WHERE deleted_at IS NULL;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['activity_types', 'activity_type_options'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format($p$CREATE POLICY tenant_isolation ON %I FOR ALL
      USING (org_id = current_org_id() OR app_is_privileged())
      WITH CHECK (org_id = current_org_id() OR app_is_privileged())$p$, t);
    EXECUTE format('CREATE TRIGGER trg_%s_touch BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_row()', t, t);
  END LOOP;
END $$;

-- --- the defaults -----------------------------------------------------------------------------------------------------------------------

-- Idempotent: running it again adds only what is missing and never touches a row an admin has changed. It runs with the caller's rights, so a
-- tenant can only seed its own workspace (the row-level security policies above decide), and it is also what the service calls the first time a
-- workspace without defaults reads the settings.
CREATE FUNCTION seed_activity_types(p_org bigint) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  a record;
  o record;
  tid bigint;
BEGIN
  FOR a IN
    SELECT * FROM (VALUES
      ('task',     0, 'task',    'task',     true,  false, true),
      ('meeting',  1, 'meeting', 'meeting',  true,  true,  true),
      ('phone',    2, 'phone',   'phone',    false, true,  false),
      ('email',    3, 'other',   'email',    false, false, false),
      ('reminder', 4, 'other',   'reminder', false, false, false),
      ('sms',      5, 'other',   'sms',      false, false, false),
      ('chat',     6, 'other',   'chat',     false, false, false)
    ) AS d(key, pos, behaves_as, icon, in_calendar, outcomes, completable)
  LOOP
    INSERT INTO activity_types (org_id, key, name, is_default, behaves_as, icon, position, show_in_calendar, outcomes_enabled, allow_complete)
    VALUES (p_org, a.key, NULL, true, a.behaves_as, a.icon, a.pos, a.in_calendar, a.outcomes, a.completable)
    ON CONFLICT (org_id, key) DO NOTHING;
  END LOOP;

  FOR o IN
    SELECT * FROM (VALUES
      ('task',    'type',    'follow_up',      0),
      ('task',    'type',    'call_reminder',  1),
      ('meeting', 'outcome', 'interested',     0),
      ('meeting', 'outcome', 'not_interested', 1),
      ('meeting', 'outcome', 'needs_follow_up',2),
      ('meeting', 'outcome', 'rescheduled',    3),
      ('meeting', 'outcome', 'no_show',        4),
      -- The seven outcomes the call log has always had: the call log's own `outcome` column keeps these keys.
      ('phone',   'outcome', 'connected',      0),
      ('phone',   'outcome', 'no_answer',      1),
      ('phone',   'outcome', 'busy',           2),
      ('phone',   'outcome', 'left_voicemail', 3),
      ('phone',   'outcome', 'wrong_number',   4),
      ('phone',   'outcome', 'declined',       5),
      ('phone',   'outcome', 'failed',         6)
    ) AS d(activity, kind, key, pos)
  LOOP
    SELECT id INTO tid FROM activity_types WHERE org_id = p_org AND key = o.activity;
    INSERT INTO activity_type_options (org_id, activity_type_id, kind, key, name, is_system, position)
    VALUES (p_org, tid, o.kind, o.key, NULL, true, o.pos)
    ON CONFLICT (org_id, activity_type_id, kind, key) DO NOTHING;
  END LOOP;
END $$;

CREATE FUNCTION trg_organizations_seed_activity_types() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  prev text := current_setting('app.privileged', true);
BEGIN
  -- The organization's insert was already authorized by the caller; this lifts RLS only for its own seed and puts the setting back.
  PERFORM set_config('app.privileged', 'on', true);
  PERFORM seed_activity_types(NEW.id);
  -- The default task outcomes of a NEW workspace (the shared `task_outcomes` list). Existing workspaces keep what they have: a migrated Waboo
  -- workspace already owns its own list, and adding rows there would change what its pickers offer.
  INSERT INTO task_outcomes (org_id, name, sort_order) VALUES
    (NEW.id, 'Interested', 0), (NEW.id, 'Left message', 1), (NEW.id, 'No response', 2),
    (NEW.id, 'Not interested', 3), (NEW.id, 'Not able to reach', 4)
  ON CONFLICT DO NOTHING;
  PERFORM set_config('app.privileged', coalesce(prev, ''), true);
  RETURN NEW;
END $$;
CREATE TRIGGER trg_organizations_seed_activity_types AFTER INSERT ON organizations
  FOR EACH ROW EXECUTE FUNCTION trg_organizations_seed_activity_types();

-- Every existing workspace gets the defaults (row-level security is forced, so the backfill runs privileged).
SELECT set_config('app.privileged', 'on', true);
SELECT seed_activity_types(id) FROM organizations;

-- --- the consumers ------------------------------------------------------------------------------------------------------------------------

ALTER TABLE tasks
  ADD COLUMN task_type_id bigint,
  ADD CONSTRAINT fk_tasks_task_type FOREIGN KEY (org_id, task_type_id)
    REFERENCES activity_type_options (org_id, id) ON DELETE SET NULL (task_type_id);

-- A follow-up task (lead handling) is of the seeded 'Follow up' type. Nothing else is typed: an untyped task stays untyped.
UPDATE tasks t SET task_type_id = o.id
  FROM activity_types a
  JOIN activity_type_options o ON o.org_id = a.org_id AND o.activity_type_id = a.id AND o.kind = 'type' AND o.key = 'follow_up'
 WHERE t.kind = 'follow_up' AND a.org_id = t.org_id AND a.key = 'task';

ALTER TABLE call_log_entries
  ADD COLUMN outcome_option_id bigint,
  ADD CONSTRAINT fk_call_log_entries_outcome_option FOREIGN KEY (org_id, outcome_option_id)
    REFERENCES activity_type_options (org_id, id) ON DELETE SET NULL (outcome_option_id);

CREATE TABLE contact_meeting_outcomes (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id    bigint NOT NULL,
  meeting_id    bigint NOT NULL,
  outcome_id    bigint,
  note          text,
  completed_at  timestamptz NOT NULL DEFAULT now(),
  completed_by  bigint,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_contact_meeting_outcomes_meeting UNIQUE (org_id, meeting_id),
  CONSTRAINT fk_contact_meeting_outcomes_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_contact_meeting_outcomes_meeting FOREIGN KEY (org_id, meeting_id) REFERENCES contact_meetings (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_contact_meeting_outcomes_outcome FOREIGN KEY (org_id, outcome_id)
    REFERENCES activity_type_options (org_id, id) ON DELETE SET NULL (outcome_id),
  CONSTRAINT fk_contact_meeting_outcomes_by FOREIGN KEY (org_id, completed_by) REFERENCES users (org_id, id) ON DELETE SET NULL (completed_by),
  CONSTRAINT ck_contact_meeting_outcomes_note CHECK (note IS NULL OR char_length(note) <= 2000)
);
CREATE INDEX idx_contact_meeting_outcomes_contact ON contact_meeting_outcomes (org_id, contact_id);
ALTER TABLE contact_meeting_outcomes ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_meeting_outcomes FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_meeting_outcomes FOR ALL
