-- email templates (BL-004 / E-14): the workspace's library of reusable emails an agent inserts into the composer of an email conversation.
-- Why this migration exists: signatures (mail_signatures) and saved replies (plain text, any channel) exist, but nothing holds a reusable email
-- with a subject and a rich-text body. A template is shared (user_id NULL: the workspace's, managed with mail.templates.manage) or personal
-- (user_id set: its owner's alone). `purpose = 'marketing'` makes a reply sent from it marketing mail, so the ConsentGate and the signed
-- unsubscribe link apply to it like to any other marketing email. The HTML is sanitised by the service on write; the CHECKs below are the
-- backstop for sizes, names and the status/purpose vocabulary.
-- Two rules live in the database so a bad write cannot get past the service: a name is unique per owner (case-insensitive; the workspace is
-- one owner), and the usage counters never move row_version, so inserting a template into a composer does not make an open edit dialog fail
-- with a 409 (same idea as saved_replies_touch). A personal template is deleted with its owner: it must never fall back to shared.

CREATE TABLE email_templates (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,                      -- NULL = shared with the workspace; set = the owner of a personal template
  name text NOT NULL,
  subject text NOT NULL DEFAULT '',    -- may hold {{variables}}; empty = the reply keeps its own subject
  body_html text NOT NULL,             -- sanitised on write; may hold {{variables}}
  body_text text NOT NULL DEFAULT '',  -- the plain text twin
  category text,
  purpose text NOT NULL DEFAULT 'general',
  status text NOT NULL DEFAULT 'active',
  used_count integer NOT NULL DEFAULT 0,
  last_used_at timestamptz,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_email_templates_name CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT chk_email_templates_subject CHECK (char_length(subject) <= 300 AND subject !~ '[\r\n]'),
  CONSTRAINT chk_email_templates_body CHECK (char_length(btrim(body_html)) >= 1 AND char_length(body_html) <= 100000 AND char_length(body_text) <= 30000),
  CONSTRAINT chk_email_templates_category CHECK (category IS NULL OR char_length(category) BETWEEN 1 AND 64),
  CONSTRAINT chk_email_templates_purpose CHECK (purpose IN ('general', 'marketing')),
  CONSTRAINT chk_email_templates_status CHECK (status IN ('active', 'archived')),
  CONSTRAINT chk_email_templates_used CHECK (used_count >= 0),
  CONSTRAINT fk_email_templates_user FOREIGN KEY (org_id, user_id)
    REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_email_templates_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
-- A name is unique per owner: one index for the workspace's templates, one for each person's own.
CREATE UNIQUE INDEX uq_email_templates_shared_name ON email_templates (org_id, lower(name)) WHERE user_id IS NULL;
CREATE UNIQUE INDEX uq_email_templates_user_name ON email_templates (org_id, user_id, lower(name)) WHERE user_id IS NOT NULL;
CREATE INDEX idx_email_templates_list ON email_templates (org_id, created_at DESC, id DESC);
CREATE INDEX idx_email_templates_user ON email_templates (org_id, user_id) WHERE user_id IS NOT NULL;

ALTER TABLE email_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE email_templates FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON email_templates FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- Using a template is not editing it: the usage counters change without moving updated_at or row_version; every other update behaves
-- like touch_row().
CREATE OR REPLACE FUNCTION email_templates_touch() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE'
     AND (to_jsonb(NEW) - 'used_count' - 'last_used_at' - 'updated_at' - 'row_version')
       = (to_jsonb(OLD) - 'used_count' - 'last_used_at' - 'updated_at' - 'row_version') THEN
    NEW.updated_at := OLD.updated_at;
    NEW.row_version := OLD.row_version;
    RETURN NEW;
  END IF;
  NEW.updated_at := now();
  IF TG_OP = 'UPDATE' THEN
    NEW.row_version := OLD.row_version + 1;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_email_templates_touch BEFORE UPDATE ON email_templates
  FOR EACH ROW EXECUTE FUNCTION email_templates_touch();
