-- Tables: google_form_sessions

-- Reference `google_form_sessions` (tenant; 0 rows in the reference DB)
CREATE TABLE google_form_sessions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  flow_session_id text NOT NULL,
  google_form_id text NOT NULL,
  contact_phone text,
  save_variable text,
  resume_port text NOT NULL DEFAULT 'submitted',
  answers_json jsonb,
  submitted_at timestamptz,
  expires_at timestamptz,
  webhook_token text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_google_form_sessions_webhook_token UNIQUE (webhook_token)
);
CREATE INDEX idx_google_form_sessions_contact_phone ON google_form_sessions (org_id, contact_phone);
CREATE INDEX idx_google_form_sessions_expires_at ON google_form_sessions (org_id, expires_at);
CREATE INDEX idx_google_form_sessions_flow_session_id ON google_form_sessions (org_id, flow_session_id);
CREATE INDEX idx_google_form_sessions_google_form_id ON google_form_sessions (org_id, google_form_id);

ALTER TABLE google_form_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE google_form_sessions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON google_form_sessions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_google_form_sessions_touch BEFORE UPDATE ON google_form_sessions
  FOR EACH ROW EXECUTE FUNCTION touch_row();
