-- ctp: companies-projects-tasks data model, ported from WaDesk
-- Why this migration exists: the tables WaDesk's companies projects tasks features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/wadesk-port/schema/README.md and docs/wadesk-port/schema/decisions.toml.
--
-- Tables: projects, tasks

-- --- additions to tables this repo already has ----------------------------------------
-- companies: WaDesk company fields without a column yet. `website` is `domain`, `owner_user_id` is `owner_id`,
-- `custom_attributes` is `data`.
ALTER TABLE companies
  ADD COLUMN email     citext,
  ADD COLUMN phone     text,
  ADD COLUMN industry  text,
  ADD COLUMN size_range text,
  ADD COLUMN address   text,
  ADD COLUMN notes     text;

-- WaDesk `projects` (tenant; 0 rows in the reference DB)
CREATE TABLE projects (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  description text,
  status text NOT NULL DEFAULT 'in_progress',
  progress smallint NOT NULL DEFAULT 0,
  contact_id bigint,
  company_id bigint,
  deal_id bigint,
  owner_id bigint,
  created_by bigint,
  start_date date,
  due_date date,
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_projects_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_projects_company_id FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_projects_deal_id FOREIGN KEY (org_id, deal_id) REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id),
  CONSTRAINT fk_projects_owner_id FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_id),
  CONSTRAINT fk_projects_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_projects_company_id ON projects (org_id, company_id);
CREATE INDEX idx_projects_contact_id ON projects (org_id, contact_id);
CREATE INDEX idx_projects_deal_id ON projects (org_id, deal_id);
CREATE INDEX idx_projects_due_date ON projects (org_id, due_date);
CREATE INDEX idx_projects_status_due_date ON projects (org_id, status, due_date);

ALTER TABLE projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON projects FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_projects_touch BEFORE UPDATE ON projects
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- WaDesk `tasks` (tenant; 0 rows in the reference DB)
CREATE TABLE tasks (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  created_by bigint,
  assignee_id bigint,
  title text NOT NULL,
  notes text,
  priority text NOT NULL DEFAULT 'medium',
  status text NOT NULL DEFAULT 'open',
  related_type text,
  related_id bigint,
  due_at timestamptz,
  reminded_at timestamptz,
  done_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_tasks_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT fk_tasks_assignee_id FOREIGN KEY (org_id, assignee_id) REFERENCES users (org_id, id) ON DELETE SET NULL (assignee_id)
);
CREATE INDEX idx_tasks_assignee_id ON tasks (org_id, assignee_id);
CREATE INDEX idx_tasks_due_at ON tasks (org_id, due_at);
CREATE INDEX idx_tasks_related_type_related_id ON tasks (org_id, related_type, related_id);
CREATE INDEX idx_tasks_status_due_at ON tasks (org_id, status, due_at);

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE tasks FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON tasks FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_tasks_touch BEFORE UPDATE ON tasks
  FOR EACH ROW EXECUTE FUNCTION touch_row();
