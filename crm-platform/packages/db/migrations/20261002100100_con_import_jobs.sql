-- con: CSV import jobs, and the contact columns an import needs.
-- Why this migration exists (TW-CON-027..031, differences #8 and #9): Reference imported synchronously inside the request,
-- kept `status` and `source` hidden inside a JSON blob (so the sidebar "Imported" filter could never match anything) and
-- reported no per-row result. A job row carries the uploaded file while the worker runs, the progress, the counted
-- outcomes and the rejected rows for the downloadable report; `contacts.source` and `contacts.import_job_id` make
-- "imported" and "where did this contact come from" queryable.

CREATE TABLE contact_import_jobs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  created_by bigint,
  status text NOT NULL DEFAULT 'queued',
  file_name text NOT NULL,
  byte_size integer NOT NULL DEFAULT 0,
  total_rows integer NOT NULL DEFAULT 0,
  processed_rows integer NOT NULL DEFAULT 0,
  created_count integer NOT NULL DEFAULT 0,
  updated_count integer NOT NULL DEFAULT 0,
  invalid_count integer NOT NULL DEFAULT 0,
  duplicates_in_file integer NOT NULL DEFAULT 0,
  limit_exceeded integer NOT NULL DEFAULT 0,
  -- mapping and the apply-to-all knobs, exactly as requested
  options jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- up to 1000 {row, reason, values}; the rest are only counted
  rejects jsonb NOT NULL DEFAULT '[]'::jsonb,
  -- the uploaded text, kept only until the job finishes
  source_csv text,
  error text,
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_contact_import_jobs_status CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  CONSTRAINT fk_contact_import_jobs_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE INDEX idx_contact_import_jobs_org_created ON contact_import_jobs (org_id, created_at DESC, id DESC);
-- the worker's recovery sweep: anything still queued or running
CREATE INDEX idx_contact_import_jobs_active ON contact_import_jobs (status) WHERE status IN ('queued', 'running');

ALTER TABLE contact_import_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_import_jobs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_import_jobs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_contact_import_jobs_touch BEFORE UPDATE ON contact_import_jobs
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Where a contact came from. Free text up to 128 characters (the import source knob, "import", "api", ...).
ALTER TABLE contacts
  ADD COLUMN source text,
  ADD COLUMN import_job_id bigint,
  ADD CONSTRAINT chk_contacts_source CHECK (source IS NULL OR char_length(source) <= 128),
  ADD CONSTRAINT fk_contacts_import_job FOREIGN KEY (org_id, import_job_id)
    REFERENCES contact_import_jobs (org_id, id) ON DELETE SET NULL (import_job_id);
CREATE INDEX idx_contacts_org_import_job ON contacts (org_id, import_job_id) WHERE import_job_id IS NOT NULL;
CREATE INDEX idx_contacts_org_source ON contacts (org_id, source) WHERE source IS NOT NULL;
