-- Product variants (Size, Colour, anything a store sells in more than one form). Reference has no variants: this is an owner
-- approved extension (2026-10-13), recorded in docs/threadwise-port/parity/catalog-products.md.
--
-- Model: a product keeps up to 3 named options in `options_json` ([{ "name": "Size", "values": ["XS","S"] }]); every sellable
-- combination is one `wa_product_variants` row. The product row stays the aggregate the old readers know: while a product has
-- variants, `price_minor` is the lowest variant price and `stock_qty` the sum of the variants (null when any is unlimited),
-- both kept by the API in the same transaction as the variant write.

ALTER TABLE wa_products ADD COLUMN options_json jsonb;

CREATE TABLE wa_product_variants (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  product_id bigint NOT NULL,
  -- the chosen value of each product option, in option order: ["M","Red"]
  option_values_json jsonb NOT NULL,
  -- "M / Red": what the buyer, the cart and the order line show
  title text NOT NULL,
  sku text,
  -- null = same as the product
  price_minor bigint,
  compare_price_minor bigint,
  image_url text,
  weight_grams integer,
  -- null = unlimited, like wa_products.stock_qty
  stock_qty integer,
  reserved_qty integer NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  position integer NOT NULL DEFAULT 0,
  meta_retailer_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_wa_product_variants_product_id FOREIGN KEY (org_id, product_id) REFERENCES wa_products (org_id, id) ON DELETE CASCADE,
  CONSTRAINT uq_wa_product_variants_title UNIQUE (org_id, product_id, title),
  CONSTRAINT chk_wa_product_variants_price CHECK (price_minor IS NULL OR price_minor >= 0),
  CONSTRAINT chk_wa_product_variants_compare CHECK (compare_price_minor IS NULL OR compare_price_minor >= 0),
  CONSTRAINT chk_wa_product_variants_stock CHECK ((stock_qty IS NULL OR stock_qty >= 0) AND reserved_qty >= 0)
);
CREATE INDEX idx_wa_product_variants_product_id ON wa_product_variants (org_id, product_id, position);
CREATE UNIQUE INDEX uq_wa_product_variants_sku ON wa_product_variants (org_id, sku) WHERE sku IS NOT NULL;

ALTER TABLE wa_product_variants ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_product_variants FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_product_variants FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_product_variants_touch BEFORE UPDATE ON wa_product_variants
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A hold or a sale of a variant is tracked on the variant; the product-level reservation columns stay for products without variants.
ALTER TABLE wa_stock_reservations ADD COLUMN variant_id bigint;
ALTER TABLE wa_stock_reservations
  ADD CONSTRAINT fk_wa_stock_reservations_variant_id FOREIGN KEY (org_id, variant_id)
  REFERENCES wa_product_variants (org_id, id) ON DELETE CASCADE;
CREATE INDEX idx_wa_stock_reservations_variant_id ON wa_stock_reservations (org_id, variant_id);
