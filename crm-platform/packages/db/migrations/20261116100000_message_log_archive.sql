-- message log: archive of old message events, the export of the log, and its permission.
-- Why this migration exists: `message_events` is the exact log of every message (queued, each attempt, accepted, each receipt, failed,
-- an agent's Retry) and grows without bound. Events stay in the live table for 90 days; a daily worker sweep (MessageLogArchiveService)
-- then writes one gzip NDJSON object per workspace and day into `message_event_archives` and deletes the live rows IN THE SAME
-- TRANSACTION, so an event is never in neither place. The archive keeps a year after the event (MESSAGE_LOG_RETENTION_DAYS), then the
-- sweep deletes it. A message's log reads both places; an export reaches the whole year.
-- Why bytea in Postgres and not an object bucket: the bucket is optional here (without one a file lands on the local disk of the
-- container that wrote it, and the worker and the API do not share a disk). The archive and the export file must be readable by both,
-- and the archive swap with the delete must be one transaction. A day of one workspace compresses to a few hundred KB; TOAST stores it
-- out of line, so the table stays small to scan.
--
-- `message_log_exports`: one row per requested export. The worker builds the CSV (live + archive), stores it gzipped in `file_gz` for
-- 7 days, and emails the requester a link to the page that offers the download. The row stays (status `expired`) after the file goes.

-- The archive sweep reads one day at a time across a month's partition.
CREATE INDEX IF NOT EXISTS idx_message_events_created ON message_events (created_at);

CREATE TABLE message_event_archives (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  -- The UTC day the events happened on.
  day         date NOT NULL,
  event_count integer NOT NULL,
  -- gzip of one JSON object per line: {id, messageId, messageCreatedAt, event, detail, at}.
  payload_gz  bytea NOT NULL,
  archived_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  CONSTRAINT uq_message_event_archives_day UNIQUE (org_id, day),
  CONSTRAINT chk_message_event_archives_count CHECK (event_count > 0)
);
-- The purge deletes old days across every workspace.
CREATE INDEX idx_message_event_archives_day ON message_event_archives (day);

ALTER TABLE message_event_archives ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_event_archives FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON message_event_archives FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TABLE message_log_exports (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  requested_by    bigint NOT NULL,
  -- Where the "your export is ready" mail went; kept so the page can say it even after the user changes address.
  emailed_to      text,
  range_from      date NOT NULL,
  range_to        date NOT NULL,
  -- Only the events of messages that ended in this status; null = every event.
  message_status  text,
  status          text NOT NULL DEFAULT 'queued',
  row_count       integer,
  file_name       text,
  file_bytes      integer,
  file_gz         bytea,
  error           text,
  requested_at    timestamptz NOT NULL DEFAULT now(),
  started_at      timestamptz,
  completed_at    timestamptz,
  expires_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, requested_by) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_message_log_exports_status CHECK (status IN ('queued', 'running', 'ready', 'failed', 'expired')),
  CONSTRAINT chk_message_log_exports_range CHECK (range_from <= range_to)
);
CREATE INDEX idx_message_log_exports_org ON message_log_exports (org_id, requested_at DESC);
-- The daily sweep finds files past their time.
CREATE INDEX idx_message_log_exports_expiry ON message_log_exports (expires_at) WHERE status = 'ready';

ALTER TABLE message_log_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_log_exports FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON message_log_exports FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

CREATE TRIGGER trg_message_log_exports_touch BEFORE UPDATE ON message_log_exports
  FOR EACH ROW EXECUTE FUNCTION touch_row();

