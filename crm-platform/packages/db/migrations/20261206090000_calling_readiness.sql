-- call: number readiness (EXT-CALL-007 to 011). Not a Reference feature: Reference showed an on/off switch per number and nothing about
-- why calling would or would not work. Here every connected WhatsApp number carries the result of its last readiness check (the checklist
-- the calling settings screen and the health page draw), and a workspace can ask for calling to be switched on by itself when a number
-- is connected.
--
--   wa_calling_readiness   one row per WhatsApp number: the checklist (codes, never sentences), Meta's own calling status at the last
--                          check, when and why it ran, and when the schedule should look again
--   wa_calling_settings    one row per workspace: whether calling is switched on automatically after a number is connected (OFF by
--                          default: nothing is ever enabled on Meta's side without a workspace admin having said so)
--
-- Not a permission change: reading uses call.calls.use and changing uses call.calling.manage, both already registered.

CREATE TABLE wa_calling_readiness (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  config_id bigint NOT NULL,
  -- never_checked | blocked | ready_to_enable | attention | ready
  status text NOT NULL DEFAULT 'never_checked',
  -- [{ key, state, code, params? }]: codes the web translates. Never free text.
  checks jsonb NOT NULL DEFAULT '[]',
  -- What Meta said calling is at the last check ('ENABLED' | 'DISABLED'); null when it could not be read.
  meta_status text,
  checked_at timestamptz,
  -- connect | manual | schedule | health | enable
  source text,
  -- When the schedule looks again; null = never scheduled yet (the sweep treats it as due).
  next_check_at timestamptz,
  -- A connect asked for calling to be switched on by itself and it has not happened yet (Meta not readable, a blocker, a refusal):
  -- every later check keeps trying while this is set. Cleared when it is switched on, when the plan or the workspace setting no
  -- longer allow it, or when a person turns calling off.
  auto_enable_pending boolean NOT NULL DEFAULT false,
  -- Checks in a row that could not read Meta while pending: picks the next, sooner, look (1, 5, 15 minutes, then the normal rhythm).
  auto_enable_attempts smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  -- One row per number; a number that is removed takes its readiness with it.
  UNIQUE (org_id, config_id),
  CONSTRAINT fk_wa_calling_readiness_config FOREIGN KEY (org_id, config_id) REFERENCES wa_provider_configs (org_id, id) ON DELETE CASCADE,
  CONSTRAINT ck_wa_calling_readiness_status CHECK (status IN ('never_checked', 'blocked', 'ready_to_enable', 'attention', 'ready')),
  CONSTRAINT ck_wa_calling_readiness_meta_status CHECK (meta_status IS NULL OR meta_status IN ('ENABLED', 'DISABLED')),
  CONSTRAINT ck_wa_calling_readiness_source CHECK (source IS NULL OR source IN ('connect', 'manual', 'schedule', 'health', 'enable'))
);
-- The schedule's lookup: the numbers that are due.
CREATE INDEX idx_wa_calling_readiness_due ON wa_calling_readiness (next_check_at);

ALTER TABLE wa_calling_readiness ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_calling_readiness FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_calling_readiness FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_wa_calling_readiness_touch BEFORE UPDATE ON wa_calling_readiness
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE wa_calling_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  -- Off until a workspace admin turns it on. Only the plan feature waba_calling lets it do anything.
  auto_enable_on_connect boolean NOT NULL DEFAULT false,
  updated_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id),
  CONSTRAINT fk_wa_calling_settings_updated_by FOREIGN KEY (org_id, updated_by) REFERENCES users (org_id, id) ON DELETE SET NULL (updated_by)
);
ALTER TABLE wa_calling_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE wa_calling_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON wa_calling_settings FOR ALL
