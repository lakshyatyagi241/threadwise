-- Immutable: what a version says never changes. The link to the publisher may be nulled (the foreign key's own ON DELETE SET NULL is an
-- UPDATE); nothing else may move.
CREATE FUNCTION web_form_versions_immutable() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.form_id, NEW.version, NEW.definition, NEW.published_at)
     IS DISTINCT FROM (OLD.form_id, OLD.version, OLD.definition, OLD.published_at) THEN
    RAISE EXCEPTION 'web_form_versions is immutable' USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_web_form_versions_immutable BEFORE UPDATE ON web_form_versions
  FOR EACH ROW EXECUTE FUNCTION web_form_versions_immutable();

