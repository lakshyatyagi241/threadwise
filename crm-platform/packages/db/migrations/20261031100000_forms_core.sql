-- Events: views, starts, steps, submits, completions. A stream: monthly RANGE partitions, retention 90 days (swept by the worker), no
-- personal data (the visit id is random per page load, no cookie).
CREATE SEQUENCE web_form_events_id_seq;
CREATE TABLE web_form_events (
  id bigint NOT NULL DEFAULT nextval('web_form_events_id_seq'),
  org_id bigint NOT NULL,
  form_id bigint NOT NULL,
  version_id bigint,
  visit_id text NOT NULL,
  kind text NOT NULL,
  step_index integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at),
  CONSTRAINT chk_web_form_events_kind CHECK (kind IN ('view', 'start', 'step', 'submit', 'complete')),
  CONSTRAINT fk_web_form_events_form FOREIGN KEY (org_id, form_id)
    REFERENCES web_forms (org_id, id) ON DELETE CASCADE
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_web_form_events_form ON web_form_events (org_id, form_id, created_at DESC);
CREATE INDEX idx_web_form_events_form_kind ON web_form_events (org_id, form_id, kind);

