-- The public page: public key -> (workspace, form). Ids, a status and the embed allow-list (the page must answer with it) only: never the
-- definition, the owner rule or the notification list. An archived form returns nothing, so it is the same 404 as an unknown key.
CREATE OR REPLACE FUNCTION web_form_lookup(p_public_key text)
RETURNS TABLE (
  route_org_id bigint,
  route_form_id bigint,
  route_status text,
  route_published_version_id bigint,
  route_allowed_origins text[]
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT f.org_id, f.id, f.status, f.published_version_id, f.allowed_origins
    FROM web_forms f
    WHERE f.public_key = p_public_key AND f.status <> 'archived'
    LIMIT 1;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION web_form_lookup(text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION web_form_lookup(text) TO crm_app_user;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_worker_user') THEN
    GRANT EXECUTE ON FUNCTION web_form_lookup(text) TO crm_worker_user;
  END IF;
END
$$;
