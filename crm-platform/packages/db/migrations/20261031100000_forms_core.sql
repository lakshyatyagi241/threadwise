  ADD CONSTRAINT fk_web_forms_published_version FOREIGN KEY (org_id, published_version_id)
    REFERENCES web_form_versions (org_id, id) ON DELETE SET NULL (published_version_id);
CREATE INDEX idx_web_forms_published_version ON web_forms (org_id, published_version_id) WHERE published_version_id IS NOT NULL;

CREATE TABLE web_form_submissions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  form_id bigint NOT NULL,
  version_id bigint NOT NULL,
  -- Made by the page, once per page load: UNIQUE (org, form, key) is the idempotency authority, not a check-then-insert.
  idempotency_key text NOT NULL,
  -- The visitor's receipt, returned by the door; the same key twice returns the same token. Not a credential for anything.
  receipt_token text NOT NULL,
  -- received = stored and being processed (a crash between the two leaves it here, and a retry or the stale-claim rule picks it up).
  status text NOT NULL DEFAULT 'received',
  -- Why a submission is needs_review, spam or failed: a stable code (no_contact_point, plan_limit_reached, submissions_cap, ...).
  reason text,
  error text,
  -- What the visitor sent (field id -> value), minus fields the form does not have. Personal data: emptied by the retention sweep and by erase.
  answers jsonb NOT NULL DEFAULT '{}'::jsonb,
  contact_id bigint,
  company_id bigint,
  -- Phase 2 (deal mapping); the column exists so the submission already has its place to point at.
  deal_id bigint,
  utm jsonb NOT NULL DEFAULT '{}'::jsonb,
  referrer text,
  page_url text,
  -- HMAC of the address with a rotating salt: enough to count and to correlate within a day, useless to find a person.
  ip_hash text,
  user_agent text,
  -- The consent line the visitor saw: { given, text, version, at }. Kept when the answers are erased: it is the evidence.
  consent jsonb,
  spam_score integer NOT NULL DEFAULT 0,
  answers_expires_at timestamptz,
  payload_purged_at timestamptz,
  -- A person erased the answers (GDPR): the row stays as a tombstone, the contact is never touched.
  erased_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_web_form_submissions_idempotency UNIQUE (org_id, form_id, idempotency_key),
  CONSTRAINT uq_web_form_submissions_receipt UNIQUE (receipt_token),
  CONSTRAINT chk_web_form_submissions_status CHECK (status IN
    ('received', 'created', 'updated', 'needs_review', 'awaiting_payment', 'paid', 'failed', 'spam')),
  CONSTRAINT chk_web_form_submissions_key CHECK (char_length(idempotency_key) BETWEEN 8 AND 64),
  CONSTRAINT chk_web_form_submissions_answers CHECK (jsonb_typeof(answers) = 'object'),
  CONSTRAINT chk_web_form_submissions_utm CHECK (jsonb_typeof(utm) = 'object'),
  CONSTRAINT fk_web_form_submissions_form FOREIGN KEY (org_id, form_id)
    REFERENCES web_forms (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_web_form_submissions_version FOREIGN KEY (org_id, version_id)
    REFERENCES web_form_versions (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_web_form_submissions_contact FOREIGN KEY (org_id, contact_id)
    REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_web_form_submissions_company FOREIGN KEY (org_id, company_id)
    REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_web_form_submissions_deal FOREIGN KEY (org_id, deal_id)
    REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id)
);
CREATE INDEX idx_web_form_submissions_recent ON web_form_submissions (org_id, form_id, created_at DESC, id DESC);
CREATE INDEX idx_web_form_submissions_status ON web_form_submissions (org_id, form_id, status, created_at DESC, id DESC);
CREATE INDEX idx_web_form_submissions_contact ON web_form_submissions (org_id, contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX idx_web_form_submissions_company ON web_form_submissions (org_id, company_id) WHERE company_id IS NOT NULL;
CREATE INDEX idx_web_form_submissions_deal ON web_form_submissions (org_id, deal_id) WHERE deal_id IS NOT NULL;
CREATE INDEX idx_web_form_submissions_version ON web_form_submissions (org_id, version_id);
-- The monthly cap counts accepted submissions of a month across forms.
CREATE INDEX idx_web_form_submissions_month ON web_form_submissions (org_id, created_at) WHERE status <> 'spam';
-- The retention sweep runs across every workspace, so it is not org-prefixed.
CREATE INDEX idx_web_form_submissions_expiry ON web_form_submissions (answers_expires_at)
  WHERE answers_expires_at IS NOT NULL AND payload_purged_at IS NULL;

