-- forms: the Forms add-on's tables (docs/specs/forms-builder-app.md sections 6 and 9; backlog BL-093, phases 0 and 1 = v0.9).
-- Why this migration exists: a workspace needs a page where a stranger types name, phone and email and lands in the CRM as a contact (and
-- a company) with an owner, a tag and a notification. Lead sources take other people's forms; nothing in the product renders a form. This is
-- NOT WaDesk's `wa_forms` (WhatsApp Flows forms, domain forms-links-groups): different names on purpose (`web_forms*`).
--
--  1. web_forms            one form: the DRAFT definition, its status, and the settings that apply live (owner rule, notification list,
--                          embed allow-list, captcha mode, retention, rate limits). `public_key` (22 random characters) is the only
--                          identifier that appears in a public URL.
--  2. web_form_versions    Publish freezes the draft here. IMMUTABLE (trigger): a submission stores the version it was made against, so a
--                          changed form never reinterprets old answers.
--  3. web_form_submissions every submission, stored under its idempotency key BEFORE it is processed (the lead pipeline's rule): one that
--                          cannot become a contact is kept as `needs_review`, never dropped. `answers` is personal data with a retention
--                          clock (`answers_expires_at`, swept by the worker); a raw IP is never stored, only a salted hash.
--  4. web_form_events      views, starts and completions, append-only, partitioned monthly, no personal data (a visit id, no cookie).
--  5. web_form_usage_monthly  counters that have no row to count: AI generations and the spam the honeypot dropped silently.
--  6. web_form_lookup()    the public page arrives with a key and no tenant. Like lead_source_lookup it is a SECURITY DEFINER function that
--                          returns ids and a status only (never the definition, the notify list or the owner rule); an archived form
--                          returns nothing.

CREATE TABLE web_forms (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  name text NOT NULL,
  public_key text NOT NULL,
  -- draft -> published (a frozen version is what the public sees) -> paused (public page says "closed") -> archived.
  status text NOT NULL DEFAULT 'draft',
  draft_definition jsonb NOT NULL,
  -- The live version. Circular with web_form_versions.form_id, so the foreign key is added after that table exists.
  published_version_id bigint,
  -- Exact origins allowed to embed the form and post to it from a browser (https://example.com, https://*.example.com). Empty = hosted only.
  allowed_origins text[] NOT NULL DEFAULT '{}',
  captcha_mode text NOT NULL DEFAULT 'inherit',
  honeypot boolean NOT NULL DEFAULT true,
  notify jsonb NOT NULL DEFAULT '{"owner":true,"userIds":[],"emails":[]}'::jsonb,
  -- Days an answer is kept before the worker purges it; NULL = until a person deletes it.
  retention_days integer DEFAULT 365,
  owner_rule jsonb NOT NULL DEFAULT '{"mode":"unassigned","userIds":[]}'::jsonb,
  rate_limits jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Round-robin position. Bookkeeping: a write that touches only this does not bump row_version (see the trigger).
  rr_cursor bigint NOT NULL DEFAULT 0,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_web_forms_status CHECK (status IN ('draft', 'published', 'paused', 'archived')),
  CONSTRAINT chk_web_forms_captcha CHECK (captcha_mode IN ('inherit', 'on', 'off')),
  CONSTRAINT chk_web_forms_name CHECK (btrim(name) <> '' AND char_length(name) <= 120),
  CONSTRAINT chk_web_forms_key CHECK (public_key ~ '^[A-Za-z0-9]{22}$'),
  CONSTRAINT chk_web_forms_definition CHECK (jsonb_typeof(draft_definition) = 'object'),
  CONSTRAINT chk_web_forms_retention CHECK (retention_days IS NULL OR retention_days BETWEEN 30 AND 3650),
  CONSTRAINT chk_web_forms_origins CHECK (cardinality(allowed_origins) <= 20),
  CONSTRAINT chk_web_forms_owner_rule CHECK (jsonb_typeof(owner_rule) = 'object'),
  CONSTRAINT chk_web_forms_notify CHECK (jsonb_typeof(notify) = 'object'),
  CONSTRAINT chk_web_forms_rates CHECK (jsonb_typeof(rate_limits) = 'object'),
  CONSTRAINT chk_web_forms_published CHECK (status NOT IN ('published', 'paused') OR published_version_id IS NOT NULL),
  CONSTRAINT fk_web_forms_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
-- A name is unique among the forms that are not archived: an archived form keeps its name without blocking a new one.
CREATE UNIQUE INDEX uq_web_forms_name ON web_forms (org_id, lower(name)) WHERE status <> 'archived';
-- The public lookup reads this; it is globally unique because the key alone finds the workspace.
CREATE UNIQUE INDEX uq_web_forms_public_key ON web_forms (public_key);
CREATE INDEX idx_web_forms_status ON web_forms (org_id, status);
CREATE INDEX idx_web_forms_recent ON web_forms (org_id, created_at DESC, id DESC);
CREATE INDEX idx_web_forms_created_by ON web_forms (org_id, created_by) WHERE created_by IS NOT NULL;

ALTER TABLE web_forms ENABLE ROW LEVEL SECURITY;
ALTER TABLE web_forms FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON web_forms FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- touch_row() for this table, except that the round-robin cursor does not bump row_version or updated_at: every accepted submission
-- moves it, and each would otherwise turn the editor's next save into a 409.
CREATE FUNCTION web_forms_touch() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) - ARRAY['rr_cursor', 'updated_at', 'row_version'])
     = (to_jsonb(OLD) - ARRAY['rr_cursor', 'updated_at', 'row_version']) THEN
    NEW.updated_at := OLD.updated_at;
    NEW.row_version := OLD.row_version;
    RETURN NEW;
  END IF;
  NEW.updated_at := now();
  NEW.row_version := OLD.row_version + 1;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_web_forms_touch BEFORE UPDATE ON web_forms
  FOR EACH ROW EXECUTE FUNCTION web_forms_touch();

