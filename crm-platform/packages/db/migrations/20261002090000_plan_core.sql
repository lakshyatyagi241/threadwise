-- 20261002090000_plan_core
-- Why this migration exists (WD-PLAN-001..008, 017): the AUTH domain needs a
-- real plan catalogue to assign at sign-up (WD-AUTH-008), to list on the
-- onboarding plan step (WD-AUTH-009) and to gate the message footer
-- (WD-AUTH-029, feature `remove_branding`). This is the thin slice of the PLAN
-- domain those three need; checkout, subscriptions, add-ons, the quota ledger
-- and the trial hard gate extend it later without renaming anything here.
--
-- Two decisions worth knowing:
--
-- 1. `organizations.plan` stays the ONE authoritative plan reference (a slug).
--    WaDesk's worst plan bug was a dual reference (slug at sign-up, numeric id
--    after checkout) that made every subscriber count and delete guard miss
--    rows. Here there is one column, always the slug, so "which orgs use this
--    plan" is a plain `WHERE plan = slug` and `org_plan_state` holds only what
--    changes over time: trial/period, billing cycle and per-org overrides.
--    There is deliberately NO foreign key from organizations.plan to plans:
--    WaDesk resolves a signup to the literal slug 'starter' even when no such
--    plan exists, and the in-use guard (not a FK) is what protects deletes.
--
-- 2. `plans` is a platform-level catalogue: no org_id. Every tenant
--    transaction may READ it (the onboarding step lists it); only the
--    privileged flag (the operator console, sign-up provisioning, seeds) may
--    write it. `org_plan_state` is a tenant table (forced RLS by org_id) that
--    a tenant can read but not write: a workspace must not be able to extend
--    its own trial.
--
-- Limits and features live in jsonb so the catalogue can grow without a
-- migration per key: `limits` holds numeric caps (0 = unlimited, WaDesk's
-- rule), `features` holds boolean flags. The key registry is in
-- @crm/contracts (plans-subscriptions-trials/catalogue.ts); a CHECK only
-- guarantees the value is an object.

CREATE TABLE plans (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  -- WaDesk's `plan_id`: stable, never a pure number (so it can never be
  -- confused with a row id), at most 32 characters (the old workspaces.plan
  -- width), assigned once and never renamed.
  slug            text NOT NULL UNIQUE,
  name            text NOT NULL,
  subtitle        text,
  detail          text,
  -- 'addon' is reserved for the ADD domain; the plan endpoints only ever see 'plan'.
  kind            text NOT NULL DEFAULT 'plan',
  -- Money is a decimal string end to end; numeric(12,2) round-trips as text.
  amount          numeric(12,2) NOT NULL DEFAULT 0,
  offer_amount    numeric(12,2),
  currency        text NOT NULL DEFAULT 'USD',
  billing_unit    text NOT NULL DEFAULT 'months',
  billing_duration integer NOT NULL DEFAULT 1,
  is_free         boolean NOT NULL DEFAULT false,
  is_lifetime     boolean NOT NULL DEFAULT false,
  is_active       boolean NOT NULL DEFAULT true,
  -- The sign-up default when the registration setting names no plan (step 2
  -- of the 4-step resolution, WD-PLAN-008). At most one row.
  is_default      boolean NOT NULL DEFAULT false,
  is_highlighted  boolean NOT NULL DEFAULT false,
  is_custom_quote boolean NOT NULL DEFAULT false,
  sort_order      integer NOT NULL DEFAULT 0,
  cta_label       text NOT NULL DEFAULT 'Get started',
  limits          jsonb NOT NULL DEFAULT '{}'::jsonb,
  features        jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_plans_slug CHECK (slug ~ '^[a-z0-9_]{1,32}$' AND slug ~ '[a-z]'),
  CONSTRAINT chk_plans_name CHECK (char_length(name) BETWEEN 1 AND 120),
  CONSTRAINT chk_plans_subtitle CHECK (subtitle IS NULL OR char_length(subtitle) <= 191),
  CONSTRAINT chk_plans_detail CHECK (detail IS NULL OR char_length(detail) <= 5000),
  CONSTRAINT chk_plans_kind CHECK (kind IN ('plan', 'addon')),
  CONSTRAINT chk_plans_amount CHECK (amount >= 0),
  -- An offer is a discount: positive and strictly below the list price.
  CONSTRAINT chk_plans_offer CHECK (offer_amount IS NULL OR (offer_amount > 0 AND offer_amount < amount)),
  CONSTRAINT chk_plans_currency CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_plans_unit CHECK (billing_unit IN ('days', 'weeks', 'months', 'years')),
  CONSTRAINT chk_plans_duration CHECK (billing_duration BETWEEN 1 AND 120),
  CONSTRAINT chk_plans_sort CHECK (sort_order >= 0),
  CONSTRAINT chk_plans_cta CHECK (char_length(cta_label) BETWEEN 1 AND 64),
  CONSTRAINT chk_plans_free CHECK (NOT is_free OR (amount = 0 AND offer_amount IS NULL AND NOT is_custom_quote)),
  CONSTRAINT chk_plans_custom CHECK (NOT is_custom_quote OR (amount = 0 AND offer_amount IS NULL)),
  -- A priced plan is paid: price 0 must be marked free (or be a custom quote).
  CONSTRAINT chk_plans_priced CHECK (is_free OR is_custom_quote OR amount > 0),
  CONSTRAINT chk_plans_default_active CHECK (NOT is_default OR is_active),
  CONSTRAINT chk_plans_limits CHECK (jsonb_typeof(limits) = 'object'),
  CONSTRAINT chk_plans_features CHECK (jsonb_typeof(features) = 'object')
);
CREATE INDEX idx_plans_listing ON plans (kind, is_active, sort_order, amount);
-- "At most one default": the database, not only the service, refuses a second.
CREATE UNIQUE INDEX uq_plans_single_default ON plans ((true)) WHERE is_default;

CREATE TRIGGER trg_plans_touch BEFORE UPDATE ON plans
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Platform catalogue: readable by every transaction, writable only when the
-- privileged flag is on. One policy per command so the read side can stay
-- `true` without opening the write side (FOR ALL with USING (true) would).
ALTER TABLE plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE plans FORCE  ROW LEVEL SECURITY;
CREATE POLICY catalogue_read ON plans FOR SELECT USING (true);
CREATE POLICY catalogue_insert ON plans FOR INSERT WITH CHECK (app_is_privileged());
CREATE POLICY catalogue_update ON plans FOR UPDATE
  USING (app_is_privileged()) WITH CHECK (app_is_privileged());
CREATE POLICY catalogue_delete ON plans FOR DELETE USING (app_is_privileged());
GRANT SELECT, INSERT, UPDATE, DELETE ON plans TO crm_app, crm_worker;

-- --- per-organization plan state ----------------------------------------------------------

CREATE TABLE org_plan_state (
  org_id          bigint PRIMARY KEY REFERENCES organizations (id) ON DELETE CASCADE,
  -- Stamped at sign-up when the resolved plan is free and trial days > 0.
  trial_ends_at   timestamptz,
  -- NULL = never expires (free plans, lifetime). PAYGW sets it on purchase.
  plan_ends_at    timestamptz,
  -- 'trial' stays after a purchase in WaDesk (informational); same here.
  billing_cycle   text NOT NULL DEFAULT 'monthly',
  -- Per-org entitlement overrides: { "limits": {key: int, -1 = unlimited},
  -- "features": {key: bool} }. Beats the plan (WD-PLAN-007 rule 1).
  overrides       jsonb NOT NULL DEFAULT '{}'::jsonb,
  -- Orgs the platform itself owns are never limited (WD-PLAN-006 rule 3).
  platform_owned  boolean NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  CONSTRAINT chk_org_plan_state_cycle CHECK (billing_cycle IN ('trial', 'monthly', 'yearly')),
  CONSTRAINT chk_org_plan_state_overrides CHECK (jsonb_typeof(overrides) = 'object')
);

CREATE TRIGGER trg_org_plan_state_touch BEFORE UPDATE ON org_plan_state
  FOR EACH ROW EXECUTE FUNCTION touch_row();

ALTER TABLE org_plan_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE org_plan_state FORCE  ROW LEVEL SECURITY;
-- A tenant reads its own state; only a privileged transaction (sign-up,
-- operator console, billing) writes it.
CREATE POLICY tenant_read ON org_plan_state FOR SELECT
  USING (org_id = current_org_id() OR app_is_privileged());
CREATE POLICY platform_insert ON org_plan_state FOR INSERT WITH CHECK (app_is_privileged());
CREATE POLICY platform_update ON org_plan_state FOR UPDATE
  USING (app_is_privileged()) WITH CHECK (app_is_privileged());
CREATE POLICY platform_delete ON org_plan_state FOR DELETE USING (app_is_privileged());
GRANT SELECT, INSERT, UPDATE, DELETE ON org_plan_state TO crm_app, crm_worker;

-- "Which orgs are on this plan" backs the delete guard and the in-use counts.
CREATE INDEX idx_organizations_plan ON organizations (plan);

-- Existing organizations get a state row (no trial: they predate it).
SELECT set_config('app.privileged', 'on', true);
INSERT INTO org_plan_state (org_id) SELECT id FROM organizations ON CONFLICT (org_id) DO NOTHING;
