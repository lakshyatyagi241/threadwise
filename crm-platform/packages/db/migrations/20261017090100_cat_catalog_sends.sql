-- cat: the log of catalog messages a workspace sent (TW-CAT-014..016).
-- Why this migration exists: Reference's Activity tab and the "recent sends" strip of the Send tab read the catalog messages out of
-- the inbox message table (kind = catalog). That table belongs to the inbox domain and is a partitioned stream this domain must
-- not read or write, so the catalog send path records its own rows here. Each row is one attempt to one recipient, written in
-- the transaction of the send; when the inbox mirror lands (blocked on TIB), it is fed from the same rows.

CREATE TABLE cat_catalog_sends (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  recipient text NOT NULL,
  mode text NOT NULL,
  header text,
  body text,
  footer text,
  product_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  product_names jsonb NOT NULL DEFAULT '[]'::jsonb,
  status text NOT NULL,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_cat_catalog_sends_mode CHECK (mode IN ('spm', 'mpm', 'link')),
  CONSTRAINT chk_cat_catalog_sends_status CHECK (status IN ('sent', 'failed')),
  CONSTRAINT fk_cat_catalog_sends_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_cat_catalog_sends_recent ON cat_catalog_sends (org_id, id DESC);

ALTER TABLE cat_catalog_sends ENABLE ROW LEVEL SECURITY;
ALTER TABLE cat_catalog_sends FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON cat_catalog_sends FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_cat_catalog_sends_touch BEFORE UPDATE ON cat_catalog_sends
  FOR EACH ROW EXECUTE FUNCTION touch_row();
