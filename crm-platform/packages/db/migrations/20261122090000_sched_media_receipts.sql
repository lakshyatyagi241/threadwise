-- sched: uploaded media for a schedule, and the receipt lookup for Cloud API reports.
-- Why this migration exists (TW-SCHED-006, 024):
--   * A schedule's file used to be a link someone pasted. A file the person picks is now stored on the workspace's object storage and
--     recorded here (who, what, how big), so a schedule can only point at a file that workspace uploaded, the sender can check the size
--     and type against the number's channel, and the file is removed when no schedule uses it any more.
--   * A Cloud API delivery report names a message id and no tenant. `sched_receipt_lookup` says which workspace and which scheduled
--     recipient the id belongs to (the same narrow SECURITY DEFINER shape as `bcast_receipt_lookup`), so a delivered/read/failed report
--     reaches the schedule, and from there the wallet (a charge on delivery, a refund on failure).

-- A recurring schedule used to put every recipient back to "pending" the moment a run ended, which erased the message ids the provider's
-- later delivered/read/failed reports are matched by: the report of a delivery that lands after the run (the normal case on the Cloud
-- API) found nobody, so it was never charged. The reset now waits for the next run: this flag says the recipients of the last run are
-- spent and must start over when the next one begins.
ALTER TABLE scheduled_messages ADD COLUMN recipients_spent boolean NOT NULL DEFAULT false;

CREATE TABLE scheduled_media (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  storage_key text NOT NULL,
  file_name text NOT NULL,
  mime text NOT NULL,
  kind text NOT NULL,
  size_bytes integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_scheduled_media_storage_key UNIQUE (org_id, storage_key),
  CONSTRAINT chk_scheduled_media_kind CHECK (kind IN ('image', 'video', 'audio', 'document')),
  CONSTRAINT chk_scheduled_media_size CHECK (size_bytes > 0),
  CONSTRAINT fk_scheduled_media_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_scheduled_media_user_id ON scheduled_media (org_id, user_id);

ALTER TABLE scheduled_media ENABLE ROW LEVEL SECURITY;
ALTER TABLE scheduled_media FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON scheduled_media FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_scheduled_media_touch BEFORE UPDATE ON scheduled_media
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- A report arrives with a message id and nothing else; the lookup must not scan every workspace's recipients.
CREATE INDEX IF NOT EXISTS idx_scheduled_message_contacts_wa_message_id_any
  ON scheduled_message_contacts (wa_message_id) WHERE wa_message_id IS NOT NULL;

CREATE OR REPLACE FUNCTION sched_receipt_lookup(p_message_id text)
RETURNS TABLE (receipt_org_id bigint, receipt_scheduled_id bigint, receipt_recipient_id bigint)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT r.org_id, r.scheduled_message_id, r.id
    FROM scheduled_message_contacts r
    WHERE r.wa_message_id = p_message_id
    ORDER BY r.id DESC LIMIT 1;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION sched_receipt_lookup(text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION sched_receipt_lookup(text) TO crm_app_user;
  END IF;
END
$$;
