-- lsc: AI lead scoring for contacts. Not a Reference feature (Reference only stores a hand-typed lead_score), so there is no Reference table to mirror.
--
-- What it adds:
--   contacts.lead_score_source / lead_score_reasons / lead_scored_at / lead_score_model: who set the number and, for an AI score, why.
--       Source NULL on a row that has a score means it was typed by a person (every score that existed before this migration), so it is
--       never overwritten: the scorer only fills an empty score or refreshes one it wrote itself (source = 'ai').
--   lead_scoring_settings: one row per workspace, the workspace's own switch (opt-in: no row means off). Sending contact data to a
--       third-party model is a privacy decision, so it is never on by default.
--   lead_scoring_runs: the ledger. One row per scoring attempt (scored, failed or skipped) with the model, the tokens, the cost in USD
--       and who paid, so the screens can say what a score cost. Append-only; a daily retention sweep deletes old rows.
-- The platform switch and model live in platform_settings under `lead_scoring.config` (no table needed).

ALTER TABLE contacts
  ADD COLUMN lead_score_source text,
  ADD COLUMN lead_score_reasons jsonb,
  ADD COLUMN lead_scored_at timestamptz,
  ADD COLUMN lead_score_model text,
  ADD CONSTRAINT ck_contacts_lead_score_source CHECK (lead_score_source IS NULL OR lead_score_source IN ('manual', 'ai'));

-- The backfill and the "needs a score" sweep look for contacts the scorer may write to.
CREATE INDEX idx_contacts_lead_score_eligible ON contacts (org_id, id)
  WHERE lead_score IS NULL OR lead_score_source = 'ai';

-- ---------------------------------------------------------------------------------------------------------------------
-- lead_scoring_settings: the workspace's switch. No row means "off".
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE lead_scoring_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  enabled boolean NOT NULL DEFAULT false,
  -- Score a contact when it is created or its details change (off: only the backfill and the Score button).
  auto_score boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id)
);

ALTER TABLE lead_scoring_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_scoring_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_scoring_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_lead_scoring_settings_touch BEFORE UPDATE ON lead_scoring_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- ---------------------------------------------------------------------------------------------------------------------
-- lead_scoring_runs: one row per attempt, with what it cost.
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE lead_scoring_runs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  -- No FK to contacts on purpose: the cost history must outlive a deleted contact (the workspace still paid for it).
  contact_id bigint,
  contact_name text,
  -- ok: a score was written; kept: the model answered but the contact has a manual score; failed: no score; skipped: never sent.
  status text NOT NULL,
  -- created / updated / manual (the Score button) / backfill.
  trigger text NOT NULL,
  score smallint,
  previous_score smallint,
  reasons jsonb,
  model text,
  prompt_tokens integer NOT NULL DEFAULT 0,
  completion_tokens integer NOT NULL DEFAULT 0,
  -- USD, what the vendor charged for this call (its own figure when it reports one, else tokens x the price list). 0 when no call was made.
  cost_usd numeric(12,8) NOT NULL DEFAULT 0,
  -- 'vendor' (OpenRouter's reported cost), 'estimate' (tokens x list price) or 'none'.
  cost_source text NOT NULL DEFAULT 'none',
  -- Which side paid: the platform's key (admin) or the workspace's own key.
  billed_against text NOT NULL DEFAULT 'admin',
  duration_ms integer,
  error text,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT ck_lead_scoring_runs_status CHECK (status IN ('ok', 'kept', 'failed', 'skipped')),
  CONSTRAINT ck_lead_scoring_runs_trigger CHECK (trigger IN ('created', 'updated', 'manual', 'backfill')),
  CONSTRAINT ck_lead_scoring_runs_score CHECK (score IS NULL OR score BETWEEN 0 AND 100),
  CONSTRAINT ck_lead_scoring_runs_billed CHECK (billed_against IN ('admin', 'workspace', 'none')),
  CONSTRAINT ck_lead_scoring_runs_cost_source CHECK (cost_source IN ('vendor', 'estimate', 'none'))
);
CREATE INDEX idx_lead_scoring_runs_created ON lead_scoring_runs (org_id, created_at DESC);
CREATE INDEX idx_lead_scoring_runs_contact ON lead_scoring_runs (org_id, contact_id, created_at DESC) WHERE contact_id IS NOT NULL;
-- The retention sweep and the platform-wide cost totals read by time across workspaces.
CREATE INDEX idx_lead_scoring_runs_time ON lead_scoring_runs (created_at);

ALTER TABLE lead_scoring_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_scoring_runs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_scoring_runs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
