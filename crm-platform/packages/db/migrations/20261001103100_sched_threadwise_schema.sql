-- sched: scheduled-queue-warmer data model, ported from Reference
-- Why this migration exists: the tables Reference's scheduled queue warmer features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: scheduled_messages, scheduled_message_contacts, warmer_daily_sends

-- Reference `scheduled_messages` (tenant; 0 rows in the reference DB)
CREATE TABLE scheduled_messages (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  campaign_id bigint,
  user_id bigint,
  device_id bigint,
  schedule_name text NOT NULL,
  message_content text,
  template_id bigint,
  template_type text NOT NULL DEFAULT 'text',
  template_overrides jsonb,
  schedule_type text NOT NULL DEFAULT 'once',
  send_date date NOT NULL,
  send_time text NOT NULL,
  scheduled_time timestamptz NOT NULL,
  timezone text NOT NULL,
  repeat_interval text,
  repeat_every integer NOT NULL DEFAULT 1,
  days_of_week jsonb,
  end_date date,
  media_file text,
  latitude numeric(10,7),
  longitude numeric(10,7),
  recipient_type text NOT NULL,
  target_queues jsonb,
  target_groups jsonb,
  target_numbers jsonb,
  total_recipients integer NOT NULL DEFAULT 0,
  from_number text,
  node_schedule_id text,
  status text NOT NULL DEFAULT 'scheduled',
  send_attempts smallint NOT NULL DEFAULT 0,
  next_attempt_at timestamptz,
  last_error text,
  next_run_at timestamptz,
  last_run_at timestamptz,
  completed_at timestamptz,
  failed_at timestamptz,
  failure_reason text,
  total_sent integer NOT NULL DEFAULT 0,
  total_delivered integer NOT NULL DEFAULT 0,
  total_failed integer NOT NULL DEFAULT 0,
  charged_sent integer NOT NULL DEFAULT 0,
  provider text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_scheduled_messages_campaign_id FOREIGN KEY (org_id, campaign_id) REFERENCES wpcampaigns (org_id, id) ON DELETE SET NULL (campaign_id),
  CONSTRAINT fk_scheduled_messages_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id),
  CONSTRAINT fk_scheduled_messages_template_id FOREIGN KEY (org_id, template_id) REFERENCES wa_templates (org_id, id) ON DELETE SET NULL (template_id)
);
CREATE INDEX idx_scheduled_messages_campaign_id ON scheduled_messages (org_id, campaign_id);
CREATE INDEX idx_scheduled_messages_device_id ON scheduled_messages (org_id, device_id);
CREATE INDEX idx_scheduled_messages_next_run_at ON scheduled_messages (org_id, next_run_at);
CREATE INDEX idx_scheduled_messages_node_schedule_id ON scheduled_messages (org_id, node_schedule_id);
CREATE INDEX idx_scheduled_messages_provider ON scheduled_messages (org_id, provider);
CREATE INDEX idx_scheduled_messages_user_id ON scheduled_messages (org_id, user_id);
CREATE INDEX idx_scheduled_messages_schedule_type ON scheduled_messages (org_id, schedule_type);
CREATE INDEX idx_scheduled_messages_status_next_run_at ON scheduled_messages (org_id, status, next_run_at);

ALTER TABLE scheduled_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE scheduled_messages FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON scheduled_messages FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_scheduled_messages_touch BEFORE UPDATE ON scheduled_messages
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `scheduled_message_contacts` (child; 0 rows in the reference DB)
CREATE TABLE scheduled_message_contacts (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  scheduled_message_id bigint NOT NULL,
  contact_id bigint,
  phone text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  error_message text,
  wa_message_id text,
  sent_at timestamptz,
  delivered_at timestamptz,
  read_at timestamptz,
  failed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_scheduled_message_contacts_status CHECK (status IN ('pending', 'sent', 'delivered', 'read', 'failed')),
  CONSTRAINT fk_scheduled_message_contacts_scheduled_message_id FOREIGN KEY (org_id, scheduled_message_id) REFERENCES scheduled_messages (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_scheduled_message_contacts_contact_id FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id)
);
CREATE INDEX idx_scheduled_message_contacts_scheduled_message_id_phone ON scheduled_message_contacts (org_id, scheduled_message_id, phone);
CREATE INDEX idx_scheduled_message_contacts_scheduled_message_id_status ON scheduled_message_contacts (org_id, scheduled_message_id, status);
CREATE INDEX idx_scheduled_message_contacts_wa_message_id ON scheduled_message_contacts (org_id, wa_message_id);

ALTER TABLE scheduled_message_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE scheduled_message_contacts FORCE  ROW LEVEL SECURITY;
