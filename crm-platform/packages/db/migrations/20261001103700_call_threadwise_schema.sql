-- Bootstrap partitions (previous month, current, next two) and a catch-all so a gap in partition
-- maintenance degrades into rows landing in _default instead of failed writes. Add each parent to
-- PARTITIONED_TABLES in apps/api/src/workers/partition-maintenance.service.ts.
DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('wa_call_events', m);
  END LOOP;
END $$;
CREATE TABLE wa_call_events_default PARTITION OF wa_call_events DEFAULT;
