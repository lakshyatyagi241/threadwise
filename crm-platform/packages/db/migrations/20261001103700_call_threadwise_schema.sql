-- call: calling-voice data model, ported from Reference
-- Why this migration exists: the tables Reference's calling voice features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: ai_call_assistants, ai_call_assistant_tools, ai_call_logs, ai_voice_usage_daily, wa_calls, wa_call_events, wa_call_permissions

-- Reference `ai_call_assistants` (tenant; 0 rows in the reference DB)
CREATE TABLE ai_call_assistants (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint,
  name text NOT NULL,
  slug text NOT NULL,
  greeting_text text,
  status text NOT NULL DEFAULT 'draft',
  is_active boolean NOT NULL DEFAULT true,
  ai_provider text NOT NULL DEFAULT 'gemini',
  ai_model text NOT NULL DEFAULT 'gemini-2.5-flash-lite',
  ai_api_key_encrypted text,  -- encrypted
  ai_system_prompt text,
  knowledge_base_url text,
  natural_conciseness boolean NOT NULL DEFAULT true,
  voice_provider text NOT NULL DEFAULT 'elevenlabs',
  voice_api_key_encrypted text,  -- encrypted
  voice_id text,
  voice_settings_json jsonb,
  stt_provider text NOT NULL DEFAULT 'elevenlabs',
  stt_settings_json jsonb,
  record_agent boolean NOT NULL DEFAULT true,
  record_user boolean NOT NULL DEFAULT true,
  auto_logging boolean NOT NULL DEFAULT true,
  exit_keywords_json jsonb,
  last_greeting text,
  meta_json jsonb,
  device_ids jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_ai_call_assistants_slug UNIQUE (org_id, slug),
  CONSTRAINT fk_ai_call_assistants_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE SET NULL (user_id)
);
CREATE INDEX idx_ai_call_assistants_user_id ON ai_call_assistants (org_id, user_id);
CREATE INDEX idx_ai_call_assistants_is_active_status ON ai_call_assistants (org_id, is_active, status);

ALTER TABLE ai_call_assistants ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_call_assistants FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_call_assistants FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_ai_call_assistants_touch BEFORE UPDATE ON ai_call_assistants
  FOR EACH ROW EXECUTE FUNCTION touch_row();

