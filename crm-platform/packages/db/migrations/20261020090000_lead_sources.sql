-- lead: the lead pipeline's tables (docs/specs/email-channel-and-social-leads.md, L-01..L-05, L-12; EXT-LEAD).
--
-- Why new tables and not the ported `incoming_webhooks` / `incoming_webhook_events` (20261001102300): those carry WaDesk's generic hook
-- inspector (a plain-text token, a relay URL, a template-send config, a raw body capped at 64 KB, no idempotency key). A lead source needs
-- the token only as a hash, an idempotency key, a retention clock on the raw body, field mapping and owner rules, and it has to serve
-- connectors that have no URL at all (a marketplace portal pushes leads through the ingest port). The ported tables stay for the
-- integrations domain's own hook inspector.
--
--  1. lead_sources       one door into the pipeline (a webhook URL today; Meta lead forms, TikTok, LinkedIn and marketplace connectors
--                        later, `kind` + `provider_key` + `external_ref` are the room for them). The token is stored as a SHA-256 only.
--  2. lead_events        every delivery, stored before it is processed. UNIQUE (org, source, external_id) is the idempotency key. The
--                        raw payload is personal data: `payload_expires_at` is its retention clock and a worker sweep nulls it.
--  3. contact_attributions  append-only touches of a contact (platform, campaign, ad set, ad, form). One row per lead event, so a
--                        person who answers three ads has three rows: first touch is the earliest, latest touch the newest. A pair of
--                        columns on `contacts` would keep only two touches, would rewrite a row other domains lock on, and could not
--                        be reported on by campaign. `contacts.source` keeps working and is filled with the platform label.
--  4. lead_source_lookup()  the public hook arrives with a token and no tenant. Like waba_route_lookup it is a SECURITY DEFINER function
--                        returning ids only, because lifting row-level security in application code is not allowed.

CREATE TABLE lead_sources (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  kind text NOT NULL DEFAULT 'webhook',
  -- The platform label a lead of this source carries ("webhook", "meta", "indiamart"): the default for `contacts.source` and attribution.
  provider_key text,
  -- A connector's own reference (a marketplace installation id). No foreign key: the connector's tables belong to another domain.
  external_ref text,
  name text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  token_hash text,
  -- The last characters of the token, for "ends in ####": enough to tell two URLs apart, useless to guess from.
  token_hint text,
  token_rotated_at timestamptz,
  -- Optional shared secret a sender must put in the X-Webhook-Secret header. AES-GCM ciphertext (credentials key); never plain text.
  secret_enc text,
  -- Where the idempotency key lives in the payload ("lead.id"); when empty, a hash of the body is used.
  external_id_path text,
  field_mapping jsonb NOT NULL DEFAULT '{}'::jsonb,
  defaults jsonb NOT NULL DEFAULT '{}'::jsonb,
  raw_retention_days integer NOT NULL DEFAULT 30,
  -- Round-robin position. Bookkeeping: a write that touches only this and last_event_at does not bump row_version (see the trigger).
  rr_cursor bigint NOT NULL DEFAULT 0,
  last_event_at timestamptz,
  created_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_lead_sources_kind CHECK (kind IN ('webhook', 'meta_lead_ads', 'tiktok', 'linkedin', 'google_ads', 'connector')),
  CONSTRAINT chk_lead_sources_status CHECK (status IN ('active', 'paused')),
  CONSTRAINT chk_lead_sources_webhook_token CHECK (kind <> 'webhook' OR token_hash IS NOT NULL),
  CONSTRAINT chk_lead_sources_retention CHECK (raw_retention_days BETWEEN 1 AND 365),
  CONSTRAINT chk_lead_sources_mapping CHECK (jsonb_typeof(field_mapping) = 'object'),
  CONSTRAINT chk_lead_sources_defaults CHECK (jsonb_typeof(defaults) = 'object'),
  CONSTRAINT fk_lead_sources_created_by FOREIGN KEY (org_id, created_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (created_by)
);
CREATE UNIQUE INDEX uq_lead_sources_name ON lead_sources (org_id, lower(name));
-- The token is globally unique: the public hook finds the workspace by it.
CREATE UNIQUE INDEX uq_lead_sources_token_hash ON lead_sources (token_hash) WHERE token_hash IS NOT NULL;
CREATE INDEX idx_lead_sources_created_by ON lead_sources (org_id, created_by);
CREATE INDEX idx_lead_sources_external_ref ON lead_sources (org_id, external_ref) WHERE external_ref IS NOT NULL;

ALTER TABLE lead_sources ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_sources FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_sources FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- touch_row() for this table, except that the round-robin cursor and the last-event stamp do not bump row_version or updated_at:
-- every incoming lead moves them, and each would otherwise turn the editor's next save into a 409.
CREATE FUNCTION lead_sources_touch() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) - ARRAY['rr_cursor', 'last_event_at', 'updated_at', 'row_version'])
     = (to_jsonb(OLD) - ARRAY['rr_cursor', 'last_event_at', 'updated_at', 'row_version']) THEN
    NEW.updated_at := OLD.updated_at;
    NEW.row_version := OLD.row_version;
    RETURN NEW;
  END IF;
  NEW.updated_at := now();
  NEW.row_version := OLD.row_version + 1;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_lead_sources_touch BEFORE UPDATE ON lead_sources
  FOR EACH ROW EXECUTE FUNCTION lead_sources_touch();

CREATE TABLE lead_events (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  source_id bigint NOT NULL,
  external_id text NOT NULL,
  -- received = stored and being processed (a crash between the two leaves it here, and a retry picks it up).
  status text NOT NULL DEFAULT 'received',
  is_test boolean NOT NULL DEFAULT false,
  -- Why a lead is `needs_review` or `failed`: a stable code (no_contact_point, plan_limit_reached, ...), and the detail.
  reason text,
  error text,
  contact_id bigint,
  deal_id bigint,
  -- The normalised lead exactly as it came in ({ externalId, fields, attribution, raw }). Personal data: null once purged.
  payload jsonb,
  payload_expires_at timestamptz,
  payload_purged_at timestamptz,
  attempts integer NOT NULL DEFAULT 1,
  -- A second delivery of the same (source, external_id) is acknowledged and counted here; it never writes a second row.
  duplicate_count integer NOT NULL DEFAULT 0,
  last_duplicate_at timestamptz,
  received_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_lead_events_idempotency UNIQUE (org_id, source_id, external_id),
  CONSTRAINT chk_lead_events_status CHECK (status IN ('received', 'created', 'updated', 'duplicate', 'needs_review', 'failed')),
  CONSTRAINT chk_lead_events_external_id CHECK (length(external_id) BETWEEN 1 AND 255),
  CONSTRAINT fk_lead_events_source FOREIGN KEY (org_id, source_id)
    REFERENCES lead_sources (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_lead_events_contact FOREIGN KEY (org_id, contact_id)
    REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_lead_events_deal FOREIGN KEY (org_id, deal_id)
    REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id)
);
CREATE INDEX idx_lead_events_source_recent ON lead_events (org_id, source_id, created_at DESC, id DESC);
CREATE INDEX idx_lead_events_source_status ON lead_events (org_id, source_id, status, created_at DESC, id DESC);
CREATE INDEX idx_lead_events_contact ON lead_events (org_id, contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX idx_lead_events_deal ON lead_events (org_id, deal_id) WHERE deal_id IS NOT NULL;
-- The retention sweep: payloads still held, oldest expiry first.
CREATE INDEX idx_lead_events_payload_expiry ON lead_events (payload_expires_at) WHERE payload IS NOT NULL;

ALTER TABLE lead_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_events FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_events FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_lead_events_touch BEFORE UPDATE ON lead_events
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE contact_attributions (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  contact_id bigint NOT NULL,
  lead_event_id bigint,
  source_id bigint,
  platform text,
  -- What `contacts.source` was given for this touch (the platform label, else the lead source's name).
  source_label text NOT NULL,
  campaign text,
  adset text,
  ad text,
  form text,
  captured_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_contact_attributions_contact FOREIGN KEY (org_id, contact_id)
    REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_contact_attributions_lead_event FOREIGN KEY (org_id, lead_event_id)
    REFERENCES lead_events (org_id, id) ON DELETE SET NULL (lead_event_id),
  CONSTRAINT fk_contact_attributions_source FOREIGN KEY (org_id, source_id)
    REFERENCES lead_sources (org_id, id) ON DELETE SET NULL (source_id)
);
-- One touch per lead event: a retried event cannot attribute twice.
CREATE UNIQUE INDEX uq_contact_attributions_lead_event ON contact_attributions (org_id, lead_event_id) WHERE lead_event_id IS NOT NULL;
CREATE INDEX idx_contact_attributions_contact ON contact_attributions (org_id, contact_id, captured_at, id);
CREATE INDEX idx_contact_attributions_platform ON contact_attributions (org_id, platform, captured_at DESC);
CREATE INDEX idx_contact_attributions_source ON contact_attributions (org_id, source_id) WHERE source_id IS NOT NULL;

ALTER TABLE contact_attributions ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_attributions FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON contact_attributions FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- Append-only: what a touch says never changes. The links to a lead event and a source may be nulled (the foreign keys' own
-- `ON DELETE SET NULL` is an UPDATE), nothing else may move.
CREATE FUNCTION contact_attributions_append_only() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.contact_id, NEW.platform, NEW.source_label, NEW.campaign, NEW.adset, NEW.ad, NEW.form, NEW.captured_at)
     IS DISTINCT FROM
     (OLD.contact_id, OLD.platform, OLD.source_label, OLD.campaign, OLD.adset, OLD.ad, OLD.form, OLD.captured_at) THEN
    RAISE EXCEPTION 'contact_attributions is append-only' USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_contact_attributions_append_only BEFORE UPDATE ON contact_attributions
  FOR EACH ROW EXECUTE FUNCTION contact_attributions_append_only();

-- The public hook: token hash -> (workspace, source). Ids and a status only: never the secret, never the mapping.
CREATE OR REPLACE FUNCTION lead_source_lookup(p_token_hash text)
RETURNS TABLE (route_org_id bigint, route_source_id bigint, route_status text)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  prior text := current_setting('app.privileged', true);
BEGIN
  PERFORM set_config('app.privileged', 'on', true);
  RETURN QUERY
    SELECT s.org_id, s.id, s.status
    FROM lead_sources s
    WHERE s.token_hash = p_token_hash
    LIMIT 1;
  PERFORM set_config('app.privileged', coalesce(prior, 'off'), true);
END;
$$;

REVOKE ALL ON FUNCTION lead_source_lookup(text) FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'crm_app_user') THEN
    GRANT EXECUTE ON FUNCTION lead_source_lookup(text) TO crm_app_user;
  END IF;
END
$$;
