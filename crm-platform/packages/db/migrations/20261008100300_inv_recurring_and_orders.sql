-- inv: recurring invoices and sales orders (owner direction: small businesses that bill on a schedule or deliver in parts).
-- Why this migration exists:
--  * RECURRING. A schedule plus a template. The worker creates one invoice per period; the unique key (schedule, period index) on the
--    run history makes that idempotent: a retried or concurrent run cannot create two invoices for one period, and a crash between
--    "invoice created" and "schedule advanced" cannot happen because both are one transaction.
--  * SALES ORDERS. estimate -> order -> one or more invoices. Lines carry ordered / invoiced / fulfilled quantities, and the database
--    keeps them honest: invoiced and fulfilled can never exceed ordered, and once an order is confirmed its prices are frozen (only
--    the two progress quantities move). Voiding or deleting an invoice made from an order gives its quantities back (the service
--    does that in the same transaction; the CHECKs catch any path that would over- or under-shoot).

-- --- recurring invoices ---------------------------------------------------------------------------------------------------------------

CREATE TABLE recurring_invoices (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  name          text NOT NULL,
  status        text NOT NULL DEFAULT 'active',
  frequency     text NOT NULL,
  interval_n    integer NOT NULL DEFAULT 1,
  start_date    date NOT NULL,
  end_date      date,
  max_runs      integer,
  mode          text NOT NULL DEFAULT 'draft',
  send_channel  text NOT NULL DEFAULT 'email',
  -- the priced content of the next invoices: buyer, lines with their tax snapshots, discount, shipping, terms ...
  template      jsonb NOT NULL,
  contact_id    bigint,
  company_id    bigint,
  deal_id       bigint,
  owner_id      bigint,
  created_by    bigint,
  -- the index of the NEXT period to generate (0 = the start date) and its date; null date = nothing left to run
  next_index    integer NOT NULL DEFAULT 0,
  next_run_date date,
  run_count     integer NOT NULL DEFAULT 0,
  failure_count integer NOT NULL DEFAULT 0,
  last_run_at   timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_recurring_invoices_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_recurring_invoices_company FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_recurring_invoices_deal FOREIGN KEY (org_id, deal_id) REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id),
  CONSTRAINT fk_recurring_invoices_owner FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_id),
  CONSTRAINT fk_recurring_invoices_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_recurring_invoices_name CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT chk_recurring_invoices_status CHECK (status IN ('active', 'paused', 'ended')),
  CONSTRAINT chk_recurring_invoices_frequency CHECK (frequency IN ('day', 'week', 'month', 'year')),
  CONSTRAINT chk_recurring_invoices_interval CHECK (interval_n BETWEEN 1 AND 365),
  CONSTRAINT chk_recurring_invoices_mode CHECK (mode IN ('draft', 'issue', 'issue_send')),
  CONSTRAINT chk_recurring_invoices_channel CHECK (send_channel IN ('link', 'email', 'whatsapp')),
  CONSTRAINT chk_recurring_invoices_window CHECK (end_date IS NULL OR end_date >= start_date),
  CONSTRAINT chk_recurring_invoices_runs CHECK (max_runs IS NULL OR max_runs >= 1),
  CONSTRAINT chk_recurring_invoices_counters CHECK (next_index >= 0 AND run_count >= 0 AND failure_count >= 0),
  -- an ended schedule has nothing to run; a live one always knows its next date
  CONSTRAINT chk_recurring_invoices_next CHECK ((status = 'ended') = (next_run_date IS NULL))
);
CREATE INDEX idx_recurring_invoices_due ON recurring_invoices (next_run_date) WHERE status = 'active';
CREATE INDEX idx_recurring_invoices_list ON recurring_invoices (org_id, created_at DESC, id DESC);

CREATE TABLE recurring_invoice_runs (
  org_id       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  recurring_id bigint NOT NULL,
  period_index integer NOT NULL,
  period_date  date NOT NULL,
  status       text NOT NULL,
  invoice_id   bigint,
  error        text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  CONSTRAINT fk_recurring_runs_recurring FOREIGN KEY (org_id, recurring_id) REFERENCES recurring_invoices (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_recurring_runs_invoice FOREIGN KEY (org_id, invoice_id) REFERENCES invoices (org_id, id) ON DELETE SET NULL (invoice_id),
  -- the idempotency key of generation: one run per schedule and period
  CONSTRAINT uq_recurring_runs_period UNIQUE (org_id, recurring_id, period_index),
  CONSTRAINT chk_recurring_runs_status CHECK (status IN ('created', 'failed'))
);
CREATE INDEX idx_recurring_runs_list ON recurring_invoice_runs (org_id, recurring_id, period_index DESC);

ALTER TABLE invoices ADD COLUMN recurring_id bigint,
  ADD CONSTRAINT fk_invoices_recurring FOREIGN KEY (org_id, recurring_id) REFERENCES recurring_invoices (org_id, id) ON DELETE SET NULL (recurring_id);

-- --- sales orders ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE sales_orders (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  series          text NOT NULL,
  seq             integer NOT NULL,
  number          text NOT NULL,
  status          text NOT NULL DEFAULT 'draft',
  quote_id        bigint,
  contact_id      bigint,
  company_id      bigint,
  deal_id         bigint,
  owner_id        bigint,
  created_by      bigint,
  buyer_name      text,
  buyer_email     text,
  buyer_phone     text,
  currency        text NOT NULL,
  currency_exponent smallint NOT NULL DEFAULT 2,
  subtotal_minor  bigint NOT NULL DEFAULT 0,
  shipping_minor  bigint NOT NULL DEFAULT 0,
  tax_minor       bigint NOT NULL DEFAULT 0,
  tax_added_minor bigint NOT NULL DEFAULT 0,
  total_minor     bigint NOT NULL DEFAULT 0,
  -- shipping is billed once, with the first invoice
  shipping_invoiced boolean NOT NULL DEFAULT false,
  reference       text,
  expected_date   date,
  notes           text,
  terms           text,
  confirmed_at    timestamptz,
  cancelled_at    timestamptz,
  cancel_reason   text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_sales_orders_number UNIQUE (org_id, number),
  CONSTRAINT uq_sales_orders_series_seq UNIQUE (org_id, series, seq),
  CONSTRAINT fk_sales_orders_quote FOREIGN KEY (org_id, quote_id) REFERENCES sales_docs (org_id, id) ON DELETE SET NULL (quote_id),
  CONSTRAINT fk_sales_orders_contact FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE SET NULL (contact_id),
  CONSTRAINT fk_sales_orders_company FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL (company_id),
  CONSTRAINT fk_sales_orders_deal FOREIGN KEY (org_id, deal_id) REFERENCES deals (org_id, id) ON DELETE SET NULL (deal_id),
  CONSTRAINT fk_sales_orders_owner FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL (owner_id),
  CONSTRAINT fk_sales_orders_created_by FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_sales_orders_status CHECK (status IN ('draft', 'confirmed', 'cancelled', 'closed')),
  CONSTRAINT chk_sales_orders_currency CHECK (currency ~ '^[A-Z]{3}$' AND currency_exponent BETWEEN 0 AND 3),
  CONSTRAINT chk_sales_orders_totals CHECK (
    subtotal_minor >= 0 AND shipping_minor >= 0 AND tax_minor >= 0 AND tax_added_minor >= 0 AND tax_added_minor <= tax_minor
    AND total_minor = subtotal_minor + tax_added_minor + shipping_minor
  ),
  CONSTRAINT chk_sales_orders_stamps CHECK (
    (status <> 'cancelled' OR cancelled_at IS NOT NULL) AND (status NOT IN ('confirmed', 'closed') OR confirmed_at IS NOT NULL)
  )
);
-- an accepted offer becomes at most one live order
CREATE UNIQUE INDEX uq_sales_orders_quote ON sales_orders (org_id, quote_id) WHERE quote_id IS NOT NULL AND status <> 'cancelled';
CREATE INDEX idx_sales_orders_list ON sales_orders (org_id, created_at DESC, id DESC);
CREATE INDEX idx_sales_orders_contact ON sales_orders (org_id, contact_id) WHERE contact_id IS NOT NULL;
CREATE INDEX idx_sales_orders_deal ON sales_orders (org_id, deal_id) WHERE deal_id IS NOT NULL;

CREATE TABLE sales_order_items (
  org_id            bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid              uuid NOT NULL DEFAULT gen_random_uuid(),
  order_id          bigint NOT NULL,
  sort              smallint NOT NULL DEFAULT 0,
  description       text NOT NULL,
  sku               text,
  hsn_sac           text,
  qty               numeric(18,4) NOT NULL,
  qty_invoiced      numeric(18,4) NOT NULL DEFAULT 0,
  qty_fulfilled     numeric(18,4) NOT NULL DEFAULT 0,
  unit_price_minor  bigint NOT NULL DEFAULT 0,
  discount_kind     text NOT NULL DEFAULT 'none',
  discount_value    bigint NOT NULL DEFAULT 0,
  -- the part of an AMOUNT discount already billed (a partial invoice carries its share; the last one carries the rest, exactly)
  discount_invoiced_minor bigint NOT NULL DEFAULT 0,
  tax_rate_id       bigint,
  tax_name          text,
  tax_type          text,
  tax_inclusive     boolean NOT NULL DEFAULT false,
  -- [{ "code": "CGST", "name": "CGST 9%", "ratePercent": "9" }, ...]
  tax_items         jsonb,
  tax_rate_percent  numeric(7,4) NOT NULL DEFAULT 0,
  line_subtotal_minor bigint NOT NULL DEFAULT 0,
  line_discount_minor bigint NOT NULL DEFAULT 0,
  tax_amount_minor  bigint NOT NULL DEFAULT 0,
  line_total_minor  bigint NOT NULL DEFAULT 0,
  currency          text NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  row_version       integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT fk_sales_order_items_order FOREIGN KEY (org_id, order_id) REFERENCES sales_orders (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_sales_order_items_tax_rate FOREIGN KEY (org_id, tax_rate_id) REFERENCES tax_rates (org_id, id) ON DELETE SET NULL (tax_rate_id),
  CONSTRAINT uq_sales_order_items_sort UNIQUE (org_id, order_id, sort),
  CONSTRAINT chk_sales_order_items_qty CHECK (
    qty > 0 AND qty_invoiced >= 0 AND qty_fulfilled >= 0 AND qty_invoiced <= qty AND qty_fulfilled <= qty
  ),
  CONSTRAINT chk_sales_order_items_discount CHECK (
    discount_kind IN ('none', 'percent', 'amount') AND discount_value >= 0
    AND (discount_kind <> 'percent' OR discount_value <= 10000) AND (discount_kind <> 'none' OR discount_value = 0)
    AND discount_invoiced_minor >= 0 AND discount_invoiced_minor <= line_discount_minor
  ),
  CONSTRAINT chk_sales_order_items_money CHECK (
    unit_price_minor >= 0 AND line_subtotal_minor >= 0 AND line_discount_minor >= 0 AND line_discount_minor <= line_subtotal_minor
    AND tax_amount_minor >= 0 AND line_total_minor >= 0
    AND line_total_minor = line_subtotal_minor - line_discount_minor + CASE WHEN tax_inclusive THEN 0 ELSE tax_amount_minor END
  )
);
CREATE INDEX idx_sales_order_items_order ON sales_order_items (org_id, order_id, sort);

