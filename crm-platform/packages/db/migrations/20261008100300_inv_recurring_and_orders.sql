-- A confirmed order's prices are frozen; only the two progress quantities (and the billed part of an amount discount) move, and
-- lines cannot be added or removed once the order leaves draft.
CREATE FUNCTION sales_order_items_freeze() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  st text;
BEGIN
  SELECT status INTO st FROM sales_orders
   WHERE org_id = CASE WHEN TG_OP = 'DELETE' THEN OLD.org_id ELSE NEW.org_id END
     AND id = CASE WHEN TG_OP = 'DELETE' THEN OLD.order_id ELSE NEW.order_id END;
  IF st IS NULL OR st = 'draft' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;
  IF TG_OP <> 'UPDATE' THEN
    RAISE EXCEPTION 'the lines of a confirmed order cannot be added or removed' USING ERRCODE = '55000';
  END IF;
  IF (NEW.qty, NEW.unit_price_minor, NEW.discount_kind, NEW.discount_value, NEW.tax_rate_percent, NEW.tax_inclusive, NEW.description,
      NEW.line_subtotal_minor, NEW.line_discount_minor, NEW.tax_amount_minor, NEW.line_total_minor)
     IS DISTINCT FROM
     (OLD.qty, OLD.unit_price_minor, OLD.discount_kind, OLD.discount_value, OLD.tax_rate_percent, OLD.tax_inclusive, OLD.description,
      OLD.line_subtotal_minor, OLD.line_discount_minor, OLD.tax_amount_minor, OLD.line_total_minor)
  THEN
    RAISE EXCEPTION 'the prices of a confirmed order are frozen' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_sales_order_items_freeze BEFORE INSERT OR UPDATE OR DELETE ON sales_order_items
  FOR EACH ROW EXECUTE FUNCTION sales_order_items_freeze();

CREATE FUNCTION sales_orders_freeze() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'draft' THEN
    RETURN NEW;
  END IF;
  IF (NEW.currency, NEW.subtotal_minor, NEW.shipping_minor, NEW.tax_minor, NEW.tax_added_minor, NEW.total_minor, NEW.number)
     IS DISTINCT FROM
     (OLD.currency, OLD.subtotal_minor, OLD.shipping_minor, OLD.tax_minor, OLD.tax_added_minor, OLD.total_minor, OLD.number)
  THEN
    RAISE EXCEPTION 'a confirmed order is frozen: its number, currency and amounts cannot change' USING ERRCODE = '55000';
  END IF;
  IF OLD.status = 'cancelled' AND NEW.status <> 'cancelled' THEN
    RAISE EXCEPTION 'a cancelled order cannot be reopened' USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_sales_orders_freeze BEFORE UPDATE ON sales_orders
  FOR EACH ROW EXECUTE FUNCTION sales_orders_freeze();

