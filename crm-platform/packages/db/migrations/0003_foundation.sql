-- 0003_foundation
-- Tenants, staff users, teams, and RBAC v3.
--
-- Convention enforced from here on:
--   * every business table carries org_id (RLS predicate + future hash-partition key)
--   * composite PK (org_id, id) — the partition key must be part of every PK
--   * every FK is composite (org_id, x) -> (org_id, id), which makes a
--     cross-tenant reference structurally impossible rather than merely wrong
--   * internal bigint id, external uuid; only the uuid ever leaves the system

CREATE TABLE organizations (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid        uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  slug        text NOT NULL UNIQUE,
  name        text NOT NULL,
  status      text NOT NULL DEFAULT 'active',
  plan        text NOT NULL DEFAULT 'starter',
  -- 'standard' | 'whale'. Whales escalate to dedicated time-subpartitioned
  -- partitions instead of sharing the hash buckets.
  tier        text NOT NULL DEFAULT 'standard',
  settings    jsonb NOT NULL DEFAULT '{}',
  -- Bumped whenever any role/grant changes; the RBAC cache key includes it, so
  -- a permission change invalidates every cached grant set for the org at once.
  roles_version integer NOT NULL DEFAULT 1,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_org_tier CHECK (tier IN ('standard', 'whale'))
);

CREATE TABLE users (
  org_id       bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id           bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid         uuid NOT NULL DEFAULT gen_random_uuid(),
  email        citext NOT NULL,
  full_name    text NOT NULL,
  password_hash text,
  -- External IdP subject. Null today; populated the day SSO lands, with no
  -- schema change (ADR-0006).
  auth_subject text,
  status       text NOT NULL DEFAULT 'active',
  settings     jsonb NOT NULL DEFAULT '{}',
  row_version  integer NOT NULL DEFAULT 1,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, email)
);
CREATE INDEX idx_users_org_status ON users (org_id, status);

CREATE TABLE teams (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  name        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, name)
);

CREATE TABLE team_members (
  org_id  bigint NOT NULL,
  team_id bigint NOT NULL,
  user_id bigint NOT NULL,
  PRIMARY KEY (org_id, team_id, user_id),
  FOREIGN KEY (org_id, team_id) REFERENCES teams (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_team_members_user ON team_members (org_id, user_id);

-- Global capability registry. Not tenant-scoped: the set of things the
-- platform can do is a property of the platform, not of a customer.
CREATE TABLE permission_defs (
  key            text PRIMARY KEY,
  label          text NOT NULL,
  category       text NOT NULL,
  supports_scope boolean NOT NULL DEFAULT false
);

CREATE TABLE roles (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  name        text NOT NULL,
  -- 'admin' | 'manager' | 'agent' | 'readonly' for platform presets.
  -- NULL for an org-defined role.
  system_key  text,
  -- The Admin preset is immutable. Enforced by trigger below, not by the UI:
  -- an org that could edit Admin could lock itself out of its own tenant.
  is_locked   boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id, name)
);

CREATE TABLE user_roles (
  org_id  bigint NOT NULL,
  user_id bigint NOT NULL,
  role_id bigint NOT NULL,
  PRIMARY KEY (org_id, user_id, role_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, role_id) REFERENCES roles (org_id, id) ON DELETE CASCADE
);

CREATE TABLE role_grants (
  org_id         bigint NOT NULL,
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  role_id        bigint NOT NULL,
  permission_key text NOT NULL REFERENCES permission_defs (key),
  -- deny beats allow when the grants of multiple roles are merged
  effect         perm_effect NOT NULL DEFAULT 'allow',
  record_scope   record_scope NOT NULL DEFAULT 'all',
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, role_id, permission_key),
  FOREIGN KEY (org_id, role_id) REFERENCES roles (org_id, id) ON DELETE CASCADE
);

-- Display-ID generator. Claimed in batches of 100 by the application so a bulk
-- insert of 50k contacts does not serialise every row on one counter row.
CREATE TABLE sequence_counters (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  module_key    text NOT NULL,
  current_value bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (org_id, module_key)
);

-- --- Admin preset immutability -------------------------------------------
CREATE OR REPLACE FUNCTION protect_locked_role() RETURNS trigger
  LANGUAGE plpgsql AS $$
DECLARE
  locked boolean;
BEGIN
  SELECT r.is_locked INTO locked
  FROM roles r
  WHERE r.org_id = COALESCE(NEW.org_id, OLD.org_id)
    AND r.id     = COALESCE(NEW.role_id, OLD.role_id);

  IF locked THEN
    RAISE EXCEPTION 'role is locked: grants of a platform preset role cannot be modified'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN COALESCE(NEW, OLD);
END $$;

CREATE TRIGGER trg_role_grants_protect
  BEFORE INSERT OR UPDATE OR DELETE ON role_grants
  FOR EACH ROW EXECUTE FUNCTION protect_locked_role();

-- --- updated_at / row_version --------------------------------------------
CREATE TRIGGER trg_users_touch  BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_teams_touch  BEFORE UPDATE ON teams FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_roles_touch  BEFORE UPDATE ON roles FOR EACH ROW EXECUTE FUNCTION touch_row();
