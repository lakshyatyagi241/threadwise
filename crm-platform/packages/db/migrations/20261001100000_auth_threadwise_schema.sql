-- auth: auth-registration-security data model, ported from Reference
-- Why this migration exists: the tables Reference's auth registration security features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: user_settings

-- Reference `user_settings` (tenant; 0 rows in the reference DB)
CREATE TABLE user_settings (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL,
  address text,
  city text,
  state text,
  country text,
  zip text,
  country_code text,
  notes text,
  welcome_email_sent_at timestamptz,
  auto_ai_summarize_enabled boolean NOT NULL DEFAULT false,
  inbox_last_seen_at timestamptz,
  quick_access jsonb,
  has_seen_intro boolean NOT NULL DEFAULT false,
  sheets_key_hash text,
  sheets_key_suffix text,
  sheets_key_created_at timestamptz,
  sheets_key_last_used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_user_settings_user_id UNIQUE (org_id, user_id),
  CONSTRAINT fk_user_settings_user_id FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_user_settings_sheets_key_hash ON user_settings (org_id, sheets_key_hash);

ALTER TABLE user_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON user_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_user_settings_touch BEFORE UPDATE ON user_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();
