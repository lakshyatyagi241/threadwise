-- Auto-assignment of contacts and deals (BL-013, BL-112 phase 3, docs/specs/contact-owner-leave-and-delegation.md section 10).
--
-- Priority-ordered rules give a NEW contact or deal without an owner to somebody: a fixed person, or a rotation (round robin, least busy)
-- over people and teams, skipping people on leave (and optionally offline ones). The workspace switch is OFF by default. A rule never
-- replaces an owner somebody set: the engine only writes where `owner IS NULL AND owner_changed_at IS NULL`, so even a person who
-- deliberately cleared the owner right after creating the record is not overruled.

CREATE TABLE assignment_settings (
  org_id           bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid             uuid NOT NULL DEFAULT gen_random_uuid(),
  enabled          boolean NOT NULL DEFAULT false,
  -- Contacts that arrive through an import are assigned only when asked for (an import that raises no events is never assigned).
  apply_to_imports boolean NOT NULL DEFAULT false,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  row_version      integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (org_id)
);
ALTER TABLE assignment_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE assignment_settings FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON assignment_settings FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_assignment_settings_touch BEFORE UPDATE ON assignment_settings
  FOR EACH ROW EXECUTE FUNCTION touch_row();

CREATE TABLE assignment_rules (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid          uuid NOT NULL DEFAULT gen_random_uuid(),
  name          text NOT NULL,
  subject       text NOT NULL,
  conditions    jsonb NOT NULL DEFAULT '{}'::jsonb,
  strategy      text NOT NULL,
  -- uuids of the people and teams the rule hands work to (kept as uuids like routing_rules: they are validated on write and
  -- re-validated on use, a removed member simply stops being a candidate).
  user_ids      jsonb NOT NULL DEFAULT '[]'::jsonb,
  team_ids      jsonb NOT NULL DEFAULT '[]'::jsonb,
  skip_offline  boolean NOT NULL DEFAULT true,
  -- The last person who took a turn (internal user id): the rotation continues after them whoever joins or leaves the pool.
  rr_cursor     bigint,
  sort          integer NOT NULL DEFAULT 0,
  is_active     boolean NOT NULL DEFAULT true,
  fired_count   bigint NOT NULL DEFAULT 0,
  last_fired_at timestamptz,
  created_by    bigint,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE SET NULL (created_by),
  CONSTRAINT chk_assignment_rules_subject CHECK (subject IN ('contact', 'deal')),
  CONSTRAINT chk_assignment_rules_strategy CHECK (strategy IN ('fixed', 'round_robin', 'least_busy')),
  CONSTRAINT chk_assignment_rules_name CHECK (char_length(name) BETWEEN 1 AND 120)
);
CREATE INDEX idx_assignment_rules_order ON assignment_rules (org_id, subject, sort, id);
ALTER TABLE assignment_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE assignment_rules FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON assignment_rules FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_assignment_rules_touch BEFORE UPDATE ON assignment_rules
  FOR EACH ROW EXECUTE FUNCTION touch_row();

