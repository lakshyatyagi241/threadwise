-- aiadm: ai-keys-usage-admin data model, ported from Reference
-- Why this migration exists: the tables Reference's ai keys usage admin features read and write, translated to this
-- repo's tenancy shape (org_id first, composite FKs, forced RLS, hard delete, touch_row) so the port starts from a
-- complete schema instead of each feature inventing its own. Translation rules and every judgement call:
-- docs/threadwise-port/schema/README.md and docs/threadwise-port/schema/decisions.toml.
--
-- Tables: admin_ai_keys, ai_provider_keys, ai_token_usage

-- Reference `admin_ai_keys` (platform_only; 6 rows in the reference DB)
CREATE TABLE admin_ai_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  provider text NOT NULL,
  name text NOT NULL,
  api_key text,  -- encrypted
  default_model text,
  extra_config text,
  is_active boolean NOT NULL DEFAULT false,
  sort_order smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_admin_ai_keys_provider UNIQUE (provider)
);

ALTER TABLE admin_ai_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_ai_keys FORCE  ROW LEVEL SECURITY;
CREATE POLICY operator_write ON admin_ai_keys FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
CREATE TRIGGER trg_admin_ai_keys_touch BEFORE UPDATE ON admin_ai_keys
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `ai_provider_keys` (tenant; 0 rows in the reference DB)
CREATE TABLE ai_provider_keys (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  provider text NOT NULL,
  api_key text NOT NULL,  -- encrypted
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT uq_ai_provider_keys_provider UNIQUE (org_id, provider)
);

ALTER TABLE ai_provider_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_provider_keys FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_provider_keys FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_ai_provider_keys_touch BEFORE UPDATE ON ai_provider_keys
  FOR EACH ROW EXECUTE FUNCTION touch_row();

-- Reference `ai_token_usage` (stream; 0 rows in the reference DB)
CREATE SEQUENCE ai_token_usage_id_seq;
CREATE TABLE ai_token_usage (
  id bigint NOT NULL DEFAULT nextval('ai_token_usage_id_seq'),
  org_id bigint NOT NULL,
  provider text NOT NULL,
  model text,
  prompt_tokens integer NOT NULL DEFAULT 0,
  completion_tokens integer NOT NULL DEFAULT 0,
  total_tokens integer NOT NULL DEFAULT 0,
  billed_against text NOT NULL DEFAULT 'admin',
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);
CREATE INDEX idx_ai_token_usage_created_at ON ai_token_usage (org_id, created_at);

ALTER TABLE ai_token_usage ENABLE ROW LEVEL SECURITY;
ALTER TABLE ai_token_usage FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON ai_token_usage FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());

-- Bootstrap partitions (previous month, current, next two) and a catch-all so a gap in partition
-- maintenance degrades into rows landing in _default instead of failed writes. Add each parent to
-- PARTITIONED_TABLES in apps/api/src/workers/partition-maintenance.service.ts.
DO $$
DECLARE
  m date;
BEGIN
  FOR m IN
    SELECT generate_series(date_trunc('month', now() - interval '1 month'),
      date_trunc('month', now() + interval '2 months'), interval '1 month')::date
  LOOP
    PERFORM ensure_monthly_partition('ai_token_usage', m);
  END LOOP;
END $$;
CREATE TABLE ai_token_usage_default PARTITION OF ai_token_usage DEFAULT;
