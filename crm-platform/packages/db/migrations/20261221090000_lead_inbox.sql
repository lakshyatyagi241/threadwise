-- lead: the lead inbox and pulling (BL-014, spec L-17, L-18).
--
--  1. Two indexes on lead_events for the inbox, which lists every source's deliveries in one list, newest received first. The existing
--     indexes all start with (org_id, source_id) and serve one source's own list. The second is partial: "needs attention" is the view
--     people open first, and it is a small slice of a large table.
--  2. lead_sync_runs: one row per "Sync now" or backfill of a pull-capable source. It is the progress the screen shows, the audit of who
--     asked, and the guard that lets only one run per source be queued or running at a time (a partial unique index, not a check in code).

CREATE INDEX idx_lead_events_org_received ON lead_events (org_id, received_at DESC, id DESC);
CREATE INDEX idx_lead_events_org_attention ON lead_events (org_id, received_at DESC, id DESC)
  WHERE status IN ('needs_review', 'failed');

CREATE TABLE lead_sync_runs (
  org_id bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid(),
  source_id bigint NOT NULL,
  kind text NOT NULL,
  status text NOT NULL DEFAULT 'queued',
  -- A backfill's range; both null for "sync now" (everything since the source's last poll).
  range_from timestamptz,
  range_to timestamptz,
  fetched integer NOT NULL DEFAULT 0,
  accepted integer NOT NULL DEFAULT 0,
  duplicates integer NOT NULL DEFAULT 0,
  failed integer NOT NULL DEFAULT 0,
  windows_done integer NOT NULL DEFAULT 0,
  windows_total integer NOT NULL DEFAULT 0,
  -- A stable code (too_soon, provider_error, credentials_refused, interrupted, ...). Never text from the provider.
  error text,
  requested_by bigint,
  started_at timestamptz,
  -- Moved on every progress report; a running row that stops moving was abandoned by a dead worker.
  heartbeat_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  CONSTRAINT chk_lead_sync_runs_kind CHECK (kind IN ('sync', 'backfill')),
  CONSTRAINT chk_lead_sync_runs_status CHECK (status IN ('queued', 'running', 'done', 'partial', 'failed')),
  CONSTRAINT chk_lead_sync_runs_range CHECK (
    (kind = 'sync' AND range_from IS NULL AND range_to IS NULL)
    OR (kind = 'backfill' AND range_from IS NOT NULL AND range_to IS NOT NULL AND range_from < range_to)),
  CONSTRAINT fk_lead_sync_runs_source FOREIGN KEY (org_id, source_id)
    REFERENCES lead_sources (org_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_lead_sync_runs_requested_by FOREIGN KEY (org_id, requested_by)
    REFERENCES users (org_id, id) ON DELETE SET NULL (requested_by)
);
-- One at a time per source.
CREATE UNIQUE INDEX uq_lead_sync_runs_active ON lead_sync_runs (org_id, source_id)
  WHERE status IN ('queued', 'running');
CREATE INDEX idx_lead_sync_runs_source ON lead_sync_runs (org_id, source_id, created_at DESC, id DESC);
CREATE INDEX idx_lead_sync_runs_requested_by ON lead_sync_runs (org_id, requested_by) WHERE requested_by IS NOT NULL;
-- The sweep that frees abandoned runs and prunes old ones, across workspaces.
CREATE INDEX idx_lead_sync_runs_open ON lead_sync_runs (heartbeat_at) WHERE status IN ('queued', 'running');
CREATE INDEX idx_lead_sync_runs_finished ON lead_sync_runs (finished_at) WHERE finished_at IS NOT NULL;

ALTER TABLE lead_sync_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE lead_sync_runs FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON lead_sync_runs FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_lead_sync_runs_touch BEFORE UPDATE ON lead_sync_runs
  FOR EACH ROW EXECUTE FUNCTION touch_row();
