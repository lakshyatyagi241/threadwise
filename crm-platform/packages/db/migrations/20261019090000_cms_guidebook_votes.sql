-- cms: the in-app guidebook counts views and helpfulness votes, and an operator-edited article must not be disturbed by it.
--
-- 1. guidebook_votes. WaDesk kept two bare counters, so one person could vote without limit and never change a vote. Here a
--    vote is a row per (workspace, user, article); the counters on the article stay as the cheap thing the admin list reads.
--    The row is tenant data (org_id, forced RLS, composite FK to the user), the article itself stays platform data.
--
-- 2. cms_guidebook_view() / cms_guidebook_vote(). A signed-in workspace user cannot write the platform article row, so the
--    counters move through two tiny SECURITY-style functions that carry the privileged flag for their own body only (the
--    same device as cms_record_blog_view). Each does exactly one thing: move a counter on a PUBLISHED article.
--
-- 3. The touch trigger no longer fires for a counter-only update, so a page view or a vote does not move `updated_at` (shown
--    to readers as "updated") or `row_version` (an editor saving the article would get a spurious conflict). WaDesk's
--    increment most likely refreshed updated_at on every view; this is a deliberate fix.

CREATE TABLE guidebook_votes (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  article_id  bigint NOT NULL REFERENCES guidebook_articles (id) ON DELETE CASCADE,
  user_id     bigint NOT NULL,
  vote        text   NOT NULL CHECK (vote IN ('helpful', 'not_helpful')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, article_id, user_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_guidebook_votes_article ON guidebook_votes (article_id);

ALTER TABLE guidebook_votes ENABLE ROW LEVEL SECURITY;
ALTER TABLE guidebook_votes FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON guidebook_votes FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
CREATE TRIGGER trg_guidebook_votes_touch BEFORE UPDATE ON guidebook_votes
  FOR EACH ROW EXECUTE FUNCTION touch_row();

DROP TRIGGER IF EXISTS trg_guidebook_articles_touch ON guidebook_articles;
CREATE TRIGGER trg_guidebook_articles_touch BEFORE UPDATE ON guidebook_articles
  FOR EACH ROW WHEN (
    OLD.views_count IS NOT DISTINCT FROM NEW.views_count
    AND OLD.helpful_count IS NOT DISTINCT FROM NEW.helpful_count
    AND OLD.not_helpful_count IS NOT DISTINCT FROM NEW.not_helpful_count
  )
  EXECUTE FUNCTION touch_row();

CREATE OR REPLACE FUNCTION cms_guidebook_view(p_slug text) RETURNS void
  LANGUAGE sql
  SET app.privileged = 'on'
  SET search_path = public, pg_temp
AS $$
  UPDATE guidebook_articles SET views_count = views_count + 1 WHERE slug = p_slug AND is_published;
$$;

-- p_old is the user's previous vote (null for a first vote), p_new the vote now in force.
CREATE OR REPLACE FUNCTION cms_guidebook_vote(p_article bigint, p_old text, p_new text) RETURNS void
  LANGUAGE sql
  SET app.privileged = 'on'
  SET search_path = public, pg_temp
AS $$
  UPDATE guidebook_articles
  SET helpful_count = greatest(0, helpful_count + (p_new = 'helpful')::int - (p_old = 'helpful')::int),
      not_helpful_count = greatest(0, not_helpful_count + (p_new = 'not_helpful')::int - (p_old = 'not_helpful')::int)
  WHERE id = p_article AND is_published;
$$;

REVOKE ALL ON FUNCTION cms_guidebook_view(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION cms_guidebook_vote(bigint, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION cms_guidebook_view(text) TO crm_app, crm_worker;
GRANT EXECUTE ON FUNCTION cms_guidebook_vote(bigint, text, text) TO crm_app, crm_worker;
