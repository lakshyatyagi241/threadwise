-- Passkeys (WebAuthn) as a phishing-resistant second factor, for workspace staff and for platform operators.
--
-- A passkey is only ever an ADDITIONAL second factor next to TOTP: it can be added once two-factor is on (so recovery codes
-- exist), it is offered at the second-factor step of sign-in, and turning two-factor off removes the person's passkeys.
-- The public key and a signature counter are all that is stored; the private key never leaves the authenticator.

CREATE TABLE webauthn_credentials (
  org_id         bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id             bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid           uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id        bigint NOT NULL,
  -- base64url credential id, as the browser reports it. Globally unique: one credential belongs to one account.
  credential_id  text NOT NULL,
  -- COSE public key, as stored by the authenticator's registration.
  public_key     bytea NOT NULL,
  -- Signature counter. A value that does not increase marks a cloned authenticator.
  counter        bigint NOT NULL DEFAULT 0,
  transports     text[] NOT NULL DEFAULT '{}',
  device_type    text NOT NULL,
  backed_up      boolean NOT NULL DEFAULT false,
  -- The label the person gave it ("YubiKey", "Work laptop").
  name           text NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  last_used_at   timestamptz,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  UNIQUE (credential_id),
  FOREIGN KEY (org_id, user_id) REFERENCES users (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_webauthn_credentials_device CHECK (device_type IN ('singleDevice', 'multiDevice')),
  CONSTRAINT chk_webauthn_credentials_name CHECK (char_length(name) BETWEEN 1 AND 60)
);
CREATE INDEX idx_webauthn_credentials_user ON webauthn_credentials (org_id, user_id);

ALTER TABLE webauthn_credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE webauthn_credentials FORCE  ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON webauthn_credentials FOR ALL
  USING      (org_id = current_org_id() OR app_is_privileged())
  WITH CHECK (org_id = current_org_id() OR app_is_privileged());
GRANT SELECT, INSERT, UPDATE, DELETE ON webauthn_credentials TO crm_app, crm_worker;

-- Platform operators have no organization: same shape, privileged access only (like platform_sessions).
CREATE TABLE platform_webauthn_credentials (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid           uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  operator_id    bigint NOT NULL REFERENCES platform_operators (id) ON DELETE CASCADE,
  credential_id  text NOT NULL UNIQUE,
  public_key     bytea NOT NULL,
  counter        bigint NOT NULL DEFAULT 0,
  transports     text[] NOT NULL DEFAULT '{}',
  device_type    text NOT NULL,
  backed_up      boolean NOT NULL DEFAULT false,
  name           text NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  last_used_at   timestamptz,
  CONSTRAINT chk_platform_webauthn_device CHECK (device_type IN ('singleDevice', 'multiDevice')),
  CONSTRAINT chk_platform_webauthn_name CHECK (char_length(name) BETWEEN 1 AND 60)
);
CREATE INDEX idx_platform_webauthn_operator ON platform_webauthn_credentials (operator_id);

ALTER TABLE platform_webauthn_credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE platform_webauthn_credentials FORCE  ROW LEVEL SECURITY;
CREATE POLICY privileged_only ON platform_webauthn_credentials FOR ALL
  USING      (app_is_privileged())
  WITH CHECK (app_is_privileged());
GRANT SELECT, INSERT, UPDATE, DELETE ON platform_webauthn_credentials TO crm_app, crm_worker;
