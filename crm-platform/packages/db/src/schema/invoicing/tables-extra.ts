export const creditNotes = pgTable(
  'credit_notes',
  {
    orgId: orgIdColumn(),
    id: idColumn('id').notNull().generatedByDefaultAsIdentity(),
    uuid: uuid('uuid').notNull().defaultRandom(),
    invoiceId: idColumn('invoice_id').notNull(),
    series: text('series'),
    creditNumber: text('credit_number'),
    seq: integer('seq'),
    status: text('status').notNull().default('draft'),
    reason: text('reason').notNull(),
    note: text('note'),
    settlement: text('settlement').notNull().default('balance'),
    currency: text('currency').notNull(),
    currencyExponent: smallint('currency_exponent').notNull().default(2),
    subtotalMinor: bigint('subtotal_minor', { mode: 'number' }).notNull().default(0),
    taxMinor: bigint('tax_minor', { mode: 'number' }).notNull().default(0),
    taxAddedMinor: bigint('tax_added_minor', { mode: 'number' }).notNull().default(0),
    totalMinor: bigint('total_minor', { mode: 'number' }).notNull().default(0),
    refundedMinor: bigint('refunded_minor', { mode: 'number' }).notNull().default(0),
    taxSummary: jsonb('tax_summary'),
    issueDate: date('issue_date'),
    issuedAt: timestamp('issued_at', { withTimezone: true }),
    voidedAt: timestamp('voided_at', { withTimezone: true }),
    voidReason: text('void_reason'),
    createdBy: idColumn('created_by'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    rowVersion: rowVersion(),
  },
  (t) => [
    primaryKey({ columns: [t.orgId, t.id] }),
    unique('uq_credit_notes_org_id_uuid').on(t.orgId, t.uuid),
    unique('uq_credit_notes_number').on(t.orgId, t.creditNumber),
    unique('uq_credit_notes_series_seq').on(t.orgId, t.series, t.seq),
    foreignKey({ name: 'fk_credit_notes_org', columns: [t.orgId], foreignColumns: [organizations.id] }).onDelete('cascade'),
    foreignKey({
      name: 'fk_credit_notes_invoice',
      columns: [t.orgId, t.invoiceId],
      foreignColumns: [invoices.orgId, invoices.id],
    }),
    foreignKey({
      name: 'fk_credit_notes_created_by',
      columns: [t.orgId, t.createdBy],
      foreignColumns: [users.orgId, users.id],
    }).onDelete('set null'),
    index('idx_credit_notes_invoice').on(t.orgId, t.invoiceId),
    index('idx_credit_notes_list').on(t.orgId, t.createdAt, t.id),
  ],
);
export type CreditNotesRow = typeof creditNotes.$inferSelect;

