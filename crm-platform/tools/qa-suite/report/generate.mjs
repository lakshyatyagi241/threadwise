#!/usr/bin/env node
// Per-task QA reports: one self-contained HTML (and optionally PDF) per task, from a fresh `pnpm qa` run.
//
//   pnpm qa:reports                      run tasks 30 31 36 40 41, write docs/quality/qa-reports/qa-<n>-<name>.html and an index README.md
//   pnpm qa:reports -- --pdf             also print each report to PDF with headless Chrome (CHROME_PATH, or the usual macOS/Linux install)
//   pnpm qa:reports -- --no-run          reuse reports/qa-suite/latest/results.json instead of running the checks again
//   pnpm qa:reports -- --out <dir>       write somewhere else
//   pnpm qa:reports -- --tasks 36,40     only those tasks
//
// Live checks (API_URL, WEB_URL, DATABASE_URL, QA_*) are passed through to `pnpm qa` if you set them; without them they show as skipped.
// The run asks for the full evidence lists (QA_MAX_EVIDENCE) so the appendices are complete, not cut at the runner's default of 40.

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUILDERS, REPORT_TASKS } from './builders.mjs';
import { page } from './render.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '../../..');
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const flag = (name) => process.argv.includes(name);

const readJson = (p, fallback) => {
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch {
    return fallback;
  }
};

/** Build every wanted report from a results object. Pure: returns [{ id, name, file, html, verdict }]. */
export function buildReports({ results, baseline, sinkReview, only }) {
  const out = [];
  for (const task of results.results) {
    const id = task.task.id;
    if (!BUILDERS[id] || (only && !only.includes(id))) continue;
    const built = BUILDERS[id]({ task, baseline, sinkReview });
    out.push({
      id,
      name: built.title,
      file: `qa-${id}-${built.slug}`,
      verdict: built.verdictHtml.replace(/<br>[\s\S]*$/, '').replace(/<[^>]+>/g, ''),
      html: page({ task, meta: results.meta, ...built }),
    });
  }
  return out;
}

export function indexMarkdown(reports, meta) {
  const rows = reports
    .map(
      (r) =>
        `| ${r.id}   | ${r.name}: [HTML](${r.file}.html) · [PDF](${r.file}.pdf) | ${r.verdict} |`,
    )
    .join('\n');
  return `# QA task reports

One report per QA task, each self-contained (HTML to read, PDF to share). Generated by \`pnpm qa:reports\` from \`pnpm qa\` on commit \`${meta.commit}\`
(${String(meta.generatedAt).slice(0, 10)}). A check that needs a running stack and was not given one shows as skipped and is never counted as a pass.
Regenerate any time with \`pnpm qa:reports\` (add \`-- --pdf\` for the PDFs); the live \`pnpm qa\` output is git-ignored (\`reports/qa-suite/\`), so these files are the durable record.

| Task | Report | Verdict at this commit |
| ---- | ------ | ---------------------- |
${rows}
`;
}

function chromePath() {
  const candidates = [
    process.env.CHROME_PATH,
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium',
    '/usr/bin/chromium-browser',
  ].filter(Boolean);
  return candidates.find((c) => existsSync(c));
}

function printPdf(chrome, htmlPath, pdfPath) {
  // Chrome prints a closed <details> as closed; open them so the appendices are in the PDF.
  const tmp = join(tmpdir(), `qa-report-${process.pid}-${Date.now()}.html`);
  writeFileSync(tmp, readFileSync(htmlPath, 'utf8').replaceAll('<details>', '<details open>'));
  const r = spawnSync(
    chrome,
    [
      '--headless',
      '--disable-gpu',
      '--no-pdf-header-footer',
      `--print-to-pdf=${pdfPath}`,
      `file://${tmp}`,
    ],
    { stdio: 'ignore' },
  );
  rmSync(tmp, { force: true });
  return r.status === 0 && existsSync(pdfPath);
}

async function main() {
  const tasks = (arg('--tasks') ?? REPORT_TASKS.join(',')).split(',').map(Number).filter(Boolean);
  const outDir = resolve(ROOT, arg('--out') ?? 'docs/quality/qa-reports');

  if (!flag('--no-run')) {
    console.log(`Running pnpm qa for tasks ${tasks.join(' ')} ...`);
    const r = spawnSync(
      process.execPath,
      [join(ROOT, 'tools/qa-suite/run.mjs'), ...tasks.map(String)],
      {
        cwd: ROOT,
        stdio: 'inherit',
        env: { ...process.env, QA_MAX_EVIDENCE: process.env.QA_MAX_EVIDENCE ?? '100000' },
      },
    );
    if (r.status !== 0) {
      console.error('pnpm qa failed to run; no reports written.');
      process.exit(r.status ?? 1);
    }
  }

  const results = readJson(join(ROOT, 'reports/qa-suite/latest/results.json'));
  if (!results) {
    console.error('No reports/qa-suite/latest/results.json. Run without --no-run first.');
    process.exit(1);
  }
  const reports = buildReports({
    results,
    baseline: readJson(join(ROOT, 'tools/qa-suite/data/baseline.json'), {}),
    sinkReview: readJson(join(ROOT, 'tools/qa-suite/data/xss-sink-review.json'), []),
    only: tasks,
  });
  if (reports.length === 0) {
    console.error(
      `None of tasks ${tasks.join(', ')} has a report builder (have: ${REPORT_TASKS.join(', ')}).`,
    );
    process.exit(1);
  }

  mkdirSync(outDir, { recursive: true });
  const chrome = flag('--pdf') ? chromePath() : undefined;
  if (flag('--pdf') && !chrome)
    console.warn('No Chrome found for --pdf (set CHROME_PATH); writing HTML only.');
  for (const r of reports) {
    const htmlPath = join(outDir, `${r.file}.html`);
    writeFileSync(htmlPath, r.html);
    const pdf = chrome ? printPdf(chrome, htmlPath, join(outDir, `${r.file}.pdf`)) : false;
    console.log(`wrote ${r.file}.html${pdf ? ' + .pdf' : ''}: ${r.verdict}`);
  }
  writeFileSync(join(outDir, 'README.md'), indexMarkdown(reports, results.meta));
  console.log(`index: ${join(outDir, 'README.md')}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
