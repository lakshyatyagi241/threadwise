-- PROPOSAL P2 (NOT APPLIED, NOT in packages/db, NOT approved): homes for the parts of Waboo's `credits_mapping_new` that no table of
-- crm-platform can hold. TEXT ONLY: the migration tool never runs this file.
--
-- What has a home already (the `pricing-seed` command writes it): the WhatsApp price per country and category -> `message_rates`.
-- What has NONE, and is therefore counted as NOT PRESENT in every report (iskm: 147 country documents, of which about 142 carry them):
--   * email price and margin per country   (`email: {price, margin}`)
--   * SMS price and margin per country     (`sms: {price, margin}`)
--   * dial code, short name and country name (`dial_code`, `short_name`, `name`); the app keeps the dial prefix -> ISO country map in
--     code (apps/api/src/modules/wallet-message-billing/phone-country.ts), there is no `countries` table
--   * the AI model price list              (`models[]`: name, provider, input / output / cached token price, currency, unit). Each
--     element also carries provider API keys (`openRouterKey`, `normalKey`): those are NEVER read by the tool and must not be stored
--   * the WhatsApp `margin` of a category: Waboo's unit is unknown (a percentage or an absolute amount per message, OQ-4b). Ours is
--     basis points on top of Meta's cost (`plan_message_margins`), so it is not applied until someone confirms what Waboo meant
--
-- Who decides: the manager, and only if email / SMS billing or per-model AI pricing is on the roadmap. Nothing in the product reads
-- these values today, so adding the tables just to hold history is NOT recommended (recommendation: leave them in the raw archive).
-- Who writes the real migration: someone running the `add-migration` skill in crm-platform (a numbered file in packages/db/migrations
-- plus the Drizzle tables). All three tables below are GLOBAL platform tables, shaped like `message_rates`: everyone reads, only a
-- privileged session writes.

-- 1. email / SMS price per country (global rate card for the channels the product does not send yet)
CREATE TABLE channel_message_rates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  channel text NOT NULL,                    -- 'email' | 'sms'
  country_code text NOT NULL DEFAULT '',    -- ISO 3166-1 alpha-2, '' = the default row (Waboo's document named "other")
  price numeric(20,6) NOT NULL,             -- in the unit Waboo used; the unit is unconfirmed (OQ-2)
  margin numeric(20,6),                     -- percentage or absolute: unconfirmed (OQ-4b)
  currency text,
  source text NOT NULL DEFAULT 'waboo',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_channel_message_rates_key UNIQUE (channel, country_code),
  CONSTRAINT chk_channel_message_rates_channel CHECK (channel IN ('email', 'sms')),
  CONSTRAINT chk_channel_message_rates_country CHECK (country_code ~ '^([A-Z]{2})?$'),
  CONSTRAINT chk_channel_message_rates_amounts CHECK (price >= 0)
);

-- 2. countries (dial code and name) -- only if something other than the pricing import needs them
CREATE TABLE countries (
  code text PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
  name text NOT NULL,
  short_name text,
  dial_code text CHECK (dial_code ~ '^[0-9]{1,4}$')   -- NOT unique: +1 serves several countries
);

-- 3. AI model prices (names, providers and prices only; never a key)
CREATE TABLE ai_model_prices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider text NOT NULL,
  model text NOT NULL,
  input_token_price numeric(20,10) NOT NULL CHECK (input_token_price >= 0),
  output_token_price numeric(20,10) NOT NULL CHECK (output_token_price >= 0),
  cached_input_token_price numeric(20,10) CHECK (cached_input_token_price >= 0),
  currency text,
  unit text,                                          -- Waboo's "unit" (per 1K or per 1M tokens): unconfirmed
  CONSTRAINT uq_ai_model_prices_model UNIQUE (provider, model)
);

