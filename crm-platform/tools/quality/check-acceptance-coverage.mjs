#!/usr/bin/env node
// Acceptance coverage (QA task 6): which Given/When/Then criteria in the inventory have a test that names them.
//
// A test names a criterion in one of three ways (title, comment or describe text):
//   AC-TW-CON-025-1          the stable criterion id from docs/quality/acceptance/acceptance.json
//   TW-CON-025 #1            feature id and the criterion number (also "#1, #2" and "#1 and #2")
//   TW-CON-025               the feature id alone: counts as FEATURE-level evidence only
// Criterion-level evidence is what proves a criterion. Feature-level evidence says a test exists somewhere for the feature.
//
// Usage: node tools/quality/check-acceptance-coverage.mjs [--report docs/quality/acceptance/REPORT.md] [--min-p0 N]
//   --min-p0 N   fail unless at least N percent of P0 criteria have criterion-level evidence
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ID = 'TW-[A-Z0-9]+-\\d+';
const AC_RE = new RegExp(`\\bAC-(${ID})-(\\d+)\\b`, 'g');
const REF_RE = new RegExp(`\\b(${ID})((?:\\s*(?:#\\d+)(?:\\s*(?:,|and|&)\\s*)?)*)`, 'g');

/** Evidence found in one test file's text. Pure. */
export function scanText(text) {
  const criteria = new Set();
  const features = new Set();
  for (const m of text.matchAll(AC_RE)) {
    criteria.add(`AC-${m[1]}-${m[2]}`);
    features.add(m[1]);
  }
  for (const m of text.matchAll(REF_RE)) {
    features.add(m[1]);
    for (const n of m[2].matchAll(/#(\d+)/g)) criteria.add(`AC-${m[1]}-${n[1]}`);
  }
  return { criteria, features };
}

/** Joins the extracted criteria with the evidence. Pure. */
export function coverage(criteriaList, evidence) {
  const rows = criteriaList.map((c) => ({
    ...c,
    proven: evidence.criteria.has(c.id),
    featureTested: evidence.features.has(c.feature),
  }));
  const bucket = (filter) => {
    const r = rows.filter(filter);
    return {
      total: r.length,
      proven: r.filter((x) => x.proven).length,
      featureOnly: r.filter((x) => !x.proven && x.featureTested).length,
      none: r.filter((x) => !x.proven && !x.featureTested).length,
    };
  };
  const byPriority = Object.fromEntries(
    ['P0', 'P1', 'P2'].map((p) => [p, bucket((r) => r.priority === p)]),
  );
  const domains = [...new Set(rows.map((r) => r.domain))].sort();
  const byDomain = domains.map((d) => ({
    domain: d,
    ...bucket((r) => r.domain === d),
    p0: bucket((r) => r.domain === d && r.priority === 'P0'),
  }));
  const knownIds = new Set(criteriaList.map((c) => c.id));
  const unknownRefs = [...evidence.criteria].filter((id) => !knownIds.has(id)).sort();
  return { rows, byPriority, byDomain, total: bucket(() => true), unknownRefs };
}

const pct = (a, b) => (b === 0 ? '-' : `${((100 * a) / b).toFixed(1)}%`);

export function renderReport(cov, meta) {
  const L = [
    '# Acceptance criteria coverage',
    '',
    '_Generated by `tools/quality/check-acceptance-coverage.mjs`. Do not edit by hand._',
    '',
    `Criteria: **${cov.total.total}** from ${meta.features} features. A criterion is *proven* when a test names it (\`AC-...\` or \`TW-XXX-NNN #n\`); *feature only* means a test mentions the feature but not this criterion.`,
    '',
    '| Priority | Criteria | Proven | Feature only | No test | Proven % |',
    '| --- | ---: | ---: | ---: | ---: | ---: |',
  ];
  for (const p of ['P0', 'P1', 'P2']) {
    const b = cov.byPriority[p];
    L.push(
      `| ${p} | ${b.total} | ${b.proven} | ${b.featureOnly} | ${b.none} | ${pct(b.proven, b.total)} |`,
    );
  }
  const t = cov.total;
  L.push(
    `| **All** | **${t.total}** | **${t.proven}** | **${t.featureOnly}** | **${t.none}** | **${pct(t.proven, t.total)}** |`,
    '',
    '## By domain (P0 criteria first)',
    '',
    '| Domain | P0 criteria | P0 proven | All criteria | Proven | Feature only | No test |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
  );
  for (const d of [...cov.byDomain].sort(
    (a, b) =>
      b.p0.none + b.p0.featureOnly - (a.p0.none + a.p0.featureOnly) ||
      a.domain.localeCompare(b.domain),
  )) {
    L.push(
      `| ${d.domain} | ${d.p0.total} | ${d.p0.proven} | ${d.total} | ${d.proven} | ${d.featureOnly} | ${d.none} |`,
    );
  }
  if (cov.unknownRefs.length)
    L.push(
      '',
      `## References to criteria that do not exist (${cov.unknownRefs.length})`,
      '',
      'A test names a criterion number the inventory does not have. Fix the test title or the inventory.',
      '',
      ...cov.unknownRefs.slice(0, 50).map((x) => `- ${x}`),
    );
  L.push('');
  return L.join('\n');
}

const TEST_FILE = /\.(spec|test)\.(ts|tsx|mjs)$/;
export function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    if (n === 'node_modules' || n === 'dist' || n === '.next' || n.startsWith('.')) continue;
    const p = join(dir, n);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (TEST_FILE.test(n)) out.push(p);
  }
  return out;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const file = join(root, 'docs/quality/acceptance/acceptance.json');
  if (!existsSync(file)) {
    console.error('run node tools/quality/extract-acceptance.mjs first');
    process.exit(2);
  }
  const data = JSON.parse(readFileSync(file, 'utf8'));
  const evidence = { criteria: new Set(), features: new Set() };
  for (const dir of [
    'apps/api/test',
    'apps/api/src',
    'apps/web/src',
    'apps/web/e2e',
    'apps/partner',
    'apps/mobile/src',
    'packages',
  ]) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const f of walk(abs)) {
      const e = scanText(readFileSync(f, 'utf8'));
      e.criteria.forEach((x) => evidence.criteria.add(x));
      e.features.forEach((x) => evidence.features.add(x));
    }
  }
  const cov = coverage(data.criteria, evidence);
  const report = renderReport(cov, { features: data.features });
  const i = process.argv.indexOf('--report');
  if (i > -1) writeFileSync(resolve(process.argv[i + 1]), report);
  else console.log(report);
  const m = process.argv.indexOf('--min-p0');
  if (m > -1) {
    const want = Number(process.argv[m + 1]);
    const b = cov.byPriority.P0;
    const got = b.total === 0 ? 100 : (100 * b.proven) / b.total;
    if (got < want) {
      console.error(`P0 criteria proven: ${got.toFixed(1)}% is below the required ${want}%`);
      process.exit(1);
    }
  }
  if (cov.unknownRefs.length)
    console.warn(
      `${cov.unknownRefs.length} reference(s) to criteria that do not exist (see the report)`,
    );
}
