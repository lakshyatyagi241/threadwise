-- 0004_crm_contacts
-- The reference vertical slice: companies + contacts + the identity graph.
--
-- These are Tier-1 storage: physical table, typed columns, real FKs. Org
-- custom fields live in `data` (Tier-2) and are defined by `fields` metadata,
-- which arrives with the kernel migration. Nothing here needs DDL to add a
-- custom field later.

CREATE TABLE companies (
  org_id          bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid            uuid NOT NULL DEFAULT gen_random_uuid(),
  name            text,
  domain          text,
  owner_id        bigint,
  lifecycle_state record_lifecycle NOT NULL DEFAULT 'active',
  status          text,
  data            jsonb NOT NULL DEFAULT '{}',
  display_id      text,
  is_archived     boolean NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  row_version     integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id) ON DELETE SET NULL
);

CREATE TABLE contacts (
  org_id           bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id               bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid             uuid NOT NULL DEFAULT gen_random_uuid(),
  name             text,
  email            citext,
  phone            text,
  company_id       bigint,
  owner_id         bigint,

  -- Dedup match keys, maintained by trigger. NON-unique on purpose: merge and
  -- lead-promotion flows pass through states where two rows legitimately share
  -- a key for a moment. Uniqueness is enforced where it belongs — on
  -- contact_identities.
  normalized_email citext,
  normalized_phone text,

  -- Platform state, distinct from business status on purpose.
  lifecycle_state  record_lifecycle NOT NULL DEFAULT 'active',
  status           text,
  -- Funnel position. This is the single field the sub-agent portal polls
  -- (ADR-0014); it is read live, never copied into the partner's own store.
  lifecycle_stage  text NOT NULL DEFAULT 'new',
  -- Tier-2: org-defined custom fields, zero DDL to add one.
  data             jsonb NOT NULL DEFAULT '{}',
  display_id       text,
  is_archived      boolean NOT NULL DEFAULT false,
  search_vector    tsvector,

  -- Id of this record in the legacy Geta system, for migration
  -- reconciliation. Null for anything created natively. See ADR-0015.
  legacy_id        text,

  created_by       bigint,
  updated_by       bigint,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  row_version      integer NOT NULL DEFAULT 1,

  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, company_id) REFERENCES companies (org_id, id) ON DELETE SET NULL,
  FOREIGN KEY (org_id, owner_id)   REFERENCES users     (org_id, id) ON DELETE SET NULL
);

-- Hot path: recent-first list, archived rows excluded. Partial so the index
-- stays small as archived rows accumulate.
CREATE INDEX idx_contacts_org_created ON contacts (org_id, created_at DESC, id DESC)
  WHERE is_archived = false;
CREATE INDEX idx_contacts_org_owner   ON contacts (org_id, owner_id, created_at DESC);
CREATE INDEX idx_contacts_org_stage   ON contacts (org_id, lifecycle_stage, created_at DESC);
CREATE INDEX idx_contacts_norm_email  ON contacts (org_id, normalized_email)
  WHERE normalized_email IS NOT NULL;
CREATE INDEX idx_contacts_norm_phone  ON contacts (org_id, normalized_phone)
  WHERE normalized_phone IS NOT NULL;
CREATE INDEX idx_contacts_search      ON contacts USING gin (search_vector);
CREATE INDEX idx_contacts_data        ON contacts USING gin (data jsonb_path_ops);
CREATE UNIQUE INDEX uq_contacts_legacy_id ON contacts (org_id, legacy_id)
  WHERE legacy_id IS NOT NULL;

-- One contact, many channel identities. The unique constraint is the auto-merge
-- backbone: an identity belongs to exactly one contact per org, so inbound
-- resolution is a single lookup and can never fan out to two people.
CREATE TABLE contact_identities (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  contact_id bigint NOT NULL,
  kind       text NOT NULL,   -- phone | email | whatsapp | web_visitor
  value      text NOT NULL,   -- normalised: E.164, lowercased email, visitor uuid
  is_primary boolean NOT NULL DEFAULT false,
  verified   boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, kind, value),
  FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_identity_kind CHECK (kind IN ('phone', 'email', 'whatsapp', 'web_visitor'))
);
CREATE INDEX idx_contact_identities_contact ON contact_identities (org_id, contact_id);

-- --- normalisation + search -----------------------------------------------
CREATE OR REPLACE FUNCTION contacts_normalize() RETURNS trigger
  LANGUAGE plpgsql AS $$
BEGIN
  NEW.normalized_email := lower(nullif(trim(NEW.email::text), ''));
  -- Strip everything that is not a digit or a leading '+'. Full E.164
  -- normalisation (country inference from the org's default region) happens in
  -- the application; this is the storage-level backstop.
  NEW.normalized_phone := nullif(regexp_replace(coalesce(NEW.phone, ''), '[^0-9+]', '', 'g'), '');

  NEW.search_vector :=
      setweight(to_tsvector('simple', coalesce(NEW.name, '')), 'A')
   || setweight(to_tsvector('simple', coalesce(NEW.email::text, '')), 'B')
   || setweight(to_tsvector('simple', coalesce(NEW.phone, '')), 'B')
   || setweight(to_tsvector('simple', coalesce(NEW.data ->> 'college_tag', '')), 'C');
  RETURN NEW;
END $$;

CREATE TRIGGER trg_contacts_normalize
  BEFORE INSERT OR UPDATE OF name, email, phone, data ON contacts
  FOR EACH ROW EXECUTE FUNCTION contacts_normalize();

CREATE TRIGGER trg_contacts_touch  BEFORE UPDATE ON contacts  FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_companies_touch BEFORE UPDATE ON companies FOR EACH ROW EXECUTE FUNCTION touch_row();
