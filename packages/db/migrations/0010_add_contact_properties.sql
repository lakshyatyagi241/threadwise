-- 0010_add_contact_properties
-- Phase 8 (docs/phase-plan.md) — Settings > Data Management > Contact
-- Properties. The Tier-2 custom-field registry that 0004_crm_contacts.sql's
-- header comment promised: "Org custom fields live in `data` (Tier-2) and
-- are defined by `fields` metadata, which arrives with the kernel
-- migration." This is that metadata. `module_key` is generic on purpose —
-- 'contacts' today, 'companies' reuses the same six tables later without a
-- new migration (see docs/contacts-schema-design.dbml).

CREATE TABLE field_sections (
  org_id      bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid        uuid NOT NULL DEFAULT gen_random_uuid(),
  module_key  text NOT NULL,
  name        text NOT NULL,
  position    integer NOT NULL DEFAULT 0,
  is_active   boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid)
);
CREATE INDEX idx_field_sections_org_module ON field_sections (org_id, module_key, position);

CREATE TABLE fields (
  org_id             bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  uuid               uuid NOT NULL DEFAULT gen_random_uuid(),
  module_key         text NOT NULL,
  section_id         bigint,
  key                text NOT NULL,
  label              text NOT NULL,
  field_type         text NOT NULL,
  is_required        boolean NOT NULL DEFAULT false,
  is_hidden          boolean NOT NULL DEFAULT false,
  is_read_only       boolean NOT NULL DEFAULT false,
  is_masked          boolean NOT NULL DEFAULT false,
  is_unique          boolean NOT NULL DEFAULT false,
  is_quick_create    boolean NOT NULL DEFAULT false,
  is_global_search   boolean NOT NULL DEFAULT false,
  is_system          boolean NOT NULL DEFAULT false,
  is_active          boolean NOT NULL DEFAULT true,
  position           integer NOT NULL DEFAULT 0,
  config             jsonb NOT NULL DEFAULT '{}',
  replaces_field_id  bigint,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  row_version        integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, uuid),
  FOREIGN KEY (org_id, section_id)        REFERENCES field_sections (org_id, id) ON DELETE SET NULL,
  FOREIGN KEY (org_id, replaces_field_id) REFERENCES fields         (org_id, id) ON DELETE SET NULL,
  CONSTRAINT chk_fields_type CHECK (field_type IN (
    'text', 'long_text', 'integer', 'big_integer', 'decimal', 'percentage',
    'currency', 'boolean', 'checkbox', 'radio', 'date', 'datetime', 'url',
    'email', 'phone', 'select', 'multiselect', 'lookup', 'rating',
    'timezone', 'formula'
  ))
);
-- A field's storage key (the key it lives under in contacts.data) must be
-- unique per org+module, or two admin-defined fields collide on write.
CREATE UNIQUE INDEX uq_fields_org_module_key ON fields (org_id, module_key, key);
CREATE INDEX idx_fields_org_module ON fields (org_id, module_key, position);
CREATE INDEX idx_fields_section    ON fields (org_id, section_id);

CREATE TABLE field_options (
  org_id     bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  field_id   bigint NOT NULL,
  value      text NOT NULL,
  label      text NOT NULL,
  position   integer NOT NULL DEFAULT 0,
  is_hidden  boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  row_version integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  FOREIGN KEY (org_id, field_id) REFERENCES fields (org_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_field_options_field ON field_options (org_id, field_id, position);

-- Field-level dependency: shows/hides the whole dependent field based on
-- another field's value (or a specific option on it).
CREATE TABLE field_dependencies (
  org_id                bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                    bigint GENERATED BY DEFAULT AS IDENTITY,
  field_id              bigint NOT NULL,
  depends_on_field_id   bigint NOT NULL,
  depends_on_option_id  bigint,
  depends_on_value      text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  FOREIGN KEY (org_id, field_id)             REFERENCES fields        (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, depends_on_field_id)  REFERENCES fields        (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, depends_on_option_id) REFERENCES field_options (org_id, id) ON DELETE CASCADE,
  CONSTRAINT chk_field_dependencies_not_self CHECK (field_id <> depends_on_field_id)
);
CREATE INDEX idx_field_dependencies_field      ON field_dependencies (org_id, field_id);
CREATE INDEX idx_field_dependencies_depends_on ON field_dependencies (org_id, depends_on_field_id);

-- Option-level, many:many: which options of the dependent field are
-- selectable given the parent field's currently-selected option.
CREATE TABLE field_option_dependencies (
  org_id            bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id                bigint GENERATED BY DEFAULT AS IDENTITY,
  parent_option_id  bigint NOT NULL,
  child_option_id   bigint NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (org_id, id),
  FOREIGN KEY (org_id, parent_option_id) REFERENCES field_options (org_id, id) ON DELETE CASCADE,
  FOREIGN KEY (org_id, child_option_id)  REFERENCES field_options (org_id, id) ON DELETE CASCADE,
  UNIQUE (org_id, parent_option_id, child_option_id)
);

-- Per-module enum groups (lifecycle_stage, deal_status, whatsapp/email/sms
-- subscription status, ...) that render as pills/dropdowns in the UI but
-- whose values an org admin can add to without a code deploy.
CREATE TABLE status_options (
  org_id        bigint NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  module_key    text NOT NULL,
  option_group  text NOT NULL,
  value         text NOT NULL,
  label         text NOT NULL,
  color         text,
  position      integer NOT NULL DEFAULT 0,
  is_default    boolean NOT NULL DEFAULT false,
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  row_version   integer NOT NULL DEFAULT 1,
  PRIMARY KEY (org_id, id),
  UNIQUE (org_id, module_key, option_group, value)
);
CREATE INDEX idx_status_options_org_group ON status_options (org_id, module_key, option_group, position);

-- --- RLS: 0007_rls_policies.sql already ran, so its table array is history —
-- every table added after it must enable/force/policy/grant itself. ---------
DO $$
DECLARE
  t text;
  new_tables text[] := ARRAY[
    'field_sections', 'fields', 'field_options',
    'field_dependencies', 'field_option_dependencies', 'status_options'
  ];
BEGIN
  FOREACH t IN ARRAY new_tables LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
    EXECUTE format($p$
      CREATE POLICY tenant_isolation ON %I
        FOR ALL
        USING      (org_id = current_org_id() OR app_is_privileged())
        WITH CHECK (org_id = current_org_id() OR app_is_privileged())
    $p$, t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO crm_app, crm_worker', t);
  END LOOP;
END $$;

CREATE TRIGGER trg_field_sections_touch  BEFORE UPDATE ON field_sections  FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_fields_touch          BEFORE UPDATE ON fields          FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_field_options_touch   BEFORE UPDATE ON field_options   FOR EACH ROW EXECUTE FUNCTION touch_row();
CREATE TRIGGER trg_status_options_touch  BEFORE UPDATE ON status_options  FOR EACH ROW EXECUTE FUNCTION touch_row();
